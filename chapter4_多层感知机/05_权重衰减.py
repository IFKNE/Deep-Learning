"""
=============================================================================
权重衰减 —— L2正则化（完整带注释版）
=============================================================================

【核心概念】
  权重衰减 (Weight Decay) = L2 正则化 (L2 Regularization)

  动机：当训练数据有限而模型参数过多时，模型容易"记住"训练样本的噪声，
  导致过拟合——训练误差低但测试误差高。

  做法：在损失函数中加入权重大小的惩罚项，迫使模型学习较小的权重值。

  数学形式：
    原始损失:         L(w, b) = (1/n) * Σ (1/2) * (wᵀx⁽ⁱ⁾ + b - y⁽ⁱ⁾)²
    加入惩罚后:       L'(w, b) = L(w, b) + (λ/2) * ||w||²
    其中 λ (lambda) 是正则化强度超参数。

  为什么叫"权重衰减"：
    在随机梯度下降更新时，权重更新公式中的 (1 - ηλ) 项使得权重在每一步迭代
    中都会按比例缩小（衰减），因此得名。

  λ=0 → 无正则化（可能严重过拟合）
  λ 越大 → 权重约束越强（模型越简单）

来源：《动手学深度学习》(D2L) - 多层感知机章节 - 权重衰减
"""

# ============================================================================
# 第1步：导入依赖库
# ============================================================================
# %matplotlib inline  # Jupyter notebook 魔术命令，在脚本中不需要，仅用于 inline 显示图表
import torch                         # PyTorch 深度学习框架核心库
from torch import nn                 # 神经网络模块，提供各种层和损失函数
from d2l import torch as d2l         # 《动手学深度学习》配套工具库，封装了常用函数


# ============================================================================
# 第2步：生成高维线性回归数据
# ============================================================================
# 【为什么用高维+小样本？】
#   当特征维度(200)远超训练样本数(20)时，模型有很多自由度来"完美"拟合训练数据，
#   此时极易过拟合，正好用来演示权重衰减的效果。这模拟了现实中"样本稀缺但特征很多"的场景。

# --- 2.1 数据生成公式 ---
# 真实模型: y = 0.05 + Σᵢ₌₁ᵈ 0.01 * xᵢ + ε
# 其中 ε ~ N(0, 0.01²) 是均值为0、标准差为0.01的高斯噪声
# 200个特征每个的真实权重都是0.01，共计200个特征

n_train, n_test, num_inputs, batch_size = 20, 100, 200, 5  # 训练集20个，测试集100个，输入维度200，批次大小5

# true_w: 真实权重，形状(200, 1)，每个元素值为0.01
# torch.ones((num_inputs, 1)) 创建一个全1的张量，* 0.01 使每个值为0.01
true_w = torch.ones((num_inputs, 1)) * 0.01  # shape: (200, 1)
true_b = 0.05                                 # 真实偏置，标量

# d2l.synthetic_data(true_w, true_b, n): 根据真实参数生成 n 个合成样本
# 返回 (features, labels)，features 服从 N(0,1)，labels 由线性模型+噪声生成
train_data = d2l.synthetic_data(true_w, true_b, n_train)   # 生成20个训练样本
# d2l.load_array(data, batch_size): 将数据包装成指定批次大小的迭代器
train_iter = d2l.load_array(train_data, batch_size)         # 训练数据迭代器，每批5个样本

test_data = d2l.synthetic_data(true_w, true_b, n_test)     # 生成100个测试样本
# is_train=False 表示测试模式，不打乱数据顺序
test_iter = d2l.load_array(test_data, batch_size, is_train=False)  # 测试数据迭代器


# ============================================================================
# 第3步：从零开始实现权重衰减
# ============================================================================

# --- 3.1 初始化模型参数 ---
def init_params():
    """
    随机初始化线性回归模型的权重和偏置。

    返回:
        [w, b] -- 权重和偏置参数列表，都设置了 requires_grad=True 以便计算梯度
    """
    # torch.normal(mean, std, size): 从正态分布 N(mean, std²) 中随机采样，返回指定形状的张量
    # requires_grad=True: 告诉 PyTorch 需要对此张量计算梯度（自动求导机制的核心开关）
    # 权重从 N(0, 1²) 中采样，这比全零初始化更好——打破对称性，让不同神经元学到不同特征
    w = torch.normal(0, 1, size=(num_inputs, 1), requires_grad=True)  # shape: (200, 1)

    # torch.zeros(n): 创建包含 n 个零的张量
    # 偏置通常初始化为0，因为偏置没有"对称性问题"
    b = torch.zeros(1, requires_grad=True)  # shape: (1,)

    return [w, b]


# --- 3.2 定义 L2 范数惩罚项 ---
# 【为什么需要惩罚项？】
#   L2 正则化在损失函数中加入 ||w||² 的惩罚。权重越大，惩罚越大。
#   这迫使优化器在"拟合数据"和"保持权重小"之间取得平衡。
#
# 【为什么除以2？】
#   当对 (w²/2) 求导时得到 w，漂亮地消去了系数2。
#   d/dw (w²/2) = w，这使得梯度表达式简洁。
def l2_penalty(w):
    """
    计算 L2 范数平方的一半: (1/2) * ||w||² = (1/2) * Σᵢ wᵢ²

    参数:
        w: 权重张量

    返回:
        (1/2) * 所有权重值的平方和，标量张量
    """
    # w.pow(2):   对张量中每个元素求平方，等价于 w ** 2
    # .sum():     将所有元素求和，返回一个标量
    # / 2:        除以2（原因见上方注释）
    return torch.sum(w.pow(2)) / 2


# --- 3.3 定义训练函数（从零实现版） ---
def train(lambd):
    """
    从零实现权重衰减的训练过程。

    参数:
        lambd (λ): 正则化强度超参数
            λ = 0: 无正则化，等价于普通线性回归
            λ > 0: λ 越大，对权重的惩罚越强，模型越简单

    流程:
        1. 初始化参数
        2. 在每个 epoch 中遍历批次数据
        3. 计算带 L2 惩罚的损失: total_loss = MSE_loss + λ * l2_penalty
        4. 反向传播计算梯度
        5. 使用 SGD 更新参数
        6. 每5个 epoch 记录训练和测试损失
    """
    # 初始化模型参数（权重和偏置）
    w, b = init_params()

    # lambda 关键字用来创建匿名函数（一行函数）
    # lambda X: d2l.linreg(X, w, b) 等价于 def net(X): return d2l.linreg(X, w, b)
    # d2l.linreg: 线性回归前向计算 X @ w + b
    # d2l.squared_loss: 平方损失函数 (预测值 - 真实值)² / 2
    net = lambda X: d2l.linreg(X, w, b)  # 模型：线性函数
    loss = d2l.squared_loss               # 损失函数：平方损失

    num_epochs, lr = 100, 0.003  # 训练100轮，学习率0.003

    # d2l.Animator: 动态绘图工具
    # yscale='log' 使用对数刻度，便于观察损失的数量级变化
    animator = d2l.Animator(xlabel='epochs', ylabel='loss', yscale='log',
                            xlim=[5, num_epochs], legend=['train', 'test'])

    for epoch in range(num_epochs):          # 外层循环：遍历100个epoch
        for X, y in train_iter:              # 内层循环：遍历训练数据的每个批次
            # 【关键步骤】计算带正则化的损失
            # loss(net(X), y): 计算预测值与真实值的平方损失
            # lambd * l2_penalty(w): L2 惩罚项，λ 控制惩罚强度
            # Python 的广播机制: lambd * l2_penalty(w) 是标量，会自动广播
            # 与 loss 的每个元素相加（等价于在每个样本损失上加同样的惩罚）
            # 完整形式: L = (1/2) * (ŷ - y)² + (λ/2) * ||w||²
            l = loss(net(X), y) + lambd * l2_penalty(w)

            # .sum(): 将批次内所有样本的损失求和（得到一个标量）
            # .backward(): 自动求导——从该标量出发，反向计算所有 requires_grad=True 的参数的梯度
            # 梯度存储在参数的 .grad 属性中（例如 w.grad, b.grad）
            l.sum().backward()

            # d2l.sgd([w, b], lr, batch_size): 小批量随机梯度下降
            # 内部实现: param = param - lr * param.grad / batch_size
            # 这个函数会使用 .grad 中的梯度来更新参数，然后自动清零梯度
            d2l.sgd([w, b], lr, batch_size)

        # 每5个epoch记录一次损失
        if (epoch + 1) % 5 == 0:
            # d2l.evaluate_loss(net, data_iter, loss): 在给定数据集上评估损失
            animator.add(epoch + 1, (d2l.evaluate_loss(net, train_iter, loss),
                                     d2l.evaluate_loss(net, test_iter, loss)))

    # torch.norm(w): 计算权重张量w的L2范数（欧几里得范数，即 √Σᵢwᵢ²）
    # .item(): 将单元素张量转换为Python标量（float）
    # 较小的范数说明权重衰减起作用了——权重被约束在接近零的值
    print('w的L2范数是：', torch.norm(w).item())


# --- 3.4 不使用权重衰减（λ = 0），观察过拟合现象 ---
print("=" * 60)
print("实验1: λ = 0（无权重衰减，应出现过拟合）")
print("=" * 60)
# lambd=0 意味着损失函数中不加入惩罚项，等价于普通线性回归
# 预期：由于只有20个训练样本但有200个参数，模型会严重过拟合
# 训练损失会很低（模型"记住"了训练数据），但测试损失较高（泛化能力差）
train(lambd=0)

# --- 3.5 使用权重衰减（λ = 3），观察正则化效果 ---
print("\n" + "=" * 60)
print("实验2: λ = 3（使用权重衰减，应缓解过拟合）")
print("=" * 60)
# lambd=3 对权重施加较大的惩罚，防止权重任意增长
# 预期：训练损失可能略有上升（模型不能完美拟合训练数据），
# 但测试损失会下降（泛化能力改善）
# 且权重的L2范数会明显小于λ=0时的情况
train(lambd=3)


# ============================================================================
# 第4步：PyTorch 简洁实现
# ============================================================================
# 【为什么框架实现更好？】
#   1. 权重衰减被集成到优化器中，不需要手动修改损失函数
#   2. 计算上更高效——权重衰减部分只与参数当前值有关，可与梯度更新合并
#   3. 可以方便地对不同参数组设置不同的衰减策略（如偏置不衰减）

def train_concise(wd):
    """
    使用 PyTorch 框架内置的权重衰减功能的训练过程。

    参数:
        wd (weight_decay): 权重衰减超参数（等价于 λ）
            - 传递给 torch.optim.SGD 的 weight_decay 参数
            - 优化器会在每次更新时自动执行: w = w - lr * grad - lr * wd * w
            - 等价于在损失中加入了 (wd/2) * ||w||² 的惩罚

    【与从零实现的对应关系】
        从零实现: loss = MSE + lambd * (||w||² / 2)
        框架实现: optimizer = SGD(params, lr, weight_decay=wd)
        两者在数学上等价，但框架实现将衰减步骤融入优化器更新中。
    """
    # nn.Sequential: 顺序容器，按顺序应用各层
    # nn.Linear(num_inputs, 1): 全连接层，输入维度200，输出维度1
    # 内部包含 weight (形状[1,200]) 和 bias (形状[1]), 均由框架自动管理
    net = nn.Sequential(nn.Linear(num_inputs, 1))

    # 初始化模型参数（重置为随机值）
    # net.parameters(): 返回模型中所有可学习参数的迭代器
    # param.data: 访问参数的底层数据（不涉及梯度计算）
    # param.data.normal_(): 从标准正态分布 N(0,1) 中随机采样，原地填充参数数据
    # 注意: 带 _ 后缀的方法表示原地操作（in-place），直接修改张量而不创建新副本
    for param in net.parameters():
        param.data.normal_()

    # nn.MSELoss: 均方误差损失函数
    # reduction='none': 不自动求均值/求和，返回每个样本各自的损失值
    # 这样我们可以后续自己决定如何聚合（如 .mean()），保留灵活性
    loss = nn.MSELoss(reduction='none')

    num_epochs, lr = 100, 0.003  # 训练轮数和学习率，与从零实现保持一致

    # 【核心】torch.optim.SGD 优化器
    # 可以为不同参数组设置不同的配置
    # net[0].weight: 第一层（Linear层）的权重——需要权重衰减
    # net[0].bias:   第一层的偏置——通常不需要权重衰减（见补充知识）
    # 这种分组配置的写法是 PyTorch 的标准范式
    trainer = torch.optim.SGD([
        {"params": net[0].weight, 'weight_decay': wd},  # 权重：应用权重衰减
        {"params": net[0].bias}                          # 偏置：不应用权重衰减
    ], lr=lr)

    animator = d2l.Animator(xlabel='epochs', ylabel='loss', yscale='log',
                            xlim=[5, num_epochs], legend=['train', 'test'])

    for epoch in range(num_epochs):
        for X, y in train_iter:
            # trainer.zero_grad(): 将优化器中所有参数的梯度清零
            # 必须在每个批次开始前调用，否则梯度会跨批次累加（PyTorch 默认行为）
            # 这相当于从零实现中 d2l.sgd 内部做的清零操作
            trainer.zero_grad()

            # 前向传播：计算预测值
            # 注意：这里损失函数没有手动加惩罚项——惩罚已经被集成到优化器中
            l = loss(net(X), y)

            # .mean(): 对批次内所有样本的损失求均值（得到标量）
            # 为什么用 .mean() 而不用 .sum()？
            #   使用均值使得损失值不受批次大小影响，便于对比不同批次大小的实验
            # .backward(): 反向传播计算梯度
            l.mean().backward()

            # trainer.step(): 执行一步参数更新
            # 内部会同时完成：1) 使用梯度更新参数  2) 应用权重衰减
            # 更新公式: w = w - lr * grad - lr * wd * w  (包含权重衰减)
            #           b = b - lr * grad                   (不包含权重衰减)
            trainer.step()

        if (epoch + 1) % 5 == 0:
            animator.add(epoch + 1,
                         (d2l.evaluate_loss(net, train_iter, loss),
                          d2l.evaluate_loss(net, test_iter, loss)))

    # net[0].weight.norm(): 计算权重张量的 L2 范数
    # 等价于 torch.norm(net[0].weight)
    # .item(): 提取 Python 标量值
    print('w的L2范数：', net[0].weight.norm().item())


# --- 4.1 简洁实现：不使用权重衰减 ---
print("\n" + "=" * 60)
print("实验3: 简洁实现 λ = 0（无权重衰减）")
print("=" * 60)
train_concise(0)

# --- 4.2 简洁实现：使用权重衰减 ---
print("\n" + "=" * 60)
print("实验4: 简洁实现 λ = 3（有权重衰减）")
print("=" * 60)
train_concise(3)


