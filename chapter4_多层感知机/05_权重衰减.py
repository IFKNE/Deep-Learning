# --- 补充1：L2 正则化 vs L1 正则化 ---
"""
【L2 正则化（权重衰减 / 岭回归 Ridge Regression）】
  惩罚项: (λ/2) * ||w||² = (λ/2) * Σᵢ wᵢ²

  特点:
  - 对大的权重施加非常大的惩罚（平方关系）
  - 倾向于让所有权重都小但非零——权重在特征间均匀分布
  - 梯度: λ * w（与权重成正比，大权重衰减更快）
  - 解是"稠密"的：所有特征都参与

  优点:
  - 对输入中的微小变化更鲁棒
  - 当所有特征都有贡献时效果好
  - 解析解存在且唯一（损失函数严格凸）

【L1 正则化（Lasso 回归 / 套索回归）】
  惩罚项: λ * ||w||₁ = λ * Σᵢ |wᵢ|

  特点:
  - 对所有非零权重施加等比例的惩罚
  - 倾向于让一些权重变成精确的零——自动特征选择
  - 梯度: λ * sign(w)（大小固定，只取决于符号）
  - 解是"稀疏"的：只保留最重要的特征

  优点:
  - 自带特征选择功能，模型更可解释
  - 当只有少数特征真正重要时效果好

【直观理解】
  假设你有一个体重管理目标：
  - L2 正则化: 对超重100斤的人比超重10斤的人惩罚严厉100倍（平方），鼓励大家"均匀地瘦"
  - L1 正则化: 对超重100斤和超重10斤的人惩罚只差10倍（绝对值），可能让一些人"瘦到消失"
"""

# --- 补充2：为什么偏置通常不正则化？ ---
"""
偏置 b 通常不被正则化的原因：

1. 【数学原因】偏置只影响函数的截距（上下平移），不影响函数的复杂度（弯曲程度）。
   过拟合通常由模型过于"扭曲"造成（权重过大 → 对输入变化过于敏感），
   而偏置只是平移不会增加模型的灵活性。

2. 【实践原因】如果对偏置施加惩罚，会迫使 b 趋近于 0，
   这可能不合理——真实数据的中心通常不在原点。

3. 【经验规律】在网络输入层和中间层，偏置也不正则化；
   但在某些实现中，输出层的偏置也可能不被正则化。

4. 【PyTorch 实现】如上面代码所示，通过参数分组可以有选择地对权重施加 weight_decay：
   torch.optim.SGD([
       {"params": 权重, 'weight_decay': wd},   # 衰减
       {"params": 偏置}                         # 不衰减
   ], lr=lr)
"""

# --- 补充3：权重衰减的数学推导 ---
"""
【从损失函数到更新公式的完整推导】

设原始损失为 ℓ(w)，加入 L2 正则化后的总损失：
  J(w) = ℓ(w) + (λ/2) * ||w||²

在 SGD 更新中，对 J 求关于 w 的梯度：
  ∇w J = ∇w ℓ + λ * w

因此权重更新公式为：
  w ← w - η * ∇w J
    = w - η * (∇w ℓ + λ * w)
    = w - η * ∇w ℓ - η * λ * w
    = (1 - η * λ) * w - η * ∇w ℓ     ← 关键形式！

解释：
  (1 - ηλ) 这一项 < 1（当 ηλ > 0 时），因此：
  - 每次更新时，权重首先被缩放到原来的 (1 - ηλ) 倍（衰减）
  - 然后再减去基于训练损失的梯度更新
  这就是"权重衰减"名称的由来。

【示例计算】
  假设 η=0.01, λ=0.1:
  每次更新 w 先乘以 0.999，衰减幅度为 0.1%
  假设 η=0.01, λ=3:
  每次更新 w 先乘以 0.97，衰减幅度为 3%（明显更强）

【PyTorch 中的实现等价性】
  从零实现: loss.backward() 计算 ∇w ℓ，再手动加上 λ * w
  框架实现: optimizer.step() 内部同时处理 ∇w ℓ + λ * w

  两者在数学上完全等价，但框架实现更高效：
  - 避免显式计算和存储惩罚项的梯度
  - 将衰减操作融入优化器的参数更新循环中
"""

