# --- 补充5：Frobenius 范数 —— 矩阵的 L2 范数 ---
"""
【Frobenius 范数】是向量 L2 范数向矩阵的自然推广。

定义：对于矩阵 W ∈ R^{m×n}
  ||W||_F = √(Σᵢ Σⱼ wᵢⱼ²) = √(tr(WᵀW))

即：矩阵所有元素的平方和的平方根。

【性质】
  ||W||_F² = tr(WᵀW) = trace(Wᵀ @ W)
  其中 trace(·) 是矩阵的迹（对角线元素之和）。

【在深度学习中的应用】
  全连接层权重是矩阵 → 使用 Frobenius 范数进行 L2 正则化
  卷积层权重是四维张量 → 同样将其展平后使用 Frobenius 范数

【PyTorch 代码示例】
  W = torch.randn(10, 5)
  frobenius_norm = torch.norm(W, p='fro')        # Frobenius 范数
  frobenius_sq = torch.sum(W.pow(2))              # Frobenius 范数的平方
  # 验证 Frobenius 范数与 L2 范数的关系
  assert torch.allclose(frobenius_norm.pow(2), frobenius_sq)
"""

# --- 补充6：常见问题与练习解答 ---
"""
【Q1: 如何选择 λ 的值？】
  - 使用验证集进行超参数搜索（类似学习率调优）
  - 典型搜索范围: [0.0001, 0.001, 0.01, 0.1, 1, 10]
  - λ 太小 → 正则化不足，仍过拟合
  - λ 太大 → 欠拟合，模型太简单无法捕捉数据规律
  - 可绘制"验证误差 vs λ"曲线来观察最优值

【Q2: L1 正则化的更新公式是什么？】
  L1 惩罚: (λ) * Σᵢ |wᵢ|
  梯度: λ * sign(w)
  更新公式: w ← w - η * ∇w ℓ - η * λ * sign(w)

  与 L2 的 (1 - ηλ) * w 衰减不同，L1 每次减去一个固定大小（ηλ），
  这会导致小权重更快地变成零（特征选择效应）。

【Q3: 除了权重衰减，还有哪些防过拟合的方法？】
  1. 增加训练数据（数据增强）
  2. Dropout（随机丢弃神经元）
  3. 早停法 (Early Stopping)：在验证误差开始上升时停止训练
  4. 数据增强 (Data Augmentation)：对训练数据施加随机变换
  5. 批量归一化 (Batch Normalization)：有一定正则化效果
  6. 简化模型结构（减少层数/神经元数）
  7. 集成学习 (Ensemble)：多个模型的平均预测

【Q4: 权重衰减与贝叶斯推断的关系？】
  在贝叶斯统计中：
    后验 ∝ 似然 × 先验
    P(w|x) ∝ P(x|w) × P(w)

  - L2 正则化 等价于 假设权重服从高斯先验分布 N(0, σ²)
    其中 λ = 1/σ²，λ 越大对应先验方差越小（对权重的先验信念越集中在0附近）
  - L1 正则化 等价于 假设权重服从拉普拉斯先验分布 Laplace(0, b)
    其中 λ = 1/b

  从贝叶斯角度看，正则化实质上是在"编码我们对模型参数的先验信念"——
  我们认为权重不应该太大（靠近0）。

【Q5: PyTorch 中 weight_decay 的实现细节】
  - torch.optim.SGD 的 weight_decay 参数实现的是 L2 正则化
  - 默认情况下，optim.SGD 对所有权重和偏置都施加 weight_decay
  - 要排除偏置，需要使用参数分组（如本代码所示）
  - 有些优化器（如 AdamW）将权重衰减与自适应学习率解耦，
    实现了"解耦权重衰减"（decoupled weight decay），
    这比在 Adam 中直接使用 L2 正则化效果更好
"""


