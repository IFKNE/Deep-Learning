"""
=============================================================================
核心要点总结
=============================================================================

1. 【三个关键概念】
   - 训练误差：模型在训练集上的错误程度
   - 泛化误差：模型在"所有可能数据"上的期望错误（无法精确计算）
   - 测试误差：用独立测试集估计的泛化误差（实际中使用的近似）

2. 【欠拟合（Underfitting）】
   - 表现：训练误差和测试误差都很高，两者差距不大
   - 原因：模型太简单，无法捕捉数据中的模式
   - 对策：增加模型复杂度（更多层、更多神经元、更高阶特征）

3. 【过拟合（Overfitting）】
   - 表现：训练误差很低，但测试误差远高于训练误差
   - 原因：模型太复杂，记住了训练数据中的噪声而非真实规律
   - 对策：正则化、早停、Dropout、数据增强、简化模型

4. 【模型选择（Model Selection）】
   - 目的：在多个候选模型中选出泛化能力最好的
   - 工具：验证集（hold-out validation）或 K 折交叉验证
   - 铁律：测试集只能用于最终评估，绝不能在模型选择过程中使用

5. 【多项式回归实验结论】
   - 三阶拟合（4 参数，与数据生成函数同阶）：训练和测试误差都低，完美
   - 线性拟合（2 参数，欠拟合）：两个误差都高，模型太简单
   - 20 阶拟合（20 参数，过拟合）：训练误差极低，测试误差高，泛化差

6. 【偏差-方差权衡】
   - 简单模型 → 高偏差 + 低方差（倾向欠拟合）
   - 复杂模型 → 低偏差 + 高方差（倾向过拟合）
   - 目标是在偏差和方差之间找到最优平衡点

7. 【实践建议】
   - 从简单模型开始，逐步增加复杂度
   - 始终监控训练误差和验证误差的差距
   - 数据量越大，可以安全使用的模型越复杂
   - 绘制学习曲线是诊断拟合问题最直观的方法
=============================================================================
"""
