"""
=============================================================================
模型选择、欠拟合和过拟合 —— 多项式回归实验（完整带注释版）
=============================================================================

本文件演示机器学习的核心难题：过拟合（overfitting）与欠拟合（underfitting）。
通过多项式回归实验，直观展示以下概念：
  - 训练误差（training error）vs 泛化误差（generalization error）
  - 验证集（validation set）与 K 折交叉验证（K-fold cross-validation）
  - 模型复杂度对拟合效果的影响
  - 数据集大小与模型选择的关系

实验流程：
  1. 用三阶多项式 + 噪声生成人工数据集
  2. 分别用低阶（线性）、同阶（三阶）、高阶（20阶）多项式拟合
  3. 对比训练误差与测试误差，观察欠拟合/正常/过拟合现象
=============================================================================
"""

# ============================================================================
# 第1步：导入依赖库
# ============================================================================
import math                             # 数学函数库，此处用于 math.gamma（阶乘函数）
import numpy as np                      # 数值计算库，用于生成数据和数组操作
import torch                            # PyTorch 深度学习框架
from torch import nn                    # nn 模块：包含各种神经网络层和损失函数
from d2l import torch as d2l            # d2l 工具包：《动手学深度学习》配套库
# d2l 提供以下关键工具：
#   d2l.Accumulator(n)  —— 累加器，用于累计 n 个不同指标的总和
#   d2l.load_array()    —— 将 ndarray/tensor 包装为 DataLoader，方便批量迭代
#   d2l.train_epoch_ch3(net, train_iter, loss, trainer)
#                       —— 执行一个 epoch 的训练，包含前向、反向、参数更新
#   d2l.Animator()      —— 动态绘图器，实时绘制训练曲线

# ============================================================================
# 第2步：生成数据集
# ============================================================================
# 本节用以下三阶多项式生成人工数据：
#
#   y = 5 + 1.2*x - 3.4*(x^2/2!) + 5.6*(x^3/3!) + ε
#
# 其中 ε ~ N(0, 0.1^2) 是高斯噪声。
# 为什么对高次项除以 i! ？
#   如果不除以 i!，高阶项 x^i 的值会非常巨大（尤其当 |x| > 1 时），
#   导致数值不稳定、梯度爆炸。除以 i! 起到特征缩放的作用。

max_degree = 20                         # 多项式的最大阶数（生成高达 x^19 的特征）
n_train, n_test = 100, 100              # 训练集和测试集各 100 个样本
true_w = np.zeros(max_degree)           # 真值权重向量，先全部初始化为 0（长度 20）
true_w[0:4] = np.array([5, 1.2, -3.4, 5.6])  # 只有前 4 个系数非零，对应三阶多项式

# --- 生成原始特征 x ---
# np.random.normal 从标准正态分布 N(0,1) 采样
# size=(200, 1) 生成 200 行 1 列的二维数组（每行一个样本，每个样本一个特征）
features = np.random.normal(size=(n_train + n_test, 1))  # shape: (200, 1)
np.random.shuffle(features)            # 随机打乱样本顺序，确保训练/测试集分布一致

# --- 生成多项式特征 ---
# np.arange(max_degree)          产生 [0, 1, 2, ..., 19] 一维数组
# .reshape(1, -1)                变为形状 (1, 20) 的行向量
# np.power(features, ...)        广播运算：features (200,1) 的每一行
#                                对 [0,1,...,19] 每个幂次求幂
# 结果 poly_features 形状为 (200, 20)：
#   第 i 列 = x^i  （第 0 列为 x^0 = 1，即偏置项）
poly_features = np.power(features, np.arange(max_degree).reshape(1, -1))

# --- 对每一列除以 i! 进行缩放 ---
# math.gamma(i+1) = i! （Gamma 函数性质：Γ(n) = (n-1)!）
# 例如：math.gamma(1)=1, math.gamma(2)=1, math.gamma(3)=2, math.gamma(4)=6
# 循环将第 i 列（对应 x^i）除以 i!
for i in range(max_degree):
    poly_features[:, i] /= math.gamma(i + 1)  # 第 i 列 /= i!，完成 x^i/i! 缩放

# --- 生成标签 y ---
# np.dot(poly_features, true_w)：矩阵乘法 (200,20) × (20,) → (200,)
# 即每个样本的标签 = Σ(w_i * x^i / i!) = 5 + 1.2x - 3.4x^2/2! + 5.6x^3/3!
labels = np.dot(poly_features, true_w)                        # shape: (200,)
# 添加高斯噪声 ε ~ N(0, 0.1^2)，模拟真实世界中数据的不确定性
# np.random.normal(scale=0.1, size=labels.shape) 生成与 labels 同形状的噪声
labels += np.random.normal(scale=0.1, size=labels.shape)     # 含噪标签

# ============================================================================
# 第3步：将 NumPy 数组转换为 PyTorch 张量
# ============================================================================
# 深度学习框架（PyTorch/TensorFlow）都使用自己的张量类型，
# 因为需要追踪梯度计算、在 GPU 上运行等。NumPy 数组不支持自动微分。

# 列表推导式：对列表中的每个元素（这里是各类数据）执行 torch.tensor() 转换
# torch.tensor(x, dtype=torch.float32) 将 numpy 数组转为 float32 类型的 PyTorch 张量
#   - float32（32位浮点数）是深度学习的标准精度：
#     比 float64 省一半内存，速度更快，精度损失通常可忽略
# 四个变量同时被重新赋值为张量版本
true_w, features, poly_features, labels = [torch.tensor(x, dtype=
    torch.float32) for x in [true_w, features, poly_features, labels]]

# ============================================================================
# 第4步：查看生成数据的前 2 个样本
# ============================================================================
# 查看原始特征 x（第 0 列是 1.0，偏置项对应的常数值）
# 查看前 20 个多项式特征（x^0/0!, x^1/1!, ..., x^19/19!）
# 查看对应的标签值 y
features[:2], poly_features[:2, :], labels[:2]

# 输出解读（示例）：
# features[:2]    = [[ 1.6580], [-1.6392]]  —— 两个样本的原始 x 值
# poly_features[0] = [1.0000, 1.6580, 1.3745, ...]  —— 第一个样本的多项式特征
#   - 第 0 列 = 1（对应偏置项）
#   - 第 1 列 = 1.6580（x^1 / 1!）
#   - 第 2 列 = 1.3745（x^2 / 2! = 1.6580^2 / 2）
#   - 第 3 列 = 0.75967（x^3 / 3! = 1.6580^3 / 6）
# labels[:2]      = [ 6.6262, -5.4505]  —— 两个样本的标签（含噪声）

# ============================================================================
# 第5步：定义损失评估函数
# ============================================================================
# 该函数用于计算模型在整个数据集上的平均损失（对标测试/验证阶段）
def evaluate_loss(net, data_iter, loss):  #@save
    """
    评估给定数据集上模型的平均损失。

    参数:
        net:       神经网络模型（nn.Module 或其子类）
        data_iter: 数据迭代器（DataLoader），每次返回一个 batch 的 (features, labels)
        loss:      损失函数（callable），接受 (pred, target) 返回损失张量

    返回:
        float: 整个数据集上的平均损失值

    工作原理：
        (1) 遍历所有 batch，对每个 batch 计算损失
        (2) 用 Accumulator 累加总损失和总样本数
        (3) 返回 总损失 / 总样本数（即平均损失）
    """
    # Accumulator(2) 创建一个能累加 2 个独立指标的累加器
    # metric[0] 累加总损失，metric[1] 累加样本总数
    metric = d2l.Accumulator(2)            # 损失总和, 样本数量

    for X, y in data_iter:                 # 每次取一个 batch 的特征 X 和标签 y
        out = net(X)                       # 前向传播：计算模型预测值
        y = y.reshape(out.shape)           # 确保标签 y 的形状与输出 out 一致
        l = loss(out, y)                   # 计算损失（reduction='none' 时不取平均，保留每个样本的损失）
        metric.add(l.sum(), l.numel())     # 累加：(batch总损失, batch样本数)
        # l.sum()  —— 该 batch 所有样本损失之和
        # l.numel()—— 该 batch 中的样本数量（numel = number of elements）

    return metric[0] / metric[1]           # 返回：总损失 / 总样本数 = 平均损失

# ============================================================================
# 第6步：定义训练函数
# ============================================================================
# 这是本节最核心的函数，包含了完整的训练流程
def train(train_features, test_features, train_labels, test_labels,
          num_epochs=400):
    """
    使用多项式特征训练线性回归模型，并绘制训练/测试损失曲线。

    参数:
        train_features: 训练集多项式特征，形状 (n_train, num_features)
        test_features:  测试集多项式特征，形状 (n_test, num_features)
        train_labels:   训练集标签，形状 (n_train,)
        test_labels:    测试集标签，形状 (n_test,)
        num_epochs:     训练周期数，默认 400

    训练流程：
        (1) 创建 MSE 损失函数
        (2) 构建单层线性网络（无偏置，因为多项式特征已含 x^0=1）
        (3) 创建 DataLoader 批量加载数据
        (4) 使用 SGD 优化器更新参数
        (5) 循环训练，每 20 轮记录一次训练/测试损失
        (6) 打印学到的权重，与真实权重对比
    """
    # --- 创建损失函数 ---
    # nn.MSELoss: 均方误差损失 = (1/n)*Σ(y_pred - y_true)^2
    # reduction='none': 不自动求平均，保留每个样本单独的损失值
    #   这样可以在 evaluate_loss 中手动累加求平均，更灵活
    loss = nn.MSELoss(reduction='none')

    # --- 获取输入特征维度 ---
    # train_features.shape 例如 (100, 4)，则 shape[-1] = 4（最后一维的大小）
    # 这是输入到线性层的特征数量（如 4 表示使用 x^0, x^1, x^2/2!, x^3/3! 四个特征）
    input_shape = train_features.shape[-1]

    # --- 构建网络 ---
    # nn.Linear(input_shape, 1, bias=False)
    #   - input_shape 个输入特征 → 1 个输出（回归值）
    #   - bias=False：不使用偏置参数，因为多项式特征的第 0 列 = x^0 = 1 已经充当了偏置
    #     实际上 w_0 * 1 就是偏置项。如果再加 bias，会导致冗余参数
    # nn.Sequential 是一个层容器，数据按顺序流经其中的各层
    # 这里只有一个 Linear 层，等价于线性回归：y = W·x （W 形状 1×input_shape）
    # 不设置偏置，因为我们已经在多项式中实现了它（x^0 = 1 那一列）
    net = nn.Sequential(nn.Linear(input_shape, 1, bias=False))

    # --- 创建数据迭代器 ---
    # batch_size: 每个小批量的大小，取 10 和训练样本数中较小的那个
    #   小批量随机梯度下降（Mini-batch SGD）是深度学习训练的标准方式
    batch_size = min(10, train_labels.shape[0])

    # d2l.load_array(data_arrays, batch_size, is_train=True)
    #   将 (features, labels) 包装成 PyTorch DataLoader
    #   is_train=True  → 数据会被随机打乱（shuffle），增加随机性，有助于泛化
    #   is_train=False → 数据不被打乱，按原始顺序评估
    # train_labels.reshape(-1, 1): 将一维标签 (100,) 变为二维 (100, 1)
    #   以匹配模型输出形状 (batch_size, 1)
    train_iter = d2l.load_array((train_features, train_labels.reshape(-1,1)),
                                batch_size)
    test_iter = d2l.load_array((test_features, test_labels.reshape(-1,1)),
                               batch_size, is_train=False)

    # --- 创建优化器 ---
    # torch.optim.SGD(params, lr=0.01)
    #   SGD = 随机梯度下降（Stochastic Gradient Descent）
    #   net.parameters() 返回模型中所有可学习参数的迭代器
    #   lr=0.01 是学习率（learning rate），控制每次参数更新的步长
    #     太大 → 无法收敛甚至发散；太小 → 收敛太慢
    trainer = torch.optim.SGD(net.parameters(), lr=0.01)

    # --- 创建绘图器 ---
    # d2l.Animator 封装了 matplotlib，用于实时绘制训练曲线
    #   xlabel='epoch':  x 轴标签为 "epoch"（训练周期数）
    #   ylabel='loss':   y 轴标签为 "loss"（损失值）
    #   yscale='log':    y 轴使用对数坐标（方便同时观察大值和小值）
    #   xlim=[1, num_epochs]: x 轴范围
    #   ylim=[1e-3, 1e2]:     y 轴范围（0.001 到 100）
    #   legend=['train', 'test']: 图例标签
    animator = d2l.Animator(xlabel='epoch', ylabel='loss', yscale='log',
                            xlim=[1, num_epochs], ylim=[1e-3, 1e2],
                            legend=['train', 'test'])

    # --- 训练循环 ---
    for epoch in range(num_epochs):
        # d2l.train_epoch_ch3(net, train_iter, loss, trainer)
        #   执行一个 epoch 的训练：
        #     (a) 遍历训练集每个 batch
        #     (b) 前向传播 → 计算损失 → 反向传播 → 参数更新
        #   注意：PyTorch 的梯度是累加的，train_epoch_ch3 内部会在每 batch 前
        #   调用 optimizer.zero_grad() 清零梯度
        d2l.train_epoch_ch3(net, train_iter, loss, trainer)

        # 每 20 个 epoch（以及第 1 个 epoch）记录一次损失
        if epoch == 0 or (epoch + 1) % 20 == 0:
            animator.add(epoch + 1, (evaluate_loss(net, train_iter, loss),
                                     evaluate_loss(net, test_iter, loss)))
            # evaluate_loss 在训练集和测试集上分别计算当前平均损失并绘制

    # --- 打印学到的权重 ---
    # net[0] 取 Sequential 中的第一个（也是唯一一个）层 = Linear 层
    # .weight 是 Linear 层的权重矩阵（形状 1×input_shape）
    # .data 直接访问底层张量数据（不经过 autograd 追踪机制）
    # .numpy() 将 PyTorch 张量转换为 NumPy 数组，便于打印
    print('weight:', net[0].weight.data.numpy())

# ============================================================================
# 第7步：三阶多项式函数拟合（正常拟合）— 与数据生成函数同阶
# ============================================================================
# 使用前 4 列多项式特征（x^0, x^1, x^2/2!, x^3/3!），恰好匹配数据生成函数。
# 预期结果：训练误差和测试误差都较低，且学到的权重接近真实值 [5, 1.2, -3.4, 5.6]。
#
# 切片解释：
#   poly_features[:n_train, :4]  → 训练集的前 4 个多项式特征，形状 (100, 4)
#   poly_features[n_train:, :4]  → 测试集的前 4 个多项式特征，形状 (100, 4)
#   labels[:n_train]             → 训练标签，形状 (100,)
#   labels[n_train:]             → 测试标签，形状 (100,)
# 从多项式特征中选择前4个维度，即 1, x, x^2/2!, x^3/3!
train(poly_features[:n_train, :4], poly_features[n_train:, :4],
      labels[:n_train], labels[n_train:])
# 输出解读：
#   weight: [[ 5.010476   1.2354498 -3.4229028  5.503297 ]]
#   接近真实值 [5, 1.2, -3.4, 5.6]，说明模型成功学到了数据中的模式
#   同时训练损失和测试损失都很低且接近，说明没有过拟合也没有欠拟合

# ============================================================================
# 第8步：线性函数拟合（欠拟合）— 模型太简单
# ============================================================================
# 只使用前 2 列特征（x^0=1 和 x^1），即线性模型 y = w0 + w1*x。
# 线性模型无法表达三阶多项式的曲线，因此无论怎么训练都无法很好地拟合数据。
# 这就是欠拟合（underfitting）：模型复杂度不足以捕捉数据中的模式。
#
# 欠拟合的特征：
#   - 训练误差居高不下（模型连训练数据都学不好）
#   - 训练误差和测试误差差距不大（泛化误差小，但两个误差都很高）
#   - 解决方法：增加模型复杂度（更多特征、更深网络、更多参数）
# 从多项式特征中选择前2个维度，即 1 和 x（线性模型）
train(poly_features[:n_train, :2], poly_features[n_train:, :2],
      labels[:n_train], labels[n_train:])
# 输出解读：
#   weight: [[3.4049764 3.9939284]]
#   只有一个斜率和一个截距，无法表达数据的非线性模式
#   训练损失在训练结束时仍然较高，说明模型"学不动"

# ============================================================================
# 第9步：高阶多项式函数拟合（过拟合）— 模型太复杂
# ============================================================================
# 使用全部 20 列多项式特征（0 到 19 阶），模型拥有 20 个参数。
# 对于只有 100 个训练样本的情况，20 个参数过多；模型会"记住"训练数据中的
# 噪声，而不是学习真正的模式。这就是过拟合（overfitting）。
#
# 注意这里 num_epochs=1500（比正常情况多了近 4 倍），
# 更长的训练时间让复杂模型有更多机会去拟合噪声。
#
# 过拟合的特征：
#   - 训练误差极低（模型几乎完美记住了训练数据）
#   - 测试误差远高于训练误差（泛化能力差）
#   - 训练误差和测试误差之间的差距很大
#   - 解决方法：正则化（L1/L2）、Dropout、早停、数据增强、简化模型
# 从多项式特征中选取所有维度（20 维特征，只有 100 个训练样本）
train(poly_features[:n_train, :], poly_features[n_train:, :],
      labels[:n_train], labels[n_train:], num_epochs=1500)
# 输出解读：
#   前 4 个权重仍接近真实值，但后面的 16 个权重（对应高阶项）偏离了 0
#   理论上真值中高阶系数为 0，但模型用这些自由度去拟合了训练数据的噪声
#   训练损失可以降到很低，但测试损失比三阶模型更高

# ============================================================================
# 补充知识点：多项式回归原理
# ============================================================================
"""
多项式回归本质上是"线性回归 + 特征工程"：

1. 原始特征 x → 通过多项式变换生成新特征 [1, x, x^2/2!, x^3/3!, ..., x^d/d!]
2. 用这些新特征做标准线性回归：y = w0*1 + w1*x + w2*x^2/2! + ... + wd*x^d/d!
3. 模型是"对参数线性"的（参数 w_i 以线性方式出现），
   但对原始输入 x 是非线性的（因为 x 的高次幂）

除以 i! 的数学意义：
  - 在 x=0 处的泰勒展开：f(x) = f(0) + f'(0)x + f''(0)x^2/2! + f'''(0)x^3/3! + ...
  - 如果我们要拟合的函数本身是光滑的，泰勒系数是有限范围的
  - 除以 i! 避免了 x^i 指数增长导致的数值爆炸
  - 等效于对特征做了 min-max 或标准化类似的缩放操作

不做缩放会怎样？
  - 当 |x|>1 且 i 很大时，x^i 的值会极大（如 2^19 ≈ 524288）
  - 损失函数曲面变得极陡峭，梯度巨大 → 梯度爆炸
  - SGD 无法正常收敛，因为学习率难以调整
"""

# ============================================================================
# 补充知识点：偏差-方差权衡（Bias-Variance Tradeoff）
# ============================================================================
"""
泛化误差可以分解为三部分：

    E[(y - f_hat(x))^2] = Bias^2 + Variance + σ^2

    其中：
      Bias^2  (偏差平方)  = 模型平均预测 与 真实值 之间差距的平方
                         → 高偏差 = 欠拟合（模型太简单，学不到真实模式）
      Variance (方差)    = 模型预测 随不同训练集 的波动程度
                         → 高方差 = 过拟合（模型太敏感，记住了噪声）
      σ^2     (不可约误差) = 数据本身的噪声方差，无法通过改进模型降低

    偏差-方差权衡：
      - 简单模型（如线性回归）：高偏差 + 低方差
      - 复杂模型（如深度神经网络）：低偏差 + 高方差
      - 最优模型在偏差和方差之间取得平衡

    本节实验的对应关系：
      - 线性拟合（2维）   → 高偏差（欠拟合）
      - 三阶拟合（4维）   → 偏差和方差平衡（正常拟合）
      - 高阶拟合（20维）  → 低偏差 + 高方差（过拟合）
"""

