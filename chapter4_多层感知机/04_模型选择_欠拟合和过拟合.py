"""
Q1: 这个多项式回归问题可以准确地解出吗？
A1: 可以。多项式回归本质上是线性回归（特征是非线性变换后的 x 的幂次）。
    线性回归有解析解（闭式解）：
        w* = (X^T X)^(-1) X^T y
    即最小二乘法的正规方程（Normal Equation）。
    当样本数 n 大于特征数 d 时，X^T X 通常可逆，可以直接求解。
    但当特征数很大时（如 20 维），矩阵求逆的计算复杂度为 O(d^3)，
    使用 SGD 等迭代方法更高效。

Q2: 绘制训练损失与多项式阶数的关系图，需要多少阶多项式才能将训练损失降到 0？
A2: 当多项式的阶数（即特征维度）≥ 训练样本数时，可以对训练数据完美插值。
    如果阶数 = 训练样本数 - 1，n 个点总存在唯一的 n-1 阶多项式通过所有点。
    但在本节中，由于 x 值可能重复或接近，完美拟合不一定总是达到 0 损失。
    将训练损失降为 0 本身没有意义——这表明严重过拟合。

Q3: 如果不对多项式特征 x^i 进行 1/i! 标准化，会发生什么？
A3: - 高阶特征的数值会极大（如 2^19 ≈ 524288）
    - 损失函数曲面严重畸变，不同参数的梯度尺度差异巨大
    - SGD 的学习率无法同时适应大小不同的梯度
    - 数值溢出风险：float32 最大约 3.4×10^38，高次幂可能超出此范围
    替代解决方案：
      (a) 对 x 做标准化（减均值、除以标准差），使 |x| 平均接近 0
      (b) 使用特征标准化（StandardScaler）
      (c) 使用双精度浮点数（float64），但内存和计算开销翻倍
      (d) 使用梯度裁剪（gradient clipping）防止梯度爆炸

Q4: 泛化误差可能为零吗？
A4: 理论上不可能（仅在一些极端情况下接近 0）。
    原因：
      (a) 数据本身包含不可约误差（噪声 σ^2），即使用最优模型也无法消除
      (b) 现实问题中独立同分布假设很少完美成立
      (c) 即使真实模型已知，有限样本的估计也会引入误差
    当测试误差"异常"接近 0 时，应该怀疑：
      - 数据泄露（训练集和测试集有重叠）
      - 任务过于简单（如 MNIST 的某些简化版本）
      - 评估指标选择不当
"""

