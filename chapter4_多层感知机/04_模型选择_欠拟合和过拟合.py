"""
模型选择的三种数据拆分策略：

┌─────────────────────────────────────────────────────────────────────┐
│ 1. 训练集 + 验证集 + 测试集（Hold-out Validation）                    │
│                                                                     │
│    原始数据 ──→ [训练集 60%] [验证集 20%] [测试集 20%]               │
│                                                                     │
│    流程：                                                            │
│      训练集  → 训练模型参数                                          │
│      验证集  → 选择超参数、选择模型架构、早停判断                      │
│      测试集  → 只用于最终评估，只用一次！                              │
│                                                                     │
│    注意：测试集绝对不能用于模型选择，否则会导致对测试集的过拟合，      │
│          失去评估泛化能力的意义                                       │
├─────────────────────────────────────────────────────────────────────┤
│ 2. K 折交叉验证（K-Fold Cross-Validation）                           │
│                                                                     │
│    将训练数据分成 K 个不重叠子集（fold）                              │
│    重复 K 次：用 K-1 个子集训练，1 个子集验证                        │
│    最终结果取 K 次的平均值                                            │
│                                                                     │
│    优点：当数据量少时，每个样本都被用于验证一次，评估更可靠            │
│    缺点：需要训练 K 次，计算开销大                                    │
│    常用 K 值：5 或 10                                                 │
├─────────────────────────────────────────────────────────────────────┤
│ 3. 留出法 + K折交叉验证 的对比                                        │
│                                                                     │
│    数据充足 → 使用简单留出法（训练/验证/测试三分）                     │
│    数据稀缺 → 使用 K 折交叉验证                                       │
│    极大数据 → 甚至不需要验证集（如 ImageNet 级别的百万级数据集）       │
└─────────────────────────────────────────────────────────────────────┘
"""

