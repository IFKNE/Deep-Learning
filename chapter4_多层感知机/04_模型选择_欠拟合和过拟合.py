"""
1. nn.MSELoss(reduction='none')
   - 均方误差：MSE = (1/n) * Σ(y_i - y_hat_i)^2
   - reduction='none' 返回每个样本单独的损失，形状和输入一致
   - reduction='mean'（默认）会自动求平均，返回标量
   - reduction='sum' 返回所有样本损失之和

2. nn.Linear(in_features, out_features, bias=True/False)
   - 做的运算：y = x @ W^T + b
   - W 的形状为 (out_features, in_features)
   - b 的形状为 (out_features,)（如果 bias=True）
   - bias=False 意味着不做 +b，只用 x @ W^T

3. torch.optim.SGD(net.parameters(), lr=0.01)
   - SGD 更新规则（最简单的优化器）：
        w = w - lr * grad
   - 其中 grad = ∂loss/∂w（损失对参数的梯度）
   - 更现代的优化器（Adam、RMSprop 等）会有自适应学习率

4. d2l.train_epoch_ch3(net, train_iter, loss, trainer)
   - 遍历 train_iter 中所有 batch
   - 对每个 batch：
        (a) optimizer.zero_grad()  —— 清零梯度（避免累加上一轮的梯度）
        (b) l = loss(net(X), y)     —— 前向传播 + 计算损失
        (c) l.sum().backward()      —— 反向传播，计算所有参数的梯度
        (d) trainer.step()          —— 使用梯度更新参数

5. d2l.load_array(data_arrays, batch_size, is_train=True)
   - 底层使用 PyTorch 的 DataLoader 和 TensorDataset
   - 等价于：
        dataset = TensorDataset(*data_arrays)
        dataloader = DataLoader(dataset, batch_size, shuffle=is_train)
"""

