"""
=============================================================================
暂退法(Dropout) —— 从零实现与简洁实现（完整带注释版）
=============================================================================

暂退法（Dropout）是一种常用的正则化技术，由 Srivastava 等人在 2014 年提出。
核心思想：在训练时，以概率 p 随机将一部分神经元的输出置为 0，
          同时将保留的神经元输出除以 (1-p)，以保持该层输出的期望值不变。
          测试时不丢弃任何神经元，直接使用完整的网络。

为什么有效：
  1. 破坏神经元之间的"共适应性"（co-adaptation），迫使每个神经元学习更有鲁棒性的特征。
  2. 相当于每次训练都在使用一个随机抽样的子网络，最终效果类似集成学习（ensemble）。
  3. 向网络注入无偏噪声，迫使函数对扰动平滑，提高泛化能力。

数学原理（期望不变性）：
  设原始激活值为 h，暂退概率为 p，则经过 Dropout 后：
    h' = 0        (概率 p)
    h' = h/(1-p)  (概率 1-p)
  期望 E[h'] = 0*p + (h/(1-p))*(1-p) = h
  即保留了激活值的期望，使得训练和测试时的数值尺度一致。

偏差-方差权衡：
  - 高偏差（线性模型）：只能表示少数函数，但在不同数据上结果稳定（低方差）。
  - 高方差（深度神经网络）：能表示极其复杂的函数，但容易在不同数据上产生差异大的结果。
  - Dropout 通过注入噪声降低模型的有效复杂度，从而降低方差、改善泛化。
"""
import torch
from torch import nn
from d2l import torch as d2l


# ============================================================================
# 第1步：从零实现 dropout_layer 函数
# ============================================================================
# dropout_layer 是暂退法的核心函数，实现了标准的 Dropout 操作：
#   1. 生成与输入同形状的随机掩码（mask），元素服从均匀分布 U[0,1]
#   2. 将概率小于 p 的元素对应位置置零（即"丢弃"）
#   3. 将保留的元素除以 (1-p)，保持输出期望不变
def dropout_layer(X, dropout):
    # ---------------------------------------------------------------
    # assert：Python 断言语句，用于调试时检查条件。如果条件为 False，程序会抛出 AssertionError。
    #         这里确保暂退概率在 [0, 1] 合法范围内。
    # ---------------------------------------------------------------
    assert 0 <= dropout <= 1
    # ---------------------------------------------------------------
    # 特殊情况1：dropout == 1，丢弃全部神经元
    # torch.zeros_like(X)：返回一个与 X 形状相同、元素全为 0 的张量
    #                      （注意 "like" 表示形状和数据类型都与 X 一致）
    # ---------------------------------------------------------------
    if dropout == 1:
        return torch.zeros_like(X)
    # ---------------------------------------------------------------
    # 特殊情况2：dropout == 0，保留全部神经元（不做任何操作）
    # ---------------------------------------------------------------
    if dropout == 0:
        return X
    # ---------------------------------------------------------------
    # 核心逻辑：
    #   torch.rand(X.shape)：生成与 X 同形状的张量，每个元素独立地从均匀分布 U[0,1] 中随机采样
    #   > dropout：逐元素比较，生成布尔型张量（True/False）
    #             True 表示该位置被保留（随机数 > dropout），False 表示该位置被丢弃
    #   .float()：将布尔值转为浮点数（True→1.0, False→0.0），得到掩码张量 mask
    #
    # 形状变化：输入 X 形状为任意形状 → mask 形状与 X 完全相同
    # ---------------------------------------------------------------
    mask = (torch.rand(X.shape) > dropout).float()
    # ---------------------------------------------------------------
    # 逐元素乘法（Hadamard 积）：
    #   mask * X：保留的神经元保持原值，丢弃的神经元变为 0
    #   / (1.0 - dropout)：将保留的神经元放大，以保持该层输出的期望值不变
    #
    # 为什么除以 (1-p)？
    #   如果不除以 (1-p)，该层输出的期望值会变为原来的 (1-p) 倍。
    #   训练和测试时的数值尺度不一致，会导致性能下降。
    #   除以 (1-p) 后，E[输出] = E[X]，保证了无偏性。
    #
    # 示例：若 dropout=0.5，则保留的神经元值会乘以 2 (=1/(1-0.5))
    # ---------------------------------------------------------------
    return mask * X / (1.0 - dropout)


# ============================================================================
# 第2步：测试 dropout_layer 函数
# ============================================================================
# 使用 torch.arange 创建 0~15 的整数序列，重塑为 2×8 矩阵，便于观察 dropout 效果
# torch.arange(16, dtype=torch.float32)：生成 tensor([0., 1., 2., ..., 15.])
# .reshape((2, 8))：将一维向量重塑为 2 行 8 列的矩阵
# 输入形状：torch.Size([2, 8])
X = torch.arange(16, dtype=torch.float32).reshape((2, 8))
print("原始输入 X (2×8):")
print(X)
# ---------------------------------------------------------------
# 测试 dropout=0.0：不丢弃任何神经元，输出应与输入完全一致
# ---------------------------------------------------------------
print("\ndropout=0.0 (不丢弃任何神经元):")
print(dropout_layer(X, 0.))
# ---------------------------------------------------------------
# 测试 dropout=0.5：以 50% 概率丢弃神经元
#   被保留的元素值会变为原来的 2 倍（除以 1-0.5=0.5）
#   被丢弃的元素值变为 0
#   每次运行结果不同，因为掩码是随机生成的
# ---------------------------------------------------------------
print("\ndropout=0.5 (丢弃约一半神经元，保留的值放大2倍):")
print(dropout_layer(X, 0.5))
# ---------------------------------------------------------------
# 测试 dropout=1.0：丢弃所有神经元，输出全零矩阵
# ---------------------------------------------------------------
print("\ndropout=1.0 (丢弃全部神经元):")
print(dropout_layer(X, 1.))


# ============================================================================
# 第3步：定义模型超参数
# ============================================================================
# Fashion-MNIST 数据集：28×28 灰度图 = 784 个像素输入
# 10 个类别（T恤、裤子、套头衫、连衣裙、外套、凉鞋、衬衫、运动鞋、包、短靴）
# 两个隐藏层，每层 256 个神经元 — 这是常见的配置，能在参数量和表达能力之间取得平衡
num_inputs, num_outputs, num_hiddens1, num_hiddens2 = 784, 10, 256, 256


# ============================================================================
# 第4步：从零实现带 Dropout 的多层感知机（自定义 Net 类）
# ============================================================================
# ---------------------------------------------------------------
# 两个隐藏层的暂退概率设置：
#   第一层暂退概率较低（0.2），保留 80% 神经元
#   第二层暂退概率较高（0.5），保留 50% 神经元
# 常见技巧：靠近输入层使用较低的暂退概率，因为输入特征需要更多信息传递；
#          越靠近输出层可以设置越高的暂退概率，增强正则化效果。
# ---------------------------------------------------------------
dropout1, dropout2 = 0.2, 0.5


class Net(nn.Module):
    """
    自定义神经网络类，继承自 nn.Module。

    Python 类继承说明：
      class Net(nn.Module) 表示 Net 继承 nn.Module 的所有属性和方法。
      必须重写 __init__() 和 forward() 两个方法。

    nn.Module 说明：
      PyTorch 中所有神经网络的基类。提供了参数管理、设备迁移、
      保存/加载模型等核心功能。任何自定义网络都必须继承它。
    """
    def __init__(self, num_inputs, num_outputs, num_hiddens1, num_hiddens2,
                 is_training=True):
        # -------------------------------------------------------
        # super().__init__()：调用父类（nn.Module）的构造函数
        # 必须首先执行，它会初始化 Module 内部的参数注册机制，
        # 否则后续定义的 nn.Linear 等层无法被正确追踪。
        # -------------------------------------------------------
        super(Net, self).__init__()
        self.num_inputs = num_inputs     # 输入特征数：784（28×28 像素）
        self.training = is_training      # 训练/测试模式标志
        # -------------------------------------------------------
        # nn.Linear(in_features, out_features)：全连接层（线性层）
        #   计算 y = x @ W^T + b
        #   @：Python 矩阵乘法运算符（等价于 torch.matmul）
        #   W 形状：(out_features, in_features)
        #   b 形状：(out_features,)
        #
        # 本网络结构（三层全连接）：
        #   输入层(784) → 隐藏层1(256) → 隐藏层2(256) → 输出层(10)
        # -------------------------------------------------------
        self.lin1 = nn.Linear(num_inputs, num_hiddens1)   # 784 → 256
        self.lin2 = nn.Linear(num_hiddens1, num_hiddens2)  # 256 → 256
        self.lin3 = nn.Linear(num_hiddens2, num_outputs)   # 256 → 10
        # -------------------------------------------------------
        # nn.ReLU()：ReLU 激活函数，f(x) = max(0, x)
        #   优点：计算简单、缓解梯度消失、产生稀疏激活
        #   注意：这里只创建一个 ReLU 实例，但可以在 forward 中多次复用
        #         （因为 ReLU 没有可学习参数，复用不会影响训练）
        # -------------------------------------------------------
        self.relu = nn.ReLU()

    def forward(self, X):
        """
        前向传播方法。
        当调用 net(X) 时，实际上执行的就是 forward()。
        不需要手动调用 forward() — PyTorch 的 nn.Module 会自动处理。

        Dropout 仅在训练时使用：self.training 标志控制。
        测试时所有神经元都参与计算，不进行丢弃。
        """
        # -------------------------------------------------------
        # 第1层：线性变换 → ReLU 激活 → Dropout（训练时）
        #
        # X.reshape((-1, self.num_inputs))：
        #   将输入展平为 (batch_size, 784)
        #   -1 表示"自动计算该维度大小"，PyTorch 会根据总元素数和另一个维度推断
        #   例如输入形状 (256, 1, 28, 28) → reshape 后变为 (256, 784)
        #   输入形状 (256, 784) → reshape 后形状不变
        #
        # self.lin1(X)：全连接，输出形状 (batch_size, 256)
        # self.relu(...)：ReLU 激活，形状不变 (batch_size, 256)
        # -------------------------------------------------------
        H1 = self.relu(self.lin1(X.reshape((-1, self.num_inputs))))
        # 训练模式下对第1个隐藏层的输出应用 Dropout
        if self.training == True:
            H1 = dropout_layer(H1, dropout1)  # 以 20% 概率丢弃，形状不变
        # -------------------------------------------------------
        # 第2层：线性变换 → ReLU 激活 → Dropout（训练时）
        # H1 形状：(batch_size, 256)
        # self.lin2(H1) 输出形状：(batch_size, 256)
        # -------------------------------------------------------
        H2 = self.relu(self.lin2(H1))
        if self.training == True:
            H2 = dropout_layer(H2, dropout2)  # 以 50% 概率丢弃，形状不变
        # -------------------------------------------------------
        # 第3层（输出层）：仅线性变换，不使用激活函数和 Dropout
        # 输出形状：(batch_size, 10) — 10 个类别的原始得分（logits）
        # 注意：交叉熵损失函数 nn.CrossEntropyLoss 内部会执行 softmax，
        #       因此这里不需要手动添加 softmax 层
        # -------------------------------------------------------
        out = self.lin3(H2)
        return out


# ---------------------------------------------------------------
# 实例化网络
# ---------------------------------------------------------------
net = Net(num_inputs, num_outputs, num_hiddens1, num_hiddens2)


# ============================================================================
# 第5步：从零实现的训练与测试
# ============================================================================
# 训练超参数
num_epochs, lr, batch_size = 10, 0.5, 256  # epoch数、学习率、批量大小
# ---------------------------------------------------------------
# nn.CrossEntropyLoss：交叉熵损失函数
#   内部集成了 LogSoftmax + NLLLoss，因此输入不需要预先做 softmax
#   reduction='none'：不对损失求平均，返回每个样本的独立损失值
#                     （d2l.train_ch3 内部会自行处理损失的聚合）
# ---------------------------------------------------------------
loss = nn.CrossEntropyLoss(reduction='none')
# ---------------------------------------------------------------
# d2l.load_data_fashion_mnist(batch_size)：
#   加载 Fashion-MNIST 数据集，返回训练集和测试集的数据迭代器
#   每个 batch 的形状：(batch_size, 1, 28, 28) — 单通道灰度图
# ---------------------------------------------------------------
train_iter, test_iter = d2l.load_data_fashion_mnist(batch_size)
# ---------------------------------------------------------------
# torch.optim.SGD：随机梯度下降优化器
#   net.parameters()：自动收集 Net 中所有可学习的参数（W 和 b）
#   lr=lr：学习率
# ---------------------------------------------------------------
trainer = torch.optim.SGD(net.parameters(), lr=lr)
# ---------------------------------------------------------------
# d2l.train_ch3：d2l 库封装的训练函数，内部执行：
#   1. 遍历每个 epoch
#   2. 对每个 batch 进行前向传播、计算损失、反向传播、参数更新
#   3. 每个 epoch 结束后在测试集上评估准确率
#   4. 自动绘制训练/测试损失和准确率曲线
# ---------------------------------------------------------------
d2l.train_ch3(net, train_iter, test_iter, loss, num_epochs, trainer)


# ============================================================================
# 第6步：简洁实现 —— 使用 PyTorch 内置的 nn.Dropout
# ============================================================================
# ---------------------------------------------------------------
# nn.Sequential：顺序容器，按添加顺序依次执行各层
#   等价于我们前面自定义 Net 类的 forward 方法，但更简洁
#
# 各层说明（从输入到输出）：
# ---------------------------------------------------------------
net = nn.Sequential(
    # -----------------------------------------------------------
    # nn.Flatten()：将输入展平
    #   输入形状：(batch_size, 1, 28, 28)
    #   输出形状：(batch_size, 784)
    #   保留第0维（batch_size），将剩余维度展平为一维
    # -----------------------------------------------------------
    nn.Flatten(),
    # -----------------------------------------------------------
    # 第1隐藏层：全连接 784→256
    # -----------------------------------------------------------
    nn.Linear(784, 256),
    nn.ReLU(),                     # ReLU 激活
    # -----------------------------------------------------------
    # nn.Dropout(p)：PyTorch 内置的 Dropout 层
    #   - 训练时：以概率 p 将输入元素随机置零，保留的元素乘以 1/(1-p)
    #   - 测试时：自动关闭（透传数据，不丢弃）
    #   - 与自定义 dropout_layer 的区别：
    #     nn.Dropout 通过 self.training 属性自动判断训练/测试模式，
    #     无需手动使用 if 语句控制，代码更简洁。
    # -----------------------------------------------------------
    nn.Dropout(dropout1),          # p=0.2，丢弃 20%
    # -----------------------------------------------------------
    # 第2隐藏层：全连接 256→256
    # -----------------------------------------------------------
    nn.Linear(256, 256),
    nn.ReLU(),
    nn.Dropout(dropout2),          # p=0.5，丢弃 50%
    # -----------------------------------------------------------
    # 输出层：全连接 256→10（10个类别的得分）
    # -----------------------------------------------------------
    nn.Linear(256, 10)
)


# ---------------------------------------------------------------
# 权重初始化函数
#   参数 m：网络中的某一层（由 net.apply 自动传入）
# ---------------------------------------------------------------
def init_weights(m):
    # -----------------------------------------------------------
    # type(m) == nn.Linear：判断当前层是否为全连接层
    #   只对线性层初始化权重，忽略 ReLU、Dropout、Flatten 等层
    # -----------------------------------------------------------
    if type(m) == nn.Linear:
        # -------------------------------------------------------
        # nn.init.normal_：从正态分布 N(mean, std) 中采样，填充权重张量
        #   注意函数名以 _ 结尾：在 PyTorch 中，_ 后缀表示原地（in-place）操作，
        #   即直接修改传入的张量，而不是返回新张量。
        #   这里从 N(0, 0.01^2) 正态分布初始化权重，
        #   使用较小的标准差可以避免梯度爆炸，有利于训练初期稳定。
        # -------------------------------------------------------
        nn.init.normal_(m.weight, std=0.01)
        # 偏置默认初始化为 0（nn.Linear 的默认行为），无需显式初始化


# ---------------------------------------------------------------
# net.apply(fn)：递归地将函数 fn 应用到网络的每一个子模块上
#   遍历顺序：深度优先，先处理子模块再处理父模块
#   这里将 init_weights 应用到每一层，自动跳过不需要初始化的层
#   分号 ";" 用于抑制 Jupyter 中不必要的输出（此处无实际影响）
# ---------------------------------------------------------------
net.apply(init_weights);
# 分号在 Jupyter 中抑制返回值的打印输出


# ============================================================================
# 第7步：简洁实现的训练与测试
# ============================================================================
trainer = torch.optim.SGD(net.parameters(), lr=lr)          # SGD 优化器
d2l.train_ch3(net, train_iter, test_iter, loss, num_epochs, trainer)  # 训练


