# 知识点5：常见问题与练习解答思路
# ============================================================================
"""
Q1：交换第一层和第二层的暂退概率会怎样？
A1：靠近输入层的暂退概率通常应较小，因为输入层承载了原始数据信息，
    过高的丢弃率会导致信息过早丢失，阻碍后续层的学习。
    如果交换（第一层 0.5、第二层 0.2），模型性能通常会下降。

Q2：为什么测试时不使用 Dropout？
A2：测试时需要模型的确定性输出，以进行可靠的预测。
    使用 Dropout 会引入随机性，导致同样输入产生不同输出。
    训练时已经通过除以 (1-p) 使期望保持一致，测试时直接使用完整网络即可。
    例外：某些研究中用测试时的 Dropout（Monte Carlo Dropout）估计不确定性。

Q3：Dropout 应用到权重矩阵而非激活值会怎样？
A3：这就是 DropConnect 的思路。DropConnect 随机丢弃权重矩阵中的连接，
    而非神经元的输出。DropConnect 可以看作是 Dropout 的推广。
    但实践中，Dropout 更常用，因为实现更简单、计算更高效。

Q4：如何发明新的噪声注入技术？
A4：可尝试的方向——
    - 高斯 Dropout：乘以 N(1, σ^2) 噪声而非置零
    - DropBlock：按空间块丢弃（对卷积层更有效）
    - 自适应 Dropout：根据激活值大小动态调整丢弃概率
    - ShakeDrop：随机缩放而非二值丢弃
"""


