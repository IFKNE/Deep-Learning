"""
一、核心概念
  - 暂退法（Dropout）：在训练时随机丢弃神经元，测试时使用完整网络。
  - 共适应性（co-adaptation）：神经元之间过度依赖彼此的输出，
    Dropout 通过随机丢弃强制每个神经元独立学习有用特征。
  - 无偏注入噪声：通过除以 (1-p) 保持激活值的期望不变。
  - 偏差-方差权衡：Dropout 降低模型有效复杂度，减少方差，改善泛化。

二、PyTorch 关键 API
  - nn.Dropout(p)：内置 Dropout 层，训练时自动丢弃，测试时自动关闭
  - nn.Linear(in, out)：全连接层，计算 y = x @ W^T + b
  - nn.ReLU()：ReLU 激活函数，f(x) = max(0, x)
  - nn.Flatten()：展平输入（保留 batch 维度）
  - nn.init.normal_(tensor, std)：从正态分布初始化张量（原地操作）
  - nn.Module：所有神经网络的基类，提供参数管理等核心功能
  - net.apply(fn)：递归地将函数应用到网络的每个子模块

三、Python/PyTorch 语法要点
  - assert：断言，用于运行时条件检查
  - class Net(nn.Module)：类继承，继承父类的所有属性和方法
  - super().__init__()：调用父类构造函数，初始化参数注册机制
  - forward()：定义前向传播逻辑，通过 net(x) 自动调用
  - _ 后缀方法（如 nn.init.normal_）：原地操作，直接修改张量而非返回副本
  - @ 运算符：矩阵乘法（Python 3.5+），等价于 torch.matmul
  - reshape((-1, dim))：-1 自动推断维度大小

四、Dropout 实践要点
  - 输入层附近使用较低的丢弃概率（如 0.1~0.3）
  - 隐藏层可使用较高的丢弃概率（如 0.5）
  - 输出层通常不使用 Dropout
  - 训练时启用、测试时关闭
  - 可与权重衰减（L2 正则化）同时使用，效果通常更好
  - 使用 Dropout 后往往需要更多训练轮数才能收敛

五、拓展阅读
  - 原始论文：Srivastava et al., "Dropout: A Simple Way to Prevent Neural
    Networks from Overfitting", JMLR 2014
  - Bishop, "Training with Noise is Equivalent to Tikhonov Regularization", 1995
  - 变体：DropConnect, Spatial Dropout, DropBlock, Gaussian Dropout, AlphaDropout
"""
