# 3.1 医学诊断 —— 协变量偏移的惨痛教训
# ----------------------------------------------------------------------------
# 案例：一家初创公司想开发血液检测算法来检测某种影响老年男性的疾病。
#
# 他们做了什么：
#   1. 从病人身上采集血液样本（患病组）
#   2. 从大学校园学生那里采集血液作为健康对照（健康组）
#   3. 用这些数据训练分类器，精度近乎完美
#
# 问题出在哪里？
#   健康组（学生）和患病组（老年男性）在以下方面存在巨大差异：
#     - 年龄
#     - 激素水平
#     - 体力活动
#     - 饮食习惯
#     - 饮酒习惯
#     - 许多与疾病无关的其他因素
#   分类器很可能学会区分"年轻人 vs 老年人"而非"健康 vs 患病"！
#
# 结果：
#   - 这是极端的协变量偏移
#   - 难以通过常规方法纠正
#   - 公司浪费了一大笔资金
#
# 教训：训练数据与实际部署场景的数据分布必须一致！

