# 第4节：分布偏移的纠正方法
# ============================================================================

# ----------------------------------------------------------------------------
# 4.1 经验风险 vs 真实风险
# ----------------------------------------------------------------------------
# 在模型训练中，我们在训练数据上最小化损失函数：
#
#   经验风险 (Empirical Risk)：
#     minimize_f  (1/n) * Σ_{i=1}^{n} l(f(x_i), y_i)
#
#   其中 l 是损失函数，度量预测 f(x_i) 与真实标签 y_i 的差距。
#
#   真实风险 (True Risk)：
#     E_{p(x,y)} [l(f(x), y)]
#     = ∫∫ l(f(x), y) * p(x,y) dxdy
#
#   即从真实分布 p(x,y) 中抽取的所有数据的总体损失期望。
#
# 核心矛盾：
#   - 我们真正想最小化的是真实风险
#   - 但我们只能获取训练样本，只能计算经验风险
#   - 经验风险最小化（ERM）是对真实风险最小化的近似
#   - 当训练分布 != 测试分布时，这个近似可能很差！
#
# 【类比】
#   经验风险 = 用你认识的人来估计全国平均身高（有偏采样可能不准）
#   真实风险 = 真正的全国平均身高（不可直接获得）

# ----------------------------------------------------------------------------
# 4.2 协变量偏移纠正 (Covariate Shift Correction)
# ----------------------------------------------------------------------------
# 问题设定：
#   - 带标签的训练数据 (x_i, y_i)，x_i 来自源分布 q(x)
#   - 测试时 x 来自目标分布 p(x)
#   - 假设条件分布不变：p(y|x) = q(y|x)
#
# 核心思想：重要性加权 (Importance Weighting)
#   通过对每个训练样本加权，调整从 q 到 p 的偏差：
#
#     ∫∫ l(f(x),y) * p(y|x) * p(x) dxdy
#   = ∫∫ l(f(x),y) * q(y|x) * q(x) * [p(x)/q(x)] dxdy
#
#   权重 β_i = p(x_i) / q(x_i)
#
#   加权经验风险最小化：
#     minimize_f  (1/n) * Σ_{i=1}^{n} β_i * l(f(x_i), y_i)
#
# 问题：我们不知道真实的 p(x) 和 q(x)，需要估计比率 p(x)/q(x)。
#
# 解决方案：对数几率回归法 (Logistic Regression Approach)
#   1. 构建一个二元分类器 h(x) 来区分来自 p 和来自 q 的样本
#   2. 标签定义：
#      - z=1：样本来自目标分布 p
#      - z=-1：样本来自源分布 q
#   3. 使用对数几率回归：
#      P(z=1|x) = p(x) / (p(x) + q(x)) = 1 / (1 + exp(-h(x)))
#   4. 由此可得：
#      β_i = P(z=1|x_i) / P(z=-1|x_i) = exp(h(x_i))
#
# 【完整算法流程】（协变量偏移纠正）：
#   Step 1: 生成二元分类训练集
#     { (x_1, -1), ..., (x_n, -1),   <- 源分布样本（标签-1）
#       (u_1, 1), ..., (u_m, 1) }    <- 目标分布样本（标签1）
#
#   Step 2: 训练对数几率回归分类器，得到函数 h
#
#   Step 3: 计算权重
#     β_i = min(exp(h(x_i)), c)    # c 是常数上限，防止权重过大
#
#   Step 4: 使用权重 β_i 对训练数据进行加权经验风险最小化
#
# 【关键假设】
#   目标分布中的每个点在训练时出现的概率必须非零。
#   如果存在 p(x) > 0 但 q(x) = 0 的点，权重会是无穷大（无法处理）。
#
# 【直观理解】
#   - 如果某个训练样本在测试分布中更常见 (p(x) > q(x))，权重 > 1，放大其影响
#   - 如果某个训练样本在测试分布中更罕见 (p(x) < q(x))，权重 < 1，减小其影响
#   - 如果两个分布一样 (p(x) = q(x))，权重 = 1，等同于常规训练

# ----------------------------------------------------------------------------
# 4.3 标签偏移纠正 (Label Shift Correction)
# ----------------------------------------------------------------------------
# 问题设定：
#   - k 个类别的分类任务
#   - 标签分布变化：q(y) != p(y)
#   - 类别条件分布不变：q(x|y) = p(x|y)
#
# 重要性权重：
#   β_i = p(y_i) / q(y_i)    （基于标签的权重，而非基于输入）
#
# 标签偏移的优势：
#   - 标签是低维的（通常就是几个类别）
#   - 不需要处理高维输入分布
#   - 可以在源分布上获得权重的一致估计
#
# 估计目标标签分布的方法：
#
# Step 1: 用训练数据训练一个分类器
#
# Step 2: 在验证集上计算混淆矩阵 C（k×k矩阵）
#   c_{ij} = 真实标签为 j，模型预测为 i 的样本比例
#
# Step 3: 对测试集进行预测，计算平均模型输出 μ(ŷ) ∈ R^k
#   μ(ŷ_i) = 模型预测测试集中第 i 类的总预测分数（所有样本取平均）
#
# Step 4: 利用标签偏移假设，求解目标标签分布 p(y)：
#   C * p(y) = μ(ŷ)
#
#   因为对每个类别 i：
#     Σ_{j=1}^{k} c_{ij} * p(y_j) = μ(ŷ_i)
#
#   （即：模型预测第 i 类的概率 = Σ 真实为 j 类且被预测为 i 类的概率 × j 类的真实比例）
#
# Step 5: 如果 C 可逆（分类器足够准确），解得：
#   p(y) = C^{-1} * μ(ŷ)
#
# Step 6: 计算权重 β_i = p(y_i) / q(y_i)，
#   其中 q(y) 直接从训练数据统计得到
#
# Step 7: 使用加权经验风险最小化训练最终模型
#
# 【重要假设（最强的一条）】
#   目标数据只包含训练时见过的类别（没有新类）。
#   如果出现新类别，整个方法失效。

# ----------------------------------------------------------------------------
# 4.4 概念偏移纠正 (Concept Shift Correction)
# ----------------------------------------------------------------------------
# 概念偏移（P(y|x) 发生变化）很难用原则性方法解决。
#
# 极端的例子：
#   问题从"区分猫狗"突然变为"区分白色和黑色动物"——
#   除了从头收集新数据重新训练，别无他法。
#
# 实际情况：概念变化通常是缓慢的
#   案例1 - 计算广告：
#     新产品推出，旧产品逐渐不受欢迎。广告分布和点击率缓慢变化。
#   案例2 - 交通摄像头：
#     镜头因环境磨损逐渐退化，图像质量缓慢下降。
#   案例3 - 新闻内容：
#     新闻话题和写作风格逐渐演变。
#
# 应对策略：增量更新
#   使用新数据更新现有网络权重（微调/在线学习），而不是从头训练。
#   这和使用训练好的网络权重进行初始化的思路类似。

# ============================================================================
# 第5节：学习问题的分类法
# ============================================================================
# 了解分布变化后，我们从更广的视角对机器学习问题进行形式化分类。

# ----------------------------------------------------------------------------
# 5.1 批量学习 (Batch Learning)
# ----------------------------------------------------------------------------
# 定义：一次性使用全部训练数据训练模型 f(x)，然后部署，不再更新。
#
# 流程：
#   1. 收集训练集 {(x_1, y_1), ..., (x_n, y_n)}
#   2. 训练模型 f(x)
#   3. 部署，对新数据评分
#
# 示例：智能猫门的猫检测器
#   - 用大量猫狗图片训练
#   - 安装在客户家中
#   - 基本永远不更新
#
# 适用场景：分布稳定的问题
# 风险：分布变化时模型会逐渐过时

# ----------------------------------------------------------------------------
# 5.2 在线学习 (Online Learning)
# ----------------------------------------------------------------------------
# 定义：逐个处理数据点，每观测到一个新样本就更新模型。
#
# 循环流程：
#   模型 f_t -> 观测输入 x_t -> 做出预测 f_t(x_t)
#   -> 观测真实标签 y_t -> 计算损失 l(y_t, f_t(x_t))
#   -> 更新模型 f_{t+1} -> 继续下一轮...
#
# 示例：股票价格预测
#   - 每天早上预测今天的股价
#   - 据此进行交易
#   - 收盘后评估预测是否盈利
#   - 用新的信息更新模型
#
# 特点：模型持续进化，能适应分布变化。

# ----------------------------------------------------------------------------
# 5.3 老虎机 (Bandits)
# ----------------------------------------------------------------------------
# 定义：在线学习的特例——只有有限数量的"手臂"（动作）可以选择。
#
# 与一般在线学习的区别：
#   - 深度网络：连续参数化的函数 f（无限多的可能输出）
#   - 老虎机：只有有限的动作集合（如 K 个选项中选择一个）
#
# 优势：由于问题更简单，可以获得更强的理论保证（如遗憾界）。
#
# 示例：A/B测试、广告投放选择、临床实验中的治疗方案分配。

# ----------------------------------------------------------------------------
# 5.4 控制 (Control)
# ----------------------------------------------------------------------------
# 定义：环境会记忆我们过去的行动，并根据历史做出反应。
#
# 示例1：咖啡锅炉控制器
#   当前温度取决于之前是否加热过锅炉。
#   解决方案：PID（比例-积分-微分）控制器。
#
# 示例2：新闻网站的推荐
#   用户的行为取决于她之前看到的内容。
#   （大多数新闻她只读一次——推荐已读内容无效）
#
# 特点：
#   - 环境有状态（记忆）
#   - 行为影响未来的观测
#   - 需要考虑时间依赖性
#
# 现代应用：
#   PID变体被用于自动调整深度学习超参数，
#   以改善解构/重建质量、生成文本多样性和生成图像质量。

# ----------------------------------------------------------------------------
# 5.5 强化学习 (Reinforcement Learning)
# ----------------------------------------------------------------------------
# 定义：智能体通过与环境交互，学习最大化累积奖励的策略。
#
# 经典应用：
#   - 国际象棋（AlphaZero）
#   - 围棋（AlphaGo）
#   - 西洋双陆棋
#   - 星际争霸
#   - 自动驾驶汽车控制
#
# 与前几种范式的关键区别：
#   - 奖励信号可能是延迟的（不是每个动作后立即得到反馈）
#   - 需要平衡探索（尝试新动作）和利用（使用已知的好动作）
#   - 环境状态随智能体的动作而变化

# ----------------------------------------------------------------------------
# 5.6 考虑到环境 —— 算法选择的决定性因素
# ----------------------------------------------------------------------------
# 不同学习范式间的关键区别：
#   在静态环境中有效的策略，在环境能够改变时可能完全失效。
#
# 示例：套利机会
#   交易者发现的套利机会，一旦开始利用它，机会就消失了。
#   （模型的行为改变了环境）
#
# 环境变化速度决定算法类型：
#   - 缓慢变化 -> 强制模型估计也缓慢改变
#   - 瞬间但罕见的变化 -> 算法需要检测和处理突变
#   - 持续剧烈变化 -> 可能需要持续在线学习
#
# 实践建议：
#   数据科学家必须理解问题如何随时间变化，
#   这是选择正确算法范式的关键。

# ============================================================================
# 第6节：机器学习中的公平、责任和透明度
# ============================================================================
# 从"优化预测模型"到"提供自动化决策工具"的跃迁，
# 不仅带来技术挑战，还带来伦理问题。
#
# 技术系统通过其决策影响每个人的生活，我们必须谨慎。

# ----------------------------------------------------------------------------
# 6.1 医疗诊断系统中的公平性
# ----------------------------------------------------------------------------
# 当我们部署医疗诊断系统时，需要知道：
#   - 它适用于哪些人群？
#   - 哪些人群可能无效？
#   - 对某个亚群体的忽视可能导致劣质护理水平。
#
# 精度不再是唯一的衡量标准。
# 当我们把预测转化为行动时，需要考虑：
#   - 不同类型错误的代价不同
#     （如：将图像错误分类为某个类别可能被视为种族歧视，
#       而错误分类为另一个类别可能是无害的）
#   - 需要根据社会价值调整决策阈值

# ----------------------------------------------------------------------------
# 6.2 失控反馈循环 (Runaway Feedback Loop)
# ----------------------------------------------------------------------------
# 案例：预测性警务系统
#   系统将巡逻人员分配到预测犯罪率高的地区。
#
# 循环过程：
#   1. 犯罪率高的社区得到更多巡逻
#   2. 因此在这些社区发现更多犯罪行为 -> 这些数据进入训练集
#   3. 面对更多的"积极因素"，模型预测这些社区还会有更多犯罪
#   4. 下一次迭代，模型更加倾向针对同一地区
#   5. 这导致更多巡逻 -> 更多发现 -> 更强的偏见...
#
# 这就是"失控反馈循环"：
#   模型的预测与训练数据之间存在自我强化的耦合机制，
#   导致偏见被不断放大。
#
# 根本问题：预测系统本身影响了被预测的现象。

# ----------------------------------------------------------------------------
# 6.3 更广泛的伦理考量
# ----------------------------------------------------------------------------
# 1. 我们是否在解决正确的问题？
#    - 预测算法在信息传播中起着巨大的中介作用
#    - 个人看到的新闻应该仅由他们喜欢的Facebook页面决定吗？
#
# 2. 算法偏见的来源：
#    - 历史数据中的偏见
#    - 采样偏差
#    - 特征选择偏差
#    - 标签定义偏差
#
# 3. 透明度要求：
#    - 受算法决策影响的人有权了解决策依据
#    - "黑箱"模型在这方面面临挑战
#
# 这些不是纯技术问题，而是需要跨学科合作（伦理学、法律、社会学）的系统性挑战。

# ============================================================================
# 第7节：小结（官方总结）
# ============================================================================
# 1. 分布偏移：
#    训练集和测试集不来自同一个分布，是机器学习部署中的常见问题。
#
# 2. 经验风险 vs 真实风险：
#    - 真实风险：从真实分布抽取的所有数据的总体损失期望（通常无法获得）
#    - 经验风险：训练数据的平均损失（用于近似真实风险）
#    - 实践中我们做经验风险最小化（ERM）
#
# 3. 偏移检测与纠正：
#    在相应的假设条件下，协变量偏移和标签偏移可以被检测和纠正。
#    不考虑偏移可能导致严重的部署问题。
#
# 4. 环境反馈：
#    环境可能"记住"自动操作并以令人惊讶的方式响应。
#    构建模型时必须考虑这种可能性，持续监控实时系统。
#
# 5. 思维开放：
#    对模型和环境以意想不到的方式纠缠在一起的可能性持开放态度。

