# ============================================================================
# 第1节：为什么要关注环境和分布偏移？
# ============================================================================
# 前面我们学习了许多机器学习应用，将模型拟合到各种数据集上。
# 但我们很少思考两个根本问题：
#   1. 数据最初从哪里来？
#   2. 我们计划最终如何处理模型的输出？
#
# 许多失败的机器学习部署都可以追溯到对这些基本问题的忽视。
# 常见的失败模式：
#   - 模型在测试集上精度很高，但部署后因数据分布改变而灾难性失败。
#   - 更隐蔽的是：模型本身的部署成为了扰乱数据分布的催化剂。
#
# 【典型案例：贷款违约预测】
#   假设训练了一个贷款违约风险模型，它发现"鞋子类型"与违约风险相关：
#     - 穿牛津鞋的申请人 -> 会偿还贷款
#     - 穿运动鞋的申请人 -> 会违约
#   模型开始据此做出放贷决策。
#   后果：申请人很快发现规律，所有人都会穿牛津鞋来申请贷款，
#   但信用度并没有真正提高——模型学到的"特征"失效了。
#
# 【核心教训】
#   通过将基于模型的决策引入环境，我们可能恰恰破坏了模型本身。
#   这就是"反馈循环"问题的雏形。
#
# 解决思路的层次：
#   1. 简单方案：要求"正确"的数据（确保训练和部署分布一致）
#   2. 技术困难方案：实施强化学习系统
#   3. 哲学/伦理方案：跳出统计预测，解决算法伦理问题

# ============================================================================
# 第2节：分布偏移的三种类型
# ============================================================================
# 在经典情景中：
#   - 训练数据从分布 p_S(x, y) 采样
#   - 测试数据从分布 p_T(x, y) 采样（含未标记样本）
#
# 【重要前提】
#   如果没有任何关于 p_S 和 p_T 之间关系的假设，学习分类器是不可能的。
#
# 【反例：为什么没有假设就不行？】
#   考虑一个猫狗二元分类问题：
#   假设输入分布完全不变：p_S(x) = p_T(x)
#   但标签全部翻转：p_S(y|x) = 1 - p_T(y|x)
#   即：过去的"猫"现在叫"狗"，过去的"狗"现在叫"猫"。
#   由于输入 x 的分布没变，我们无法判断分布是否发生了偏移！
#
# 幸运的是，在一些限制性假设下，我们可以检测甚至纠正分布偏移。

# ----------------------------------------------------------------------------
# 2.1 协变量偏移 (Covariate Shift)
# ----------------------------------------------------------------------------
# 定义：输入分布 p(x) 可能随时间改变，但标签函数（条件分布 P(y|x)）不变。
#
# 核心假设：
#   - p_S(x) != p_T(x)   （输入/特征分布变了）
#   - p_S(y|x) = p_T(y|x) （给定输入，输出的条件分布不变）
#
# 命名由来："协变量"即特征（covariate），偏移由特征分布的变化引起。
# 因果关系视角：当我们认为 x 导致 y 时，协变量偏移是自然的假设。
#
# 【示例：猫狗分类器的协变量偏移】
#   训练集：真实照片中的猫和狗
#   测试集：卡通图片中的猫和狗
#   -> 输入图像的特征分布完全不同（真实 vs 卡通）
#   -> 但"猫还是猫，狗还是狗"（条件分布不变）
#   -> 如果在照片上训练，直接用于卡通，效果会很差

# ----------------------------------------------------------------------------
# 2.2 标签偏移 (Label Shift)
# ----------------------------------------------------------------------------
# 定义：标签边缘概率 P(y) 可以改变，但类别条件分布 P(x|y) 不变。
#
# 核心假设：
#   - p_S(y) != p_T(y)          （标签的边缘分布变了）
#   - p_S(x|y) = p_T(x|y)       （给定标签，生成输入的条件分布不变）
#
# 因果关系视角：当我们认为 y 导致 x 时，标签偏移是合理的假设。
#
# 【示例：疾病诊断中的标签偏移】
#   场景：根据症状预测疾病
#   - 训练时某种疾病很常见（p(y) 较高）
#   - 部署时该疾病发病率下降（p(y) 降低）
#   - 但疾病仍会引起相同症状（p(x|y) 不变）
#   -> 这是标签偏移——因为疾病(y)导致症状(x)
#
# 【重要说明】
#   标签偏移和协变量偏移可以同时成立。
#   当标签确定时（如 y 严格决定 x 的分布），协变量偏移假设也满足。
#   但基于标签偏移的方法往往更有利：
#     - 标签通常是低维的（如类别标签）
#     - 输入通常是高维的（如图像像素）
#     -> 处理标签分布比处理输入分布更容易

# ----------------------------------------------------------------------------
# 2.3 概念偏移 (Concept Shift)
# ----------------------------------------------------------------------------
# 定义：标签的定义本身发生了变化——即 P(y|x) 发生变化。
# 这是最棘手的一种偏移，因为连"什么是什么"都变了。
#
# 【示例1：软饮名称的地理偏移】
#   在美国不同地区，"碳酸饮料"的称呼不同：
#     - 某些地区叫 "pop"
#     - 某些地区叫 "soda"
#     - 某些地区叫 "coke"（甚至用于非可口可乐的饮料）
#   概念偏移图显示了这种区域性的语义漂移。
#
# 【示例2：精神疾病诊断标准的变化】
#   DSM（精神疾病诊断手册）的版本更新会改变疾病的定义。
#
# 【示例3：工作头衔的演变】
#   "程序员" -> "软件工程师" -> "开发者" -> ... 头衔的含义随时代变化。
#
# 【应对策略】
#   概念偏移很难用原则性方法解决——极端情况下只能从头收集数据。
#   但通常概念变化是缓慢的，可以利用时间/空间上的渐变性。

