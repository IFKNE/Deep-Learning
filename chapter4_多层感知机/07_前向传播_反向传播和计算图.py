# 补充知识点3：手动推导一个简单例子
# ============================================================================
#
# 我们用一个极简的网络来手动验证上述反向传播公式。
#
# 【网络结构】
#   输入 x = [x1, x2]^T，形状 (2,)
#   隐藏层 1 个单元（无激活函数以简化），W^(1) = [w1, w2]，形状 (1, 2)
#   z = W^(1) · x = w1*x1 + w2*x2
#   输出 1 个单元，W^(2) = [w3]，形状 (1, 1)
#   o = W^(2) · z = w3 * z
#   损失 L = (1/2) * (o - y)^2（均方误差，无正则化）
#
# 【前向传播】
#   z  = w1*x1 + w2*x2
#   o  = w3 * z
#   L  = (1/2) * (o - y)^2
#
# 【反向传播（手动推导）】
#
#   (1) ∂L/∂o = o - y
#
#   (2) ∂L/∂w3 = (∂L/∂o) · (∂o/∂w3) = (o - y) · z
#
#   (3) ∂L/∂z = (∂L/∂o) · (∂o/∂z) = (o - y) · w3
#
#   (4) ∂L/∂w1 = (∂L/∂z) · (∂z/∂w1) = (o - y) · w3 · x1
#       ∂L/∂w2 = (∂L/∂z) · (∂z/∂w2) = (o - y) · w3 · x2
#
# 【数值验证】
#   假设 x1=1, x2=2, w1=0.5, w2=0.3, w3=0.8, y=1.0
#   则 z = 0.5*1 + 0.3*2 = 1.1
#      o = 0.8 * 1.1 = 0.88
#      L = 0.5 * (0.88 - 1.0)^2 = 0.5 * (-0.12)^2 = 0.0072
#
#   梯度计算：
#     ∂L/∂o    = 0.88 - 1.0 = -0.12
#     ∂L/∂w3   = -0.12 * 1.1 = -0.132
#     ∂L/∂z    = -0.12 * 0.8 = -0.096
#     ∂L/∂w1   = -0.096 * 1 = -0.096
#     ∂L/∂w2   = -0.096 * 2 = -0.192
#
#   参数更新（学习率 η=0.1）：
#     w1_new = 0.5 - 0.1 * (-0.096) = 0.5096
#     w2_new = 0.3 - 0.1 * (-0.192) = 0.3192
#     w3_new = 0.8 - 0.1 * (-0.132) = 0.8132
#
#   可以手工演算验证，加深理解。


