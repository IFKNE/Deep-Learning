# 补充知识点4：含偏置项的网络推广
# ============================================================================
#
# 上面的推导省略了偏置项以简化公式。下面给出含偏置项的情况。
#
# 【含偏置项的前向传播】
#
#   z = W^(1) · x + b^(1)          b^(1) ∈ R^h 是隐藏层偏置
#   h = φ(z)
#   o = W^(2) · h + b^(2)          b^(2) ∈ R^q 是输出层偏置
#
# 【含偏置项的反向传播】
#
#   ∂J/∂b^(2)  = ∂J/∂o            （因为 ∂o/∂b^(2) = I）
#   ∂J/∂b^(1)  = ∂J/∂z            （因为 ∂z/∂b^(1) = I，穿过 φ 后）
#
#   偏置项通常不包含在 L2 正则化中（只对权重做正则化）。
#
# 【对应的计算图变化】
#   在 z 和 o 节点处各自增加一个加法操作，b^(1) 和 b^(2) 作为额外的叶节点。


# ============================================================================
# 补充知识点5：二阶导数与计算图
# ============================================================================
#
# 【问题】如果我们要计算二阶导数，计算图会发生什么？
#
# 【答案】
#   1. 一阶导数的计算图也需要被保留，因为二阶导数是一阶导数的导数。
#   2. 二阶导数在计算图上再构建一层计算图（"梯度的梯度"）。
#   3. 内存占用大幅增加：需要同时存储前向传播的中间值、
#      一阶梯度的计算图、以及各节点的二阶梯度。
#   4. 计算开销大幅增加：二阶偏导数的数量是 O(n^2)（n 是参数数量），
#      对百万参数的网络，Hessian 矩阵有 10^12 个元素，不可行。
#
# 【实际应用中的解决方案】
#   - 使用 Hessian-vector 乘积（HVP）而非完整 Hessian，只需 O(n) 开销
#   - 使用近似方法（如 KFAC、Shampoo 等二阶优化器）
#   - 通常深度学习训练只用一阶梯度（SGD、Adam 等）就足够了


# ============================================================================
# 补充知识点6：计算图的 GPU 分布式并行
# ============================================================================
#
# 【问题】当计算图太大，单个 GPU 显存放不下时怎么办？
#
# 【方案1：模型并行（Model Parallelism）】
#   将模型的不同层放到不同的 GPU 上。
#   例如：GPU0 负责第 1-3 层，GPU1 负责第 4-6 层。
#   优点：可以训练超大模型（如 GPT-4 有数千亿参数）。
#   缺点：GPU 之间需要传输中间激活值，通信开销大；
#         GPU 利用率不均匀（后面的 GPU 要等前面的算完）。
#
# 【方案2：数据并行（Data Parallelism）】
#   每个 GPU 持有模型的完整副本，但处理不同的数据子集。
#   优点：实现简单，通信只在梯度同步时发生。
#   缺点：每个 GPU 必须能容纳完整模型。
#
# 【方案3：混合并行（Hybrid Parallelism）】
#   结合模型并行和数据并行，用于最大规模的训练。
#   例如：NVIDIA Megatron-LM 使用张量并行 + 流水线并行 + 数据并行。
#
# 【方案4：梯度检查点（Gradient Checkpointing）】
#   用计算换内存：不保存所有中间变量，只保存部分"检查点"。
#   反向传播时从最近的检查点重新计算中间值。
#   优点：大幅减少内存占用。
#   缺点：增加了计算时间（约 20-30% 的额外前向计算）。


