# 练习解答提示
# ============================================================================
#
# 1. 标量函数 f(X) 对 n×m 矩阵 X 的梯度维数是多少？
#    答：梯度 ∂f/∂X 的形状与 X 相同，即 n×m。
#       因为标量对矩阵的梯度仍是一个同形矩阵（按元素求偏导）。
#
# 2. 向隐藏层添加偏置项：
#    (a) 计算图：在 z 节点增加一个加法操作和偏置变量 b^(1)
#    (b) 前向传播：z = W^(1)x + b^(1)；反向传播：∂J/∂b^(1) = ∂J/∂z
#        （注意：偏置项通常不加入正则化）
#
# 3. 内存占用分析：
#    训练时除了参数外，还需存储同形的梯度、优化器状态、
#    以及批量大小倍的中间激活值。推理时只需参数和当前样本的激活值。
#
# 4. 二阶导数：
#    计算图需要保留更多信息，Hessian 矩阵的元素数是参数数量的平方，
#    对大规模网络不可行。实际中使用 Hessian-vector 乘积或近似方法。
#
# 5. 多 GPU 划分：
#    优点：可训练超大规模模型
#    缺点：通信开销、实现复杂度增加、GPU 利用率可能不均衡


# ============================================================================
# 总结
# ============================================================================
#
# 【核心概念回顾】
#
# 1. 前向传播（Forward Propagation）：
#    - 按输入→输出的顺序计算每层结果
#    - 存储中间变量（z, h, o）供反向传播复用
#    - 计算目标函数 J = L + s
#
# 2. 计算图（Computational Graph）：
#    - 有向无环图（DAG），节点=变量或操作，边=数据流
#    - 是自动微分的基础数据结构
#    - PyTorch 动态构建计算图（Define-by-Run）
#
# 3. 反向传播（Backward Propagation）：
#    - 按输出→输入的逆序计算梯度
#    - 核心工具：链式法则（Chain Rule）
#    - 梯度 = 外层梯度 × 内层梯度（从外到内逐层乘积）
#
# 4. 链式法则（Chain Rule）：
#    - ∂Z/∂X = prod(∂Z/∂Y, ∂Y/∂X)
#    - prod 自动处理矩阵乘法、转置、Hadamard 积等
#    - 是反向传播的数学基础
#
# 5. 训练 vs 推理：
#    - 训练：前向 + 反向，需要存储中间值和梯度，内存占用大
#    - 推理：仅前向，不存中间值和梯度，内存占用小
#    - 训练内存 ≈ 推理内存 × (3~5)
#
# 6. 自动微分（Autograd）：
#    - 深度学习框架自动计算梯度，无需手工推导
#    - 反向模式（Reverse Mode）适合神经网络（多输入→单输出）
#    - .backward() 一次调用即可获得所有参数梯度
#
# 【梯度计算的核心模式】
#
#   对于权重矩阵 W，梯度的通用形式是：
#
#     ∂J/∂W = (从上层传来的梯度) ⊗ (本层的输入)^T + λ·W
#              \________________/   \_________/    \__/
#               外层梯度 × 内层梯度              正则化梯度
#
#   这解释了为什么在 PyTorch 中我们只需要调用 .backward() ——
#   框架自动遍历计算图并应用这个模式。
