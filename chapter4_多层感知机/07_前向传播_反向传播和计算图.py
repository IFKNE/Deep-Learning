# ============================================================================
# 第1节：前向传播 (Forward Propagation)
# ============================================================================
#
# 【定义】
# 前向传播 (forward propagation / forward pass) 指的是：
#   按顺序（从输入层到输出层）计算和存储神经网络中每层的结果。
#
# 【为什么叫"前向"？】
# 数据流动的方向是"向前"的：输入 → 隐藏层 → 输出层 → 损失函数。
# 就像流水线一样，每个步骤的输出成为下一步骤的输入。
#
# 【研究场景】
# 我们以带权重衰减（L2正则化）的单隐藏层多层感知机为例，
# 逐步推导前向传播中的所有数学公式。
#
# --------------------------------------------------------------------------
# 1.1 符号约定
# --------------------------------------------------------------------------
#
# 设输入样本为 x ∈ R^d（d 维向量，d 个输入特征）
# 隐藏层没有偏置项（简化推导），隐藏单元数为 h
# 输出层也没有偏置项，输出类别数为 q
#
# W^(1) ∈ R^{h × d}  : 隐藏层的权重矩阵（h 行 d 列）
#                       每一行是一个隐藏单元对应的 d 个权重
#                       每一列对应一个输入特征连接到 h 个隐藏单元的权重
#
# W^(2) ∈ R^{q × h}  : 输出层的权重矩阵（q 行 h 列）
#                       每一行是一个输出类别对应的 h 个权重
#
# φ(·)              : 激活函数（如 ReLU、sigmoid、tanh），按元素作用
# l(·, ·)           : 损失函数（如交叉熵损失、均方误差）
# y                  : 样本的真实标签
# λ                  : L2 正则化的超参数（控制正则化的强度）
#
# --------------------------------------------------------------------------
# 1.2 前向传播的逐步推导
# --------------------------------------------------------------------------
#
# 第1步：计算隐藏层的"加权和"（未激活的中间变量）
#
#   z = W^(1) · x
#
#   z ∈ R^h，形状为 (h,)
#   = W^(1) 的每一行与向量 x 做内积
#   = 每个隐藏单元接收到所有输入特征的加权和
#
#   例如：如果 x 是一个 28×28=784 维的图像向量，隐藏层有 256 个单元，
#   那么 W^(1) 的形状是 (256, 784)，z 的形状是 (256,)。
#
# --------------------------------------------------------------------------
#
# 第2步：通过激活函数得到隐藏激活向量
#
#   h = φ(z)
#
#   h ∈ R^h，形状为 (h,)
#   激活函数 φ 按元素（element-wise）作用在 z 的每个分量上。
#
#   激活函数的作用：引入非线性变换。
#   如果没有激活函数，无论堆叠多少层，整个网络等价于一个线性变换，
#   无法拟合复杂的非线性函数。
#
#   常见激活函数示例：
#     ReLU:    φ(z_i) = max(0, z_i)
#     sigmoid: φ(z_i) = 1 / (1 + exp(-z_i))
#     tanh:    φ(z_i) = (exp(z_i) - exp(-z_i)) / (exp(z_i) + exp(-z_i))
#
#   h 是一个"中间变量"——它既不是输入也不是最终输出，而是前向传播中
#   计算出的中间结果，在反向传播时需要被复用。
#
# --------------------------------------------------------------------------
#
# 第3步：计算输出层的"logits"（未归一化的输出）
#
#   o = W^(2) · h
#
#   o ∈ R^q，形状为 (q,)
#   = W^(2) 的每一行与向量 h 做内积
#   = 每个输出类别得到一个分数（原始分数，未经 softmax 归一化）
#
#   在分类任务中，o 通常再经过 softmax 转换为概率分布。
#
# --------------------------------------------------------------------------
#
# 第4步：计算单个样本的损失
#
#   L = l(o, y)
#
#   其中 l 是损失函数，y 是真实标签。
#   L 是一个标量（scalar），表示该样本的预测与真实标签之间的差异。
#
#   常见损失函数：
#     均方误差（回归）:   L = (1/2) * ||o - y||^2
#     交叉熵损失（分类）: L = -log(softmax(o)[y])
#
# --------------------------------------------------------------------------
#
# 第5步：计算 L2 正则化项
#
#   s = (λ/2) * ( ||W^(1)||_F^2 + ||W^(2)||_F^2 )
#
#   其中 ||·||_F 表示 Frobenius 范数（下面详解）。
#
#   L2 正则化的作用：
#     - 通过惩罚过大的权重值来防止过拟合
#     - 鼓励模型学习更"平滑"的决策边界
#     - λ 越大，正则化强度越高，权重倾向于更小
#
# --------------------------------------------------------------------------
#
# 第6步：计算目标函数（正则化后的总损失）
#
#   J = L + s
#
#   J 称为目标函数（objective function），是我们真正要最小化的量。
#   它 = 数据损失 + 正则化损失。
#   在后续的反向传播中，我们对 J 求梯度，而不是单独对 L 求梯度。
#
# --------------------------------------------------------------------------
# 1.3 关键概念：Frobenius 范数
# --------------------------------------------------------------------------
#
# 【定义】
# Frobenius 范数（简称 F 范数）是将矩阵"展平"为向量后应用的 L2 范数。
#
# 【数学定义】
# 对矩阵 A ∈ R^{m × n}：
#
#   ||A||_F = sqrt( Σ_{i=1}^{m} Σ_{j=1}^{n} |a_{ij}|^2 )
#
#   即：矩阵中所有元素的平方和再开方。
#
# 【直观理解】
#   把矩阵的所有元素想象成一个"大向量"，然后计算这个向量的欧几里得长度。
#
# 【举例】
#   矩阵 A = [[1, 2],
#            [3, 4]]
#   ||A||_F = sqrt(1^2 + 2^2 + 3^2 + 4^2) = sqrt(30) ≈ 5.48
#
# 【为什么使用 F 范数作为正则化？】
#   - F 范数是 L2 范数在矩阵上的自然推广
#   - 平方后对每个元素求导很方便：∂(||W||_F^2)/∂W = 2W
#   - 与向量 L2 正则化的数学性质保持一致
#
# --------------------------------------------------------------------------
# 1.4 前向传播总结
# --------------------------------------------------------------------------
#
# 完整的前向传播数据流：
#
#   x ──[乘以 W^(1)]──→ z ──[激活函数 φ]──→ h ──[乘以 W^(2)]──→ o ──[损失 l]──→ L
#                                                                                  │
#                                        W^(1), W^(2) ──[F范数平方]──→ s           │
#                                                                                  │
#                                                                  J = L + s ←─────┘
#
# 其中存储的中间变量有：z, h, o（在反向传播中复用）


# ============================================================================
# 第2节：前向传播计算图 (Computational Graph)
# ============================================================================
#
# 【什么是计算图？】
# 计算图是一种有向图，用于可视化计算过程中操作符和变量之间的依赖关系。
#
# 【节点类型】
#   - 方形节点（□）：表示变量（数据），如 x, z, h, o, L, s, J
#   - 圆形节点（○）：表示操作符（运算），如矩阵乘法、激活函数、损失函数
#
# 【边的方向】
#   数据流的箭头方向主要向右和向上：
#     - 输入在左下角
#     - 输出在右上角
#     - 从输入到输出，从底层到高层
#
# 【计算图的结构（单隐藏层 MLP）】
#
#        x ──────→ [matmul] ──→ z ──→ [φ] ──→ h ──→ [matmul] ──→ o ──→ [l] ──→ L
#                     ↑                                  ↑                          │
#                   W^(1)                             W^(2)                         │
#                     │                                  │                          │
#                     └────→ [F范数²] ←──────────────────┘                          │
#                                │                                                  │
#                                └────→ s ──→ [+] ←─────────────────────────────────┘
#                                               │
#                                               ↓
#                                               J
#
# 【计算图的用途】
#   1. 可视化：帮助理解数据如何从输入流向输出
#   2. 自动微分：深度学习框架内部用计算图来追踪所有操作，自动计算梯度
#   3. 依赖分析：清楚知道哪些变量依赖于哪些变量，反向传播时按反方向遍历
#   4. 内存优化：确定哪些中间值需要在反向传播中复用，哪些可以释放
#
# 【静态图 vs 动态图】
#   - 静态图（TensorFlow 1.x）：先定义整个计算图，再运行
#   - 动态图（PyTorch）：每次前向传播时动态构建计算图，更灵活、更 Pythonic
#   - PyTorch 的 autograd 在每次 .backward() 调用后默认释放计算图，除非指定 retain_graph=True
#
# 【计算图中的"中间变量"】
#   在本例中，z, h, o 都是中间变量。
#   中间变量是指：既不是原始输入（x），也不是最终目标（J），
#   而是计算过程中产生的、连接输入和输出的"桥梁"变量。
#
#   在反向传播中，这些中间变量的值被复用来计算梯度，因此必须被存储。
#   这就是为什么训练比推理需要更多内存的原因之一。


# ============================================================================
# 第3节：反向传播 (Backward Propagation)
# ============================================================================
#
# 【定义】
# 反向传播（backward propagation / backpropagation）指的是：
#   按相反的顺序（从输出层到输入层）遍历网络，
#   利用微积分中的链式法则（chain rule）计算每个参数的梯度。
#
# 【为什么叫"反向"？】
#   前向传播：输入 → 输出（"向前"流动）
#   反向传播：输出 → 输入（"向后"流动），
#   梯度的计算方向与数据流动方向相反。
#
# 【核心思想】
#   计算 ∂J/∂W^(1) 和 ∂J/∂W^(2)（目标函数对每个参数的偏导数），
#   用于后续的参数更新（如梯度下降：W := W - η * ∂J/∂W）。
#
# --------------------------------------------------------------------------
# 3.1 链式法则 (Chain Rule) —— 反向传播的数学基石
# --------------------------------------------------------------------------
#
# 【经典链式法则（标量版本）】
#   若有函数 Y = f(X) 和 Z = g(Y)，其中 X, Y, Z 都是标量，则：
#
#     dZ/dX = (dZ/dY) · (dY/dX)
#
#   即：Z 对 X 的导数 = Z 对中间变量 Y 的导数 × Y 对 X 的导数。
#
# 【推广到张量版本】
#   当 X, Y, Z 是任意形状的张量时，链式法则的形式为：
#
#     ∂Z/∂X = prod(∂Z/∂Y, ∂Y/∂X)
#
#   其中 prod 是一个"广义乘法"运算符，它根据张量的维度自动执行：
#     - 对向量：矩阵-向量乘法或向量-向量外积
#     - 对矩阵：矩阵-矩阵乘法
#     - 对高维张量：相应的张量缩并操作
#     - 必要时自动做转置（transpose）和维度重排
#
# 【直观理解链式法则】
#   链式法则就像一个"连锁反应"：
#     X 变化一点点 → Y 变化一定的量（由 ∂Y/∂X 决定）
#                  → Z 变化一定的量（由 ∂Z/∂Y 决定）
#     总的影响 = ∂Z/∂Y × ∂Y/∂X
#
#   在神经网络中，每一层都是一个函数变换，链式法则让我们能"穿透"多层
#   变换来追溯输出对输入（或参数）的敏感程度。
#
# --------------------------------------------------------------------------
# 3.2 反向传播的逐步推导
# --------------------------------------------------------------------------
#
# ============================================================
# 第0步：目标函数对损失项和正则项的梯度
# ============================================================
#
# 目标函数 J = L + s，由于 J 对 L 和 s 都是直接相加关系：
#
#   ∂J/∂L = 1
#   ∂J/∂s = 1
#
# 【含义】L 增加 1 单位，J 也增加 1 单位；s 同理。
#         这是最简单的链式法则起点。
#
# ============================================================
# 第1步：目标函数对输出层 o 的梯度
# ============================================================
#
#   ∂J/∂o = prod(∂J/∂L, ∂L/∂o)
#         = 1 × ∂L/∂o
#         = ∂L/∂o ∈ R^q
#
# 【含义】目标函数对输出 o 的梯度，实际上就是损失函数对输出 o 的梯度。
#         因为正则项 s 不依赖于 o，所以 ∂s/∂o = 0。
#
# 【举例：均方误差】
#   若 L = (1/2)||o - y||^2，则 ∂L/∂o = o - y
#   （预测值减去真实值，直观地表示"预测偏差"）
#
# 【举例：交叉熵 + softmax】
#   若 L = -log(softmax(o)[y])，则 ∂L/∂o = softmax(o) - onehot(y)
#   （softmax 概率减去真实标签的 one-hot 向量）
#
# ============================================================
# 第2步：正则化项对两个权重矩阵的梯度
# ============================================================
#
#   s = (λ/2) * (||W^(1)||_F^2 + ||W^(2)||_F^2)
#
#   ∂s/∂W^(1) = λ · W^(1)
#   ∂s/∂W^(2) = λ · W^(2)
#
# 【推导】
#   ||W||_F^2 = Σ_{i,j} w_{ij}^2
#   ∂(||W||_F^2)/∂w_{ij} = 2w_{ij}
#   因此 ∂( (λ/2) · ||W||_F^2 )/∂W = (λ/2) · 2W = λW
#
# 【含义】正则化对权重的梯度正比于权重本身。
#         这意味着权重的更新方向上总有一个"衰减"分量，
#         推动权重变小（weight decay 名称的由来）。
#
# ============================================================
# 第3步：目标函数对输出层权重 W^(2) 的梯度
# ============================================================
#
#   ∂J/∂W^(2) = prod(∂J/∂o, ∂o/∂W^(2)) + prod(∂J/∂s, ∂s/∂W^(2))
#             = ∂J/∂o · h^T + λ · W^(2)
#
# 【推导详解】
#   前一项：o = W^(2) · h，所以 ∂o/∂W^(2) = h^T（外积形式的导数）
#           用链式法则：∂J/∂W^(2)（来自 o 的贡献）= (∂J/∂o) · h^T
#           其中 ∂J/∂o 是 (q,) 的向量，h^T 是 (1, h) 的行向量，
#           外积结果为 (q, h) 的矩阵，与 W^(2) 的形状一致。
#
#   后一项：∂J/∂s = 1，∂s/∂W^(2) = λW^(2)
#
#   总梯度 = 来自数据损失的梯度 + 来自正则化的梯度
#
# 【形状检查】
#   ∂J/∂o     : (q,)
#   h          : (h,)
#   ∂J/∂o ⊗ h : (q, h)  ← 与 W^(2) 的形状完全一致
#   λW^(2)     : (q, h)  ← 正则化梯度，形状也一致
#
# ============================================================
# 第4步：目标函数对隐藏层输出 h 的梯度（反向传播到隐藏层）
# ============================================================
#
#   ∂J/∂h = prod(∂J/∂o, ∂o/∂h)
#         = W^(2)^T · (∂J/∂o)
#
# 【推导】
#   o = W^(2) · h，所以 ∂o/∂h = W^(2)
#   应用链式法则：∂J/∂h = (∂J/∂o)^T · W^(2) = W^(2)^T · ∂J/∂o
#
#   （注意：这里出现了转置。∂J/∂o 是 (q,) 列向量，W^(2) 是 (q, h)，
#    需要通过 W^(2)^T (h, q) 来得到 (h,) 的向量。）
#
# 【含义】输出层的误差通过 W^(2)^T "反向传播"到隐藏层。
#         可以理解为：每个输出类别的误差按连接权重分配回各个隐藏单元。
#
# ============================================================
# 第5步：目标函数对隐藏层加权和 z 的梯度（穿越激活函数）
# ============================================================
#
#   ∂J/∂z = prod(∂J/∂h, ∂h/∂z)
#         = ∂J/∂h ⊙ φ'(z)
#
# 【推导】
#   h = φ(z)，激活函数按元素作用，所以 ∂h/∂z 是一个对角矩阵形式。
#   使用按元素乘法 ⊙（Hadamard 积 / element-wise product）：
#
#   ∂J/∂z_i = ∂J/∂h_i · φ'(z_i)   对每个元素 i
#
#   即向量 ∂J/∂h 与导数向量 φ'(z) 逐元素相乘。
#
# 【重要】φ'(z) 是激活函数的导数值，具体取决于使用的激活函数：
#
#   ReLU:     φ'(z_i) = 1  if z_i > 0 else 0
#   sigmoid:  φ'(z_i) = φ(z_i) · (1 - φ(z_i))
#   tanh:     φ'(z_i) = 1 - φ(z_i)^2
#
#   例如，ReLU 的导数：正区间梯度为 1，负区间梯度为 0。
#   这就是所谓的"梯度消失"风险的来源——如果 z_i < 0，梯度被截断为 0。
#
# ============================================================
# 第6步：目标函数对输入层权重 W^(1) 的梯度（最内层参数的梯度）
# ============================================================
#
#   ∂J/∂W^(1) = prod(∂J/∂z, ∂z/∂W^(1)) + prod(∂J/∂s, ∂s/∂W^(1))
#             = ∂J/∂z · x^T + λ · W^(1)
#
# 【推导】
#   前一项：z = W^(1) · x，所以 ∂z/∂W^(1) = x^T
#           用链式法则：∂J/∂W^(1)（来自数据损失的贡献）= (∂J/∂z) · x^T
#           其中 ∂J/∂z 是 (h,) 的向量，x^T 是 (1, d) 的行向量，
#           外积结果为 (h, d) 的矩阵，与 W^(1) 的形状一致。
#
#   后一项：∂J/∂s = 1，∂s/∂W^(1) = λW^(1)
#
#   总梯度 = 来自数据损失的梯度 + 来自正则化的梯度
#
# 【形状检查】
#   ∂J/∂z     : (h,)
#   x          : (d,)
#   ∂J/∂z ⊗ x : (h, d)  ← 与 W^(1) 的形状完全一致
#   λW^(1)     : (h, d)  ← 正则化梯度，形状也一致
#
# --------------------------------------------------------------------------
# 3.3 反向传播全流程总结
# --------------------------------------------------------------------------
#
# 按"从后往前"的顺序，梯度计算流程如下：
#
#   输出端 ←───────────────────────────────────────────→ 输入端
#
#   (1) ∂J/∂L = 1,  ∂J/∂s = 1                    [目标函数对组成部分]
#   (2) ∂J/∂o = ∂L/∂o                             [穿过损失函数]
#   (3) ∂J/∂W^(2) = (∂J/∂o)·h^T + λW^(2)          [输出层权重梯度 ✓]
#   (4) ∂J/∂h = W^(2)^T · (∂J/∂o)                 [传到隐藏层]
#   (5) ∂J/∂z = (∂J/∂h) ⊙ φ'(z)                  [穿过激活函数]
#   (6) ∂J/∂W^(1) = (∂J/∂z)·x^T + λW^(1)          [隐藏层权重梯度 ✓]
#
# 【关键观察】
#   - 步骤(2)依赖 o（前向传播的输出）
#   - 步骤(3)依赖 h（前向传播的中间变量）
#   - 步骤(4)依赖 W^(2)（当前参数值）
#   - 步骤(5)依赖 z 和 h（前向传播的中间变量）
#   - 步骤(6)依赖 x（输入数据）
#
#   由此可见，反向传播严重依赖前向传播中保存的中间值！


# ============================================================================
# 第4节：训练神经网络的流程
# ============================================================================
#
# 【前向传播与反向传播的交替】
# 在训练神经网络时，前向传播和反向传播是相互依赖、交替进行的：
#
#   ┌─────────────────────────────────────────────────────────┐
#   │                                                         │
#   │  初始化参数 W^(1), W^(2)                                 │
#   │       │                                                 │
#   │       ↓                                                 │
#   │  ┌──────────┐    中间变量(z,h,o)     ┌──────────┐       │
#   │  │ 前向传播  │ ───────────────────→  │ 反向传播  │       │
#   │  │ 计算 J   │                       │ 计算梯度  │       │
#   │  └──────────┘                       └──────────┘       │
#   │       ↑                                   │             │
#   │       │         参数更新（梯度下降）        │             │
#   │       └───────────────────────────────────┘             │
#   │                                                         │
#   │  重复此循环，直到收敛                                    │
#   └─────────────────────────────────────────────────────────┘
#
# 【为什么训练比推理需要更多内存？】
#
#   原因1：反向传播需要复用前向传播中的中间变量。
#         例如，计算 ∂J/∂W^(2) 需要用到 h，
#         计算 ∂J/∂z 需要用到 h 和 z。
#         因此，前向传播时不能释放这些中间值，必须保留到反向传播完成。
#
#   原因2：中间值的大小与批量大小成正比。
#         批量大小为 B 时：
#           z: (B, h)  而非 (h,)
#           h: (B, h)  而非 (h,)
#           o: (B, q)  而非 (q,)
#         每个中间变量的存储量都乘以了批量大小 B。
#
#   原因3：内存占用与网络深度和宽度的关系。
#         更深的网络 → 更多的中间层 → 更多的中间变量 → 更多内存。
#         更大的批量 → 每个中间变量都变大 → 更多内存。
#         因此，使用大 batch_size 训练深层网络时容易 OOM (Out Of Memory)。
#
#   原因4：推理（预测）时只需要前向传播，不需要存储中间变量，
#         也不需要存储梯度，因此内存需求远小于训练。
#
# 【具体的内存占用分析（本节模型）】
#
#   训练时：
#     - 存储参数：W^(1) (h×d), W^(2) (q×h)
#     - 存储梯度：∂J/∂W^(1) (h×d), ∂J/∂W^(2) (q×h) — 与参数同形
#     - 存储中间值（批量大小为 B）：
#       z: B×h, h: B×h, o: B×q
#       ∂J/∂z: B×h, ∂J/∂h: B×h, ∂J/∂o: B×q
#     - 优化器状态（如 Adam 需要存储动量和二阶矩）：与参数同形 × 2
#
#   推理时：
#     - 存储参数：W^(1) (h×d), W^(2) (q×h)
#     - 中间值：只需当前样本的 z, h, o，用完即丢
#     - 不需要存储梯度和优化器状态
#
#   粗略估计，训练时的内存占用大约是推理时的 3-5 倍。
#
# 【一个完整的训练步骤（伪代码）】
#
#   for epoch in range(num_epochs):
#       for X_batch, y_batch in data_loader:
#           # ---- 前向传播 ----
#           z = W1 @ X_batch.T               # 计算隐藏层加权和
#           h = activation(z)                 # 应用激活函数
#           o = W2 @ h                        # 计算输出
#           L = loss(o, y_batch)              # 计算损失
#           s = (lambda/2) * (||W1||_F^2 + ||W2||_F^2)  # 正则化项
#           J = L + s                         # 目标函数
#
#           # ---- 反向传播（自动微分）----
#           J.backward()                      # 自动计算所有参数的梯度
#
#           # ---- 参数更新 ----
#           with torch.no_grad():
#               W1 -= lr * W1.grad            # 梯度下降更新
#               W2 -= lr * W2.grad
#               W1.grad.zero_()               # 清零梯度（避免累加）
#               W2.grad.zero_()


# ============================================================================
# 第5节：反向传播的完整矩阵形式汇总
# ============================================================================
#
# 将上述推导整理为紧凑的矩阵形式，方便查阅和记忆。
#
# 【前向传播】
#
#   输入 → 隐藏层：        z = W^(1) · x                         (h,)
#   激活：                 h = φ(z)                              (h,)
#   隐藏层 → 输出：        o = W^(2) · h                         (q,)
#   损失：                 L = l(o, y)                          (scalar)
#   正则化：               s = (λ/2)(||W^(1)||_F^2 + ||W^(2)||_F^2)  (scalar)
#   目标：                 J = L + s                            (scalar)
#
# 【反向传播】
#
#   输出层梯度：           ∂J/∂o = ∂L/∂o                        (q,)
#   W^(2) 梯度：           ∂J/∂W^(2) = (∂J/∂o)·h^T + λ·W^(2)    (q, h)
#   隐藏层梯度：           ∂J/∂h = W^(2)^T · (∂J/∂o)             (h,)
#   激活函数梯度：         ∂J/∂z = (∂J/∂h) ⊙ φ'(z)              (h,)
#   W^(1) 梯度：           ∂J/∂W^(1) = (∂J/∂z)·x^T + λ·W^(1)    (h, d)
#
# 【参数更新（梯度下降）】
#
#   W^(2) := W^(2) - η · ∂J/∂W^(2)
#   W^(1) := W^(1) - η · ∂J/∂W^(1)
#
#   其中 η 是学习率（learning rate）。


# ============================================================================
# 补充知识点1：前向传播与反向传播的关系总结
# ============================================================================
#
# 【类比：做预算】
#   前向传播像是"花钱"——一笔一笔计算支出（从收入到结余）。
#   反向传播像是"记账"——反过来追踪每一笔钱花在哪里（从结余回溯到收入）。
#
# 【类比：电路分析】
#   前向传播：给定电压源，计算电路中各点的电压和电流。
#   反向传播：从输出端"注入"误差信号，计算每个元件对总误差的贡献。
#
# 【核心区别】
#
#   ┌────────────┬──────────────────────┬───────────────────────┐
#   │   维度      │     前向传播          │      反向传播          │
#   ├────────────┼──────────────────────┼───────────────────────┤
#   │ 方向        │ 输入层 → 输出层       │ 输出层 → 输入层        │
#   │ 计算内容    │ 激活值（中间变量）     │ 梯度（偏导数）          │
#   │ 依赖关系    │ 顺着依赖方向           │ 逆着依赖方向           │
#   │ 数学工具    │ 矩阵乘法、激活函数     │ 链式法则、矩阵转置      │
#   │ 存储需求    │ 中间值（供反向传播用） │ 梯度值（供参数更新用）   │
#   │ 时间开销    │ 约占总时间的 1/3       │ 约占总时间的 2/3        │
#   └────────────┴──────────────────────┴───────────────────────┘
#
#   （反向传播通常比前向传播慢约 2 倍，因为需要额外计算偏导数和转置操作）
#
# 【为什么反向传播比前向传播慢？】
#   1. 链式法则涉及额外的乘法操作（梯度之间的乘积）
#   2. 需要计算激活函数的导数（前向传播只需要计算函数本身）
#   3. 矩阵乘法的转置形式可能无法充分利用硬件加速


# ============================================================================
# 补充知识点2：自动微分原理简介
# ============================================================================
#
# 【什么是自动微分（Automatic Differentiation, AD）？】
# 自动微分是一组计算技术，用于自动计算计算机程序的导数值。
# 它不是数值微分（用差分近似），也不是符号微分（手工推导公式），
# 而是利用链式法则将程序分解为基本操作的组合，精确高效地计算导数。
#
# 【两种模式】
#
#   1. 前向模式（Forward Mode）：
#      - 从输入向输出方向计算梯度
#      - 同时计算函数值和导数值
#      - 适合：输入维度 << 输出维度（f: R → R^n）
#      - 一次前向传播只能计算一个输入参数的梯度
#
#   2. 反向模式（Reverse Mode）：
#      - 从输出向输入方向计算梯度（即反向传播）
#      - 先做一次前向传播记录所有操作，再反向计算梯度
#      - 适合：输入维度 >> 输出维度（f: R^n → R，神经网络的典型场景）
#      - 一次反向传播计算所有参数的梯度
#
# 【为什么深度学习使用反向模式？】
#   神经网络通常有百万甚至数十亿参数（输入维度极大），
#   但只有 1 个标量损失值（输出维度极小）。
#   反向模式只需 1 次反向传播就能得到所有参数的梯度，
#   而前向模式需要 N 次（N = 参数数量）。
#
# 【PyTorch autograd 的工作原理】
#
#   1. 构建计算图：
#      - 每个 requires_grad=True 的张量在执行操作时，
#        PyTorch 自动在后台记录操作历史（计算图）。
#      - 每个节点保存：创建它的操作（grad_fn）和输入张量。
#
#   2. 调用 .backward()：
#      - 从输出节点开始，按拓扑逆序遍历计算图。
#      - 对每个操作，调用其反向函数（backward）计算输入梯度。
#      - 将梯度累加到对应张量的 .grad 属性中。
#
#   3. 释放计算图：
#      - 默认情况下，.backward() 后计算图被释放（节省内存）。
#      - 如需多次反向传播，使用 retain_graph=True。
#
#   【简单示例】
#
#   import torch
#
#   x = torch.tensor([2.0], requires_grad=True)
#   y = x ** 2           # grad_fn=<PowBackward0>
#   z = y * 3            # grad_fn=<MulBackward0>
#   z.backward()         # 计算 dz/dx
#   print(x.grad)        # tensor([12.]) 因为 dz/dx = d(3x²)/dx = 6x = 12


