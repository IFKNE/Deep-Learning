# ============================================================================
# 1. 深度卷积神经网络（AlexNet）
#    源文件: alexnet.ipynb
#    目标文件: 01_AlexNet.py
# ----------------------------------------------------------------------------
#  内容要点:
#    - 深度学习历史的转折点：2012年ImageNet夺冠
#    - 8层网络：5卷积 + 3全连接
#    - ReLU激活函数替代Sigmoid
#    - Dropout正则化防止过拟合
#    - 数据增强（翻转、裁剪、颜色扰动）
#    - GPU训练的早期实践
#  学习目标:
#    理解AlexNet相比LeNet的关键改进，以及深度学习爆发的历史背景
#  前置知识:
#    卷积层、池化层、全连接层的基本概念（第6章）
#  学习建议:
#    关注AlexNet与LeNet的设计差异，特别是大卷积核(11×11)和ReLU的使用动机
# ============================================================================

# ============================================================================
# 2. 使用块的网络（VGG）
#    源文件: vgg.ipynb
#    目标文件: 02_VGG.py
# ----------------------------------------------------------------------------
#  内容要点:
#    - VGG块：多个3×3卷积 + 最大池化的重复模式
#    - 两个3×3卷积的感受野 = 一个5×5卷积，但参数更少
#    - VGG-11架构：8卷积 + 3全连接
#    - 块的抽象：用循环和子程序构建深层网络
#  学习目标:
#    掌握"用块设计网络"的思想，理解小卷积核堆叠的优势
#  前置知识:
#    AlexNet架构，卷积核感受野概念
#  学习建议:
#    重点关注vgg_block函数的参数化设计，这是模块化构建深层网络的范式
# ============================================================================

# ============================================================================
# 3. 网络中的网络（NiN）
#    源文件: nin.ipynb
#    目标文件: 03_NiN.py
# ----------------------------------------------------------------------------
#  内容要点:
#    - 1×1卷积：通道维度的全连接，逐像素的非线性变换
#    - NiN块：普通卷积 + 两个1×1卷积
#    - 全局平均池化替代全连接层 → 大幅减少参数
#    - 完全取消全连接层的设计
#  学习目标:
#    理解1×1卷积的作用和全局平均池化的优势
#  前置知识:
#    卷积的通道维度概念，全连接层的参数计算
#  学习建议:
#    对比NiN和AlexNet的参数量差异，体会1×1卷积的降维/升维作用
# ============================================================================

# ============================================================================
# 4. 含并行连结的网络（GoogLeNet）
#    源文件: googlenet.ipynb
#    目标文件: 04_GoogLeNet.py
# ----------------------------------------------------------------------------
#  内容要点:
#    - Inception块：4条并行路径（1×1, 3×3, 5×5卷积 + 3×3最大池化）
#    - 1×1卷积做Bottleneck降维，节省计算
#    - 9个Inception块的堆叠
#    - 全局平均池化 + 辅助分类器
#  学习目标:
#    掌握多尺度并行提取特征的设计思想
#  前置知识:
#    NiN的1×1卷积，VGG的块设计
#  学习建议:
#    重点理解Inception块中四条路径的通道数分配逻辑和Bottleneck设计
# ============================================================================

# ============================================================================
# 5. 批量规范化（Batch Normalization）
#    源文件: batch-norm.ipynb
#    目标文件: 05_批量规范化.py
# ----------------------------------------------------------------------------
#  内容要点:
#    - 原理：小批量均值/方差标准化 + 可学习拉伸/偏移
#    - 全连接层 vs 卷积层的BN实现差异
#    - 训练模式（用小批量统计）vs 预测模式（用移动平均）
#    - 从零实现 + PyTorch简洁实现
#    - 允许更大学习率，加速收敛，自带正则化
#  学习目标:
#    彻底理解BN的数学原理、训练/预测模式差异、代码实现
#  前置知识:
#    全连接层、卷积层的输出形状，动量（momentum）概念
#  学习建议:
#    这是本章最重要的训练技术之一，建议动手从零实现一遍加深理解
# ============================================================================

# ============================================================================
# 6. 残差网络（ResNet）
#    源文件: resnet.ipynb
#    目标文件: 06_ResNet.py
# ----------------------------------------------------------------------------
#  内容要点:
#    - 残差学习：F(x) = H(x) - x，学习残差比直接学习映射更容易
#    - 跳跃连接（Skip Connection）：梯度可直接流过，解决梯度消失
#    - 残差块：两个3×3卷积 + BN + 跳跃连接
#    - 1×1卷积调整通道数以匹配跳跃连接
#    - ResNet-18架构
#  学习目标:
#    理解残差学习为何能训练超深网络，掌握残差块的两种变体
#  前置知识:
#    批量规范化，VGG块设计
#  学习建议:
#    重点理解"恒等映射"的数学直觉，以及跳跃连接如何让梯度流动
# ============================================================================

# ============================================================================
# 7. 稠密连接网络（DenseNet）
#    源文件: densenet.ipynb
#    目标文件: 07_DenseNet.py
# ----------------------------------------------------------------------------
#  内容要点:
#    - 密集连接：每层与前面所有层在通道维上连结（concat）
#    - 稠密块（DenseBlock）+ 过渡层（Transition Layer）
#    - 增长率（growth rate）控制通道增长
#    - 过渡层用1×1卷积 + 平均池化压缩通道和空间
#  学习目标:
#    理解特征复用的极致形态，对比ResNet的相加与DenseNet的连结
#  前置知识:
#    ResNet的跳跃连接，通道维度的concat操作
#  学习建议:
#    画出稠密块中通道数增长的示意图，理解增长率k的含义
# ============================================================================

