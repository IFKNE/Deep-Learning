#  本章介绍现代卷积神经网络架构，从 AlexNet (2012) 到 DenseNet (2017)，
#  涵盖 ImageNet 竞赛中一系列里程碑式的模型。每个模型都为深层网络的设计
#  提供了关键启示：更深、更宽、更密、更轻、更智能。
