"""
=============================================================================
深度卷积神经网络（AlexNet）—— 完整带注释版
=============================================================================
AlexNet 是深度学习历史上的里程碑（2012年），首次在 ImageNet 大规模视觉
识别挑战赛中击败传统计算机视觉方法。它证明了"学习到的特征"可以超越
"手工设计的特征"，开启了深度学习的热潮。

核心创新：
  - 8层网络：5个卷积层 + 3个全连接层
  - ReLU 激活函数替代 Sigmoid
  - Dropout 正则化防止过拟合
  - GPU 并行训练
  - 数据增强（翻转、裁剪、颜色扰动）

输入: Fashion-MNIST 28×28 → 放大到 224×224
输出: 10 个类别的分类概率
=============================================================================
"""

import torch
from torch import nn
from d2l import torch as d2l


# ============================================================================
# AlexNet 模型定义
# ============================================================================
# 与 LeNet 的核心区别：
#   (1) 更深：5卷积 + 3全连接（LeNet只有3卷积 + 2全连接）
#   (2) 卷积窗口更大：第一层用 11×11 捕获大尺寸目标
#   (3) 通道数更多：是 LeNet 的 10 倍
#   (4) ReLU 替代 Sigmoid：梯度在正区间恒为1，缓解梯度消失
#   (5) Dropout：随机丢弃50%神经元，防止全连接层过拟合
#   (6) 针对 ImageNet 设计：输入 224×224，1000 类输出（此处用 Fashion-MNIST 的 10 类）

net = nn.Sequential(
    # ---- 第1个卷积块 ----
    # Conv2d(输入通道=1, 输出通道=96, 卷积核=11×11, 步幅=4, 填充=1)
    #   使用 11×11 的大窗口来捕获目标（ImageNet图像远大于MNIST）
    #   步幅=4 大幅降低空间尺寸，输出形状: (batch, 96, 54, 54)
    nn.Conv2d(1, 96, kernel_size=11, stride=4, padding=1), nn.ReLU(),
    # MaxPool2d(核=3×3, 步幅=2)：输出形状 (batch, 96, 26, 26)
    nn.MaxPool2d(kernel_size=3, stride=2),

    # ---- 第2个卷积块 ----
    # Conv2d(96, 256, 5×5, 填充=2)：填充=2 使得输入输出高宽一致
    #   输出形状: (batch, 256, 26, 26)
    nn.Conv2d(96, 256, kernel_size=5, padding=2), nn.ReLU(),
    # MaxPool2d(3×3, 步幅=2)：输出形状 (batch, 256, 12, 12)
    nn.MaxPool2d(kernel_size=3, stride=2),

    # ---- 第3~5个卷积块（连续三个卷积层，中间不插入池化） ----
    # Conv2d(256, 384, 3×3, 填充=1)：进一步增加通道数
    #   输出形状: (batch, 384, 12, 12)
    nn.Conv2d(256, 384, kernel_size=3, padding=1), nn.ReLU(),
    # Conv2d(384, 384, 3×3, 填充=1)：保持通道数不变，加深非线性
    #   输出形状: (batch, 384, 12, 12)
    nn.Conv2d(384, 384, kernel_size=3, padding=1), nn.ReLU(),
    # Conv2d(384, 256, 3×3, 填充=1)：降通道（为后续全连接层控制参数）
    #   输出形状: (batch, 256, 12, 12)
    nn.Conv2d(384, 256, kernel_size=3, padding=1), nn.ReLU(),
    # MaxPool2d(3×3, 步幅=2)：输出形状 (batch, 256, 5, 5)
    nn.MaxPool2d(kernel_size=3, stride=2),

    # ---- 展平 ----
    # Flatten: 将 (batch, 256, 5, 5) → (batch, 256*5*5=6400)
    nn.Flatten(),

    # ---- 全连接层部分 ----
    # 第1个全连接层: 6400 → 4096，参数约 6400×4096 ≈ 26M，是主要内存消耗
    #   Dropout(p=0.5): 训练时随机丢弃一半神经元，防止过拟合
    nn.Linear(6400, 4096), nn.ReLU(),
    nn.Dropout(p=0.5),
    # 第2个全连接层: 4096 → 4096
    nn.Linear(4096, 4096), nn.ReLU(),
    nn.Dropout(p=0.5),
    # 输出层: 4096 → 10（Fashion-MNIST 有 10 个类别）
    #   原论文针对 ImageNet 使用 1000 类
    nn.Linear(4096, 10))


# ============================================================================
# 查看各层输出形状
# ============================================================================
# 构造一个高度和宽度都为 224 的单通道数据（批量大小=1，通道=1）
# torch.randn: 从标准正态分布 N(0,1) 随机采样，生成张量
X = torch.randn(1, 1, 224, 224)
print("=== AlexNet 各层输出形状 ===")
for layer in net:
    X = layer(X)  # 逐层传递数据
    # layer.__class__.__name__ 获取层类名（如 'Conv2d', 'ReLU'）
    # X.shape 获取当前输出的张量形状
    print(layer.__class__.__name__, 'output shape:\t', X.shape)


# ============================================================================
# 读取 Fashion-MNIST 数据集
# ============================================================================
# AlexNet 原为 ImageNet (224×224) 设计，Fashion-MNIST 只有 28×28
# 使用 resize=224 参数将图像放大到 224×224（通常不是好做法，但这里为兼容架构）
# batch_size=128: 每次迭代使用 128 张图片进行梯度计算
batch_size = 128
train_iter, test_iter = d2l.load_data_fashion_mnist(batch_size, resize=224)


# ============================================================================
# 训练 AlexNet
# ============================================================================
# lr=0.01: 学习率比 LeNet 小，因为网络更深更宽、图像分辨率更高
#   较大的学习率可能导致深层网络的梯度更新过猛而发散
# num_epochs=10: 在 Fashion-MNIST 上训练 10 轮
# d2l.try_gpu(): 自动检测是否有可用的 GPU，有则使用 CUDA 加速
lr, num_epochs = 0.01, 10
d2l.train_ch6(net, train_iter, test_iter, num_epochs, lr, d2l.try_gpu())
# 预期输出: loss ~0.33, train acc ~0.88, test acc ~0.88


# ============================================================================
# 补充知识点：AlexNet 的历史意义与设计抉择
# ============================================================================

# 1. 为什么 ReLU 优于 Sigmoid？
#    Sigmoid: σ(x) = 1/(1+e^(-x))，x 很大或很小时梯度≈0（饱和区）
#            多层网络中梯度连续相乘 → 指数级衰减 → "梯度消失"
#    ReLU:    f(x) = max(0, x)，正区间梯度恒为 1，不衰减
#            计算也更简单（无指数运算），加速训练

# 2. 为什么第一层用 11×11 卷积？
#    ImageNet 图像约 224×224，是 MNIST (28×28) 的 10 倍
#    大卷积核捕获更大的空间结构（如狗的眼睛 vs 整个字符）

# 3. Dropout 原理：
#    训练时以概率 p 随机将神经元输出置为 0
#    等价于每次迭代训练一个不同的子网络
#    推理时不丢弃，但输出乘以 (1-p) 做缩放补偿
#    是一种集成学习的近似，有效防止全连接层过拟合

# 4. 为什么原版 AlexNet 要用两个 GPU？
#    2012年单GPU显存仅 3GB，1GB 模型参数 + 数据放不下
#    因此将网络拆成两半各放一个 GPU 上，只在某些层交换数据
#    现在 GPU 显存充裕（如 24GB+），不再需要这种设计

# ============================================================================
# 核心公式回顾
# ============================================================================
#   ReLU:     f(x) = max(0, x)
#   Dropout:  h' = h ⊙ mask, mask_i ~ Bernoulli(1-p)
#   卷积输出大小: o = ⌊(n + 2p - k) / s⌋ + 1
#     （n=输入尺寸, p=填充, k=卷积核, s=步幅）

# ============================================================================
# 总结
# ============================================================================
# 1. AlexNet 是第一个在大规模数据集上证明深度学习有效性的 CNN
# 2. 关键创新：ReLU、Dropout、数据增强、GPU 训练
# 3. 架构：5 卷积层 + 3 全连接层，8 层总计约 60M 参数
# 4. 虽然已被更高效的架构超越，但它是从浅层走向深层的关键一步
# 5. 在 Fashion-MNIST 上训练需将图像放大到 224×224（因为网络结构固定）
