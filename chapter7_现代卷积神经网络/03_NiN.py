"""
=============================================================================
网络中的网络（NiN）—— 完整带注释版
=============================================================================
NiN (Network in Network) 提出两个关键创新，深刻影响了后续 CNN 设计：

1. 1×1 卷积 —— 在通道维度上进行非线性变换，等价于逐像素的全连接层
2. 全局平均池化（Global Average Pooling）替代全连接层 —— 大幅减少参数

核心理念：在每个像素位置（每个高度和宽度）独立应用一个小型多层感知机(MLP)，
       让每个像素位置都能学习更复杂的特征表示。

输入: Fashion-MNIST 28×28 → resize 到 224×224
输出: 10 类分类
=============================================================================
"""

import torch
from torch import nn
from d2l import torch as d2l


# ============================================================================
# NiN 块
# ============================================================================
# NiN 块结构：
#   普通卷积层（核大小可配置）→ ReLU → 1×1卷积 → ReLU → 1×1卷积 → ReLU
#
# 1×1 卷积的作用：
#   - 数学上等价于在每个像素位置独立应用全连接层
#   - 可以在不改变空间尺寸的情况下改变通道数（降维/升维）
#   - 增加了网络的非线性表达能力（1×1卷积 + ReLU = 逐像素非线性变换）
#   - 参数效率高：1×1 卷积参数仅为 1×1×C_in×C_out
#
# 为什么后接两个 1×1 卷积？
#   - 第一个 1×1：对主卷积提取的特征做非线性组合
#   - 第二个 1×1：进一步增加非线性，增强局部特征表达

def nin_block(in_channels, out_channels, kernel_size, strides, padding):
    """
    构建一个 NiN 块。

    参数:
        in_channels: 输入通道数
        out_channels: 输出通道数（三个卷积层统一使用）
        kernel_size: 第一个卷积层的核大小
        strides: 第一个卷积层的步幅
        padding: 第一个卷积层的填充

    返回:
        nn.Sequential: 包含一个主卷积 + 两个 1×1 卷积的 NiN 块
    """
    return nn.Sequential(
        # 主卷积层：提取空间特征，核大小和步幅可配置
        nn.Conv2d(in_channels, out_channels, kernel_size, strides, padding),
        nn.ReLU(),
        # 第1个 1×1 卷积：逐像素的非线性特征变换
        #   kernel_size=1 → 等价于在每个像素位置独立做全连接
        nn.Conv2d(out_channels, out_channels, kernel_size=1), nn.ReLU(),
        # 第2个 1×1 卷积：进一步增加非线性
        nn.Conv2d(out_channels, out_channels, kernel_size=1), nn.ReLU())


# ============================================================================
# NiN 完整模型
# ============================================================================
# NiN 整体架构（模仿 AlexNet 的结构，但取消全连接层）：
#   块1: 11×11 卷积(1→96) + 两个1×1卷积 + 3×3 MaxPool(stride=2)
#   块2: 5×5 卷积(96→256) + 两个1×1卷积 + 3×3 MaxPool(stride=2)
#   块3: 3×3 卷积(256→384) + 两个1×1卷积 + 3×3 MaxPool(stride=2)
#   块4: 3×3 卷积(384→10)  + 两个1×1卷积 + 全局平均池化 → Flatten → (batch, 10)
#
# 关键设计：最后一个 NiN 块输出通道 = 类别数 (10)
#   后面接 AdaptiveAvgPool2d((1,1)) 把每个通道的空间维度平均成 1×1
#   得到 (batch, 10, 1, 1) → Flatten → (batch, 10)
#   这就是"用全局平均池化替代全连接层"！

net = nn.Sequential(
    # 块1: 下采样 224→54×54，通道 1→96
    nin_block(1, 96, kernel_size=11, strides=4, padding=0),
    nn.MaxPool2d(3, stride=2),  # 54 → 26

    # 块2: 通道 96→256，padding=2 保持高宽
    nin_block(96, 256, kernel_size=5, strides=1, padding=2),
    nn.MaxPool2d(3, stride=2),  # 26 → 12

    # 块3: 通道 256→384
    nin_block(256, 384, kernel_size=3, strides=1, padding=1),
    nn.MaxPool2d(3, stride=2),  # 12 → 5

    # Dropout(0.5): 训练时随机丢弃 50% 神经元，防止过拟合
    nn.Dropout(0.5),

    # 块4: 最后一个 NiN 块，输出通道=类别数 10
    #   此时特征图大小为 5×5
    nin_block(384, 10, kernel_size=3, strides=1, padding=1),
    # AdaptiveAvgPool2d((1,1)): 自适应平均池化
    #   无论输入多大（这里是 5×5），强制输出 1×1
    #   对每个通道独立操作：将 5×5 取平均 → 1 个标量
    #   输出形状: (batch, 10, 1, 1)
    nn.AdaptiveAvgPool2d((1, 1)),
    # Flatten: (batch, 10, 1, 1) → (batch, 10)
    #   10 个标量就是 10 个类别的原始预测值（logits）
    nn.Flatten())


# ============================================================================
# 查看各层输出形状
# ============================================================================
X = torch.rand(size=(1, 1, 224, 224))
print("=== NiN 各层输出形状 ===")
for layer in net:
    X = layer(X)
    print(layer.__class__.__name__, 'output shape:\t', X.shape)
# 最终输出: (1, 10)  — 直接就是 10 个类别的 logits


# ============================================================================
# 训练 NiN
# ============================================================================
# resize=224: NiN 预期 224×224 输入
lr, num_epochs, batch_size = 0.1, 10, 128
train_iter, test_iter = d2l.load_data_fashion_mnist(batch_size, resize=224)
d2l.train_ch6(net, train_iter, test_iter, num_epochs, lr, d2l.try_gpu())


# ============================================================================
# 补充知识点
# ============================================================================

# 1. 1×1 卷积的本质
#    普通卷积操作：对每个空间位置，在通道维度做加权求和
#    1×1 卷积：没有空间邻域信息，只在通道维度做线性组合 + 非线性
#    可以理解为"通道维度的全连接层"，每个像素位置共享参数
#
#    应用场景：
#      - 降维：减少通道数，降低后续计算量（如 GoogLeNet 的 Bottleneck）
#      - 升维：增加通道数，增强表达能力
#      - 跨通道信息融合：让不同通道之间"交流"

# 2. 全局平均池化 vs 全连接层
#    全连接层的参数: C_in × H × W × C_out（例如: 256×5×5×10 = 64,000）
#    全局平均池化:  0 个可学习参数！
#    优势:
#      - 零参数，无过拟合风险
#      - 天然对空间平移不变性友好
#      - 各通道直接对应各类别，可解释性强
#    缺点:
#      - 训练可能比全连接层慢（需要更多卷积层来补偿表达能力的损失）

# 3. 一次性将 384×5×5→10×5×5 的问题
#    直接在空间维度降通道（384→10）会丢失大量信息
#    NiN 通过多个 NiN 块逐步降通道：96→256→384→10
#    最后用全局平均池化把空间维度（5×5）压缩为 1×1

# ============================================================================
# 核心公式回顾
# ============================================================================
#   1×1 卷积:    输出[i,j,c] = Σ_{k} 输入[i,j,k] × 权重[1,1,k,c]
#   全局平均池化:  输出[c] = (1/(H×W)) × Σ_{i,j} 输入[i,j,c]
#   NiN 参数对比: AlexNet ~60M, VGG ~102M, NiN ~ 远小于两者

# ============================================================================
# 总结
# ============================================================================
# 1. NiN 块: 普通卷积 + 两个 1×1 卷积 → 逐像素的 MLP
# 2. 1×1 卷积是通道维度的全连接层，可降维、升维、融合信息
# 3. 全局平均池化替代全连接层 → 参数大幅减少，防止过拟合
# 4. 完全取消全连接层的设计深刻影响了 GoogLeNet 和 ResNet
# 5. 训练 NiN 在 Fashion-MNIST 上约需 3K examples/sec，比 AlexNet 稍慢
