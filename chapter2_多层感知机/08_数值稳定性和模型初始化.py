# --------------------------------------------------------------------------
# 补充1：梯度消失与梯度爆炸的数学原理
# --------------------------------------------------------------------------
#
# 考虑 L 层网络，每层的雅可比矩阵为 J_l = ∂h^(l)/∂h^(l-1)
# 损失函数 L 对第 l 层权重的梯度为：
#
#     ∂L/∂W^(l) = (J_L * ... * J_(l+1)) * ∂h^(l)/∂W^(l)
#
# 对连乘矩阵做特征值分解：每个 J 的奇异值 σ_i(J)
# 连乘后的谱范数约等于 Π ||J_k||_2
#
#   若几乎所有 ||J_k||_2 < 1 → 梯度指数衰减 → 梯度消失
#   若几乎所有 ||J_k||_2 > 1 → 梯度指数增长 → 梯度爆炸
#
# 对于 sigmoid 激活：σ'(x) ≤ 0.25，所以 ||J|| ≤ 0.25 * ||W||
#   若 ||W|| < 4，连乘仍可能导致梯度消失
# 对于 tanh 激活：tanh'(x) ≤ 1，情况稍好但仍然存在饱和区
# 对于 ReLU 激活：ReLU'(x) ∈ {0, 1}，不会让梯度衰减，缓解消失问题

# --------------------------------------------------------------------------
# 补充2：为什么 ReLU 能缓解梯度消失
# --------------------------------------------------------------------------
#
# ReLU(x) = max(0, x)
# ReLU'(x) = 1（x > 0 时）或 0（x < 0 时）
#
# 与 sigmoid 的对比：
#   - sigmoid 梯度最大值仅 0.25，且输入绝对值大时趋近于 0
#   - ReLU 在正半轴的梯度恒为 1（不衰减！）
#   - 只要层输出大多为正，梯度就能畅通无阻地传播
#
# 代价：x < 0 时梯度为 0，可能导致"死神经元"——
#   一旦某神经元对所有输入都输出负值，它将永远不再更新。
#   解决方法：LeakyReLU（负半轴给一个很小的斜率 0.01）、
#   PReLU（可学习的负斜率）、ELU 等变体。

# --------------------------------------------------------------------------
# 补充3：He 初始化（Kaiming 初始化）
# --------------------------------------------------------------------------
#
# He 初始化由 Kaiming He 等人 (2015) 提出，专为 ReLU 及其变体设计。
# 核心区别：
#   - Xavier 假设激活函数关于原点对称且近似线性于原点附近
#     （适用于 sigmoid / tanh），此时方差条件为 σ^2 = 2/(n_in + n_out)
#   - He 考虑到 ReLU 输出非负（均值不为 0），会将方差减半，
#     因此需要将方差放大一倍来补偿
#
# He 初始化公式（高斯分布）：
#     σ^2 = 2 / n_in          （仅考虑输入数量，有些实现也使用 2/n_out）
#     W ~ N(0, sqrt(2/n_in))
#
# He 初始化公式（均匀分布）：
#     W ~ U(-sqrt(6/n_in), sqrt(6/n_in))
#
# PyTorch 中 nn.Linear 和 nn.Conv2d 的默认初始化就是 kaiming_uniform_
# （He 均匀分布版本），因此如果你使用 ReLU 激活，PyTorch 已经
# 为你选好了默认初始化。
#
# 代码示例：
#   nn.init.kaiming_normal_(tensor, mode='fan_in', nonlinearity='relu')
#   nn.init.kaiming_uniform_(tensor, mode='fan_in', nonlinearity='relu')

# --------------------------------------------------------------------------
# 补充4：其他常见初始化方法
# --------------------------------------------------------------------------
#
# 1. LeCun 初始化（LeCun et al., 1998）：
#    - σ^2 = 1/n_in，专为 sigmoid/tanh 设计（仅考虑前向传播方差）
#    - PyTorch: nn.init.normal_(tensor, std=sqrt(1/n_in))
#
# 2. 正交初始化（Orthogonal Initialization）：
#    - 生成一个正交矩阵（或半正交矩阵），乘以一个缩放因子
#    - 优点：谱范数严格为 1，前向/反向传播中范数完全不变
#    - PyTorch: nn.init.orthogonal_(tensor, gain=...)
#
# 3. 稀疏初始化（Sparse Initialization）：
#    - 每个神经元仅与一小部分随机选择的输入相连
#    - PyTorch: nn.init.sparse_(tensor, sparsity, std=...)
#
# 4. 恒等初始化（Identity Initialization）：
#    - 将权重矩阵初始化为单位矩阵（或其倍数）
#    - 常用于 RNN/LSTM 的循环权重矩阵
#
# 5. 常数初始化：
#    - 所有权重初始化为相同常数（如前所述，这会破坏对称性，通常不推荐）

# --------------------------------------------------------------------------
# 补充5：常见问题与练习
# --------------------------------------------------------------------------
#
# Q1: 除了多层感知机的排列对称性，还能设计出其他需要打破对称性的情况吗？
# A1: CNN 中同一层的多个卷积核之间也存在排列对称性（交换两个卷积核的位置
#     不影响输出）；RNN 中不同时间步的权重共享本身也体现了一种对称性结构；
#     注意力机制中多个注意力头之间理论上也存在排列对称性。
#
# Q2: 能否将线性回归或 softmax 回归中的所有权重初始化为相同值？
# A2: 不能。原因同 MLP——相同的初始权重会导致梯度相同，更新后仍相同，
#     模型等效于只使用一个特征。例外：如果使用 L1/L2 正则化且正则化强度
#     足够大，可能间接打破对称性，但这不是可靠的方法。
#
# Q3: 两个矩阵乘积特征值的解析界对梯度条件有何启示？
# A3: 令 A, B 为矩阵，则 σ_min(A)σ_min(B) ≤ σ(AB) ≤ σ_max(A)σ_max(B)
#     若所有层的最大奇异值 < 1，梯度消失；若最小奇异值 > 1，梯度爆炸。
#     理想情况下每层的条件数（σ_max/σ_min）应接近 1，这可以通过
#     正交初始化来近似实现。
#
# Q4: 如何检测你的网络是否出现了梯度消失/爆炸？
# A4: 训练时监控各层梯度的范数（L2 范数）。如果某些层的梯度范数远小于
#     其他层（如相差几个数量级），可能存在梯度消失；如果梯度范数在
#     训练中急剧增大或变成 NaN，可能存在梯度爆炸。
#     PyTorch 中可以通过注册 hook 来追踪梯度：
#       tensor.register_hook(lambda grad: print(grad.norm()))
#     也可以使用 torch.nn.utils.clip_grad_norm_ 进行梯度裁剪。

# ============================================================================
# 总结
# ============================================================================
#
# 1. 梯度消失：深层网络中，sigmoid/tanh 的饱和特性导致梯度连乘后
#    指数级衰减，浅层参数基本不更新。ReLU 的正半轴梯度恒为 1，
#    有效缓解了这一问题。
#
# 2. 梯度爆炸：当每层雅可比矩阵的特征值 > 1 时，梯度连乘导致数值
#    指数级爆炸。合理的参数初始化可将梯度范数控制在稳定范围内。
#    梯度裁剪（gradient clipping）是工程上的补充手段。
#
# 3. 对称性破坏：随机初始化是打破隐藏单元排列对称性的最基本手段，
#    保证不同隐藏单元可以学习到不同的特征。
#
# 4. Xavier 初始化（Glorot 初始化）：
#    - 数学目标：保持前向激活值和反向梯度的方差在各层间稳定
#    - 高斯形式：W ~ N(0, 2/(n_in + n_out))
#    - 均匀形式：W ~ U(-√(6/(n_in+n_out)), √(6/(n_in+n_out)))
#    - 适用场景：sigmoid / tanh 激活函数
#
# 5. He 初始化（Kaiming 初始化）：
#    - 专为 ReLU 设计：W ~ N(0, 2/n_in)
#    - PyTorch 的 nn.Linear 和 nn.Conv2d 默认使用此方法
#    - 适用场景：ReLU / LeakyReLU / PReLU 等激活函数
#
# 核心原则：
#   sigmoid/tanh + Xavier 初始化
#   ReLU + He（Kaiming）初始化
#   永远不要将所有参数初始化为相同值
