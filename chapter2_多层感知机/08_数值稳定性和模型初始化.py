# 导入必要的库
# %matplotlib inline 是 Jupyter Notebook 魔法命令，在 .py 脚本中可注释掉
# 它使得 matplotlib 图表直接嵌入 notebook 输出中，而非弹出独立窗口
# 如果你在 PyCharm 等 IDE 中运行，plt.show() 会自动调用
import torch                     # PyTorch 深度学习框架
from d2l import torch as d2l     # 《动手学深度学习》配套工具包，封装了绘图等功能


# ============================================================================
# 第1节：sigmoid 函数导致梯度消失的可视化
# ============================================================================
# 背景：sigmoid 函数 σ(x) = 1/(1+exp(-x)) 曾是神经网络最常用的激活函数，
# 因其"类阈值"特性（输出范围 (0,1)）而受生物神经科学启发。然而，它的梯度
# σ'(x) = σ(x)*(1-σ(x)) 在输入绝对值较大时迅速趋近于 0，这就是"梯度消失"。
# 当反向传播经过多层时，链式法则连乘导致深层梯度指数级衰减，浅层参数几乎
# 不更新，模型无法有效学习。

# ----- 创建从 -8 到 8 的输入张量，步长为 0.1 -----
# torch.arange(start, end, step) 类似 Python 的 range()，但返回的是 PyTorch 张量
# requires_grad=True 告诉 PyTorch 需要追踪这个张量上的所有操作，
# 以便后续通过 .backward() 计算梯度。这是自动微分（autograd）的核心机制。
x = torch.arange(-8.0, 8.0, 0.1, requires_grad=True)  # x 形状：[160]，值从 -8.0 到 7.9

# ----- 计算 sigmoid 函数值 -----
# torch.sigmoid(x) = 1 / (1 + exp(-x))，输出范围 (0, 1)
# 对 x 的每个元素分别计算
y = torch.sigmoid(x)                                    # y 形状：[160]

# ----- 反向传播计算梯度 -----
# torch.ones_like(x) 创建一个与 x 形状相同、所有元素为 1 的张量
# 作为"外部梯度"传入（等价于 ∂L/∂y = 1，即假设损失 L 对 y 的梯度全为 1）
# .backward(gradient) 触发反向传播，计算梯度并累积到 x.grad 中
# 这里得到 dy/dx = sigmoid'(x) = sigmoid(x) * (1 - sigmoid(x))
y.backward(torch.ones_like(x))                          # 梯度存储在 x.grad 中

# ----- 绘制 sigmoid 函数及其梯度曲线 -----
# .detach() 将张量从计算图中分离，返回一个不需要梯度的新张量
#    这用于把数据从 autograd 计算图中取出，防止进一步追踪梯度
# .numpy() 将 PyTorch 张量转换为 NumPy 数组（仅限 CPU 张量）
# x.grad 是 backward() 后存储在 x 上的梯度值
# figsize=(4.5, 2.5) 设置图形尺寸（宽4.5英寸，高2.5英寸）
d2l.plot(x.detach().numpy(),                            # x 轴：输入值
         [y.detach().numpy(), x.grad.numpy()],           # y 轴：[sigmoid值, sigmoid梯度]
         legend=['sigmoid', 'gradient'],                 # 图例标签
         figsize=(4.5, 2.5))                             # 图形尺寸

# 可视化解读：
# - sigmoid 曲线：S 形，中心在 x=0，输出范围 (0, 1)
# - 梯度曲线：钟形，在 x=0 处达到最大值 0.25，|x| 较大时趋近于 0
# - 当输入 x 在 (-5, 5) 之外时，梯度几乎为 0 —— 这就是"梯度消失"的根源
# - 在深层网络中，若每层的输出都落在 sigmoid 的饱和区，反向传播的梯度
#   连乘后会指数级衰减，靠近输入的层几乎得不到有效更新


# ============================================================================
# 第2节：梯度爆炸的数值演示 —— 连续矩阵乘法
# ============================================================================
# 背景：与梯度消失相反，梯度爆炸指反向传播中梯度指数级增长。
# 考虑 L 层网络的梯度链式法则：∂L/∂W^(l) = M^(L) * ... * M^(l+1) * v^(l)
# 如果每个雅可比矩阵 M 的特征值 > 1，连乘后梯度将爆炸。
# 本节通过随机矩阵连续相乘来直观展示这一现象。

# ----- 生成一个 4x4 的高斯随机矩阵作为初始矩阵 -----
# torch.normal(mean, std, size) 从正态分布 N(mean, std^2) 中采样
# 这里 mean=0, std=1，即标准正态分布 N(0, 1)
# 方差 σ^2 = 1，每个元素独立采样
M = torch.normal(0, 1, size=(4, 4))    # 4x4 随机高斯矩阵
print('一个矩阵 \n', M)

# ----- 连续乘以 100 个随机矩阵 -----
# for i in range(100): Python 循环，i 从 0 到 99
# torch.mm(A, B) 是矩阵乘法（matrix multiplication），等价于 @ 运算符
#   要求：A 的形状为 (m, n)，B 的形状为 (n, k)，结果为 (m, k)
#   注意区别于 torch.mul()（逐元素乘法）和 torch.matmul()（广义矩阵乘）
# 每次迭代都乘以一个新的 4x4 高斯随机矩阵
for i in range(100):
    M = torch.mm(M, torch.normal(0, 1, size=(4, 4)))  # M = M @ 新随机矩阵

print('乘以100个矩阵后\n', M)
# 输出解读：矩阵内的数值达到 10^26 量级 —— 爆炸了！
# 原因：每个随机矩阵的谱半径（最大特征值的模）平均约为 2√n ≈ 4（对4x4矩阵）
# 100 次连乘后，范数约为 4^100 ≈ 1.6×10^60 量级
# 在训练中，这意味着参数梯度值极其巨大，优化器会做出巨大的参数更新，
# 导致参数值发散到 NaN（Not a Number），模型完全无法收敛

# 小结：梯度消失和梯度爆炸是深度网络训练中的核心挑战。
# - 梯度消失 → 参数几乎不更新 → 模型学不动
# - 梯度爆炸 → 参数剧烈震荡/NaN → 模型崩溃
# 解决方案：合理的参数初始化（如 Xavier）+ 适当的激活函数（如 ReLU）+ 梯度裁剪


# ============================================================================
# 第3节：打破对称性 —— 为什么不能初始化为相同的值
# ============================================================================
# 这是一个概念性章节，原 notebook 无对应代码，此处用注释阐明原理。
#
# 问题描述：
# 假设一个单隐藏层 MLP，隐藏层有 2 个单元，隐藏层权重为 W^(1)。
# 如果我们将 W^(1) 的所有元素初始化为同一常量 c，那么：
#
#   前向传播：
#     隐藏单元 h_1 和 h_2 接收相同的输入和权重，
#     因此产生相同的激活值：h_1 = h_2。
#     它们对下一层而言完全"不可区分"。
#
#   反向传播：
#     损失函数对 W^(1) 每个元素的梯度相同（因为对称性），
#     梯度更新后 W^(1) 的所有元素仍然是相同的值。
#
#   后果：
#     - 无论训练多少轮，两个隐藏单元始终表现得像一个单元
#     - 网络的表达能力被严重削弱（隐藏层实际上宽度为 1）
#     - 这是一种"对称性陷阱"：小批量 SGD 本身无法打破它
#
#   打破对称性的方法：
#     1. 随机初始化权重（最常用、最基础）
#     2. Dropout（暂退法）正则化 —— 每次随机丢弃不同单元，自然打破对称
#     3. 对偏置使用不同初始化值
#
#   例外情况：
#     在某些特殊架构中（如 Siamese 网络、权重共享的 CNN），
#     会刻意保持对称性以实现"参数绑定"。
#     但对于标准 MLP，对称性是必须被打破的。


# ============================================================================
# 第4节：Xavier 初始化的数学推导（作为注释呈现）
# ============================================================================
#
# Xavier 初始化由 Glorot & Bengio (2010) 提出，旨在解决深度网络中
# 信号（前向传播的激活值）的方差在层间指数级增长或衰减的问题。
#
# --------------------------------------------------------------------------
# 前向传播的方差分析
# --------------------------------------------------------------------------
#
# 考虑一个全连接层，有 n_in 个输入和 n_out 个输出（无激活函数）。
# 对于输出 o_i：
#
#     o_i = Σ(j=1..n_in) w_ij * x_j
#
# 假设条件（"不存在非线性"是理想化假设）：
#   - 权重 w_ij 独立同分布，均值为 0，方差为 σ^2
#   - 输入 x_j 独立同分布，均值为 0，方差为 γ^2
#   - w_ij 与 x_j 相互独立
#
# 计算 o_i 的均值和方差：
#
#     E[o_i] = Σ E[w_ij * x_j]
#            = Σ E[w_ij] * E[x_j]           [独立→乘积期望=期望乘积]
#            = Σ 0 * 0 = 0
#
#     Var[o_i] = E[o_i^2] - (E[o_i])^2
#              = E[(Σ w_ij * x_j)^2]        [E[o_i]=0]
#              = Σ E[w_ij^2 * x_j^2]        [交叉项期望为0，因独立且均值为0]
#                + Σ(i≠k) E[w_ij * w_ik * x_j * x_k]
#              = Σ E[w_ij^2] * E[x_j^2]     [交叉项：E[w_ij]*E[w_ik]*...=0]
#              = Σ σ^2 * γ^2                [E[w^2]=Var[w]=σ^2，E[x^2]=Var[x]=γ^2]
#              = n_in * σ^2 * γ^2
#
# 要保持前向传播中方差不缩放，需要 n_in * σ^2 = 1，即 σ^2 = 1/n_in
#
# --------------------------------------------------------------------------
# 反向传播的方差分析
# --------------------------------------------------------------------------
#
# 反向传播时，梯度从输出层向输入层传播。
# 类似的分析可得，要保证梯度方差不变，需要 n_out * σ^2 = 1，即 σ^2 = 1/n_out
#
# 矛盾：无法同时满足 n_in * σ^2 = 1 和 n_out * σ^2 = 1（除非 n_in = n_out）
#
# --------------------------------------------------------------------------
# Xavier 折中方案
# --------------------------------------------------------------------------
#
# 取调和平均数意义上的折中：
#
#     σ^2 = 2 / (n_in + n_out)              [高斯分布版本]
#     σ   = sqrt(2 / (n_in + n_out))        [标准差]
#
# 如果用均匀分布 U(-a, a) 代替高斯分布：
#     均匀分布 U(-a, a) 的方差 = a^2 / 3
#     令 a^2/3 = 2/(n_in + n_out)
#     a = sqrt(6 / (n_in + n_out))
#
#     初始化范围：[-sqrt(6/(n_in+n_out)), +sqrt(6/(n_in+n_out))]
#
# --------------------------------------------------------------------------
# 实际效果
# --------------------------------------------------------------------------
# Xavier 初始化使得：
#   - 前向传播时各层激活值的方差不发生指数级变化
#   - 反向传播时各层梯度的方差也不发生指数级变化
#   - 配合 sigmoid/tanh 等对称激活函数使用效果较好
#   - 但对于 ReLU 激活函数，Xavier 推导中"均值为 0"的假设被破坏
#     （ReLU 输出非负），因此 He 初始化更为合适（见末尾补充知识）


