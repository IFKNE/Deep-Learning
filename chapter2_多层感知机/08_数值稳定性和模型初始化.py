# 第5节：小结（原 notebook 小结翻译 + 代码示例）
# ============================================================================

# 下面用 PyTorch 代码演示 Xavier 初始化在实际中的使用方式
# 在实际项目中，你通常不需要手动计算 Xavier 公式，
# PyTorch 的 nn.init 模块已经实现了各种初始化方法

# 创建一个线性层以演示参数初始化
import torch.nn as nn

# 示例：一个简单的全连接层，输入维度 256，输出维度 128
linear = nn.Linear(256, 128)

# ----- 方法1：使用默认初始化（PyTorch 会自动使用 kaiming_uniform_） -----
# nn.Linear 在创建时已经自动调用了初始化方法
print("默认初始化后的权重方差：",
      torch.var(linear.weight).item())         # 查看权重的实际方差

# ----- 方法2：手动应用 Xavier 初始化（高斯分布版本） -----
# nn.init.xavier_normal_ 对应 Xavier 高斯分布版本
# _ 后缀表示这是一个"原地操作"（in-place），直接修改张量而不创建新张量
nn.init.xavier_normal_(linear.weight)          # 权重使用 Xavier 正态初始化
nn.init.zeros_(linear.bias)                    # 偏置初始化为 0（常见做法）

# ----- 方法3：手动应用 Xavier 初始化（均匀分布版本） -----
# nn.init.xavier_uniform_ 对应 Xavier 均匀分布版本
nn.init.xavier_uniform_(linear.weight)

# 打印初始化后的权重统计信息，验证 Xavier 是否按预期工作
print("Xavier初始化后的权重均值：", torch.mean(linear.weight).item(),
      "（应接近 0）")
print("Xavier初始化后的权重方差：",
      torch.var(linear.weight).item(),
      f"（理论值应为 2/({256}+{128}) = {2/(256+128):.6f}）")

# Xavier 理论方差
n_in, n_out = 256, 128
theoretical_var = 2 / (n_in + n_out)
print(f"理论方差：{theoretical_var:.6f}")


