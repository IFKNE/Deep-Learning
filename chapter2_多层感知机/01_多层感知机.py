# ============================================================================
# 补充 2：为什么 ReLU 更好 —— 梯度消失问题详解
# ============================================================================
# 梯度消失 (Vanishing Gradient) 问题：
#   - 在深层网络中，梯度通过链式法则从输出层反向传播到输入层
#   - 如果每一层的导数都小于 1（如 sigmoid 最大 0.25），
#     则传播到浅层时梯度会指数级衰减：
#     梯度 ≈ 0.25^L（L 为层数）
#   - 当 L=10 时，梯度约为 0.25^10 ≈ 9.5e-7，几乎为 0
#   - 接近输入层的参数几乎无法更新，训练停滞
#
# ReLU 如何缓解：
#   - 正区间的导数恒为 1（不是小于 1 的分数）
#   - 梯度在正区间不衰减：1^L = 1
#   - 实践中，一部分神经元输出为负（导数为 0），但至少有一部分
#     神经元保持正区间，梯度可以顺利传播
#
# 形象比喻：
#   sigmoid: 传话游戏，每次传递信息量只剩 25%，传 10 次后几乎没信息了
#   ReLU:    有些传话员不说话（导数为 0），但说话的人一字不漏（导数为 1）


# ============================================================================
# 补充 3：通用近似定理的深入理解
# ============================================================================
# 定理正式表述（Cybenko, 1989; Hornik, 1991）：
#   设 φ 是一个非常数、有界、单调递增的连续函数。
#   对于任意连续函数 f 定义在紧致集 K ⊂ R^d 上，
#   和任意 ε > 0，存在整数 N 和参数 v_i, w_i, b_i 使得：
#
#       |F(x) - f(x)| < ε,   F(x) = Σ_{i=1}^{N} v_i · φ(w_i^T x + b_i)
#
#   其中 φ 是激活函数（如 sigmoid），x 输入，F(x) 是单隐藏层网络的输出。
#
# 关键点：
#   1. 单隐藏层理论上就够了 —— 但可能需要指数级数量的神经元
#   2. 深层网络可以用更少的神经元总数表达同样的函数
#   3. 定理保证的是"存在性"，不保证能用梯度下降学到这些参数
#   4. 实际中，网络架构设计（深度、宽度、连接方式）决定了学习的难易程度


# ============================================================================
# 补充 4：相关公式证明
# ============================================================================
# 4.1 证明 tanh(x) + 1 = 2 * sigmoid(2x):
#
#   左边: tanh(x) + 1
#       = (1 - e^{-2x})/(1 + e^{-2x}) + 1
#       = (1 - e^{-2x} + 1 + e^{-2x})/(1 + e^{-2x})
#       = 2/(1 + e^{-2x})
#
#   右边: 2 * sigmoid(2x)
#       = 2/(1 + e^{-2x})
#
#   左边 = 右边，证毕。
#
# 4.2 pReLU 的导数:
#   pReLU(x) = max(0, x) + α * min(0, x)
#
#               { 1,  x > 0
#   pReLU'(x) = { 不存在, x = 0 (工程中取 α)
#               { α,  x < 0
#
#   当 α=0 时退化为标准 ReLU 的导数；当 α 可学习时，负区间的斜率由数据决定。


# ============================================================================
# 补充 5：常见问题 / 练习思考
# ============================================================================
# Q1: 计算 pReLU 激活函数的导数。
# A1: pReLU'(x) = 1 (x>0), α (x<0), 不存在 (x=0，工程取左侧导数 α)。
#
# Q2: 证明一个仅使用 ReLU（或 pReLU）的多层感知机构造了一个连续的分段线性函数。
# A2: ReLU 本身是分段线性的（两段：0 和 x）。
#     多个 ReLU 层的复合 = 多个分段线性函数的复合 = 分段线性函数。
#     且 ReLU 是连续的，复合连续函数仍连续。
#     这意味着 MLP 的决策边界由折线段组成，而非曲线。
#
# Q3: 证明 tanh(x) + 1 = 2 * sigmoid(2x)
# A3: 见上方补充 4.1 的详细推导。
#
# Q4: 假设我们有一个非线性单元，将它一次应用于一个小批量的数据。这会导致什么样的问题？
# A4: 如果将激活函数应用于整个小批量（按批次而非按元素），
#     一个样本的特征值会受同批次其他样本的影响，
#     破坏了样本间的独立性。
#     正确做法：激活函数应按元素独立计算（不跨样本、不跨特征）。
#
# Q5: 什么情况下 sigmoid 和 tanh 仍然优于 ReLU？
# A5: - sigmoid 用于二分类输出层（需要概率输出）
#     - tanh 用于需要零中心输出的场景（如 RNN/LSTM 中的门控）
#     - 当网络很浅时（1-2 层），梯度消失不是问题，sigmoid/tanh 表现也不错
#     - 某些需要输出范围严格在 (-1,1) 或 (0,1) 的场景


# ============================================================================
# 总结
# ============================================================================
# 1. 多层感知机 (MLP):
#    - 在输入层和输出层之间加入隐藏层
#    - 每个隐藏层后进行非线性激活函数变换
#    - 没有激活函数的多层网络等价于单层线性模型
#
# 2. 激活函数的作用:
#    - 引入非线性，赋予网络表达非线性关系的能力
#    - 使深层网络能够学习层次化的特征表示
#
# 3. 三种激活函数对比:
#    - ReLU: max(0, x) — 实现简单、梯度不衰减、最常用
#    - sigmoid: 1/(1+e^{-x}) — 输出 (0,1)，适合二分类输出层
#    - tanh: (1-e^{-2x})/(1+e^{-2x}) — 输出 (-1,1)，零中心
#
# 4. 关键 PyTorch 概念:
#    - requires_grad=True: 标记需要追踪梯度
#    - .backward(): 反向传播自动计算梯度
#    - .grad: 存放梯度值的属性
#    - .detach(): 从计算图分离张量
#    - .zero_(): 原地清零（_ 后缀 = 原地操作）
#    - torch.ones_like(): 创建形状相同的全 1 张量
#    - retain_graph=True: 保留计算图以便多次反向传播
