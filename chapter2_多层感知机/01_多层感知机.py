from d2l import torch as d2l         # 《动手学深度学习》配套工具包，封装了绘图等常用功能


# ============================================================================
# 第1节：隐藏层
# ============================================================================
# ============================================================================
# 1.1  线性模型可能会出错 —— 为什么需要非线性
# ============================================================================
# 线性模型的核心假设：
#   y = XW + b  (仿射变换)
#
# 局限性 1：单调性假设
#   - 如果权重为正：特征增大 -> 输出总是增大
#   - 如果权重为负：特征增大 -> 输出总是减小
#   - 现实世界并非总是单调的。例如：体温与死亡率的关系 —
#     体温高于37°C时，温度越高风险越大；
#     体温低于37°C时，温度越高风险越小（呈 V 形关系）。
#
# 局限性 2：无法建模特征交互
#   - 图像分类中，像素 (13, 17) 的重要性取决于周围像素的上下文
#   - 线性模型假设每个像素独立贡献，这显然不符合现实
#
# 结论：我们需要一种方法来自动学习特征之间的交互关系，
#       这就是隐藏层 + 非线性激活函数的作用。


# ============================================================================
# 1.2  在网络中加入隐藏层 —— MLP 架构
# ============================================================================
# 多层感知机 (MLP, Multilayer Perceptron) 结构：
#
#   输入层 (d个特征) -> 隐藏层 (h个隐藏单元) -> 输出层 (q个类别)
#
# 数学表达（无激活函数时）：
#   H = X W^(1) + b^(1)        (输入 -> 隐藏)
#   O = H W^(2) + b^(2)        (隐藏 -> 输出)
#
# 其中：
#   X  ∈ R^{n×d}   : n个样本，每个d个特征
#   W^(1) ∈ R^{d×h} : 第一层权重矩阵
#   b^(1) ∈ R^{1×h} : 第一层偏置
#   H  ∈ R^{n×h}   : 隐藏表示 (hidden representation)
#   W^(2) ∈ R^{h×q} : 第二层权重矩阵
#   b^(2) ∈ R^{1×q} : 第二层偏置
#   O  ∈ R^{n×q}   : 输出


# ============================================================================
# 1.3  从线性到非线性 —— 激活函数的必要性
# ============================================================================
# 关键洞察：如果没有激活函数，多层网络等价于单层线性模型！
#
# 证明：
#   O = (X W^(1) + b^(1)) W^(2) + b^(2)
#     = X (W^(1) W^(2)) + (b^(1) W^(2) + b^(2))
#     = X W + b    (其中 W = W^(1)W^(2), b = b^(1)W^(2)+b^(2))
#
# 这正是为什么我们需要在隐藏层之后添加非线性激活函数 σ：
#   H = σ(X W^(1) + b^(1))     (新增：激活函数打破线性链)
#   O = H W^(2) + b^(2)
#
# 激活函数按行（逐样本）、按元素（逐隐藏单元）独立计算，不依赖其他单元的值。


# ============================================================================
# 1.4  通用近似定理 (Universal Approximation Theorem)
# ============================================================================
# 定理内容：
#   即使只有一个隐藏层，只要有足够多的神经元和正确的权重，
#   多层感知机可以逼近任意连续函数（在紧致集上）。
#
# 类比：神经网络 ~ C语言
#   - C语言理论上能表达任何可计算程序（图灵完备）
#   - 但实际中，写出正确的程序才是最困难的部分
#   - 类似地，MLP 理论上能拟合任意函数，但学习正确的权重才是挑战
#
# 实践建议：
#   - 虽然单隐藏层足够，但更深（而非更宽）的网络通常更容易学习复杂函数
#   - 深层网络每一层学习不同层次的抽象特征


# ============================================================================
# 第2节：激活函数
# ============================================================================
# 激活函数的作用：
#   对隐藏单元的输出进行非线性变换，赋予网络表达非线性关系的能力
#
# 本章介绍三种常用激活函数：
#   1. ReLU   (Rectified Linear Unit) — 最常用
#   2. sigmoid — 将输出压缩到 (0, 1)
#   3. tanh    — 将输出压缩到 (-1, 1)

# --- 准备数据：创建 x 轴数据 ---
# torch.arange(start, end, step, requires_grad=True):
#   start=-8.0 : 起始值
#   end=8.0    : 终止值（不包含）
#   step=0.1   : 步长，生成 [-8.0, -7.9, -7.8, ..., 7.8, 7.9] 共160个点
#   requires_grad=True : 告诉 PyTorch 需要追踪此张量上的所有操作，
#                        以便后续使用 .backward() 自动计算梯度
x = torch.arange(-8.0, 8.0, 0.1, requires_grad=True)   # 形状: (160,)


# ============================================================================
# 2.1  ReLU 函数 (Rectified Linear Unit，修正线性单元)
# ============================================================================
# 数学定义：
#   ReLU(x) = max(0, x)
#
# 直观理解：
#   - x > 0  时：输出 = x（直接通过）
#   - x <= 0 时：输出 = 0（完全阻断）
#   - 相当于一个"半波整流器"，只保留正信号，丢弃负信号
#
# 优点：
#   1. 计算极简单：只需要 max(0, x)，没有指数运算
#   2. 导数简单：正区间导数为 1，负区间导数为 0
#   3. 缓解梯度消失：正区间的梯度恒为 1（不像 sigmoid 那样饱和）
#   4. 稀疏激活：约 50% 的神经元输出为 0，计算更高效
#
# 缺点：
#   1. "死亡 ReLU"问题：如果某个神经元对所有输入都输出负值，
#      则梯度恒为 0，该神经元永远无法更新
#   2. 不是零中心的（输出始终 >= 0）

# --- ReLU 函数曲线 ---
# torch.relu(x): 对张量 x 中的每个元素应用 ReLU 函数 max(0, x)
# 输出形状: (160,)
y = torch.relu(x)

# d2l.plot(x轴, y轴, x轴标签, y轴标签, figsize=图形大小):
#   x.detach(): 从计算图中分离 x，得到不含梯度信息的副本
#               因为绘图只需要数值，不需要追踪梯度
#   .detach() 返回一个新的张量，与原始张量共享数据但不参与梯度计算
#   figsize=(5, 2.5): 宽5英寸，高2.5英寸
d2l.plot(x.detach(), y.detach(), 'x', 'relu(x)', figsize=(5, 2.5))


# ============================================================================
# 2.2  ReLU 函数的导数
# ============================================================================
# ReLU 的导数（分段函数）：
#             { 0,  x < 0
#   ReLU'(x) ={ 不存在, x = 0 (实际工程中默认取左侧导数 0，但输入几乎不会恰好为 0)
#             { 1,  x > 0
#
# 关键特性：
#   - 导数不是 0 就是 1，"要么让参数消失，要么让参数通过"
#   - 正区间的梯度恒为 1，不会像 sigmoid 那样随 |x| 增大而趋近于 0
#   - 这是 ReLU 能缓解梯度消失问题的根本原因

# --- 绘制 ReLU 的导数曲线 ---
# .backward(gradient, retain_graph=True):
#   - 自动微分/反向传播：从当前张量开始，沿计算图反向传播，
#                        计算所有 requires_grad=True 的张量的梯度
#   - gradient 参数：因为 y 不是标量（y 是向量，形状 (160,)），
#                     需要传入一个与 y 形状相同的"上游梯度"张量。
#                     这里用 torch.ones_like(x) 创建全1张量作为上游梯度，
#                     表示我们对 y 的每个分量同等看待。
#   - retain_graph=True : 保留计算图，以便后续再次调用 .backward()
#                          默认情况下 .backward() 后会释放计算图以节省内存
y.backward(torch.ones_like(x), retain_graph=True)
# torch.ones_like(x): 创建一个与 x 形状相同、全为 1 的张量，形状: (160,)

# d2l.plot 绘制导数曲线
# x.grad: 存放 x 的梯度值，即 d(loss)/dx
#         在调用 .backward() 之后，x.grad 中包含了 x 每个元素的梯度
d2l.plot(x.detach(), x.grad, 'x', 'grad of relu', figsize=(5, 2.5))


# ============================================================================
# 2.3  pReLU 函数 (Parameterized ReLU，参数化ReLU) —— ReLU 的变体
# ============================================================================
# 数学定义：
#   pReLU(x) = max(0, x) + α * min(0, x)
#
# 直观理解：
#   - x > 0 时：pReLU(x) = x（与 ReLU 相同）
#   - x < 0 时：pReLU(x) = α * x（不再是 0，而是一个斜率为 α 的线性函数）
#
# α 是一个可学习的参数（通常初始化为 0.25），允许负区间有微小的非零输出。
# 这样即使神经元输出为负，梯度也不会完全消失，缓解了"死亡 ReLU"问题。
# 当 α = 0 时，pReLU 退化为标准 ReLU。


# ============================================================================
# 2.4  sigmoid 函数
# ============================================================================
# 数学定义：
#   sigmoid(x) = 1 / (1 + exp(-x))
#
# 直观理解：
#   - 将任意实数 (-inf, +inf) 压缩到 (0, 1) 区间
#   - 因此又称"挤压函数" (squashing function)
#   - x → +inf  时，sigmoid(x) → 1
#   - x → -inf  时，sigmoid(x) → 0
#   - x = 0     时，sigmoid(x) = 0.5
#
# 历史意义：
#   - 最早用于模拟生物神经元的"激发/不激发"
#   - 平滑可微，适合基于梯度的学习
#   - 可用于二分类输出层（将输出解释为概率）
#
# 为什么隐藏层中不再常用：
#   1. 梯度消失问题：当 |x| 很大时，导数趋近于 0
#   2. 包含指数运算，计算较慢
#   3. 输出不是零中心的（范围 0~1），可能影响梯度下降效率

# --- sigmoid 函数曲线 ---
# torch.sigmoid(x): 对每个元素应用 sigmoid 函数 1/(1+exp(-x))
y = torch.sigmoid(x)
d2l.plot(x.detach(), y.detach(), 'x', 'sigmoid(x)', figsize=(5, 2.5))


# ============================================================================
# 2.5  sigmoid 函数的导数
# ============================================================================
# sigmoid 的导数推导：
#   σ(x) = 1 / (1 + e^{-x})
#
#   σ'(x) = d/dx [ (1 + e^{-x})^{-1} ]
#         = -(1 + e^{-x})^{-2} * (-e^{-x})
#         = e^{-x} / (1 + e^{-x})^2
#         = [1/(1+e^{-x})] * [e^{-x}/(1+e^{-x})]
#         = [1/(1+e^{-x})] * [(1+e^{-x}-1)/(1+e^{-x})]
#         = [1/(1+e^{-x})] * [1 - 1/(1+e^{-x})]
#         = σ(x) * (1 - σ(x))
#
# 关键特性：
#   - x = 0 时导数最大，为 0.25
#   - |x| 增大时导数迅速趋近于 0
#   - 在深层网络中，多层 sigmoid 的导数连乘会导致梯度指数级衰减
#     这就是经典的"梯度消失"问题

# --- 绘制 sigmoid 的导数曲线 ---
# .zero_(): 下划线后缀表示原地操作 (in-place)，直接修改原张量而不创建新张量
# x.grad.data.zero_(): 将 x 的梯度数据清零
# 因为之前调用 .backward() 时 x.grad 中已累积了 ReLU 的梯度，
# 现在要计算新的梯度，必须先清零
x.grad.data.zero_()
y.backward(torch.ones_like(x), retain_graph=True)
d2l.plot(x.detach(), x.grad, 'x', 'grad of sigmoid', figsize=(5, 2.5))


# ============================================================================
# 2.6  tanh 函数 (双曲正切)
# ============================================================================
# 数学定义：
#   tanh(x) = (1 - exp(-2x)) / (1 + exp(-2x))
#
# 也可以写成：
#   tanh(x) = 2 * sigmoid(2x) - 1
#
# 直观理解：
#   - 将任意实数 (-inf, +inf) 压缩到 (-1, 1) 区间
#   - x → +inf  时，tanh(x) → 1
#   - x → -inf  时，tanh(x) → -1
#   - x = 0     时，tanh(x) = 0
#
# 与 sigmoid 的对比：
#   - tanh 是零中心的（输出范围 -1 到 1），优化更稳定
#   - tanh 的形状与 sigmoid 相似，都是 S 形曲线
#   - tanh 的导数在 0 附近更大（最大值 1 vs 0.25）
#   - 同样存在梯度消失问题（|x| 大时导数趋近于 0）

# --- tanh 函数曲线 ---
# torch.tanh(x): 对每个元素应用双曲正切函数
y = torch.tanh(x)
d2l.plot(x.detach(), y.detach(), 'x', 'tanh(x)', figsize=(5, 2.5))


# ============================================================================
# 2.7  tanh 函数的导数
# ============================================================================
# tanh 的导数推导：
#   tanh(x) = sinh(x) / cosh(x) = (e^x - e^{-x}) / (e^x + e^{-x})
#
#   tanh'(x) = sech^2(x) = 1 - tanh^2(x)
#
# 关键特性：
#   - x = 0 时导数最大，为 1
#   - |x| 增大时导数趋近于 0（与 sigmoid 类似）
#   - 但由于输出范围是 (-1, 1) 且零中心，
#     在深层网络的早期层中，tanh 比 sigmoid 表现稍好

# --- 绘制 tanh 的导数曲线 ---
# 再次清零梯度，因为 x.grad 中仍保留着 sigmoid 的梯度
x.grad.data.zero_()
y.backward(torch.ones_like(x), retain_graph=True)
d2l.plot(x.detach(), x.grad, 'x', 'grad of tanh', figsize=(5, 2.5))


