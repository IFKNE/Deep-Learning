# ============================================================================
# 1. 多层感知机（MLP）在 softmax 回归的基础上增加了隐藏层和激活函数，
#    从而具备了学习非线性决策边界的能力。
#
# 2. PyTorch 的高级 API（nn.Sequential、nn.Linear、nn.ReLU）让我们可以
#    用不到 5 行代码搭建一个完整的 MLP。
#
# 3. 模型架构与训练流程解耦：
#    - 模型定义：决定网络的层数、宽度、激活函数
#    - 训练流程：损失函数、优化器、epoch 数保持不变
#    这种模块化设计便于快速实验和迭代。
#
# 4. 隐藏层 + 非线性激活函数 = 表达能力飞跃。
#    没有激活函数的多层网络等价于单层线性模型，激活函数是关键。
#
# 5. CrossEntropyLoss 内部已包含 Softmax，模型输出层无需再手动添加，
#    这是数值稳定性方面的最佳实践。
