"""
=============================================================================
多层感知机的简洁实现 —— 使用 PyTorch 高级 API（完整带注释版）
=============================================================================

本节对应《动手学深度学习》(d2l) 教材 sec_mlp_concise 章节。
与 softmax 回归的简洁实现相比，唯一的区别在于：
  - 添加了 2 个全连接层（之前只有 1 个输出层）
  - 第一层为隐藏层，包含 256 个隐藏单元，使用 ReLU 激活函数
  - 第二层为输出层，输出 10 个类别的预测分数

通过高级 API (nn.Sequential, nn.Linear, nn.ReLU 等)，我们可以用极少的代码
搭建一个多层感知机（MLP）模型。
"""

# ============================================================================
# 第1步：导入所需模块
# ============================================================================
import torch                          # PyTorch 深度学习框架核心库
from torch import nn                  # nn 模块：包含神经网络层、损失函数等构建组件
from d2l import torch as d2l          # d2l 工具包：《动手学深度学习》配套工具库


# ============================================================================
# 第2步：定义模型架构（使用 nn.Sequential 搭建多层感知机）
# ============================================================================

# nn.Sequential 是一个"顺序容器"：将多个网络层按顺序串联在一起，
# 数据会依次流过容器中的每一层，就像流水线一样。
# 这使得模型定义非常简洁，不需要手动编写 forward 函数。
net = nn.Sequential(
    # ----------------------------------------------------------------------
    # 第2.1层：nn.Flatten()
    #   作用：将输入的二维图像（批量, 通道, 高, 宽）展平为一维向量（批量, 特征数）
    #   输入形状：(batch_size, 1, 28, 28) — Fashion-MNIST 的 28x28 灰度图
    #   输出形状：(batch_size, 784)  — 28*28 = 784 个像素特征
    #   nn.Flatten() 默认从第 1 维开始展平（保留第 0 维 batch 维度不变）
    # ----------------------------------------------------------------------
    nn.Flatten(),

    # ----------------------------------------------------------------------
    # 第2.2层：nn.Linear(784, 256)
    #   全连接层（也叫线性层、Dense 层）：y = Wx + b
    #   参数说明：
    #     - 第一个参数 784：输入特征数（来自 Flatten 后的 784 个像素）
    #     - 第二个参数 256：输出特征数，即隐藏单元个数
    #   nn.Linear 内部自动创建可训练的参数矩阵 W (形状: [256, 784]) 和偏置 b (形状: [256])
    #   输入形状：(batch_size, 784)
    #   输出形状：(batch_size, 256)
    # ----------------------------------------------------------------------
    nn.Linear(784, 256),

    # ----------------------------------------------------------------------
    # 第2.3层：nn.ReLU()
    #   ReLU(Rectified Linear Unit) 激活函数：f(x) = max(0, x)
    #   作用：
    #     - 引入"非线性"：没有激活函数，多层线性层等价于单层线性层
    #     - 缓解梯度消失：相比 Sigmoid/Tanh，ReLU 在正区间梯度恒为 1
    #     - 计算简单高效：只需要判断是否大于 0
    #   注意：ReLU 没有可训练参数，只做逐元素的非线性变换
    #   输入/输出形状不变：(batch_size, 256)
    # ----------------------------------------------------------------------
    nn.ReLU(),

    # ----------------------------------------------------------------------
    # 第2.4层：nn.Linear(256, 10)
    #   输出层：将隐藏层的 256 维表示映射到 10 个类别
    #   参数说明：
    #     - 256：输入特征数（隐藏层输出的维度）
    #     - 10：输出特征数（Fashion-MNIST 的 10 个类别）
    #   注意：这里没有加 Softmax，因为后续的 nn.CrossEntropyLoss 内部会
    #         自动计算 softmax + 交叉熵（数值更稳定）
    #   输入形状：(batch_size, 256)
    #   输出形状：(batch_size, 10) — 每个样本对应 10 个类别的原始分数（logits）
    # ----------------------------------------------------------------------
    nn.Linear(256, 10)
)


# ============================================================================
# 第2步续：自定义权重初始化
# ============================================================================

def init_weights(m):
    """
    权重初始化函数，用于 net.apply() 对每个子模块进行回调。

    参数 m：网络中的每个子模块（nn.Flatten、nn.Linear、nn.ReLU 等）

    为什么需要自定义初始化？
      - 合理的初始权重有助于加速收敛、避免梯度消失/爆炸
      - 默认的 Kaiming 初始化（针对 ReLU）其实已经很好，这里展示自定义方法
    """
    # isinstance(m, nn.Linear) 也可以；这里用 type(m) == nn.Linear 做精确类型检查
    # type() 不会匹配子类，isinstance() 会匹配子类 —— 此处效果相同（我们没有子类化）
    if type(m) == nn.Linear:
        # ------------------------------------------------------------------
        # nn.init.normal_(m.weight, std=0.01)
        #   以正态分布 N(0, 0.01^2) 随机初始化权重矩阵
        #   注意末尾的 "_" 下划线：PyTorch 命名约定中，带 _ 后缀的方法表示"原地操作"
        #   即直接修改张量本身，而不是返回新张量
        #
        #   m.weight 形状：[输出维度, 输入维度]，即 (out_features, in_features)
        #     - 第一个全连接层：m.weight 形状 (256, 784)
        #     - 第二个全连接层：m.weight 形状 (10, 256)
        #   std=0.01：标准差设为 0.01（较小，避免初始激活值过大）
        #
        #   注意：这里没有初始化偏置 m.bias，PyTorch 默认会将 bias 初始化为 0
        # ------------------------------------------------------------------
        nn.init.normal_(m.weight, std=0.01)


# --------------------------------------------------------------------------
# net.apply(init_weights)
#   apply() 方法：对 net 中的每个子模块递归调用传入的函数
#   遍历顺序：从外到内、深度优先
#   在本例中，会依次调用：
#     init_weights(nn.Flatten)  → type(m) != nn.Linear → 不做操作
#     init_weights(nn.Linear(784, 256)) → 初始化权重
#     init_weights(nn.ReLU)     → type(m) != nn.Linear → 不做操作
#     init_weights(nn.Linear(256, 10))  → 初始化权重
#
#   分号 ";" 的作用：在一行中写多个语句（这里仅为了抑制 Jupyter 输出，无实际功能意义）
# --------------------------------------------------------------------------
net.apply(init_weights)  # 分号仅用于 notebook 环境中抑制输出打印


# ============================================================================
# 第3步：定义超参数、损失函数和优化器
# ============================================================================

# --- 超参数设置 ---
batch_size = 256   # 批量大小：每次迭代使用 256 个样本计算梯度
                   # 较大的 batch_size 梯度估计更稳定，但内存消耗更大
lr = 0.1           # 学习率 (Learning Rate)：控制参数更新的步长
                   # 太大→可能发散/震荡；太小→收敛过慢
num_epochs = 10    # 训练轮数：完整遍历数据集 10 次
                   # 适当的 epoch 数取决于数据集大小和模型复杂度

# --- 损失函数 ---
# nn.CrossEntropyLoss(reduction='none')
#   交叉熵损失函数：结合了 LogSoftmax 和 NLLLoss
#   输入要求：
#     - 模型输出：形状 (batch_size, num_classes)，包含原始分数（logits），不需要预先做 softmax
#     - 真实标签：形状 (batch_size,)，值为类别索引（0~9 的整数），不需要 one-hot 编码
#   reduction='none' 含义：
#     - 不对 batch 维度求平均/求和，返回每个样本的独立损失，形状 (batch_size,)
#     - d2l.train_ch3 内部会根据这个特性做进一步处理（如计算准确率时取均值）
#     - 选项：'mean'(默认, 求平均)，'sum'(求和)，'none'(不做归约)
loss = nn.CrossEntropyLoss(reduction='none')

# --- 优化器 ---
# torch.optim.SGD(net.parameters(), lr=lr)
#   SGD（随机梯度下降）优化器
#   参数说明：
#     - net.parameters()：获取网络中所有需要训练的参数
#       * net.parameters() 返回一个生成器，包含所有 requires_grad=True 的张量
#       * 具体包含：
#         - 第一个 Linear 层的 weight (256, 784) 和 bias (256)
#         - 第二个 Linear 层的 weight (10, 256) 和 bias (10)
#       * nn.Flatten 和 nn.ReLU 没有可训练参数，因此不在其中
#       * 这些参数在创建时就自动设置了 requires_grad=True（默认行为）
#     - lr=lr：学习率，这里传入 0.1
#   SGD 更新公式：w = w - lr * grad(w)
#     grad(w) 由反向传播自动计算（通过 loss.backward()）
trainer = torch.optim.SGD(net.parameters(), lr=lr)


# ============================================================================
# 第4步：加载数据并开始训练
# ============================================================================

# 加载 Fashion-MNIST 数据集
# d2l.load_data_fashion_mnist(batch_size) 封装了以下操作：
#   1. 下载/加载 Fashion-MNIST 数据集（如果本地没有则自动下载）
#   2. 将图片从 PIL Image 转换为 PyTorch Tensor，并将像素值归一化到 [0, 1]
#   3. 创建 DataLoader，按 batch_size 分组，支持多进程加载
# 返回值使用元组解包：两个变量同时赋值
#   train_iter：训练集迭代器，60000 张 28x28 灰度图
#   test_iter：  测试集迭代器，10000 张 28x28 灰度图
# 注意：这是 Python 的元组解包 (tuple unpacking) 语法
train_iter, test_iter = d2l.load_data_fashion_mnist(batch_size)

# d2l.train_ch3(net, train_iter, test_iter, loss, num_epochs, trainer)
#   d2l 封装的训练函数，内部执行完整的训练循环：
#     每个 epoch：
#       1. 将 net 设为训练模式 (net.train())
#       2. 遍历训练集，对每个 batch：
#          a. 前向传播：计算模型输出 net(X)
#          b. 计算损失：loss(net(X), y)
#          c. 反向传播：loss.backward() — 自动计算所有 requires_grad=True 的参数的梯度
#          d. 参数更新：trainer.step() — 按 SGD 公式更新参数
#          e. 梯度清零：trainer.zero_grad() — 避免梯度累积
#       3. 在测试集上评估准确率
#       4. 打印当前 epoch 的训练损失和测试准确率
#   train_ch3 会实时显示训练曲线图（训练损失 + 测试准确率）
d2l.train_ch3(net, train_iter, test_iter, loss, num_epochs, trainer)


