# --------------------------------------------------------------------------
# 1. 数值稳定性：为什么 CrossEntropyLoss 内部做 Softmax？
# --------------------------------------------------------------------------
# 如果在模型输出层加 nn.Softmax()，再计算交叉熵，会导致数值不稳定：
#   步骤1：计算 softmax = exp(logit) / sum(exp(logit))
#          → 当 logit 较大时，exp(logit) 可能溢出为 inf
#   步骤2：计算 log(softmax) → log(inf) = inf，导致损失为 NaN
#
# nn.CrossEntropyLoss 的做法（Log-Sum-Exp 技巧）：
#   将 softmax + log + NLL 合并为一步：
#     loss = -logit[y] + log(sum(exp(logit)))  # logit[y] 是正确类别的分数
#   利用 log(sum(exp(x))) = a + log(sum(exp(x-a))) （a 取 max(x)），
#   减去最大值后指数运算不会溢出，数值更稳定。
#   这就是为什么输出层不加 Softmax，而让损失函数内部处理的原因。

# --------------------------------------------------------------------------
# 2. 核心公式回顾
# --------------------------------------------------------------------------
# 多层感知机（一个隐藏层）的数学表达：
#
#   输入层：X ∈ R^(n × d)        # n 个样本，d 个特征（784 像素）
#   隐藏层：H = σ(X·W1 + b1)     # W1 ∈ R^(d × h)，b1 ∈ R^h
#         H ∈ R^(n × h)          # h = 256 个隐藏单元
#   输出层：O = H·W2 + b2        # W2 ∈ R^(h × q)，b2 ∈ R^q，q = 10 类
#
#   其中 σ 为激活函数（ReLU）：σ(x) = max(0, x)
#
#   如果没有 σ（即去掉 ReLU 层）：
#     O = (X·W1 + b1)·W2 + b2 = X·(W1·W2) + (b1·W2 + b2) = X·W' + b'
#     多层退化为单层！这就是为什么激活函数不可或缺。

# --------------------------------------------------------------------------
# 3. 训练流程总结
# --------------------------------------------------------------------------
# 完整的深度学习训练流程（5 步）：
#   (1) 定义模型  → nn.Sequential / 自定义 nn.Module
#   (2) 定义损失  → nn.CrossEntropyLoss / nn.MSELoss 等
#   (3) 定义优化器 → torch.optim.SGD / Adam 等
#   (4) 训练循环  → 前向传播 → 计算损失 → 反向传播 → 参数更新 → 梯度清零
#   (5) 验证评估  → 在测试集上计算准确率等指标
#
#   关键代码模板：
#     for X, y in train_iter:
#         l = loss(net(X), y)           # 前向 + 损失
#         trainer.zero_grad()           # 清零梯度（否则会累积）
#         l.mean().backward()           # 反向传播（计算梯度）
#         trainer.step()                # 更新参数

# --------------------------------------------------------------------------
# 4. 常见问题 / 练习提示
# --------------------------------------------------------------------------
# Q1: 尝试添加不同数量的隐藏层，怎样设置效果最好？
#     - 可以插入额外的 nn.Linear(h, h) + nn.ReLU() 对
#     - 层数不是越多越好：层数过深可能导致梯度消失、过拟合
#     - 对于 Fashion-MNIST，2~3 个隐藏层通常足够
#     - 学习率可能需要适当调小（如 0.01）来适应更深的网络
#
# Q2: 尝试不同的激活函数，哪个效果最好？
#     - nn.Sigmoid()：输出 [0,1]，但容易梯度饱和（两端梯度趋近 0）
#     - nn.Tanh()：输出 [-1,1]，零中心但仍有饱和问题
#     - nn.ReLU()：计算简单，但存在"死亡 ReLU"问题（负输入梯度为 0）
#     - nn.LeakyReLU(0.01)：给负输入一个小梯度，缓解死亡 ReLU
#     - nn.GELU()：近年流行，在 Transformer 等模型中广泛使用
#     - 对于 Fashion-MNIST，ReLU 系列通常表现不错
#
# Q3: 尝试不同的权重初始化方案：
#     - nn.init.xavier_uniform_()：适用于 Sigmoid/Tanh 激活
#     - nn.init.kaiming_uniform_()：适用于 ReLU 激活（PyTorch Linear 层默认）
#     - nn.init.normal_(std=0.01)：小标准差正态初始化（本例使用）
#     - 经验：ReLU 激活 → Kaiming 初始化通常最优
#     - 错误初始化（如全 0 或全 1）会导致对称性问题，网络无法学习
#
# Q4: 关键概念速查表
#     概念                 | 一句话解释
#     ---------------------|----------------------------------------------
#     nn.Sequential        | 层的有序容器，数据依次流过
#     nn.Flatten           | 将多维输入（如图像）展平为一维向量
#     nn.Linear            | 全连接层 y = Wx + b，自动管理可训练参数
#     nn.ReLU              | 非线性激活函数 max(0, x)
#     net.apply(fn)        | 对网络所有子模块递归调用函数 fn
#     nn.init.normal_      | 用正态分布初始化张量（_ 表示原地操作）
#     net.parameters()     | 返回网络中所有 requires_grad=True 的参数
#     requires_grad        | 张量属性，True 表示需要计算梯度
#     torch.optim.SGD      | 随机梯度下降优化器
#     nn.CrossEntropyLoss  | 交叉熵损失（内置 Softmax，数值稳定）
#     * 解包               | Python 语法：将可迭代对象展开为独立参数
#     isinstance/type      | 类型检查：isinstance 可匹配子类，type 精确匹配
#     with...as            | 上下文管理器：自动管理资源（如文件、梯度计算）
#     元组解包             | a, b = (x, y)，同时给多个变量赋值


