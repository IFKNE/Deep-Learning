"""
=============================================================================
多层感知机的从零开始实现 —— 单隐藏层MLP在Fashion-MNIST上的完整实现（带详细注释版）
=============================================================================

本文件对应于《动手学深度学习》第2版 sec_mlp_scratch 节。
手动实现一个具有单隐藏层（256个隐藏单元）的多层感知机，
在 Fashion-MNIST 图像分类数据集上训练并评估。

关键概念：
  - 多层感知机（MLP）：在输入层和输出层之间加入隐藏层，并使用非线性激活函数
  - ReLU激活函数：max(x, 0)，引入非线性，使网络能够学习复杂模式
  - nn.Parameter：将张量注册为模型可训练参数
  - 交叉熵损失：多分类任务的标准损失函数
"""

# ============================================================================
# 第1步：导入库和加载数据
# ============================================================================
import torch                                                         # PyTorch深度学习框架
from torch import nn                                                 # 神经网络模块，提供层、损失函数等
from d2l import torch as d2l                                         # 《动手学深度学习》配套工具包，封装了数据加载和训练循环

batch_size = 256                                                     # 批量大小：每次训练/测试使用256个样本
# d2l.load_data_fashion_mnist() 下载并加载Fashion-MNIST数据集
# 返回两个迭代器：(train_iter, test_iter)
# train_iter：训练数据迭代器，内含60000张28x28灰度图
# test_iter：测试数据迭代器，内含10000张28x28灰度图
# 内部已自动做了标准化：将像素值从[0,255]缩放到[0,1]
train_iter, test_iter = d2l.load_data_fashion_mnist(batch_size)
# 10个类别：T恤、裤子、套头衫、连衣裙、外套、凉鞋、衬衫、运动鞋、包、短靴

# ============================================================================
# 第2步：初始化模型参数
# ============================================================================
# --- 超参数定义 ---
num_inputs, num_outputs, num_hiddens = 784, 10, 256   # 输入特征数(28×28=784)，输出类别数(10)，隐藏单元数(256)
# 层宽度通常选2的幂次（如128、256、512），原因：
# 1. GPU/CPU 内存分配和寻址方式对2的幂次更友好
# 2. 矩阵运算库（如cuBLAS）在2的幂次维度上性能更优

# --- 第一层参数：输入层 → 隐藏层 ---
# nn.Parameter 将一个普通张量包装成"可训练参数"
#   - 被 nn.Parameter 包装的张量会自动添加到模型的 parameters() 列表中
#   - 优化器（如 SGD）会遍历所有 nn.Parameter 来更新参数
#   - 等效于普通张量设置 requires_grad=True，但会额外注册为模块参数
# torch.randn() 从标准正态分布 N(0,1) 采样，*0.01 缩小方差以稳定训练
# 参数形状：(784, 256) —— 每个输入特征连接到每个隐藏单元
# requires_grad=True：告诉PyTorch需要计算此张量相对于损失函数的梯度
#   - 前向传播时，PyTorch记录对该张量的所有操作，构建计算图
#   - 反向传播时，PyTorch沿计算图自动计算损失对该张量的梯度，存入 .grad 属性
W1 = nn.Parameter(torch.randn(
    num_inputs, num_hiddens, requires_grad=True) * 0.01)
# 偏置形状：(256,) —— 每个隐藏单元一个偏置，初始化为全零
b1 = nn.Parameter(torch.zeros(num_hiddens, requires_grad=True))

# --- 第二层参数：隐藏层 → 输出层 ---
# 参数形状：(256, 10) —— 每个隐藏单元连接到每个输出类别
W2 = nn.Parameter(torch.randn(
    num_hiddens, num_outputs, requires_grad=True) * 0.01)
# 偏置形状：(10,) —— 每个输出类别一个偏置
b2 = nn.Parameter(torch.zeros(num_outputs, requires_grad=True))

# 将所有可训练参数放入列表，便于统一管理和传给优化器
# 这里用列表（而非 nn.Module）手动管理参数，适合"从零实现"的教学场景
params = [W1, b1, W2, b2]

# ============================================================================
# 第3步：实现ReLU激活函数
# ============================================================================
def relu(X):
    """
    手动实现ReLU（Rectified Linear Unit，修正线性单元）激活函数

    公式：ReLU(x) = max(0, x)
      - 如果输入 x > 0，输出 x（保留正信号）
      - 如果输入 x <= 0，输出 0（抑制负信号）

    为什么需要激活函数？
      - 如果没有激活函数（或使用线性激活），多层线性变换等价于单层线性变换
      - 例如：H = X@W1 + b1, O = H@W2 + b2 → O = X@(W1@W2) + (b1@W2 + b2)
      - 即多层网络退化为单层，无法学习非线性模式
      - 激活函数打破线性链，使网络能够逼近任意复杂函数（万能逼近定理）

    为什么选择ReLU？
      - 计算简单：只需一个 max 操作，没有指数运算
      - 缓解梯度消失：正区域的梯度恒为1，不会像sigmoid那样梯度趋于0
      - 稀疏激活：负区域输出为0，使部分神经元"失活"，有助于特征筛选
    """
    a = torch.zeros_like(X)             # 创建与X形状相同的全零张量
    return torch.max(X, a)              # 逐元素取最大值，实现 max(0,x)

# ============================================================================
# 第4步：定义模型（前向传播）
# ============================================================================
def net(X):
    """
    多层感知机的前向传播函数

    网络结构：
      输入层(784) → 全连接 + ReLU → 隐藏层(256) → 全连接 → 输出层(10)

    参数形状流动（以批量大小256为例）：
      X:    (256, 1, 28, 28)    原始图像，通道=1（灰度），高=28，宽=28
      ↓   X.reshape((-1, num_inputs))
      X:    (256, 784)           展平为向量，-1表示自动推断该维度大小
      ↓   X @ W1 + b1
           矩阵乘法规则：(256,784) @ (784,256) → (256,256)，再广播加 (256,)
      H:    (256, 256)           隐藏层输出（ReLU激活前）
      ↓   relu(H)
      H:    (256, 256)           隐藏层激活后（负值被置为0）
      ↓   H @ W2 + b2
           (256,256) @ (256,10) → (256,10)，再广播加 (10,)
      O:    (256, 10)            输出层：每个样本对应10类的原始分数（logits）
    """
    # .reshape((-1, num_inputs)) 将每个二维图像展平为长度为784的一维向量
    # -1 是PyTorch的自动推断语法：根据总元素数和其它维度，自动计算该维度大小
    # 这里 -1 会推断为 batch_size（即256）
    X = X.reshape((-1, num_inputs))
    # @ 运算符表示矩阵乘法（Python 3.5+ 支持），等价于 torch.matmul()
    # 第一层：线性变换 + ReLU激活
    H = relu(X @ W1 + b1)           # 隐藏层输出 = ReLU(输入@权重 + 偏置)
    # 第二层：线性变换（输出层不使用激活函数，原始分数直接传给交叉熵损失）
    # nn.CrossEntropyLoss 内部会自动做 softmax，所以这里不需要手动加 softmax
    return (H @ W2 + b2)

# ============================================================================
# 第5步：定义损失函数
# ============================================================================
# nn.CrossEntropyLoss：交叉熵损失函数，专用于多分类任务
# 内部流程：先对预测分数做 softmax 转换为概率分布，再计算负对数似然
#   - softmax：将原始分数（logits）转换为概率（所有类别概率和为1）
#   - 负对数似然：对正确类别的概率取 -log，概率越高损失越低
#
# reduction='none' 的含义：
#   - 'none'：返回每个样本的独立损失，形状为 (batch_size,)
#   - 'mean'（默认）：返回所有样本损失的平均值（一个标量）
#   - 'sum'：  返回所有样本损失的总和（一个标量）
# 这里用 'none' 是因为 d2l.train_ch3 内部需要逐样本的损失来计算准确率
loss = nn.CrossEntropyLoss(reduction='none')

# ============================================================================
# 第6步：训练模型
# ============================================================================
# --- 超参数 ---
num_epochs, lr = 10, 0.1                     # 训练10轮，学习率0.1

# torch.optim.SGD：随机梯度下降优化器
# 工作流程：
#   1. 在每个batch后调用 optimizer.step() —— 根据梯度更新参数
#   2. 更新公式（无动量的标准SGD）：param = param - lr * param.grad
#   3. 更新前需调用 optimizer.zero_grad() 清除累积的旧梯度
# 这里传入 params 列表，优化器会跟踪所有 nn.Parameter 的 .grad 属性
updater = torch.optim.SGD(params, lr=lr)

# d2l.train_ch3：D2L封装的训练函数（适用于第三章的分类任务）
# 内部流程（每个epoch）：
#   1. 遍历 train_iter 中的每个batch
#   2. 前向传播：调用 net(X) 得到预测分数
#   3. 计算损失：loss(net(X), y)
#   4. 反向传播：l.mean().backward() → 计算所有参数梯度
#       - .backward()：从标量损失出发，沿计算图反向传播，自动计算每个 requires_grad=True
#          张量的梯度，结果存入各张量的 .grad 属性
#   5. 参数更新：updater.step() → 更新参数
#   6. 梯度清零：updater.zero_grad() → 将 .grad 置零
#       - 必须清零！PyTorch默认会累积梯度（.grad 是累加而非覆盖）
#       - 不清零会导致梯度越来越大，训练不稳定
#   7. 计算训练集和测试集的准确率并显示
d2l.train_ch3(net, train_iter, test_iter, loss, num_epochs, updater)

# ============================================================================
# 第7步：模型评估（可视化预测结果）
# ============================================================================
# d2l.predict_ch3：在测试数据上运行模型并可视化预测结果
# 会展示6张测试图像及其预测标签（正确=绿色，错误=红色）
# 用于直观检查模型的学习效果
d2l.predict_ch3(net, test_iter)

# ============================================================================
# 补充知识1：数值稳定性改进 —— 权重初始化详解
# ============================================================================
# 为什么用 randn * 0.01 而不是直接用 randn？
#
# 标准正态分布 N(0,1) 输出的值大部分在 [-3, 3] 范围内。
# 对于784个输入特征的加权和，方差会累积到约784（每个输入方差约1），
# 导致隐藏层激活值过大 → sigmoid/tanh饱和 → 梯度消失。
#
# 乘以0.01后，方差缩小为原来的 0.0001 倍，这在一定程度上缓解了问题，
# 但并非最优方案。现代实践中常用 Xavier 初始化：
#   W ~ U(-sqrt(6/(n_in + n_out)), sqrt(6/(n_in + n_out)))
#   或 Kaiming 初始化（专为ReLU设计）：
#   W ~ N(0, sqrt(2/n_in))
#
# 这里用 *0.01 是早期的一种简单启发式方法，适合浅层网络入门演示。

# ============================================================================
# 补充知识2：核心公式回顾
# ============================================================================
# 前向传播：
#   隐藏层（线性部分）：  Z₁ = X @ W₁ + b₁      # (N,784) @ (784,256) → (N,256)
#   隐藏层（激活后）：    H  = ReLU(Z₁) = max(0, Z₁)
#   输出层：              O  = H @ W₂ + b₂       # (N,256) @ (256,10) → (N,10)
#   概率分布：            P  = softmax(O)        # 由 CrossEntropyLoss 内部完成
#
# 损失函数（交叉熵）：
#   L = - (1/N) * Σᵢ log(Pᵢ[yᵢ])
#   其中 yᵢ 是第 i 个样本的真实类别索引
#
# 反向传播（链式法则）：
#   ∂L/∂W₂ = ∂L/∂O * ∂O/∂W₂ = (P - Y_onehot)ᵀ @ H    # 形状：(10,256)
#   ∂L/∂b₂ = ∂L/∂O * ∂O/∂b₂ = Σ(P - Y_onehot)         # 形状：(10,)
#   ∂L/∂W₁ = ∂L/∂H * ∂H/∂Z₁ * ∂Z₁/∂W₁                 # ReLU的梯度：>0时为1，≤0时为0
#            = [∂L/∂O @ W₂ᵀ ⊙ ReLU'(Z₁)]ᵀ @ X          # ⊙ 表示逐元素乘
#            = [∂L/∂H ⊙ (Z₁ > 0)]ᵀ @ X                 # ReLU'即 >0 的布尔掩码
#
# 参数更新：
#   W₁ = W₁ - lr * ∂L/∂W₁
#   b₁ = b₁ - lr * ∂L/∂b₁
#   W₂ = W₂ - lr * ∂L/∂W₂
#   b₂ = b₂ - lr * ∂L/∂b₂

# ============================================================================
# 补充知识3：训练流程总结 —— 标准PyTorch训练循环五步法
# ============================================================================
# for epoch in range(num_epochs):
#     for X, y in train_iter:              # 1. 取一个batch
#         y_hat = net(X)                    # 2. 前向传播：计算预测
#         l = loss(y_hat, y).mean()         # 3. 计算损失（取均值得到标量）
#         updater.zero_grad()               # 4a. 清零旧梯度（必须！否则梯度累积）
#         l.backward()                      # 4b. 反向传播：自动计算所有参数梯度
#         updater.step()                    # 5. 参数更新：沿负梯度方向移动一步
#
# 关键概念回顾：
#   - requires_grad=True：标记该张量需要在反向传播时计算梯度
#   - .backward()：从标量出发，沿计算图自动求导，梯度存入 .grad
#   - .grad：张量的梯度属性，.backward() 后的梯度值，初始为 None
#   - .zero_grad()：将梯度清零。PyTorch 默认累积梯度（.grad += 新梯度），
#     不清零会导致梯度越来越大，训练发散
#   - torch.no_grad()：上下文管理器，在其作用域内的操作不会被记录到计算图
#     常用于推理/评估阶段，节省内存和计算
#   - nn.Parameter：将张量注册为模块的可训练参数，自动出现在 net.parameters() 中
#   - net.parameters()：返回模型中所有 nn.Parameter 的迭代器
#   - net.apply(fn)：对模型中的每个子模块（递归地）应用函数 fn
#   - nn.init.normal_(tensor, mean, std)：将 tensor 原地（_ 后缀）填充为正态分布随机值
#   - nn.Sequential：容器模块，将多个子模块按顺序串联，输入依次通过每个子模块
#     net = nn.Sequential(nn.Linear(784,256), nn.ReLU(), nn.Linear(256,10))
#   - _ 后缀方法（如 .zero_(), .normal_()）：原地操作，直接修改原张量而不创建副本

# ============================================================================
# 补充知识4：Python语法要点
# ============================================================================
# 1. * 解包操作符：
#    - 函数调用中：func(*list) 将列表/元组的元素展开为位置参数
#      例：loss(*model_output) 等价于 loss(output, target)
#    - 赋值中：a, *b = [1,2,3,4] → a=1, b=[2,3,4]（收集剩余元素）
#
# 2. with...as 上下文管理器：
#    - with torch.no_grad(): 进入上下文时禁用梯度计算，退出时恢复
#    - 确保资源正确获取和释放，即使发生异常也会执行清理
#
# 3. 元组解包：
#    - for X, y in train_iter:  每次迭代，train_iter 返回一个 (data, label) 元组
#    - 直接用 X, y 接收，等效于：
#      batch = next(iter(train_iter)); X, y = batch[0], batch[1]
#
# 4. 列表推导式：
#    - [x**2 for x in range(10) if x % 2 == 0] → [0,4,16,36,64]
#    - 紧凑的循环+筛选+变换语法
#
# 5. lambda 表达式（匿名函数）：
#    - lambda x: x + 1  等效于  def f(x): return x + 1
#    - 常用于不需要命名的简单回调函数，如 net.apply(lambda m: init(m.weight))

# ============================================================================
# 常见问题 / 练习（对应原书练习）
# ============================================================================
#
# Q1: 更改 num_hiddens 对结果有何影响？
# A:  隐藏单元数太少 → 模型容量不足，欠拟合，训练/测试准确率都低
#     隐藏单元数太多 → 模型容量过大，可能过拟合（训练准确率高但测试准确率下降）
#     最佳值通常在 128~512 之间，需通过验证集调参确定
#
# Q2: 添加更多隐藏层会怎样？
# A:  深层网络理论上能学习更复杂的特征层次，但：
#     - 从零手动实现每层参数很繁琐（这就是为什么后续章节引入 nn.Module）
#     - 更深不一定更好：可能引发梯度消失/爆炸、过拟合
#     - Fashion-MNIST 任务简单，2~3层通常足够
#
# Q3: 学习率的影响？
# A:  太小 → 收敛慢，需要更多epoch
#     太大 → 训练震荡甚至发散，损失不降反升
#     典型搜索范围：[0.001, 0.003, 0.01, 0.03, 0.1, 0.3, 1.0]
#     通常通过对数尺度搜索找到最佳值
#
# Q4: 联合优化所有超参数？
# A:  网格搜索（Grid Search）：对所有超参数组合逐一实验，选出验证集性能最好的
#     随机搜索（Random Search）：随机采样组合，效率高于网格搜索（尤其在参数多时）
#     贝叶斯优化：基于之前的实验结果智能选择下一组参数
#
# Q5: 为什么多个超参数更具挑战性？
# A:  - 组合爆炸：n个超参数各有k个候选值 → k^n 种组合
#     - 参数间存在交互：最优学习率可能依赖隐藏层大小
#     - 评估成本高：每组参数都需要完整训练一次
#
# Q6: 聪明的搜索策略？
# A:  - 粗到细搜索：先用大范围、大步长找到大致区域，再在该区域精细搜索
#     - 坐标下降式：固定其他参数，依次优化每个超参数
#     - 贝叶斯优化（如 Optuna、Hyperopt库）：用概率模型指导搜索方向
#     - 学习率优先：学习率通常是影响最大的超参数，应优先调优

# ============================================================================
# 总结
# ============================================================================
# | 概念           | 说明                                              |
# | -------------- | ------------------------------------------------- |
# | 隐藏层         | 输入层和输出层之间的层，赋予网络学习非线性模式的能力  |
# | ReLU           | max(0,x)，计算高效，缓解梯度消失                   |
# | nn.Parameter   | 将张量注册为可训练参数，优化器自动跟踪和更新         |
