# ============================================================================
# 1. 本节无代码，是一份纯粹的 BPTT 理论推导笔记，用"简化记号"和"严谨矩阵记号"两条线讲清。
# 2. BPTT = 把 RNN 按时间展开成长计算图，再做反向传播；难点在"共享权重 w_h / W_hh"。
# 3. 共享权重的梯度 = 所有时间步"局部梯度之和"，每个局部梯度都要穿过"往未来连乘"的长路径。
# 4. Γ_连乘既是计算量的大头，也是数值不稳定的根源：矩阵高次幂 → 梯度爆炸 / 梯度消失。
# 5. 三种处理策略：完全计算（不可行的慢、易爆）、截断时间步（实用、偏短期、自带正则）、
#    随机截断（期望无偏、理论漂亮但实际未必更优）。
# 6. 实践结论：用"截断 BPTT"（如每 35 步截断一次、每 5 步重新初始化/分离隐状态）来加速训练，
#    这是兼顾速度、稳定性与"短范围交互偏好"的工程折中。
