# 核心公式回顾
# ============================================================================
# RNN 前向（无偏置 + 恒等激活的最简形式）：
#   h_t = W_hx * x_t + W_hh * h_{t-1}， o_t = W_qh * h_t
# 损失（对 T 个时间步平均）：
#   L = (1/T) * Σ_{t=1}^{T} l(o_t, y_t)
# 对输出的导数：
#   ∂L/∂o_t = ∂l(o_t, y_t) / (T * ∂o_t)
# 对输出层权重：
#   ∂L/∂W_qh = Σ_{t=1}^{T} (∂L/∂o_t) * h_t^T
# 末步隐状态梯度：
#   ∂L/∂h_T = W_qh^T * ∂L/∂o_T
# 隐状态递归梯度（t < T 关键）：
#   ∂L/∂h_t = W_hh^T * ∂L/∂h_{t+1} + W_qh^T * ∂L/∂o_t
# 递推展开为闭式：
#   ∂L/∂h_t = Σ_{i=t}^{T} (W_hh^T)^{T-i} * W_qh^T * ∂L/∂o_{T+t-i}
# 对隐藏层权重（共享权重，各时间步求和）：
#   ∂L/∂W_hx = Σ_{t=1}^{T} (∂L/∂h_t) * x_t^T
#   ∂L/∂W_hh = Σ_{t=1}^{T} (∂L/∂h_t) * h_{t-1}^T
#   矩阵连乘写法：
#     ∂L/∂W_hh = Σ_{t=1}^{T} [ ∂L/∂O_T * ∂O_T/∂H_T * (Π_{k=t+1}^{T} ∂H_k/∂H_{k-1}) * ∂H_t/∂W_hh ]
# 简化记号（思想版）：
#   ∂h_t/∂w_h = ∂f/∂w_h + Σ_{i=1}^{t-1} ( Π_{j=i+1}^{t} ∂f/∂h_{j-1} ) * ∂f(x_i,...)/∂w_h
# 随机截断（期望无偏）：
#   z_t = ∂f/∂w_h + ξ_t * (∂f/∂h_{t-1}) * ∂h_{t-1}/∂w_h， E[z_t] = ∂h_t/∂w_h
#   其中 P(ξ_t = 0) = 1 - π_t， P(ξ_t = π_t^{-1}) = π_t， E[ξ_t] = 1

