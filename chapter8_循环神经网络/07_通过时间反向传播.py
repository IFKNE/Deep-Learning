# ============================================================================
# 循环神经网络的梯度分析
# ============================================================================
# 这一节用"最简化的记号"把 BPTT 的核心思想讲清楚。
# 为了不让符号分散注意力，作者故意不严格区分标量 / 向量 / 矩阵，
# 先用最朴素的写法说明"问题出在哪"，下一节再给出严谨的矩阵版本。

# 简化模型（忽略隐状态内部结构的细节）:
#   时间步 t 的隐状态  h_t = f(x_t, h_{t-1}, w_h)     <- 由当前输入 x_t、上一时刻隐状态 h_{t-1}
#                                                         以及隐藏层共享权重 w_h 一起决定
#   时间步 t 的输出    o_t = g(h_t, w_o)              <- 由当前隐状态 h_t 和输出层权重 w_o 决定
#   其中 f 是隐藏层变换，g 是输出层变换。
#   注意 w_h 在每一个时间步都是同一个（共享参数），这正是 RNN 与普通 MLP 的本质区别。

# 于是我们有了一个链式依赖：
#   {..., (x_{t-1}, h_{t-1}, o_{t-1}), (x_t, h_t, o_t), ...}
#   相邻三元组之间通过"循环计算"彼此依赖——h_t 依赖 h_{t-1}，h_{t-1} 依赖 h_{t-2}……
#   前向传播很简单：一次一个时间步地扫过这些三元组即可。

# 目标函数：在所有 T 个时间步上评估输出 o_t 与真实标签 y_t 的差异，取平均：
#   L(x_1,...,x_T, y_1,...,y_T, w_h, w_o) = (1/T) * Σ_{t=1}^{T} l(y_t, o_t)
#     l(y_t, o_t) 是第 t 步的损失（如交叉熵），除以 T 得到整个序列的平均损失。

# ---- 核心难点：L 对共享权重 w_h 的梯度 ----
# 前向容易，反向就麻烦了，尤其是"目标函数 L 对隐藏层共享权重 w_h 的梯度"：
#   ∂L/∂w_h = (1/T) * Σ_{t=1}^{T} ∂l(y_t, o_t)/∂w_h
#           = (1/T) * Σ_{t=1}^{T} [ ∂l(y_t, o_t)/∂o_t * ∂g(h_t, w_o)/∂h_t * ∂h_t/∂w_h ]
#   这个乘积里的第一项、第二项都很容易算；
#   麻烦的是第三项 ∂h_t/∂w_h —— 因为 w_h 对 h_t 的影响是"循环"的：
#     h_t 既依赖 h_{t-1}，又依赖 w_h；而 h_{t-1} 的计算里同样用了 w_h。
#   所以 w_h"间接穿过"了从 t 之前所有时间步的路径。

# 用链式法则展开这个循环依赖，得到递推式：
#   ∂h_t/∂w_h = ∂f(x_t, h_{t-1}, w_h)/∂w_h
#             + ∂f(x_t, h_{t-1}, w_h)/∂h_{t-1} * ∂h_{t-1}/∂w_h
#   读法：w_h 对 h_t 的影响分成两条支路：
#     (a) 直接支路 —— w_h 在当前步直接影响 f 的输入；
#     (b) 间接支路 —— w_h 先影响 h_{t-1}，再由 h_{t-1} 传导到 h_t（这条又递归）。
#   这就是"循环"之处：要算 ∂h_t/∂w_h，又得先知道 ∂h_{t-1}/∂w_h。

# ---- 用三个子序列把上面的递推"解构"成可展开的闭式 ----
# 假设有三个序列 {a_t}, {b_t}, {c_t}，满足 a_0 = 0，且 a_t = b_t + c_t * a_{t-1}。
# 对 t >= 1 反复代入，可以得到：
#   a_t = b_t + Σ_{i=1}^{t-1} ( Π_{j=i+1}^{t} c_j ) * b_i
#   即"当前项 = 当前直接项 b_t，加上所有更早的直接项 b_i 乘上它们到 t 的连乘传递系数"。

# 我们把三个占位符替换成真实梯度：
#   a_t = ∂h_t/∂w_h                         （我们要算的）
#   b_i = ∂f(x_i, h_{i-1}, w_h)/∂w_h        （第 i 步 w_h 的直接贡献）
#   c_j = ∂f(x_j, h_{j-1}, w_h)/∂h_{j-1}    （第 j 步隐状态对隐状态的传递系数）
# 代入后，去掉递推中的"循环调用"，得到 ∂h_t/∂w_h 的展开式：
#   ∂h_t/∂w_h = ∂f(x_t, h_{t-1}, w_h)/∂w_h
#             + Σ_{i=1}^{t-1} ( Π_{j=i+1}^{t} ∂f(x_j, h_{j-1}, w_h)/∂h_{j-1} ) * ∂f(x_i, h_{i-1}, w_h)/∂w_h

# ---- 直觉：这串公式在说什么 ----
#   它把"循环依赖"展开成了"从任意过去时间步 i 出发、一路连乘传递到当前步 t"的求和。
#   中间那根"连乘" Π_{j=i+1}^{t} ∂h_j/∂h_{j-1} 是问题所在：
#     递推距离 t - i 越长，参与的因子越多，连乘就越容易出问题。
#   虽然可以用链式法则递归地算 ∂h_t/∂w_h，但当 t 很大时这条"链"会长到吓人。
#   必须想办法缓解，接下来的三个小节给出三种取舍。

# ----------------------------------------------------------------------------
# 完全计算（Completely Computed BPTT）
# ----------------------------------------------------------------------------
# 最直接的想法：把上面展开式里的"全部总和"老老实实全部算完。
#   结论：非常缓慢，而且很可能梯度爆炸。
#     原因：初始条件的微小变化，经过漫长连乘会放大成结果上的巨大差异，
#           也就是"蝴蝶效应"——输入稍变，输出就天翻地覆。
#   对一个我们想用来"泛化稳定模型"的估计器来说，这种敏感是不可接受的。
#   因此：实践中几乎从不使用完整的 BPTT（当序列很长时既慢又数值危险）。

# ----------------------------------------------------------------------------
# 截断时间步（Truncated BPTT）
# ----------------------------------------------------------------------------
# 替代方案：在算展开式时，走到 τ 步就"切断"求和，不让递归无限蔓延。
#   做法：把求和终止在 ∂h_{t-τ}/∂w_h 处（只回头 τ 步），把更远的路径忽略掉。
#   这正是前面 RNN 从零实现里"在序列上调用 detach / 分离梯度"在做的事。
#   代价：得到的是真实梯度的"近似"，不是精确值。
#   好处：模型会主要关注"短期影响"，而不是被过远的长期依赖拖累；
#         这在现实中常常是种优点——它把估计值偏向"更简单、更稳定"的模型。
#   注意：这个"每一步截断回头 τ 步"的做法，也就是常说的**截断的通过时间反向传播**。

# ----------------------------------------------------------------------------
# 随机截断（Randomized Truncation）
# ----------------------------------------------------------------------------
# 第三种思路：用一个"随机变量"去替换 ∂h_t/∂w_h。
#   要求：这个随机变量在"期望"意义上是正确的，但会截断序列。
#   实现：引入随机序列 ξ_t，预先给定一组概率 0 <= π_t <= 1：
#       P(ξ_t = 0)         = 1 - π_t      （以 1-π_t 的概率，直接截断，不再往下传）
#       P(ξ_t = π_t^{-1})  = π_t          （以 π_t 的概率，把尺度放大 1/π_t 再往下传）
#       从而 E[ξ_t] = 1（期望为 1，保证"平均意义的正确性"）。
#   用它替换 ∂h_t/∂w_h 的递推式，得到：
#       z_t = ∂f(x_t, h_{t-1}, w_h)/∂w_h
#           + ξ_t * ∂f(x_t, h_{t-1}, w_h)/∂h_{t-1} * ∂h_{t-1}/∂w_h
#   由 ξ_t 的定义可证 E[z_t] = ∂h_t/∂w_h（无偏！）。
#   直观理解：每当 ξ_t = 0，递归就在这个时间步 t 戛然而止（截断）；
#             这样一来，不同长度的"片段"会被加权求和。
#             长片段出现的概率低，但只要出现（ξ_t = π_t^{-1}）就被放大 1/π_t，
#             于是期望上等价于"完整的真实梯度"，这就是它在理论上吸引人的地方。

# ----------------------------------------------------------------------------
# 比较策略（以《时间机器》前若干字符、t=4、T=35 为例）
# ----------------------------------------------------------------------------
# 教材用一张图对比了"在 t=4 时刻、总步数 T=35"时，几种不同做法的梯度量级：
#   第一行 · 随机截断： 把文本切成长度不等的片段，在几个不同位置估算梯度。
#                       从图上看，它的梯度量级随 t 的时间步变化，靠近几个截断点附近
#                       与真实梯度大致贴合，但因为只有少数几个"跳跃点"，显得比较稀疏。
#   第二行 · 常规截断： 把文本切成等长子序列，每走一段就重新从该处算（这就是我们
#                       在 RNN 实验里一直在做的），梯度呈现周期性的"阶梯"形态。
#   第三行 · 完整计算： 不做任何截断，理论上最"精确"，但代价是表达式在计算上不可行
#                       （序列一长，连乘项多到没法算，而且数值极不稳定）。
#   （对比时通常还隐性参照"真实梯度"，作为四条线的参照系。）

# 为什么随机截断在实际中未必更优：
#   1. 对过去若干时间步做反向传播后，观测到的"依赖关系"已经足以被捕获，
#      再多回头几步收益有限，反而增加计算。
#   2. 随机截断引入的方差会抵消"时间步越多、梯度越精确"的好处。
#   3. 我们真正想要的往往是"短范围交互"的模型；
#      而截断 BPTT 自带的"轻度正则化"恰好能诱导出这种更稳定的模型。
#   综合这三条，实践中常规截断往往已经够用，随机截断更多是理论上的漂亮结果。

# ============================================================================
# 通过时间反向传播的细节
# ============================================================================
# 上一节用"简化记号"讲清了思想；这一节换回严谨的矩阵记号，
# 推导"目标函数对每一个分解参数"的梯度。为保持简单，本节假设：
#   - 无偏置参数（b 都省了）；
#   - 隐藏层激活函数用恒等映射 φ(x) = x（把非线性去掉，纯线性，便于看清矩阵结构）。
# 对时间步 t，设单个样本输入 x_t ∈ R^d，标签 y_t，隐状态 h_t ∈ R^h，输出 o_t ∈ R^q：
#   h_t = W_hx * x_t + W_hh * h_{t-1}        <- W_hx ∈ R^{h×d}，W_hh ∈ R^{h×h}
#   o_t = W_qh * h_t                          <- W_qh ∈ R^{q×h}
# 其中 W_hx 是"输入到隐藏"，W_hh 是"隐藏到隐藏"（共享循环权重），W_qh 是"隐藏到输出"。
# 目标函数的总体损失（对所有 T 个时间步取平均）：
#   L = (1/T) * Σ_{t=1}^{T} l(o_t, y_t)

# 训练需要这三组参数的梯度：∂L/∂W_hx、∂L/∂W_hh、∂L/∂W_qh。
# 依据计算图，沿着"箭头的反方向"遍历即可依次算出并存储梯度。
# 为表示不同形状的矩阵/向量/标量乘法的灵活性，我们沿用 prod() 这个"占位乘法算子"
# （prod(a, b) 表示按链式法则把相邻梯度，以适配各自形状的方式相乘，等价于矩阵乘法）。

# ---- 第 1 步：目标函数对输出 o_t 的微分 ----
# 任意时间步 t，这是最简单的：
#   ∂L/∂o_t = (∂l(o_t, y_t)) / (T * ∂o_t) ∈ R^q
#   注意多了一个 T：因为 L = (1/T)Σ l，对 o_t 求偏导时只有第 t 项存活，且要除以 T。

# ---- 第 2 步：目标函数对输出层权重 W_qh 的梯度 ----
# L 通过 o_1, ..., o_T 依赖 W_qh（o_t = W_qh h_t），所以把所有时间步的贡献求和：
#   ∂L/∂W_qh = Σ_{t=1}^{T} prod( ∂L/∂o_t, ∂o_t/∂W_qh )
#            = Σ_{t=1}^{T} (∂L/∂o_t) * h_t^T            ∈ R^{q×h}
#   推导要点：∂o_t/∂W_qh 这一项，因为 o_t = W_qh h_t 是线性，贡献就是 h_t；
#             写成 (∂L/∂o_t) h_t^T 正好堆出一个 q×h 的外积求和。

# ---- 第 3 步：最后一步的隐状态梯度 ∂L/∂h_T ----
# 在最后时间步 T，L 只通过 o_T 依赖 h_T（再没有 h_{T+1} 了），所以链式法则很简单：
#   ∂L/∂h_T = prod( ∂L/∂o_T, ∂o_T/∂h_T ) = W_qh^T * ∂L/∂o_T      ∈ R^h
#   推导要点：∂o_T/∂h_T = W_qh，所以转置后是 W_qh^T。

# ---- 第 4 步：任意中间步的隐状态梯度 ∂L/∂h_t（t < T 的关键） ----
# 对 t < T，L 同时通过两条路依赖 h_t：
#   (a) 经由 h_{t+1}：h_t 通过 W_hh 影响 h_{t+1}，进而影响后面；   <- "回头看"的路径
#   (b) 经由 o_t：    h_t 直接影响当前输出 o_t。                   <- "立刻显现"的路径
# 所以递推式为（这是 BPTT 的核心递推）：
#   ∂L/∂h_t = prod( ∂L/∂h_{t+1}, ∂h_{t+1}/∂h_t ) + prod( ∂L/∂o_t, ∂o_t/∂h_t )
#           = W_hh^T * ∂L/∂h_{t+1} + W_qh^T * ∂L/∂o_t             ∈ R^h
#   推导要点：∂h_{t+1}/∂h_t = W_hh（线性），∂o_t/∂h_t = W_qh（线性），均需转置对齐维度。

# ---- 第 5 步：把递推展开成闭式 ----
# 对任意 1 <= t <= T，反复代入上式、把递推完全展开（消去所有 h_{t+1}），得到：
#   ∂L/∂h_t = Σ_{i=t}^{T} (W_hh^T)^{T-i} * W_qh^T * ∂L/∂o_{T+t-i}
#   这个式子把"梯度从时间步 t 向未来传播"的过程写成了 W_hh^T 的幂次求和。

# ---- 关键洞察：W_hh^T 的高次幂 = 数值不稳定的根源 ----
#   从上式可以清楚地看到，∂L/∂h_t 陷入到 (W_hh^T) 的"潜在非常大的幂"里：
#     矩阵 W_hh 的特征值决定了它若干次幂后的走向：
#       - 特征值小于 1：高次幂后慢慢趋向 0  → **梯度消失**（早期的信息传不回来）；
#       - 特征值大于 1：高次幂后指数级放大 → **梯度爆炸**（梯度大得无法训练）。
#   这正是长序列模型的两大顽疾。解决思路之一就是按需"截断时间步"，
#   即给定步数后把梯度 detach（分离）下来，不继续往回传 —— 前面小节已详述。
#   后续更复杂的序列模型（如 LSTM）会用门控机制进一步缓解"梯度消失"。

# ---- 第 6 步：目标函数对隐藏层权重 W_hx、W_hh 的梯度 ----
# L 通过 h_1, ..., h_T 依赖 W_hx 和 W_hh（h_t 由它们决定），所以同样对所有时间步求和：
#   ∂L/∂W_hx = Σ_{t=1}^{T} prod( ∂L/∂h_t, ∂h_t/∂W_hx ) = Σ_{t=1}^{T} (∂L/∂h_t) * x_t^T    ∈ R^{h×d}
#   ∂L/∂W_hh = Σ_{t=1}^{T} prod( ∂L/∂h_t, ∂h_t/∂W_hh ) = Σ_{t=1}^{T} (∂L/∂h_t) * h_{t-1}^T  ∈ R^{h×h}
#   推导要点：h_t = W_hx x_t + W_hh h_{t-1} 是线性，所以 ∂h_t/∂W_hx 贡献 x_t，∂h_t/∂W_hh 贡献 h_{t-1}。
#   特别地，∂L/∂h_t 是由上面第 3、4 步递推算出来的，是整个推导里决定数值稳定性的关键量。

# ---- 补充：用矩阵乘法把"共享权重"的梯度写清楚 ----
# 把上面"对所有时间步求和"的思想，换一种更贴合任务要求的写法：
# 共享权重 W_hh（同理 W_xh = W_hx）的梯度 = 各时间步"局部梯度之和"，
# 其中每个时间步的局部梯度，都要把前面所有时间步的隐状态一路连乘传过来：
#   ∂L/∂W_hh = Σ_{t=1}^{T} [ ∂L/∂O_T * ∂O_T/∂H_T
#                             * ( Π_{k=t+1}^{T} ∂H_k/∂H_{k-1} ) * ∂H_t/∂W_hh ]
#   读法：
#     乘积中从右往左读：∂H_t/∂W_hh 是第 t 步的局部门派；
#     Π_{k=t+1}^{T} ∂H_k/∂H_{k-1} 是"从 t 一路递推到 T"的连乘传递（每个因子都是 ∂H_k/∂H_{k-1} = W_hh 的转置）；
#     ∂O_T/∂H_T 把隐状态映射到最终输出；∂L/∂O_T 是最终输出处的损失梯度。
#   之所以能"把所有时间步加起来"，正是因为 W_hh 是共享的：同一个参数出现在每一个时间步，
#   所以它的总梯度 = 它每次出现时的那条路径梯度之和（这正是"对共享参数求导 = 各局部位点贡献之和"）。

