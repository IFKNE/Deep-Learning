# 1. 梯度截断的两种常用落地方式
#    - 按时间步截断（Truncated BPTT）：每走固定步数就 detach，切断往回传的路径。
#      这就是本节"截断时间步"的实际代码形态。
#    - 按梯度的范数裁剪（Gradient Clipping）：当梯度的 L2 范数超过阈值（如 clip_theta）
#      就按比例缩放梯度，避免某一步算出爆炸的梯度毁掉整次更新。RNN 从零实现里用的是这种。
# 2. 为什么 detach() 能实现"截断"？
#    detach 把张量从计算图里"摘出来"，后续对它求梯度时，梯度不会继续沿这条边往回传，
#    等价于在计算图里"切一刀"，从而把 BPTT 的连乘链在某处砍断。
# 3. 符号对照（本节的 w_h/w_o 与 W_hh/W_qh）
#    - 简化分析用的是小写标量/向量记号 w_h（隐藏层）、w_o（输出层），重在"讲清思想"；
#    - 细节推导用的是大写矩阵记号 W_hx / W_hh / W_qh，重在"给出严格可算的梯度"。
#    - W_hh 正是 RNN 里唯一的"循环共享权重"，也是梯度爆炸/消失的源头。
# 4. "对共享参数求导 = 各使用点梯度和"的直觉
#    在普通 MLP 里，每个权重只用一次；RNN 里同一个 W_hh 被 T 次使用，
#    每个时间步都有一条"从该时刻到最终损失"的梯度路径。求总梯度就是把这 T 条路全部加总。
# 5. 梯度爆炸/消失的现实意义
#    梯度消失：早期时间步的信息无法传回，RNN 记不住长距离依赖（这也是 LSTM 诞生的动因）；
#    梯度爆炸：梯度数值过大，更新震荡、甚至溢出 NaN。二者都来自 W_hh 的高次幂。

