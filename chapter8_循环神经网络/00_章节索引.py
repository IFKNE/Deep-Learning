# ============================================================================
# 4. 循环神经网络
#    源文件: rnn.ipynb
#    目标文件: 04_循环神经网络.py
# ----------------------------------------------------------------------------
#  内容要点:
#    - 无隐状态的神经网络：把序列前若干项拼起来喂给 MLP
#    - 有隐状态的循环神经网络：隐状态 H_t 同时依赖当前输入 X_t 与上一步
#      隐状态 H_{t-1}，形成"记忆"，且各时间步共享参数
#      H_t = φ(X_t W_xh + H_{t-1} W_hh + b_h)
#    - 基于 RNN 的字符级语言模型：输入序列 vs 输出序列错开一个字符
#    - 困惑度（Perplexity）：e^{交叉熵}，1 为完美、∞ 为全错
#  学习目标:
#    彻底理解 RNN 隐状态的递归公式与权重共享的含义
#  前置知识:
#    MLP、激活函数、矩阵乘法、语言模型概率
#  学习建议:
#    亲手验证 X W_xh + H W_hh = [X, H] [W_xh; W_hh] 的拼接等价写法
# ============================================================================

