# 7. 通过时间反向传播（BPTT）
#    源文件: bptt.ipynb
#    目标文件: 07_通过时间反向传播.py
# ----------------------------------------------------------------------------
#  内容要点:
#    - RNN 梯度 = 各时间步局部梯度之和，且含连乘项 Π ∂H_k/∂H_{k-1}
#    - 完全计算（完整 BPTT）：计算量大且连乘导致数值不稳（爆炸/消失）
#    - 截断时间步：在 tau 步处切断计算图，只近似反传有限步
#    - 随机截断：按概率切断，期望上等于真实梯度
#    - 比较四种策略的梯度量级，说明实践中用"截断 BPTT"
#  学习目标:
#    理解 BPTT 的推导与三类近似方法，解释 RNN 难训练的原因
#  前置知识:
#    链式法则/雅可比矩阵连乘、RNN 前向与反向过程
#  学习建议:
#    重点看懂"连乘→梯度爆炸/消失"的一步，这是 LSTM/GRU 诞生的动机
# ============================================================================

