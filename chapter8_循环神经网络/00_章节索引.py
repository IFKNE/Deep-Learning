# ============================================================================
# 1. 序列模型
#    源文件: sequence.ipynb
#    目标文件: 01_序列模型.py
# ----------------------------------------------------------------------------
#  内容要点:
#    - 序列数据无处不在（股票、文本、语音），预测 x_t 依赖历史 x_1..x_{t-1}
#    - 自回归模型：用前 tau 个观测预测当前值（f(x_{t-1},...,x_{t-tau})）
#    - 马尔可夫假设：只保留最近几步，把依赖截断成有限阶
#    - 用正弦 + 噪声合成序列数据，训练 MLP 做一步预测
#    - 单步预测 vs 多步（k 步）预测：误差随步数累积、预测迅速退化
#  学习目标:
#    理解为什么"多步预测难"，以及自回归/马尔可夫建模的基本思想
#  前置知识:
#    线性回归、多层感知机、小批量梯度下降
#  学习建议:
#    亲手对比 tau 取不同值、不同步数的预测曲线，直观体会累积误差
# ============================================================================

