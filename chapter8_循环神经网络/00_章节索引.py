#    - 词表 Vocab：token ↔ 索引双向映射，处理未知词 <unk> 与填充 <pad>
#    - 整合为 load_corpus_time_machine：直接产出"字符级"语料
#  学习目标:
#    掌握 NLP 任务前最基础的数据预处理步骤
#  前置知识:
#    Python 集合/字典/列表推导式
#  学习建议:
#    弄清楚词表"按字符"和"按词"两种粒度的取舍
