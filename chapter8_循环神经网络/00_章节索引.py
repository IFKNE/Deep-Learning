# 3. 语言模型和数据集
#    源文件: language-models-and-dataset.ipynb
#    目标文件: 03_语言模型和数据集.py
# ----------------------------------------------------------------------------
#  内容要点:
#    - 语言模型 = 估计词序列概率 P(x_1,...,x_T)，用链式法则展开
#    - 马尔可夫模型与 n 元语法：用最近 n-1 个词近似条件概率
#    - 自然语言统计：一元/二元/三元词频呈长尾分布（Zipf 定律现象）
#    - 随机采样 vs 顺序分区：两种从长语料切出 (特征 X, 标签 Y) 小批量的方式
#    - SeqDataLoader 与 load_data_time_machine 整合加载器
#  学习目标:
#    理解语言模型的概率定义，掌握 RNN 训练数据的两种取法及其差异
#  前置知识:
