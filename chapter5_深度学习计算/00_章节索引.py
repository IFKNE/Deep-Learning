# ============================================================================
# 1. 层和块
#    源文件: model-construction.ipynb (slides版本)
#    目标文件: 01_层和块.py
# ----------------------------------------------------------------------------
#  内容要点:
#    - nn.Module 作为所有网络模块的基类
#    - nn.Sequential 的有序层容器机制
#    - 自定义块：继承 nn.Module 并重写 __init__ 和 forward
#    - 手动实现 MySequential 理解内部 _modules 字典
#    - 在 forward 中编写任意 Python 控制流代码（动态计算图）
#    - 块的嵌套与组合（NestMLP, chimera）
#  学习目标:
#    深刻理解 nn.Module 的设计模式，能自如地继承和组合模块来搭建任意网络结构。
#  前置知识:
#    多层感知机基础（第4章）、Python 类与继承的基本概念
#  学习建议:
#    动手实现一个 MySequential，对比 nn.Sequential 的源码理解其实现原理。
# ============================================================================

# ============================================================================
# 2. 参数管理
#    源文件: parameters.ipynb (slides版本)
#    目标文件: 02_参数管理.py
# ----------------------------------------------------------------------------
#  内容要点:
#    - 通过 state_dict() 和 named_parameters() 访问模型参数
#    - Parameter 对象与普通 Tensor 的区别
#    - net.apply(fn) 递归初始化所有子模块
#    - 内置初始化方法：正态、常数、Xavier
#    - 对不同子模块应用不同的初始化策略
#    - 自定义初始化：稀疏初始化等技巧
#    - 参数绑定：多个层共享同一组权重
#  学习目标:
#    掌握模型参数的全生命周期管理，能灵活定制初始化策略。
#  前置知识:
#    第 1 节（nn.Module 结构）、基本的概率统计知识
#  学习建议:
#    重点理解 .apply() 的递归机制和参数绑定的实际应用场景（如孪生网络）。
# ============================================================================

# ============================================================================
# 3. 自定义层
#    源文件: custom-layer.ipynb (slides版本)
#    目标文件: 03_自定义层.py
# ----------------------------------------------------------------------------
#  内容要点:
#    - 无参数自定义层（如 CenteredLayer：输入减均值）
#    - 带参数自定义层（如 MyLinear：手动实现 Linear）
#    - nn.Parameter 的作用：将张量标记为可学习参数
#    - 自定义层与 Sequential 的无缝集成
#  学习目标:
#    能够根据需求独立设计和实现任意功能的网络层。
#  前置知识:
#    第 1 节（nn.Module）、第 2 节（参数管理）
#  学习建议:
#    尝试实现一个自定义的 Dropout 层或 BatchNorm 层来加深理解。
# ============================================================================

# ============================================================================
# 4. 读写文件
#    源文件: read-write.ipynb (slides版本)
#    目标文件: 04_读写文件.py
# ----------------------------------------------------------------------------
#  内容要点:
#    - torch.save() / torch.load() 序列化 Python/PyTorch 对象
#    - 保存和加载张量、张量列表、字典
#    - 保存和加载模型参数（state_dict 方式）
#    - load_state_dict() 恢复模型参数
#    - model.eval() 设置评估模式
#  学习目标:
#    掌握模型持久化的标准方法，能够在训练中断后恢复继续训练。
#  前置知识:
#    Python 文件操作基础、第 1-2 节
#  学习建议:
#    实践中始终使用 state_dict 方式保存而非直接保存整个模型对象。
# ============================================================================

# ============================================================================
# 5. GPU 计算
#    源文件: use-gpu.ipynb (slides版本)
#    目标文件: 05_GPU计算.py
# ----------------------------------------------------------------------------
#  内容要点:
#    - torch.device 指定计算设备（CPU / CUDA）
#    - 查询可用 GPU 数量和设备信息
#    - try_gpu() / try_all_gpus() 安全设备选择
#    - 张量在设备之间的复制：.cuda()、.to(device)
#    - 跨设备运算的限制（必须在同一设备）
#    - net.to(device) 将模型迁移到 GPU
#  学习目标:
#    能够编写与设备无关的代码，灵活利用 GPU 加速训练和推理。
#  前置知识:
#    Linux 命令行基础（nvidia-smi）、前几节内容
#  学习建议:
#    在一台有 GPU 的机器上实际运行本节代码，感受 GPU 加速的效果。
