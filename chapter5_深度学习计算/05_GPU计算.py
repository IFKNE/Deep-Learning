"""
=============================================================================
GPU 计算 —— 设备管理与多 GPU 编程（完整带注释版）
=============================================================================
本文件讲解 PyTorch 中 GPU 计算的核心操作：
  - torch.device 指定计算设备
  - 查询可用 GPU 数量和设备信息
  - 张量在设备之间的复制
  - 编写设备无关的代码（try_gpu）
  - 将模型迁移到 GPU 上训练和推理
=============================================================================
"""

# ============================================================================
# 第1步：导入库
# ============================================================================
import torch
from torch import nn


# ============================================================================
# 第1节：查看 GPU 信息
# ============================================================================
# nvidia-smi: NVIDIA System Management Interface
#   这是 Linux 命令行工具，在 Jupyter Notebook 中用 ! 前缀可以直接运行 shell 命令
#   在 .py 文件中需要用 subprocess 模块调用或直接在终端运行
#   显示信息包括：GPU 型号、驱动版本、CUDA 版本、显存使用率、温度等

# 以下代码在终端等效于：
# !nvidia-smi


# ============================================================================
# 第2节：计算设备 —— torch.device()
# ============================================================================
# torch.device(type, index) 创建设备对象，用于指定张量/模型在哪个硬件上计算。
#
# 设备类型：
#   'cpu'      → 中央处理器（CPU）
#   'cuda'     → NVIDIA GPU（需要 CUDA 支持）
#   'cuda:0'   → 第 1 块 GPU（索引从 0 开始）
#   'cuda:1'   → 第 2 块 GPU
#   'mps'      → Apple Silicon GPU（Mac M1/M2/M3 等，PyTorch 1.12+ 支持）

# 创建设备对象（不会实际分配资源，只是创建标识符）
torch.device('cpu'), torch.device('cuda'), torch.device('cuda:1')


# ============================================================================
# 第3节：查询可用 GPU 数量
# ============================================================================
# torch.cuda.device_count()：
#   返回系统中有多少块 CUDA 兼容 GPU
#   如果系统没有 GPU 或 CUDA 驱动未安装，返回 0
torch.cuda.device_count()


# ============================================================================
# 第4节：安全获取 GPU 的辅助函数 —— 设备无关编程
# ============================================================================
# 以下两个函数是"设备无关代码"的核心工具。
# 不要硬编码 'cuda'，通过它们让代码自动适应有无 GPU 的环境。

def try_gpu(i=0):
    """
    尝试返回第 i 块 GPU；如果不存在，则退回 CPU。

    参数:
        i (int): GPU 索引，从 0 开始。默认为 0（第一块 GPU）。

    返回:
        torch.device 对象：GPU(i) 或 CPU

    原理：
        如果 torch.cuda.device_count() >= i+1（至少有 i+1 块 GPU），
        则说明第 i 块 GPU 存在，返回对应设备。
        否则返回 CPU。

    使用场景：
        device = try_gpu()     # 有 GPU 就用 GPU 0，没有就用 CPU
        device = try_gpu(2)    # 用第 3 块 GPU（如果存在的话）
    """
    if torch.cuda.device_count() >= i + 1:
        return torch.device(f'cuda:{i}')
    return torch.device('cpu')

def try_all_gpus():
    """
    返回所有可用的 GPU 设备列表。

    列表推导式 [expr for var in iterable]：
      这是 Python 中最常用的语法糖之一。
      等价于：
        devices = []
        for i in range(torch.cuda.device_count()):
            devices.append(torch.device(f'cuda:{i}'))

    Python 三元表达式 X if cond else Y：
      等价于 C/C++ 的 cond ? X : Y
      如果 devices 列表非空（即有 GPU），返回 devices；
      否则返回 [cpu]（只含 CPU 的单元素列表）。
    """
    # 列表推导式：为每块 GPU 创建一个 device 对象
    devices = [torch.device(f'cuda:{i}')
               for i in range(torch.cuda.device_count())]
    # 三元表达式：如果有 GPU 就返回 GPU 列表，否则返回 [cpu]
    return devices if devices else [torch.device('cpu')]

# 测试辅助函数
try_gpu(), try_gpu(10), try_all_gpus()


# ============================================================================
# 第5节：查询张量所在的设备
# ============================================================================
# 默认情况下，torch.tensor() 创建的张量在 CPU 上
# 张量的 .device 属性返回其所在的设备
x = torch.tensor([1, 2, 3])
x.device  # device(type='cpu')


# ============================================================================
# 第6节：在 GPU 上创建张量
# ============================================================================
# 方式一：创建时直接指定 device 参数
#   torch.ones(size, device=...)：创建全 1 张量
X = torch.ones(2, 3, device=try_gpu())
X  # device='cuda:0'（如果有 GPU）


# ============================================================================
# 第7节：在指定 GPU 上创建随机张量
# ============================================================================
# torch.rand(size, device=...)：从 [0, 1) 均匀分布采样
# try_gpu(1) = 第 2 块 GPU（如果有的话）；没有第 2 块 GPU 时自动退回 CPU
Y = torch.rand(2, 3, device=try_gpu(1))
Y  # 多 GPU 机器上是 cuda:1；本机只有 1 块 GPU，所以自动退回 cpu


# ============================================================================
# 第8节：跨 GPU 复制数据 —— .cuda() 和 .to()
# ============================================================================
# 不同设备上的张量不能直接运算！
# 例如 X (cuda:0) + Y (cuda:1) 会抛出 RuntimeError。
# 需要先把它们移到同一设备上。

# X.cuda(1)：将 X 复制到 cuda:1（第 2 块 GPU）
#   如果 X 已经在 cuda:1 上，则不做任何事（返回自身 —— 幂等操作）
#   如果 X 在 CPU 或其他 GPU 上，则创建副本并传输
#
# ⚠️ 注意：以下多 GPU 操作需要机器有 ≥2 块 GPU 才能运行。
#   本机（RTX 4060 Laptop）只有 1 块 GPU（device_count() == 1），
#   直接 X.cuda(1) 会报错 "CUDA error: invalid device ordinal"。
#   所以用 if 守卫：多 GPU 机器自动演示，单 GPU 机器自动跳过。
if torch.cuda.device_count() >= 2:
    Z = X.cuda(1)  # 复制 X 到 GPU 1
    print(X)       # X 仍在 device='cuda:0'（没变）
    print(Z)       # Z 在 device='cuda:1'（副本）

    # ========================================================================
    # 第9节：同设备上的张量可以正常运算
    # ========================================================================
    # 现在 Z 和 Y 都在 cuda:1 上，可以正常进行张量运算
    # 加法操作会在 GPU 上并行执行（利用大量 CUDA 核心）
    Y + Z  # device='cuda:1'

    # 验证 .cuda() 的幂等性：
    # 对已经在目标设备上的张量再调用 .cuda()，返回自身（不是副本）
    Z.cuda(1) is Z  # True（同一个 Python 对象）
else:
    print(f"本机只有 {torch.cuda.device_count()} 块 GPU，跳过多 GPU 演示（cuda:1 不存在）")


# ============================================================================
# 第10节：将模型迁移到 GPU —— net.to(device)
# ============================================================================
# net.to(device) 将模型的所有参数和缓冲区移动到指定设备
#   内部递归遍历所有子模块，逐个调用它们的 .to(device)

net = nn.Sequential(nn.Linear(3, 1))     # 模型最初在 CPU 上
net = net.to(device=try_gpu())            # 将所有参数搬到 GPU

# 传入 GPU 上的数据 → 前向传播在 GPU 上执行
# 如果模型在 GPU 但数据在 CPU → 报错！
net(X)  # X 在 cuda:0，模型参数也在 cuda:0 → 可以正常计算


# ============================================================================
# 第11节：确认模型参数存储在 GPU 上
# ============================================================================
# 验证模型参数确实被搬到了 GPU
# device(type='cuda', index=0) 说明参数在 GPU 0 上
net[0].weight.data.device


