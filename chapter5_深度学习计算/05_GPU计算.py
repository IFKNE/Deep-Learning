"""
陷阱 1：模型和数据在不同设备上
  model = MyModel().to('cuda')
  for X, y in dataloader:
      # ❌ 错误！数据默认在 CPU，模型在 GPU
      output = model(X)
      # ✅ 正确：把数据也搬到 GPU
      X, y = X.to(device), y.to(device)
      output = model(X)

陷阱 2：optimizer 在 to(device) 之前创建
  model = MyModel()
  optimizer = SGD(model.parameters(), lr=0.01)  # ❌ 优化器指向 CPU 参数
  model = model.to(device)                       # 模型参数已经搬到 GPU 了
  # optimizer 仍持有旧的 CPU 参数引用！
  # ✅ 正确顺序：
  model = MyModel().to(device)
  optimizer = SGD(model.parameters(), lr=0.01)

陷阱 3：在 GPU 上创建的张量不会被自动垃圾回收
  GPU 显存有限（通常 8-32 GB），不及时释放会导致 OOM (Out of Memory)。
  可以用 del tensor 手动删除 + torch.cuda.empty_cache() 清空缓存。

陷阱 4：跨 GPU 传输数据的隐式开销
  CPU ↔ GPU 数据传输是训练中的主要瓶颈之一。
  应尽量减少 CPU/GPU 间的不必要数据传输。
  例如：不要在训练循环中频繁 .cpu() 再 .cuda()。
"""


