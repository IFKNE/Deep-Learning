"""
Q1: torch.tensor([1,2,3]) 创建的张量在哪个设备上？
A1: 默认在 CPU 上。可以通过 device 参数指定设备：
    torch.tensor([1,2,3], device='cuda')

Q2: .cuda() 和 .to('cuda') 有什么区别？
A2: 对于 GPU 目标来说完全等价。.to() 是更通用的接口：
    .to('cuda') 等价于 .cuda()
    .to('cpu')  等价于 .cpu()
    .to(device) 可以用同一个变量切换不同的目标设备。
    推荐使用 .to(device) 以编写设备无关代码。

Q3: 如果两个张量都在 cuda:0，但一个来自不同进程会怎样？
A3: CUDA 张量不能跨进程共享。每个进程拥有独立的 CUDA 上下文，
    张量只能在创建它的进程中使用。
    跨进程通信需要使用 multiprocessing 或 torch.distributed。

Q4: 如何在多 GPU 上训练一个大模型？
A4: 几种策略：
    - 数据并行 (DataParallel/DDP)：每块 GPU 有完整模型副本，数据拆分
    - 模型并行：模型的不同层放在不同 GPU 上
    - 混合并行：数据和模型都拆分
    - 使用框架：PyTorch FSDP、DeepSpeed 等自动处理分布式训练
"""


# ============================================================================
# 总结
# ============================================================================
"""
1. 设备管理：
   - torch.device 指定计算设备（'cpu' / 'cuda:0' / 'cuda:1' ...）
   - .to(device) / .cuda() 将张量或模型移动到目标设备
   - 不同设备上的张量不能直接运算

2. 设备无关编程：
   - try_gpu(i)：有 GPU 就用，没有则退回 CPU
   - try_all_gpus()：返回所有可用 GPU 列表
   - 避免硬编码 'cuda'，让代码在任何环境下都能运行

3. 模型迁移：
   - net.to(device)：递归将所有参数/缓冲区搬到目标设备
   - 数据和模型必须在同一设备上
   - 先 to(device) 再创建 optimizer（否则 optimizer 指向旧参数）

4. 关键 API：
   - torch.cuda.device_count()：查询 GPU 数量
   - tensor.device：查询张量所在的设备
"""
