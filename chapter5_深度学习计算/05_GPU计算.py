"""
写法一：全局 device 变量（简单项目）
  device = torch.device('cuda' if torch.cuda.is_available() else 'cpu')
  model = MyModel().to(device)
  X = X.to(device)

写法二：带 try_gpu 的自选设备（本文件风格）
  device = try_gpu(0)  # 用第 1 块 GPU，没有则 CPU

写法三：支持多 GPU 的 DataParallel（简单并行）
  model = MyModel()
  if torch.cuda.device_count() > 1:
      model = nn.DataParallel(model)  # 自动将数据拆分到多块 GPU
  model.to(device)

写法四：分布式数据并行 DDP（生产环境推荐）
  使用 torch.distributed 和 DistributedDataParallel，
  每块 GPU 运行一个独立进程，通过 all-reduce 同步梯度。
  比 DataParallel 更快，但配置更复杂。
"""


