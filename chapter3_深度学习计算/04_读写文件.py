"""
=============================================================================
读写文件 —— 张量与模型的保存/加载（完整带注释版）
=============================================================================
本文件讲解 PyTorch 中数据持久化的标准方法：
  - torch.save() / torch.load()：序列化与反序列化
  - 保存/加载单个张量、张量列表、字典
  - 保存/加载模型参数（state_dict 方式）
  - load_state_dict() 恢复模型
  - model.eval() 评估模式设置
=============================================================================
"""

# ============================================================================
# 第1步：导入库
# ============================================================================
import torch
from torch import nn
from torch.nn import functional as F


# ============================================================================
# 第1节：保存与加载单个张量
# ============================================================================
# torch.arange(end)：生成从 0 到 end-1 的整数张量
# 类似 Python 的 range(end)，但返回的是 Tensor 对象
# 形状：一维，包含 4 个元素 [0, 1, 2, 3]
x = torch.arange(4)

# torch.save(obj, filepath)：将 Python/PyTorch 对象序列化保存到磁盘
#   底层使用 Python 标准库的 pickle（序列化协议）
#   可以保存几乎任何 Python 对象：张量、列表、字典、模型参数……
#   文件扩展名通常用 .pt 或 .pth，但没有强制要求
torch.save(x, 'x-file')

# torch.load(filepath)：从磁盘反序列化加载对象
#   返回之前保存的对象，类型和值完全一致
x2 = torch.load('x-file')
x2  # tensor([0, 1, 2, 3])


# ============================================================================
# 第2节：保存与加载张量列表
# ============================================================================
# 可以保存包含多个张量的 Python 列表
y = torch.zeros(4)                          # 全零张量，形状 (4,)

# 保存列表：[x, y] 是一个包含两个张量的 Python list 对象
torch.save([x, y], 'x-files')

# 加载后自动恢复为列表
# 元组解包：将列表的两个元素分别赋给 x2 和 y2
#   等价于：loaded = torch.load('x-files')
#          x2 = loaded[0]
#          y2 = loaded[1]
x2, y2 = torch.load('x-files')
(x2, y2)  # (tensor([0, 1, 2, 3]), tensor([0., 0., 0., 0.]))


# ============================================================================
# 第3节：保存与加载字典
# ============================================================================
# 字典（dict）是 Python 中最灵活的数据结构之一
# 用字典保存数据比列表更清晰（有语义化的键名）
#   类比 C++ 的 std::unordered_map<std::string, Tensor>

mydict = {'x': x, 'y': y}             # 创建字典：键='x'/'y'，值=对应张量
torch.save(mydict, 'mydict')          # 保存字典
mydict2 = torch.load('mydict')        # 加载字典（键值结构完整保留）
mydict2  # {'x': tensor([0, 1, 2, 3]), 'y': tensor([0., 0., 0., 0.])}


# ============================================================================
# 第4节：定义用于保存的模型
# ============================================================================
# 在讲解模型参数保存之前，先构建一个示例模型

class MLP(nn.Module):
    """标准 MLP：20 输入 → 256 隐藏 → 10 输出"""
    def __init__(self):
        super().__init__()
        self.hidden = nn.Linear(20, 256)
        self.output = nn.Linear(256, 10)

    def forward(self, x):
        # F.relu() 函数式 API，与 nn.ReLU() 效果相同
        return self.output(F.relu(self.hidden(x)))

net = MLP()
# torch.randn() 从标准正态分布 N(0, 1) 采样（与 torch.rand 的 [0,1) 均匀分布不同）
X = torch.randn(size=(2, 20))
Y = net(X)  # 记录输出，用于后续与加载的模型做对比验证


# ============================================================================
# 第5节：保存模型参数（推荐方式）
# ============================================================================
# net.state_dict() 返回一个 OrderedDict：
#   键 = 参数名（如 'hidden.weight'、'hidden.bias'、'output.weight'、'output.bias'）
#   值 = 参数张量
#
# 注意：state_dict 只保存参数的值（数字），不保存模型的结构（类的定义）！
#   这意味着加载时需要重新定义同样的模型类并实例化。

torch.save(net.state_dict(), 'mlp.params')
# 文件 'mlp.params' 中现在存储了模型的所有参数值


# ============================================================================
# 第6节：加载模型参数
# ============================================================================
# 完整的加载流程：
#   (1) 重新定义/导入模型类（必须与保存时的结构完全一致！）
#   (2) 实例化一个新的模型（此时参数是随机初始化的）
#   (3) 调用 load_state_dict() 用保存的参数覆盖随机初始化的参数
#   (4) 调用 eval() 设置评估模式

# 步骤 (1) + (2)：创建结构相同的"空模型"
clone = MLP()

# 步骤 (3)：加载参数
#   torch.load('mlp.params') → 读取保存的 OrderedDict
#   clone.load_state_dict(dict) → 将参数字典中的值逐键复制到 clone
#   load_state_dict 会严格检查参数名和形状是否匹配
clone.load_state_dict(torch.load('mlp.params'))

# 步骤 (4)：设置为评估模式
#   model.eval() 起什么作用？
#     它会将 self.training 标志设为 False，影响以下层的行为：
#       - Dropout：不再随机丢弃神经元（所有神经元都参与推理）
#       - BatchNorm：使用训练时累积的全局均值和方差，而非当前批次的统计量
#     忘记调用 .eval() 会导致推理结果不稳定（Dropout 随机丢弃）或不准确（BatchNorm）
clone.eval()


# ============================================================================
# 第7节：验证加载后的参数完全一致
# ============================================================================
# 用同一个输入 X 分别过原始网络和克隆网络，输出应该完全一致
Y_clone = clone(X)

# 逐元素比较：由于参数完全相同 + eval 模式下没有随机性
# 所有值应该全为 True
Y_clone == Y


# ============================================================================
# 补充知识点
# ============================================================================

# ============================================================================
# 补充 1：state_dict 方式 vs 直接保存模型 —— 对比分析
# ============================================================================
"""
┌──────────────────────┬──────────────────────────┬──────────────────────────┐
│                      │ state_dict 方式 (推荐)    │ 直接保存整个模型           │
├──────────────────────┼──────────────────────────┼──────────────────────────┤
│ 保存代码              │ torch.save(              │ torch.save(model,        │
│                      │   model.state_dict(),    │   'model.pth')           │
│                      │   'model.pth')           │                          │
│ 加载代码              │ model.load_state_dict(   │ model = torch.load(      │
│                      │   torch.load('model.pth')│   'model.pth')           │
│                      │ )                        │                          │
│ 需要模型类定义         │ 是                       │ 是（pickle 还原时需要）    │
│ 跨 Python 版本兼容     │ ✅ 好                    │ ❌ 差                    │
│ 类定义改变后能否加载    │ ✅ 可以（只加载匹配的参数）│ ❌ 可能失败               │
│ 文件大小              │ 小（只含参数）             │ 大（含整个对象图）         │
│ 安全性               │ 安全（纯数据）             │ 有风险（pickle 可执行代码）│
└──────────────────────┴──────────────────────────┴──────────────────────────┘

结论：始终使用 state_dict 方式保存模型参数。
"""


