"""
=============================================================================
正弦位置编码（Sinusoidal Positional Encoding）—— 完整带注释版
=============================================================================
源文件: exercises/block_03_transformer/task_21_sinusoidal_position/position.py

任务：给每个整数位置 pos 生成一个固定的 D 维向量，再把它加到 token embedding 上，
     让不含顺序信息的 self-attention 也能感知"谁在前、谁在后"。

  核心：PE(pos, 2i)   = sin( pos / 10000^(2i/D) )
        PE(pos, 2i+1) = cos( pos / 10000^(2i/D) )
        相邻的偶数、奇数维共用同一频率，分别放 sin 和 cos；i 不同则频率不同。

输入：max_len（需要的最大位置数）、dim（embedding 维度 D，必须为正偶数）
输出：(max_len, D) 的位置编码表，不参与训练

依赖：math、torch。本文件可独立运行。
=============================================================================
"""

# ============================================================================
# 第1步：导入依赖
# ============================================================================
import math                       # 需要 math.log(10000.0) 来构造指数形式的分母

import torch                      # 全程用 PyTorch 张量运算，方便直接搬到 GPU


# ============================================================================
# 第2步：为什么需要位置编码
# ============================================================================
# self-attention 只比较向量内容，不会凭空知道 token 的先后顺序。
#
#   "小猫追小狗" 和 "小狗追小猫" 包含同一组 token，顺序却改变了句意。
#
# 把两句话的词向量集合丢进 attention，位置对调前后得到的是同一个多重集，
# 模型无法区分。所以必须把"位置"这个信息显式地注入进去。
#
# 原始 Transformer 的做法：为每个整数位置准备一个固定向量，加到 token embedding 上。
# 这张位置表【不参与训练】，所有数值都由 sin/cos 公式给出 —— 这正是"正弦"二字的意思。
#
# 另一种做法（本模块第 06 节 TinyLanguageModel 用）是可学习的位置表 nn.Embedding：
#   self.position_embedding = nn.Embedding(max_seq_len, dim)
# 两者属于不同示例，本模块的完整模型 MiniMindCore 不使用二者，
# 而是在每层 attention 内用 RoPE 处理 Q/K（见 03_RoPE旋转位置编码.py）。
# ============================================================================


# ============================================================================
# 第3步：公式怎样落到数组中
# ============================================================================
# 对位置 pos 和维度对 i：
#
#     PE(pos, 2i)   = sin( pos / 10000^(2i/D) )     # 偶数维放 sin
#     PE(pos, 2i+1) = cos( pos / 10000^(2i/D) )     # 相邻奇数维放 cos
#
#   - pos 是 token 在序列中的整数位置（0,1,2,...）；
#   - D   是 embedding 维度；
#   - 相邻的偶数、奇数维使用【同一个频率】，分别放 sin 和 cos；
#   - i 不同，频率也不同。
#
# ── 代码为什么写成指数形式 ────────────────────────────────────────────────
# 直接算 1 / 10000^(2i/D) 也行，但实现里写成等价的指数形式：
#
#     div_term = exp( arange(0, D, 2) * (-log(10000) / D) )
#     angles   = position * div_term
#
# 因为  1/10000^(2i/D) = 10000^(-2i/D) = exp( -2i/D · log(10000) )
#       = exp( i · (-log(10000)·2/D) )     ← 注意 arange(0,D,2) 步长是 2
# 而 exp 比"先算幂再取倒数"在数值上更稳、写起来也更短。
#
# ── 频率的直观理解 ────────────────────────────────────────────────────────
# 低编号维度（i 小）→ 分母小 → 频率高 → 在同样的位置范围里变化很快；
# 高编号维度（i 大）→ 分母大 → 频率低 → 变化很慢，几乎是一条直线。
#
# 所以只画一条波形无法表示这张表的结构：它是一组【多频率】的 sin/cos。
# 效果类似二进制计数：低位快速翻转、高位缓慢翻转，
# 合起来就能唯一地标记每一个位置。
# ============================================================================


# ============================================================================
# 第4步：实现 sinusoidal_position_encoding
# ============================================================================
def sinusoidal_position_encoding(max_len, dim, device=None):
    """
    生成正弦位置编码表。

    参数:
        max_len: 需要的最大位置数；返回表有 max_len 行
        dim:     embedding 维度 D，必须为正偶数（每对 sin/cos 占两位）
        device: 目标设备（如 "cuda" / "cpu"）；不传则用默认设备

    返回:
        (max_len, dim) 的 float32 张量，第 pos 行就是位置 pos 的编码向量

    分步说明 / 计算过程：
        (1) position  → (max_len, 1)，每个位置一个角度因子
        (2) div_term  → (dim//2,)，每一维对的角度"步长"
        (3) angles = position * div_term → (max_len, dim//2)
        (4) 偶数维填 sin(angles)，奇数维填 cos(angles)
    """
    # ── 入参校验：把错误挡在第一步，而不是让它跑到后面的广播里报 shape 错 ──
    if max_len <= 0:
        # 0 行或负数行的表没有任何意义
        raise ValueError("max_len must be positive")
    if dim <= 0 or dim % 2 != 0:
        # 实现分别写入 0::2 和 1::2，每个 sin 列都有一个相邻 cos 列。
        # 若 D 为奇数，最后一维无法组成完整配对 —— 所以这里要求正偶数。
        # 注意：这是【当前实现的接口约束】，并不意味着所有位置编码都必须偶数维。
        raise ValueError("dim must be a positive even integer")

    # torch.arange(max_len) 生成 [0,1,2,...,max_len-1]，即所有位置下标
    # .float()     转成 float32（整数张量不能做三角函数）
    # .unsqueeze(1)在第 1 维插入一个长度为 1 的轴：
    #              (max_len,) → (max_len, 1)
    #              这一维是为了后面与 div_term 做【广播】乘法：
    #              (max_len,1) * (dim//2,) → (max_len, dim//2)
    position = torch.arange(max_len, device=device).float().unsqueeze(1)

    # torch.arange(0, dim, 2) 生成偶数下标 [0,2,4,...,dim-2]，共 dim//2 个 → 对应上面公式里的 i
    # 乘上 (-math.log(10000.0) / dim) 得到 -2i/D·log(10000) 的一半…
    # 准确地说：每一步等于 -2i/D · log(10000)，恰好等于 log(10000^(-2i/D))
    # torch.exp(...) 之后就是 10000^(-2i/D) = 1 / 10000^(2i/D)，即公式中的分母
    div_term = torch.exp(
        torch.arange(0, dim, 2, device=device).float() * (-math.log(10000.0) / dim)
    )

    # 先用零填满整张表，再分别覆盖偶数列和奇数列
    # 形状 (max_len, dim)：每行一个位置，每列一个特征维度
    pe = torch.zeros(max_len, dim, device=device)

    # position * div_term： (max_len,1) × (dim//2,) → (max_len, dim//2)
    # 第 pos 行第 i 列 = pos / 10000^(2i/D)，正是公式里的角度
    # pe[:, 0::2] 取所有偶数维（0,2,4,...），把 sin(角度) 写进去
    # 注意左边 (max_len, dim//2) 与右边 (max_len, dim//2) 形状一致，无需广播
    pe[:, 0::2] = torch.sin(position * div_term)

    # pe[:, 1::2] 取所有奇数维（1,3,5,...），把 cos(角度) 写进去
    # 用的是【同一个 angles】，所以第 2i 维和第 2i+1 维频率相同，只差 sin/cos
    pe[:, 1::2] = torch.cos(position * div_term)

    # 返回 (max_len, dim) 的完整表；调用方按当前序列长度切片使用
    return pe


# ============================================================================
# 第5步：两个方便的手算点（自检用）
# ============================================================================
# (1) pos = 0 时，所有角度都是 0：
#
#         sin(0) = 0,  cos(0) = 1
#         PE[0] = [0, 1, 0, 1, 0, 1, ...]
#
#     这能很快查出两件事：
#       - sin/cos 列是否放反了（如果变成 [1,0,1,0,...] 就是放反了）；
#       - position 是否误从 1 开始（那样第 0 行就不是这个模式了）。
#
# (2) 对同一维度对，可以利用和角公式：
#
#         sin(a+b) = sin a · cos b + cos a · sin b
#         cos(a+b) = cos a · cos b - sin a · sin b
#
#   也就是说，位置 pos+k 的这一对数值【可以由位置 pos 的数值做一次
#   与 k 有关的线性变换得到】：
#
#         [sin(θ(pos+k))]   [ cos(kω)  sin(kω)] [sin(θ(pos))]
#         [cos(θ(pos+k))] = [-sin(kω)  cos(kω)] [cos(θ(pos))]
#
#   其中 ω = 1/10000^(2i/D) 是该维度对的角速度，是常数。
#   这是原论文选择 sin/cos 的一个重要动机：
#   模型若学会"关注相对位移 k"，就能用固定的线性变换表达它，
#   而不必为每一个绝对位置组合单独学习一组参数。
# ============================================================================


# ============================================================================
# 第6步：怎样加到 embedding 上
# ============================================================================
# 函数返回整张表，shape 为 (max_len, dim)。
# 当前 batch 的 embedding 是 (B,T,D)，处理方式就是：
#
#     x = token_embedding(input_ids)          # (B,T,D)
#     x = x + position_table[:T][None, :, :]  # 取前 T 行并增加 batch 轴
#     #   (B,T,D) + (1,T,D) -> (B,T,D)        # 广播到每个样本
#
# 关键点：
#   - 只取前 T 行，因为当前序列只有 T 个 token；
#   - [None, :, :] 在第 0 维插入长度为 1 的轴，让位置表在 batch 维【广播】：
#     同一位置对所有样本使用完全相同的编码；
#   - 是【逐元素相加】，不是拼接。所以 D 不变，仍是 (B,T,D)。
#
# 这也解释了为什么位置编码的维度必须等于 embedding 维度：
# 只有维度相同，才能直接相加。
# ============================================================================


# ============================================================================
# 第7步：运行与核对
# ============================================================================
# 在仓库根目录运行：
#
#     python exercises/block_03_transformer/task_21_sinusoidal_position/position.py
#
# 输出包含：
#
#     shape: (4, 8)
#     position 0: [0.0, 1.0, 0.0, 1.0, 0.0, 1.0, 0.0, 1.0]
#
# 位置编码的边界也收录在 Block 3 测试中：
#
#     python -m unittest discover -s tests -p 'test_block3.py' -v
#
# 运行结果和测试中可以核对这些性质：
#   - 返回值为 (max_len, D)；
#   - 第 0 行与手算结果一致（0/1 交替）；
#   - 不同维度对使用不同频率；
#   - 指定 device 后可直接与 embedding 相加；
#   - 奇数 D 会触发 ValueError。
#
# 下一节保留多频率 sin/cos，但不再把位置表加到 embedding，
# 而是用它旋转 attention 的 Q/K —— 这就是 RoPE。
# ============================================================================


if __name__ == "__main__":
    # 构造一个小例子：4 个位置、8 维编码，方便肉眼核对
    encoding = sinusoidal_position_encoding(4, 8)
    # tuple(...) 把 torch.Size 打印成更常见的 (4, 8) 形式
    print("shape:", tuple(encoding.shape))          # 期望 (4, 8)

    # .tolist() 把张量转成嵌套 Python 列表，便于直接看数值
    # 期望输出 [0.0, 1.0, 0.0, 1.0, 0.0, 1.0, 0.0, 1.0]
    # —— 这正是"pos=0 时所有角度为 0"的手算结果
    print("position 0:", encoding[0].tolist())


# ============================================================================
# 补充知识点：位置编码的几种方案对照
# ============================================================================
#   方案                形式                    是否训练    相对位置    本模块位置
#   ─────────────────   ─────────────────────   ────────    ────────    ──────────
#   正弦编码(本节)       emb + PE(pos)           否          线性可及    02
#   可学习位置表         emb + Emb(pos)          是          靠学习      06 的小模型
#   RoPE                旋转 Q/K                否          点积显式    03
#   ALiBi               在 score 上加线性偏置   否          线性偏置    （未涉及）
#
# ── 本节方案的两个局限 ────────────────────────────────────────────────────
# (1) 位置信息只在【第一层输入】处注入一次，之后靠网络自己传递；
#     层数越深，位置信号可能被稀释。
# (2) 训练时见过的最大长度限制了外推能力 —— 表只建到 max_len 行。
#     RoPE 之所以成为现代 LLM 的主流，正是因为它绕开了这两点：
#     位置在【每一层的 Q/K 上】直接生效，且频率公式天然支持外推。
# ============================================================================


# ============================================================================
# 核心公式回顾
# ============================================================================
# (1) 位置编码定义
#
#         PE(pos, 2i)   = sin( pos / 10000^(2i/D) )
#         PE(pos, 2i+1) = cos( pos / 10000^(2i/D) )
#
# (2) 代码里的等价指数形式
#
#         div_term[i] = exp( -2i·log(10000) / D ) = 10000^(-2i/D)
#         angles[pos, i] = pos · div_term[i]
#
# (3) 注入方式（逐元素相加 + batch 广播）
#
#         x = token_embedding(input_ids) + PE[:T][None, :, :]
#            (B,T,D)                     + (1,T,D)  →  (B,T,D)
#
# (4) 手算自检点
#
#         PE(0, ·) = [0, 1, 0, 1, …]
#
# (5) 相对位置可由线性变换得到（和角公式）
#
#         sin(a+b) = sin a cos b + cos a sin b
#         cos(a+b) = cos a cos b - sin a sin b
# ============================================================================


# ============================================================================
# 总结
# ============================================================================
# 1. self-attention 本身是"位置无关"的，位置信息必须外部注入。
#    本节用的是最经典的注入方式：把一张固定的 sin/cos 表加到 embedding 上。
#
# 2. 这张表的精髓是【多频率】：
#    低维变化快、高维变化慢，合起来让每个位置拥有一组独特的取值模式，
#    而且邻近位置之间是"平滑相近"的，不是随机区分的。
#
# 3. 表不参与训练 —— 没有 nn.Parameter，没有梯度。
#    所以它不占参数预算，也不受训练数据规模影响。
#
# 4. 两个实用自检点：
#    - pos=0 时输出 [0,1,0,1,...]，一测就知道 sin/cos 有没有放反；
#    - 和角公式说明相对位移是线性可及的，这是原论文的选型动机。
#
# 5. 边界由接口约定：max_len > 0 且 dim 为正偶数。
#    校验写在函数最前面，让错误尽早、尽量明确地暴露出来。
#
# 6. 本节的位置表是"加在 embedding 上"的；
#    下一节 RoPE 换成"旋转 Q/K"，位置从输入端搬到了 attention 内部。
#    记住这个搬家的动作，03 节读起来就顺了。
# ============================================================================
