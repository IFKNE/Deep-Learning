"""
=============================================================================
SwiGLU 前馈网络（Gated Feed-Forward Network）—— 完整带注释版
=============================================================================
源文件: exercises/block_03_transformer/task_24_swiglu_ffn/ffn.py

任务：实现 decoder block 里的第二个子层 —— FFN。
     Attention 负责 token 之间的信息交换，FFN 则在每个 token 内部变换特征。

  核心：普通 FFN    FFN(x) = W₂ · ReLU(W₁x)              ← 一条通道
        SwiGLU      SwiGLU(x) = W_down( SiLU(W_gate·x) ⊙ W_up·x )
                                                        ↑ 两路投影 + 一扇门

        SiLU(z) = z · σ(z)，σ 是 sigmoid；⊙ 是逐元素相乘。

输入：x: (B,T,D)
输出：(B,T,D)   —— 与输入同 shape，因此可以直接做残差相加

依赖：torch、torch.nn、torch.nn.functional。本文件可独立运行。
=============================================================================
"""

# ============================================================================
# 第1步：导入依赖
# ============================================================================
import torch                               # randn 用于 smoke test
from torch import nn                       # nn.Sequential / nn.Linear / nn.Module
from torch.nn import functional as F       # F.silu —— SiLU 激活函数


# ============================================================================
# 第2步：普通 FFN —— 一条通道
# ============================================================================
# 原始 Transformer 的前馈网络只有一条路径：
#
#     FFN(x) = W₂ · ReLU(W₁x)
#
# 先扩张再压回：
#
#     (B,T,D) -> (B,T,4D) -> (B,T,D)
#
# d_model = 4096 的大模型里，中间维度通常是 4 倍即 16384。
#
# ── ReLU 的问题：它是一扇只有"开"和"关"的闸门 ────────────────────────────
# ReLU(z) = max(0, z)：大于零原样通过，小于零直接归零。
# 对每个中间特征来说，决定只有两种 —— 保留或丢弃，没有中间状态。
#
# 对于 dim=4096 的模型，这意味着 16384 个中间特征各自做一次二值决定，
# 特征选择的粒度比较粗。
# ============================================================================


# ============================================================================
# 第3步：SwiGLU —— 两条投影加一扇门
# ============================================================================
# SwiGLU 把输入同时投影成两路：
#
#     g = W_gate · x        ← 门控分支
#     u = W_up   · x        ← 内容分支
#
#     SwiGLU(x) = W_down( SiLU(g) ⊙ u )
#
# 其中 ⊙ 是逐元素相乘，W_down 把乘积投影回模型维度。
#
# 数据流：
#
#     x ──→ W_gate ──→ SiLU ──┐
#                              ⊙ ──→ W_down ──→ 输出
#     x ──→ W_up   ───────────┘
#
# ── 直观理解这一步相乘 ────────────────────────────────────────────────────
#
#         SiLU(W_gate·x)          ⊙          W_up·x
#         ↑ 决定放行多少                      ↑ 放行的内容
#
# 门控分支像每个特征自己的【音量旋钮】，连续地控制另一路特征通过多少；
# ReLU 则只有"保留或归零"两个状态。
#
# ── 名字的来历 ────────────────────────────────────────────────────────────
#     Swi = Swish（也就是 SiLU）
#     GLU = Gated Linear Unit（门控线性单元）
# 合起来：用 Swish 做门的 GLU。
# ============================================================================


# ============================================================================
# 第4步：SiLU —— 平滑的门
# ============================================================================
#     SiLU(z) = z · σ(z),        σ(z) = 1 / (1 + e^(-z))
#
# 与 ReLU 相比，SiLU 有两点不同：
#
#   (1) 处处平滑（无限可导）—— 梯度不会在 0 点出现突变；
#   (2) 允许小幅负值通过 —— z = -1 时 SiLU(-1) ≈ -0.27，不是 0。
#
# 因此门可以从"几乎全关"连续拧到"全开"，中间任何开度都可用。
# 这正是"连续控制通过量"这个说法能成立的原因。
#
# ── PyTorch 里怎么用 ──────────────────────────────────────────────────────
#   F.silu(x)         函数式，本文件用的就是它
#   nn.SiLU()         模块式，可以放进 nn.Sequential
#   两者是同一个东西，选哪个只看写法方便程度
# ============================================================================


# ============================================================================
# 第5步：参数量 —— 为什么中间维度取 8/3·d 而不是 4d
# ============================================================================
# 普通 FFN 有两个矩阵（d→4d 和 4d→d），参数量约为：
#
#     4d² + 4d² = 8d²
#
# SwiGLU 有三个矩阵（d→m 两次、m→d 一次）：
#
#     3 · d · m
#
# 若仍取 m = 4d，参数量会变成 3·d·4d = 12d²，比普通 FFN 多一半 ——
# 那样比较两者效果就不公平了（不是结构更好，只是参数更多）。
#
# 为了让两者接近，令：
#
#     3dm ≈ 8d²      ⟹      m ≈ 8d/3 ≈ 2.67d
#
# 所以使用 SwiGLU 后中间维度不再取 4d。
#
# LLaMA 的 d = 4096：
#
#     4096 × 8/3 ≈ 10923
#
# 再为硬件计算效率对齐（通常是 256 的倍数），LLaMA 取 11008。
#
# ── 本仓库的取值 ──────────────────────────────────────────────────────────
#     ffn.py 的独立示例      hidden_dim = 2×dim
#     Task 27 的模型主干     hidden_dim = 1.5×dim
#
# 教学模型在 CPU 上运行，参数量优先保证跑得动；比例本身不是 SwiGLU 的结构约束。
# 换句话说：8/3 是"配平"的结果，不是"必须"的规则。
# 真正的结构约束是"两路投影 + 逐元素相乘 + 投影回来"，比例可以自由调。
# ============================================================================


# ============================================================================
# 第6步：FeedForward —— 普通版本（对照组）
# ============================================================================
class FeedForward(nn.Module):
    """普通两层 FFN：Linear -> GELU -> Linear。

    这里用 GELU 而不是 ReLU，是因为 GELU 也是平滑激活，
    用它做对照能更公平地突出"门控"这一结构差异，而不是激活函数的差异。
    """

    def __init__(self, dim, hidden_dim):
        """
        参数:
            dim:        模型维度 D（输入输出都是它）
            hidden_dim: 中间维度 H，通常取 4D
        """
        super().__init__()

        # nn.Sequential 是一个"层容器"：数据依次流过 A→B→C
        # 等价于手写 forward 里的 x = B(A(x))，但少写一个方法。
        #   nn.Linear(dim, hidden_dim)        升维：D → H
        #   nn.GELU()                         非线性激活（逐元素，不改变 shape）
        #   nn.Linear(hidden_dim, dim)        降维：H → D，回到模型维度
        # 注意最后一个 Linear 必须回到 dim，否则残差相加时 shape 对不上。
        self.net = nn.Sequential(nn.Linear(dim, hidden_dim), nn.GELU(), nn.Linear(hidden_dim, dim))

    def forward(self, x):
        # x: (B,T,D) → (B,T,H) → (B,T,H) → (B,T,D)
        # 整个过程沿最后一维运算，batch 和 sequence 维始终保留 ——
        # 也就是说 FFN 【不沿 T 维混合信息】，每个位置独立处理。
        return self.net(x)


# ============================================================================
# 第7步：SwiGLU —— 门控版本
# ============================================================================
class SwiGLU(nn.Module):
    """门控前馈网络：W_down( SiLU(W_gate·x) ⊙ W_up·x )。

    参数:
        dim:        模型维度 D
        hidden_dim: 中间维度 H（门控分支与内容分支都是这个宽度）
    """

    def __init__(self, dim, hidden_dim):
        super().__init__()

        # 三组独立投影（本文件沿用 ffn.py 的 w1/w2/w3 命名）
        #   w1: 门控分支，输出会过 SiLU
        #   w2: 内容分支，原样保留
        #   w3: 输出投影，把逐元素乘积压回模型维度
        # 三者都是【无 bias】或【有 bias】并不影响分支结构；
        # 本文件用 nn.Linear 的默认 bias=True，
        # 而 Task 27 的 minimind_core.py 用 bias=False（LLaMA 命名 gate/up/down）。
        self.w1 = nn.Linear(dim, hidden_dim)       # (B,T,D) → (B,T,H)  门控
        self.w2 = nn.Linear(dim, hidden_dim)       # (B,T,D) → (B,T,H)  内容
        self.w3 = nn.Linear(hidden_dim, dim)       # (B,T,H) → (B,T,D)  回落

    def forward(self, x):
        """
        参数:
            x: (B,T,D)

        返回:
            (B,T,D)

        分步说明 / 计算过程：
            (1) self.w1(x)  → (B,T,H)，门控分支
            (2) F.silu(...) → (B,T,H)，把门连续地拧到 (0,1) 区间附近
            (3) self.w2(x)  → (B,T,H)，内容分支（不过激活）
            (4) 两者逐元素相乘 → (B,T,H)，shape 一致才能 ⊙
            (5) self.w3(...) → (B,T,D)，投影回模型维度
        """
        # F.silu(self.w1(x)) * self.w2(x)
        #   ↑ 这两个张量形状都是 (B,T,H)，逐元素相乘即为"门"：
        #     门分支决定放行比例，内容分支提供被放行的数值
        # 外层 self.w3(...) 把 H 维压缩回 D 维，以便与残差相加
        return self.w3(F.silu(self.w1(x)) * self.w2(x))


# ============================================================================
# 第8步：ffn.py 中的两个版本对照
# ============================================================================
#     FeedForward  Linear -> GELU -> Linear
#     SwiGLU       w3( SiLU(w1(x)) * w2(x) )
#
# 对应关系：
#
#   1. w1、w2 是两个不同的 nn.Linear，都把 D 投影到 H；
#   2. 只有 w1 分支经过 SiLU；
#   3. w3 把乘积投影回 D；
#   4. batch 和 sequence 维始终保留。
#
# ── 命名对照 ──────────────────────────────────────────────────────────────
# LLaMA 系模型给同样的三个矩阵起名为 gate_proj / up_proj / down_proj：
#
#     ffn.py        w1         w2       w3
#     LLaMA 系      gate_proj  up_proj  down_proj
#
# Task 27 的 minimind_core.py 就采用这一套命名，并把三个投影设为 bias=False；
# ffn.py 使用 nn.Linear 的默认 bias。
# 命名与 bias 都不改变分支结构 —— 读代码时不要被名字差异迷惑。
#
# ── 一个常见误解 ──────────────────────────────────────────────────────────
# 下面这个结构【不】等价于 SwiGLU：
#
#     Linear -> SiLU -> Linear
#
# 它只有一次上投影，没有独立的 up 分支，是普通两层 FFN，不是 SwiGLU。
# 判断方法很简单：数一下有没有两个并行的、都从 D 投到 H 的线性层。
# ============================================================================


# ============================================================================
# 第9步：为什么门控更好
# ============================================================================
#   - ReLU FFN 对每个特征做二值决定；SwiGLU 根据当前输入连续地控制通过量，
#     特征选择更灵活；
#   - SiLU 的平滑性也让优化更稳定（梯度在负半轴不是硬性的 0）；
#   - 在【相近参数量和计算量】下，门控 FFN 普遍取得更低的语言建模损失。
#
# 最后一条是 LLaMA、PaLM 等模型采用它的直接原因。
# 注意"相近参数量"这个前提 —— 前面 8/3·d 的推导正是为了满足它。
# ============================================================================


# ============================================================================
# 第10步：FFN 不会破坏 causal 性质
# ============================================================================
# 可把计算理解为：
#
#     x[:,0,:] -> 同一个 ffn -> out[:,0,:]
#     x[:,1,:] -> 同一个 ffn -> out[:,1,:]
#     ...
#
# FFN 不沿 T 维求和，也不做任何跨位置的运算，所以不会让早期位置读到未来。
# 序列方向的信息边界仍由 attention 的 causal mask 决定。
#
# ── 这一点在写代码时的实际意义 ────────────────────────────────────────────
# 只要 FFN 的输入输出 shape 都是 (B,T,D) 且只在最后一维运算，
# 就不用为它考虑任何 mask。整个 Transformer 里需要处理 mask 的地方
# 只有 attention 一处 —— 这也是把 mask 相关代码全部集中在 04 节的原因。
# ============================================================================


# ============================================================================
# 第11步：运行与核对
# ============================================================================
#     python exercises/block_03_transformer/task_24_swiglu_ffn/ffn.py
#
# 输出形如：
#
#     SwiGLU output: (2, 6, 32)
#
# SwiGLU 的结构性质也收录在 Block 3 测试中：
#
#     python -m unittest discover -s tests -p 'test_block3.py' -v
#
# 输出与测试中可以看到：
#   - 输入输出均为 (B,T,D)；
#   - 两次上投影使用不同 Parameter（w1 与 w2 不是同一个对象）；
#   - 逐元素乘法前 shape 一致；
#   - 前向结果有限且可正常反向传播。
#
# 参考：GLU Variants Improve Transformer  https://arxiv.org/abs/2002.05202
# ============================================================================


if __name__ == "__main__":
    # 模拟一个 batch：2 个样本、6 个 token、32 维
    values = torch.randn(2, 6, 32)

    # SwiGLU(32, 64)：中间维度取 2×dim（教学模型的小比例，见第 5 步的说明）
    # 注意这是一个"立即调用"的写法：
    #   SwiGLU(32, 64)       先建一个模块实例（内部会随机初始化 w1/w2/w3）
    #   (values)             紧接着调用它的 __call__，触发 forward
    # nn.Module 重写了 __call__，所以可以直接把实例当函数用，
    # 而不必显式写 .forward(values)（写 .forward 会绕开一些 hook 机制，不推荐）
    # 最终输出 shape 应回到 (2,6,32)，与输入一致
    print("SwiGLU output:", tuple(SwiGLU(32, 64)(values).shape))


# ============================================================================
# 补充知识点：三种 FFN 变体的对照
# ============================================================================
#   结构              公式                              中间维度惯例
#   ───────────────   ───────────────────────────────   ──────────────
#   原始 FFN          W₂·ReLU(W₁x)                      4d
#   GELU 变体         W₂·GELU(W₁x)                      4d
#   SwiGLU            W_down(SiLU(W_gate·x) ⊙ W_up·x)   8d/3 ≈ 2.67d
#
# ── 为什么"门控"这个想法有效 ──────────────────────────────────────────────
# 从乘法角度看，SwiGLU 引入了【二阶项】：
#     SiLU(W_gate·x) ⊙ (W_up·x)
# 展开后含有 x 的二次型，因此它比单纯的线性+激活能表达更丰富的特征交互。
# 这与"注意力用 Q·Kᵀ 引入位置间的二阶交互"在思路上是相通的：
# 都是用一个乘法去创造非线性的组合能力。
#
# ── 工程上的注意点 ────────────────────────────────────────────────────────
# 1. 三个投影的中间维度必须一致，否则 ⊙ 会因为 shape 不同而报错；
# 2. w3 必须把维度投回 D，否则残差相加失败 —— 这是最常见的 shape 错误来源；
# 3. 用 bias=False 可以省下 3·H 个参数（在 H 很大时不可忽略），
#    LLaMA 系一律不用 bias，教学实现也跟着这么做。
# ============================================================================


# ============================================================================
# 核心公式回顾
# ============================================================================
# (1) 普通 FFN
#
#         FFN(x) = W₂ · ReLU(W₁ x)
#         (B,T,D) → (B,T,4D) → (B,T,D)
#
# (2) SwiGLU
#
#         g = W_gate · x            ← 门控分支
#         u = W_up   · x            ← 内容分支
#         SwiGLU(x) = W_down( SiLU(g) ⊙ u )
#
# (3) SiLU（Swish）
#
#         SiLU(z) = z · σ(z),       σ(z) = 1 / (1 + e^(-z))
#         SiLU(-1) ≈ -0.27         ← 允许小幅负值通过
#
# (4) 参数量配平
#
#         普通 FFN:  4d² + 4d² = 8d²
#         SwiGLU  :  3·d·m
#         令 3dm = 8d²  ⟹  m = 8d/3 ≈ 2.67d
#         LLaMA: 4096 × 8/3 ≈ 10923 → 对齐到 11008
# ============================================================================


# ============================================================================
# 总结
# ============================================================================
# 1. FFN 与 Attention 的分工是清楚的：
#      Attention 沿【序列维 T】混合信息（token 之间交换）；
#      FFN 沿【特征维 D】变换信息（每个 token 内部加工）。
#    因此 FFN 天然不破坏 causal 性质，也不需要任何 mask。
#
# 2. SwiGLU 的关键不是"换了个激活函数"，而是【加了一扇门】：
#      SiLU(W_gate·x) ⊙ (W_up·x)
#    一路决定放行多少（连续可调），另一路提供放行的内容。
#
# 3. 中间维度从 4d 变成 8d/3，是【配平参数量】推出来的，不是拍脑袋定的。
#    教学实现用 1.5×d 或 2×d，比例可调，结构不变。
#
# 4. 三个投影的命名在不同代码里不一样（w1/w2/w3 或 gate/up/down），
#    认结构比认名字可靠：找到"两个并行 D→H 投影 + 一个 H→D 投影"就是 SwiGLU。
#
# 5. "Linear → SiLU → Linear" 不是 SwiGLU。判断口诀：数并行上投影的个数。
# ============================================================================
