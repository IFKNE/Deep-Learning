# 补充知识点：把本节公式变成 shape —— 后续 10 个文件的公共字典
# ============================================================================
# 这张表建议背下来，读后面任何一节时都可以回来对照：
#
#   记号        shape            含义
#   ────────    ─────────────    ────────────────────────────────────────
#   B           ()               batch size
#   T           ()               当前序列长度（含 KV Cache 时是"新 token 数"）
#   D           ()               hidden dimension，模型主干宽度
#   H           ()               query head 数量（n_heads）
#   Hkv         ()               K/V head 数量（n_kv_heads），GQA 时 Hkv < H
#   Dh          ()               head_dim = D / H
#   V           ()               vocab_size，词表大小
#
#   x           (B,T,D)          输入 hidden states
#   Q           (B,H,T,Dh)       query，已拆头
#   K,V         (B,Hkv,T,Dh)     key/value，GQA 下 head 数更少
#   scores      (B,H,T,T)        Q·Kᵀ/√Dh，位置两两匹配分
#   weights     (B,H,T,T)        softmax 后的注意力权重，每行和为 1
#   out         (B,H,T,Dh)       weights·V
#   concat      (B,T,D)          转置 + reshape 回主干宽度，可直接接残差
#
# ── 一句话总结整个 Transformer 主干 ──────────────────────────────────────
#     x = x + Attention(Norm(x))     # 位置之间交换信息
#     x = x + FFN(Norm(x))           # 每个位置内部变换特征
# 这两行重复 N 层，就是本章（以及 LLaMA、GPT 等）的全部主干。
