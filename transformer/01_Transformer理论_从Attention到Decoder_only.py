# ============================================================================
# 核心公式回顾
# ============================================================================
# (1) 缩放点积注意力
#
#                       ⎛ Q·Kᵀ     ⎞
#         Attention = softmax⎜ ───── + M ⎟ · V
#                       ⎝ √d_head  ⎠
#
#     Q = X·Wq,  K = X·Wk,  V = X·Wv
#     M：可见位为 0，禁止位为 -∞（实现用 -torch.finfo(dtype).max 代替）
#
# (2) causal mask（T=4）
#
#              k0    k1    k2    k3
#         q0 [  0    -∞    -∞    -∞ ]
#         q1 [  0     0    -∞    -∞ ]
#         q2 [  0     0     0    -∞ ]
#         q3 [  0     0     0     0 ]
#
# (3) 缩放项的方差推导（直观版）
#
#     若 q_i、k_i 独立同分布且方差为 σ²，则 q·k = Σ_{i=1..Dh} q_i k_i
#     的方差约为 Dh·σ⁴，标准差约 √Dh·σ²。
#     除以 √Dh 后标准差回到 σ² 量级，与 Dh 无关。
#
# (4) 多头
#
#         MultiHead = W_o · [head_1 ; head_2 ; … ; head_H]
#         head_i    = Attention(X·Wq_i, X·Wk_i, X·Wv_i)
# ============================================================================


# ============================================================================
# 总结
# ============================================================================
# 1. attention 的本质是"按相关性加权求和"：
#    Q/K 算出权重，V 提供被加权的内容。三者的来源决定了这是 self 还是 cross。
#
# 2. 除以 √d_head 是为了控制 score 的量级，避免 softmax 在高维下饱和、梯度消失。
#    这是一个数值稳定性设计，不是可有可无的装饰。
#
# 3. mask 必须在 softmax 之前生效。mask 分两类，各管一件事，不能互相替代：
#      causal mask  (1,1,T,T)  → 不能看未来
#      padding mask (B,T)      → 不能读填充值
#
# 4. 多头 = 多组投影 + 多次注意力 + 拼接 + 输出投影。
#    拆头靠 view + transpose，目的是能一次做完 (B,H,T,T) 的批量矩阵乘法。
#
# 5. 原论文是 encoder-decoder（含 cross-attention、加性位置编码、Post-LayerNorm、
#    ReLU FFN）；本模块是 decoder-only（无 encoder、RoPE、Pre-RMSNorm、SwiGLU）。
#    骨架相同，差别就是上面这几处替换 —— 这也是后面每一节要逐个交代的东西。
#
# 6. 读后续代码时的自检问题（很有效）：
#      这一步的输入 shape 是什么？输出 shape 是什么？
#      位置信息是在哪一步进去的？（本章：RoPE，在 attention 内部）
#      哪一步可能泄漏未来信息？（答案是：只要 mask 在 softmax 之后就会）
# ============================================================================


