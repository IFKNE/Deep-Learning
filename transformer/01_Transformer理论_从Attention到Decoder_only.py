# ============================================================================
# 第1节：为什么是 Attention
# ============================================================================
# 卷积用固定窗口读取局部区域（比如 3×3 只看相邻像素/相邻词）；
# RNN 按顺序把状态一路传下去，理论上能记住很远，但梯度会衰减。
#
# 文本中的依赖却可能隔得很远：
#   读到句尾的"它"时，模型也许要回到十几个 token 以前寻找所指对象。
#
# Self-attention 把这件事写成矩阵运算：
#   先把整段序列放进同一个张量，再让每个位置计算"自己该从哪些位置取信息"。
#
# 一句话对比三种结构的信息通路长度：
#   卷积： 位置 i ← 位置 i±k        通路 O(1)，但视野固定
#   RNN：  位置 i ← 位置 i-1 ← …    通路 O(T)，靠状态串行传递
#   Attn： 位置 i ← 任意位置 j      通路 O(1)，且视野是全序列
# ============================================================================


# ============================================================================
# 第2节：Q、K、V
# ============================================================================
# 输入 hidden states 记为：
#
#     X: (B,T,D)
#       B = batch size（一次喂几个句子）
#       T = sequence length（句子有多少个 token）
#       D = hidden dimension（每个 token 用一个 D 维向量表示）
#
# 同一个 X 经过三组不同参数（三个独立的线性层）：
#
#     Q = X @ Wq    # 当前位置要匹配什么（query，提问）
#     K = X @ Wk    # 每个位置可以怎样被匹配（key，索引标签）
#     V = X @ Wv    # 匹配以后取回的内容（value，实际内容）
#
# ── 一个 attention head 的计算 ─────────────────────────────────────────────
#
#                    ⎛ Q·Kᵀ          ⎞
#     Attention(Q,K,V) = softmax ⎜ ─────── + M ⎟ · V
#                    ⎝ √d_head       ⎠
#
#   其中 M 是与 score 同 shape 的加法掩码：
#     可见位置取 0，禁止位置取 -∞
#     （实现里用有限的最小值代替，见 04_Causal注意力与GQA.py）
#
# ── 三步走 ────────────────────────────────────────────────────────────────
#   (1) Q·Kᵀ            → 位置两两之间的 score，shape (B,H,T,T)
#   (2) softmax(...,dim=-1) → 沿 key 方向把 score 变成权重，每行和为 1
#   (3) 权重 · V         → 用权重加权 V，得到每个位置的新表示
#
#   所以可以简单记成：Q/K 决定"看哪里"，V 决定"拿回来什么"。
#
# ── 缩放项 √d_head 的来历 ─────────────────────────────────────────────────
# 若 Q、K 各维近似独立且方差相近，点积 q·k = Σ_i q_i·k_i 的方差会随 d_head 线性增长。
# 维度越大，score 的绝对值越容易变得很大；
# 而 softmax 对大的输入会"饱和"：最大的那一项接近 1，其余接近 0，
# 于是梯度几乎为 0，训练不动。
# 除以 √d_head 把方差拉回 O(1)，softmax 就不容易因为维度变大而过早饱和。
# ============================================================================


# ============================================================================
# 第3节：从一个 head 到多个 head
# ============================================================================
# 以 D=32, H=4 为例，head_dim = D / H = 8：
#
#     Q: (B,T,32) -> (B,4,T,8)
#     K: (B,T,32) -> (B,4,T,8)
#     V: (B,T,32) -> (B,4,T,8)
#
#     scores:       (B,4,T,T)
#     head outputs: (B,4,T,8)
#     concat:       (B,T,32)
#
# ── 为什么分开算 ──────────────────────────────────────────────────────────
# 四个 head 使用不同的投影参数 Wq_i / Wk_i / Wv_i，等于给模型留下多组匹配空间，
# 可以在不同子空间里同时关注不同关系。
#
# ── 一个常见误解 ──────────────────────────────────────────────────────────
# 它们学到什么完全由数据决定，并没有预先分配好的"语法 head""指代 head"等固定角色。
# 事后分析能观察到某些 head 表现出某种倾向，但那是结果而非设计。
#
# ── 拆头为什么这么写 ──────────────────────────────────────────────────────
# 实现上通常是：
#     q = self.q_proj(x).view(B, T, H, Dh).transpose(1, 2)   # (B,H,T,Dh)
# 即"投影出 H*Dh 维 → view 成 (T,H,Dh) → 把 H 换到 batch 后面"，
# 这样才能用 (B,H,T,T) 的批量矩阵乘法一次算完所有 head。
# ============================================================================


# ============================================================================
# 第4节：为什么语言模型要遮住未来
# ============================================================================
# 训练 next-token 模型时，整段序列是【并行】计算的：
# 位置 2 的输入旁边虽然已经放着位置 3、4（因为它们在同一个张量里），
# 但它不能借此读取目标答案 —— 否则模型只需要"抄下一格"，学不到任何东西。
#
# T=4 时，可见关系是：
#
#     q0 -> k0
#     q1 -> k0 k1
#     q2 -> k0 k1 k2
#     q3 -> k0 k1 k2 k3
#
# 这就是下三角 causal mask，也就是代入公式里 M 的方式：
#
#     下三角（含对角线）取 0        → 可见
#     上三角取 -∞                   → 禁止
#
# 禁止位置便在 softmax 之前从 score 中排除，而不是"算完再乘掉"。
# 这一点很重要：如果被禁止的 score 参加了 softmax，
# 它仍会分走一部分概率，留下来的权重也会随之改变。
#
# ── 一个可直接观察的性质 ──────────────────────────────────────────────────
# 固定前缀、任意改动未来 token，前缀位置的输出保持不变。
# 这条性质是判断"你写的到底是不是 causal attention"最省事的实验：
#
#     x2 = x.clone()
#     x2[:, 4:] = torch.randn_like(x2[:, 4:])
#     y1 = attention(x); y2 = attention(x2)
#     # y1[:, :4] 与 y2[:, :4] 在浮点容差内一致
#
# 反向对照：改动前文通常会改变后面位置的输出。
# 如果末位 logits 始终不随前文变化，实际运行的可能仍是逐 token MLP。
# ============================================================================


# ============================================================================
# 第5节：原论文和本章模型并不相同
# ============================================================================
# 《Attention Is All You Need》用于机器翻译，结构是 encoder-decoder：
#
#     source -> Encoder ------------------+
#                                           -> Decoder -> target logits
#     shifted target -> masked self-attn --+   (含 cross-attention)
#
#   左半：Encoder 读源语言句子，产出 context；
#   右半：Decoder 一边看已生成的目标语言前缀（masked self-attn），
#         一边通过 cross-attention 去读 Encoder 的 context。
#
# 本章走 decoder-only 路线：
#
#     已有 token -> causal self-attention -> next-token logits
#
#   Decoder-only 没有 encoder，也没有 cross-attention；
#   Q/K/V 全部来自当前 token 序列。
#
# ── 对照表：两种结构中 Q/K/V 的来源 ───────────────────────────────────────
#   self-attention  : Q、K、V 全部来自同一序列
#   cross-attention : Q 来自 decoder，K、V 来自 encoder 的 context
#
# 也就是说，"cross"指的是 Q 与 K/V 不同源。理解了这点，
# 就能把任何 attention 变体归结为一句：Q 从哪来，K/V 从哪来。
# ============================================================================


