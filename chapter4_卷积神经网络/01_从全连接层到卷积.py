"""
=============================================================================
从全连接层到卷积 —— 为什么需要卷积神经网络（完整带注释版）
=============================================================================
本节从全连接层处理图像的局限性出发，推导出卷积层的数学表达。
核心思想：
  - 平移不变性 (translation invariance)：无论物体出现在图像哪里，检测方式应相同
  - 局部性 (locality)：每个神经元只需关注图像的一小块区域
  - 通道 (channel)：图像的第三维度（RGB 三色）
通过这三个概念，卷积层将全连接层的 10^9 级参数量降低到几百个。
=============================================================================
"""

# ============================================================================
# 补充 0：背景 —— 全连接层处理图像时的问题
# ============================================================================
"""
（本节为纯理论/markdown，无代码。以下为关键概念的注释版总结。）

问题：全连接层处理百万像素图像的困境
  假设一张 1000×1000 的图片 = 100 万个像素 = 输入维度 10^6
  如果隐藏层有 1000 个神经元：
    参数量 = 10^6 × 10^3 = 10^9（10 亿个参数！）

  后果：
    - 需要海量 GPU 显存和分布式训练经验
    - 需要海量标注数据来防止过拟合
    - 训练成本不可接受

  关键洞察：
    图像数据有丰富的"空间结构"可以利用，全连接层却完全忽略这些结构。

卷积神经网络的设计来自两个基本假设：
"""

# ============================================================================
# 补充 1：平移不变性（Translation Invariance）
# ============================================================================
"""
定义：
  无论检测对象出现在图像中的哪个位置，神经网络的前几层应该
  对相同的图像模式产生相同的响应。

直观理解：
  "沃尔多在哪里"游戏 —— 沃尔多的样子不取决于他藏在哪个位置。
  我们可以用同一个"沃尔多检测器"扫描整张图像的每个区域。

数学表达：
  从全连接的 4 阶权重张量 W[i,j,k,l] 到卷积的 2 阶核 V[a,b]：

  全连接：H[i,j] = U + sum_k sum_l W[i,j,k,l] * X[k,l]
    每个输出位置 (i,j) 都有自己独立的一组权重 W[i,j,:,:]

  平移不变性施加后：V 不依赖于位置 (i,j)
    H[i,j] = u + sum_a sum_b V[a,b] * X[i+a, j+b]

  这就是卷积！同一个核 V 滑过整个图像，在不同位置共享参数。
  效果：参数量从 O(H×W×h×w) 降到 O(h×w)。

类比 C/C++ 编程：
  全连接 = 每个像素位置都写一个专门的 if 判断来检测沃尔多
  卷积   = 写一个通用的"沃尔多检测函数"，然后在每个位置调用它
"""

# ============================================================================
# 补充 2：局部性（Locality）
# ============================================================================
"""
定义：
  神经网络的前几层应该只探索输入图像中的局部区域，
  不过度关注图像中相隔很远区域之间的关系。
  全局信息可以在后续层中通过聚合局部特征来获得。

数学表达：
  限制 |a| > Δ 或 |b| > Δ 时 V[a,b] = 0：
    H[i,j] = u + sum_{a=-Δ}^{Δ} sum_{b=-Δ}^{Δ} V[a,b] * X[i+a, j+b]

  Δ 决定了卷积核的大小（如 3×3 时 Δ=1, 5×5 时 Δ=2）
  每层只关注一个局部窗口，深层网络再逐步聚合全局信息。

直观理解：
  要识别一只猫，不需要同时看到猫耳朵和猫尾巴的像素。
  底层只需检测边缘、纹理等局部特征；
  高层再将这些局部特征组合成耳朵、眼睛、尾巴等部件；
  最终汇聚成"这是一只猫"的全局判断。

这是层次化特征学习的核心思想。
"""

# ============================================================================
# 补充 3：通道（Channel）
# ============================================================================
"""
图像不仅是二维的（高×宽），还有第三维——通道：
  - RGB 彩色图：3 个通道（红、绿、蓝）
  - 灰度图：1 个通道
  - 中间层特征：可以有任意多个通道（如 64, 128, 256...）

三维表示：
  X[i, j, c] 表示位置 (i, j) 处第 c 个通道的值

多通道卷积的完整形式：
  H[i, j, d] = sum_{a=-Δ}^{Δ} sum_{b=-Δ}^{Δ} sum_c V[a, b, c, d] * X[i+a, j+b, c]

  其中：
    c = 输入通道索引（0 到 c_i-1）
    d = 输出通道索引（0 到 c_o-1）
    V 的形状：(k_h, k_w, c_i, c_o) —— 4 阶张量

  每个输出通道 d 都有自己的一组卷积核（覆盖所有输入通道），
  不同的输出通道学习不同的特征模式：
    通道 0 可能检测水平边缘
    通道 1 可能检测垂直边缘
    通道 2 可能检测纹理
    ...

通道 = 特征映射 (feature map) = 从不同角度描述同一个空间位置。
"""

# ============================================================================
# 补充 4：互相关 vs 严格卷积
# ============================================================================
"""
在深度学习中，我们说的"卷积"其实指的是"互相关"（cross-correlation）：

  互相关：(f ★ g)(i, j) = sum_a sum_b f(a, b) * g(i+a, j+b)
  严格卷积：(f * g)(i, j) = sum_a sum_b f(a, b) * g(i-a, j-b)
                                    ↑ 这里是减法（核被翻转了）

关键区别：严格卷积会翻转卷积核（上下+左右颠倒），互相关不翻转。

为什么深度学习中不区分？
  因为卷积核的权重是从数据中学习到的，无论翻转与否，
  学到的权重会自动调整方向，最终效果完全相同。
  所以我们统一叫"卷积"，实际做的是"互相关"。
"""

# ============================================================================
# 总结
# ============================================================================
"""
1. 为什么需要 CNN：全连接层处理图像的参数量爆炸（10^9 级）
2. 平移不变性 → 不同位置共享同一组权重（卷积核），大幅减少参数
3. 局部性 → 每层只关注局部窗口，通过层次化堆叠获得全局视野
4. 通道 → 图像有多个通道（RGB），每层输出多个通道（特征映射）
5. 卷积层参数 = 卷积核大小 × 输入通道数 × 输出通道数（通常几百到几千）
6. "卷积"在深度学习中实际是"互相关"，但两者对学习结果无影响
"""
