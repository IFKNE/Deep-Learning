# 补充 3：常见问题 / 练习思考
# ============================================================================
"""
Q1: corr2d 函数中为什么用双重循环而不是矩阵乘法？
A1: 这里是最直接的"滑动窗口"算法（im2col 的前身），
    旨在帮助理解互相关的本质。实际 nn.Conv2d 使用高度优化的
    im2col + GEMM（矩阵乘法）实现，利用了 GPU 的并行计算能力。

Q2: 为什么偏置 b 是一个标量（不是与输出同形状的张量）？
A2: 卷积层的偏置是"逐通道"的。每个输出通道只有一个偏置值，
    该值被广播加到该通道的所有空间位置上。
    这保持了平移不变性 —— 偏置不依赖于空间位置。

Q3: 转置图像后边缘检测失败说明什么？
A3: 说明卷积核有"方向性"。要检测水平边缘，
    需要 [[1], [-1]] 这样的垂直核。
    这也是为什么 CNN 需要多个输出通道 —— 每个通道学习不同的方向/模式。

Q4: 为什么 pytorch 的 nn.Conv2d 输入是四维的？
A4: (N, C, H, W) 格式：
    N = batch size（批量大小，一次处理多个样本）
    C = channels（通道数，RGB 图=3，灰度图=1）
    H = height（图像高度）
    W = width（图像宽度）
    这允许一次前向传播处理一整批图像，充分利用 GPU 并行能力。
"""

