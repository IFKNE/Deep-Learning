"""
1. 互相关运算 = 卷积核在输入上滑动，每个位置做逐元素乘法 + 求和
2. 自定义卷积层：用 nn.Parameter 包裹 weight 和 bias
3. 卷积核可以检测边缘：[1, -1] 核检测垂直边缘
4. 卷积核的权重可以通过梯度下降从数据中学习
5. 互相关 vs 严格卷积：翻转核可等价，不影响学习结果
6. 感受野 = 影响某个神经元的所有输入区域，堆叠层数 = 扩大感受野
"""
