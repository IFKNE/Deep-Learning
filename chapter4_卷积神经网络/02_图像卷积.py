# ============================================================================
# 补充 1：互相关 vs 严格卷积
# ============================================================================
"""
互相关 (cross-correlation)：Y[i,j] = sum_a sum_b X[i+a, j+b] * K[a, b]
严格卷积 (convolution)：    Y[i,j] = sum_a sum_b X[i-a, j-b] * K[a, b]
                                          ↑ 核被水平+垂直翻转

为什么在深度学习中不区分？
  - 卷积核是从数据中学到的，不是手工设计的
  - 互相关学到的核 ≈ 严格卷积学到了翻转后的核
  - 最终输出完全等价，不影响模型效果
  - "卷积"比"互相关"更广为人知，所以沿用了这个名字

类似：数学中说的 f*g 是严格卷积，但代码里 nn.Conv2d 做的是互相关。
"""

# ============================================================================
# 补充 2：感受野 (Receptive Field)
# ============================================================================
"""
定义：
  对于网络中某一层的任意元素 x，其感受野 = 前向传播期间可能影响 x 计算
  的所有输入元素（来自之前所有层）。

示例：
  第1层：2×2 卷积 → 每个输出元素的感受野 = 输入中的 2×2=4 个元素
  第2层：在输出上再做 2×2 卷积 → 最终输出 T 的每个元素
    → T 的感受野 = 第1层输出中的 2×2 个元素
    → 追溯到输入 = 输入中的 3×3 个元素

关键结论：
  堆叠更多卷积层 = 每个神经元的感受野增大
  浅层 → 小感受野（只看到局部纹理）
  深层 → 大感受野（可以看到整个物体的轮廓）

这解释了为什么深度 CNN 有效：逐层扩大"视野"，从细节到全局。
"""

