# ============================================================================
# 理论铺垫：注意力为什么重要？—— 双组件框架
# ============================================================================
# 人的感官输入每分钟约 10^8 位，远超大脑处理能力，因此必须"聚焦"。
# 威廉·詹姆斯提出的双组件框架：
#   - 非自主性提示（基于突出性）：如一张黑白桌面上的红色咖啡杯，
#     它太醒目，注意力会"不由自主"地被吸过去。
#   - 自主性提示（基于意识/目标）：如"我想读书"，于是主动把注意力转向书本。
#
# 从这个框架抽象出注意力机制的三要素：
#   - 查询 query：自主性提示（用户/任务想找什么）
#   - 键 key：   非自主性提示（每个候选的"标签/索引"）
#   - 值 value： 感官输入（每个候选的内容/特征表示）
#
# 注意力池化（attention pooling）的作用：
#   用查询去跟每个键匹配，把匹配程度变成权重，
#   再按权重对"值"做加权求和，从而"选择性聚焦"到与查询最匹配的值上。
#
# 与全连接/池化层的本质区别：注意力机制引入了"自主提示（查询）"，
# 而全连接/池化层只能做无脑的平均或固定映射。


# ============================================================================
# 第1步：导入依赖
# ============================================================================
import torch
from d2l import torch as d2l


# ============================================================================
# 第2步：可视化注意力权重 show_heatmaps
# ============================================================================
def show_heatmaps(matrices, xlabel, ylabel, titles=None, figsize=(2.5, 2.5),
                  cmap='Reds'):
    """显示矩阵热图（用于可视化注意力权重）"""
    # 使用 SVG 渲染以便在 notebook 中清晰显示
    d2l.use_svg_display()
    # matrices 形状：(要显示的"行"数, "列"数, 查询数, 键数)
    #   前两维是"子图网格"的行列，后两维是每个子图里要画的矩阵
    num_rows, num_cols = matrices.shape[0], matrices.shape[1]
    # 创建 num_rows×num_cols 的子图网格
    fig, axes = d2l.plt.subplots(num_rows, num_cols, figsize=figsize,
                                 sharex=True, sharey=True, squeeze=False)
    for i, (row_axes, row_matrices) in enumerate(zip(axes, matrices)):
        for j, (ax, matrix) in enumerate(zip(row_axes, row_matrices)):
            # imshow 绘制热图，颜色映射 cmap 决定"权重大的地方更红"
            pcm = ax.imshow(matrix.detach().numpy(), cmap=cmap)
            if i == num_rows - 1:   # 只在最后一行标 x 轴（Keys）
                ax.set_xlabel(xlabel)
            if j == 0:              # 只在第一列标 y 轴（Queries）
                ax.set_ylabel(ylabel)
            if titles:
                ax.set_title(titles[j])   # 每个子图一个标题
    # 添加右侧颜色条
    fig.colorbar(pcm, ax=axes, shrink=0.6)


# ============================================================================
# 第3步：用单位矩阵演示"只匹配自身"
# ============================================================================
# 构造一个 (1,1,10,10) 的单位阵 attention_weights：
#   对角线为 1，其余为 0 —— 表示"查询和键相同时权重为1，否则为0"。
attention_weights = torch.eye(10).reshape((1, 1, 10, 10))
# 画出热图：横轴是键（Keys），纵轴是查询（Queries）
show_heatmaps(attention_weights, xlabel='Keys', ylabel='Queries')
# 你会看到一条从左上到右下的对角线 —— 每个查询只"关注"和自己相同的那个键。


# ============================================================================
# 补充知识点
# ============================================================================
# 1. 【查询/键/值在机器学习中的直观映射】
#    - 查询 query：你"想要找什么"（例如：翻译时当前想生成的词）
#    - 键 key：    候选的"地址/标签"（例如：源序列每个词元的位置）
#    - 值 value：  候选的"内容"（例如：源序列每个词元的表示向量）
#    注意力输出 = 每个值的加权平均，权重由"查询×键的契合度"决定。

# 2. 【为什么平均池化(mean pooling)不算注意力？】
#    平均池化把所有值一视同仁、权重相同，它没有"查询"——即没有主观目标，
#    所以无法根据任务需要去"挑选"。引入查询后，权重才会因查询而异，
#    这就是"注意力"与"普通汇聚"的分水岭。

# 3. 【可微性】
#    有些任务用不可微的注意力模型（配合强化学习），但本课程强调"可微"注意力，
#    这样就能用反向传播端到端训练。show_heatmaps 就是用来观察"可微注意力"学
#    到的注意力权重的工具。

# 4. 【为什么强调"键和值是成对的"】
#    每个键 k_i 绑定一个值 v_i。注意力通过"查询+键"算出权重，再作用于对应值。
#    键是"索引式提示"，值是"内容"，二者必须配对出现。


# ============================================================================
# 核心公式回顾
# ============================================================================
#   注意力池化：f(q, (k_1,v_1),...,(k_m,v_m)) = Σ_{i=1}^m α(q, k_i) · v_i
#   其中注意力权重（归一化成概率分布）：
#       α(q, k_i) = softmax( a(q, k_i) )
#   - α(q, k_i) 非负且和为 1（有效概率分布）
#   - a 是"注意力评分函数"，不同的 a 得到不同的注意力机制（见 03 节）


