"""
=============================================================================
自注意力与位置编码（Self-Attention & Positional Encoding）—— 完整带注释版
=============================================================================
任务：让"同一组输入词元"同时充当查询、键和值来做注意力，即"自注意力"。
     比较 CNN / RNN / 自注意力三者的计算复杂度、并行性与最大路径长度。
     最后介绍"位置编码"——给没有顺序信息的自注意力注入位置信息。

依赖：d2l 包。本文件可独立运行。
=============================================================================
"""

# ============================================================================
# 第1步：导入依赖
# ============================================================================
import math
import torch
from torch import nn
from d2l import torch as d2l


# ============================================================================
# 第2步：自注意力 = 用多头注意力直接对同一组输入做注意力
# ============================================================================
# 给定序列 x_1,...,x_n（每个 x_i ∈ R^d），自注意力输出等长序列 y_1,...,y_n：
#   y_i = f( x_i, (x_1, x_1), ..., (x_n, x_n) ) ∈ R^d
# 也就是每个查询 x_i 去跟"所有键值对(它们也是 x_1..x_n)"做注意力池化。

num_hiddens, num_heads = 100, 5
# 复用上一节的多头注意力作为"自注意力"实现
attention = d2l.MultiHeadAttention(num_hiddens, num_hiddens, num_hiddens,
                                   num_hiddens, num_heads, 0.5)
attention.eval()

batch_size, num_queries, valid_lens = 2, 4, torch.tensor([3, 2])
# 输入 X 形状 (batch, num_steps, num_hiddens)
X = torch.ones((batch_size, num_queries, num_hiddens))
# 自注意力：查询/键/值全部 = X（同一组输入）
attention(X, X, X, valid_lens).shape   # torch.Size([2, 4, 100])，输入输出同形状


# ============================================================================
# 第3步：比较 CNN、RNN、自注意力（理论）
# ============================================================================
# 目标：把 n 个词元（各 d 维）映射成等长序列。比较三个指标：
#
# ┌──────────────────┬────────────────────┬─────────────┬─────────────────┐
# │ 架构             │ 计算复杂度         │ 顺序操作数  │ 最大路径长度     │
# ├──────────────────┼────────────────────┼─────────────┼─────────────────┤
# │ CNN(核大小 k)    │ O(k·n·d²)          │ O(1)        │ O(n/k)          │
# │ RNN              │ O(n·d²)            │ O(n)        │ O(n)            │
# │ 自注意力         │ O(n²·d)            │ O(1)        │ O(1)            │
# └──────────────────┴────────────────────┴─────────────┴─────────────────┘
#
# 解读：
#   - 顺序操作越少 → 越能并行（自注意力 O(1)，可整体并行）。
#   - 最大路径越短 → 越容易学到"远距离依赖"。自注意力每个位置都直接连到所有位置，
#     所以路径只有 O(1)；RNN 需经过 O(n) 步；CNN 需叠 O(n/k) 层。
#   - 但注意：自注意力复杂度 O(n²·d) 随序列长度 n 呈二次方增长，长序列会很慢。


# ============================================================================
# 第4步：位置编码 PositionalEncoding
# ============================================================================
# 自注意力因并行而放弃了"顺序操作"，模型不知道词元先后顺序。
# 解决办法：给输入表示加上"位置编码"，注入绝对或相对位置信息。
# 下面是基于正弦/余弦函数的"固定"位置编码：
#   p_{i,2j}   = sin( i / 10000^{2j/d} )
#   p_{i,2j+1} = cos( i / 10000^{2j/d} )

class PositionalEncoding(nn.Module):
    """位置编码"""
    def __init__(self, num_hiddens, dropout, max_len=1000):
        super(PositionalEncoding, self).__init__()
        self.dropout = nn.Dropout(dropout)
        # P 形状 (1, max_len, num_hiddens)：第 i 行是第 i 个位置的编码
        self.P = torch.zeros((1, max_len, num_hiddens))
        # X 是位置索引 i 与"频率倒数"的比值，用于生成三角函数参数
        #   分子：arange(max_len) 即位置 i (0,1,2,...)
        #   分母：10000^{2j/d}，j 从 0 到 num_hiddens-1 每隔 2 取
        #   这使"低频维"(高 j)周期更长，"高频维"(低 j)周期更短
        X = torch.arange(max_len, dtype=torch.float32).reshape(
            -1, 1) / torch.pow(10000, torch.arange(
                0, num_hiddens, 2, dtype=torch.float32) / num_hiddens)
        # 偶数维(0,2,4,...)用 sin，奇数维(1,3,...)用 cos
        self.P[:, :, 0::2] = torch.sin(X)
        self.P[:, :, 1::2] = torch.cos(X)

    def forward(self, X):
        # P 的前 X.shape[1] 行加上输入（位置编码与嵌入逐元素相加）
        X = X + self.P[:, :X.shape[1], :].to(X.device)
        # 用 dropout 做正则化
        return self.dropout(X)


# 演示编码维度与频率的关系：第 6、7 列频率高于第 8、9 列
encoding_dim, num_steps = 32, 60
pos_encoding = PositionalEncoding(encoding_dim, 0)
pos_encoding.eval()
X = pos_encoding(torch.zeros((1, num_steps, encoding_dim)))
P = pos_encoding.P[:, :X.shape[1], :]
# 画第 6~9 列随"位置(行)"的变化曲线：低维(6,7)振荡快，高维(8,9)振荡慢
d2l.plot(torch.arange(num_steps), P[0, :, 6:10].T, xlabel='Row (position)',
         figsize=(6, 2.5), legend=["Col %d" % d for d in torch.arange(6, 10)])


# ============================================================================
# 第5步：绝对位置信息 —— 用"二进制表示"做直觉类比
# ============================================================================
# 打印 0..7 的二进制：低位(最低位)交替快，高位交替慢。
for i in range(8):
    print(f'{i}的二进制是：{i:>03b}')
# 0→000, 1→001, ..., 7→111
# 位置编码其实很像"连续的二进制"：低编码维振荡快(对应低位)，高编码维振荡慢(对应高位)。
# 但二进制是离散的，而位置编码用三角函数给出连续值，更节省空间、也便于求导。

# 画出整个位置编码矩阵的热图（横轴=编码维，纵轴=位置）
P = P[0, :, :].unsqueeze(0).unsqueeze(0)
d2l.show_heatmaps(P, xlabel='Column (encoding dimension)',
                  ylabel='Row (position)', figsize=(3.5, 4), cmap='Blues')


# ============================================================================
# 第6步：相对位置信息 —— 位置编码为什么能表示"相对偏移"？
# ============================================================================
# 令 ω_j = 1 / 10000^{2j/d}。位置 i+δ 的编码可被位置 i 的编码"线性投影"过去：
#   [ p_{i+δ,2j} ]     [ cos(δω_j)   sin(δω_j) ]   [ p_{i,2j} ]
#   [ p_{i+δ,2j+1} ] = [ -sin(δω_j)  cos(δω_j) ] · [ p_{i,2j+1} ]
# 这个 2×2 旋转/投影矩阵只依赖偏移 δ，不依赖索引 i。
#   —— 这就是"相对位置信息"的数学来源：位置编码不仅含绝对位置，还能线性地
#      编码出"任意相对偏移"。


# ============================================================================
# 补充知识点
# ============================================================================
# 1. 【自注意力的"完美并行 + 最短路径"价值】
#    相比 CNN/RNN，自注意力既支持整体并行计算，又让任意两位置之间路径最短(O(1))，
#    因而特别适合学习长距离依赖。代价是 O(n²·d) 的复杂度在长序列上暴涨。

# 2. 【为什么用 sin/cos 而不是可学的位置向量？】
#    固定的 sin/cos 无需训练、且天然能表达"相对偏移"（见上面的线性投影恒等式），
#    还能外推到比训练更长的序列。当然也可改成可学习的位置编码（见练习2）。

# 3. 【编码逐维频率递减的设计】
#    位置编码把"位置 i"编码成一个 d 维向量，最低维频率最高（像二进制最低位），
#    用连续浮点数替代二进制的离散 0/1，既保留绝对位置又支持微小的连续差异。

# 4. 【位置编码如何加进嵌入】
#    直接做"逐元素相加"：X_embed + P。要求二者形状一致（都含 num_hiddens 维）。


