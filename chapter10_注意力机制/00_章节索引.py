# ============================================================================
#  《动手学深度学习》第10章：注意力机制 — 章节索引
# ============================================================================
#  第9章我们用"编码器-解码器"把变长序列翻译成变长序列，但解码器每一步都用
#  *同一个*上下文变量 c，而实际上只有部分源词元对当前词元有用。本章引入
#  "注意力机制"来解决这个"选择性聚焦"问题：
#
#    核心思想：给每个"值"（感官输入）配一个"键"，再用"查询"（自主提示）去跟键
#    匹配，算出注意力权重，最终加权求和得到输出。即
#        attention(q, (k_1,v_1),...) = Σ_i α(q, k_i) · v_i
#
#  学习主线：注意力提示(概念) → Nadaraya-Watson 核回归(第一个注意力模型) →
#            注意力评分函数(加性/点积) → Bahdanau注意力(seq2seq应用) →
#            多头注意力(多个子空间) → 自注意力与位置编码(Transformer地基) →
#            Transformer(完全基于注意力)。
# ============================================================================

# ============================================================================
# 1. 注意力提示
#    源文件: attention-cues.ipynb
#    目标文件: 01_注意力提示.py
# ----------------------------------------------------------------------------
#  内容要点:
#    - 注意力是稀缺资源；人脑只把注意力投向"醒目/值得关注"的一小部分信息
#    - 双组件框架：非自主性提示(基于突出性，如红杯子) 与 自主性提示(基于意识/目标)
#    - 注意力机制三要素：查询 query = 自主提示、键 key = 非自主提示、
#      值 value = 感官输入；注意力池化把"查询×键"匹配到的权重赋给对应值
#    - 与全连接/池化层的关键区别：是否引入了"自主提示(查询)"
#    - 可视化注意力权重 show_heatmaps(用单位阵演示)
#  学习目标:
#    建立"查询-键-值"的注意力框架直觉，能可视化注意力权重
#  前置知识:
#    无（本章第一节，纯概念）
#  学习建议:
#    记住"查询/键/值"的对应关系，这是全章最核心的三个词
# ============================================================================

# ============================================================================
# 2. 注意力汇聚：Nadaraya-Watson 核回归
#    源文件: nadaraya-waston.ipynb
#    目标文件: 02_Nadaraya-Watson核回归.py
# ----------------------------------------------------------------------------
#  内容要点:
#    - 核回归问题：由 {(x_i,y_i)} 学 f，预测新点 x 的输出
#    - 平均池化 f(x)=Σy_i/n（最差，忽略输入）
#    - 非参数注意力池化：f(x)=Σ_i α(x,x_i) y_i，用高斯核 K(u)=exp(-u²/2)
#      → α = softmax(-(x-x_i)²/2)，键越接近查询权重越大
#    - 带参数的注意力池化：再乘一个可学习标量 w，softmax(-((x-x_i)w)²/2)
#    - 批量矩阵乘法 torch.bmm：高效算多批量加权平均
#    - NWKernelRegression 类 + 训练 + 对比非参数/带参数曲线平滑度
#  学习目标:
#    理解"注意力池化=加权平均"，并能用 PyTorch 实现非参数与带参数两种版本
#  前置知识:
#    核函数、softmax、矩阵乘法、线性回归/MLP 训练
#  学习建议:
#    亲手比较"平均池化/非参数/带参数"三条预测曲线的差异
# ============================================================================

# ============================================================================
# 3. 注意力评分函数
#    源文件: attention-scoring-functions.ipynb
#    目标文件: 03_注意力评分函数.py
# ----------------------------------------------------------------------------
#  内容要点:
#    - 通用框架：α(q,k_i)=softmax(a(q,k_i))，a 即"评分函数"
#    - 掩蔽 softmax masked_softmax：把超出有效长度的位置置为 0（1d/2d 有效长度）
#    - 加性注意力 AdditiveAttention：a = w_vᵀ tanh(W_q q + W_k k)，适合 q、k 长度不同
#    - 缩放点积注意力 DotProductAttention：a = q·k/√d，适合 q、k 长度相同且效率更高
#    - 二者用相同键值演示，得到均匀权重（键无法区分）
#  学习目标:
#    掌握两种主流评分函数的适用场景与实现
#  前置知识:
#    注意力池化框架、softmax、多层感知机、广播
#  学习建议:
#    理解为什么点积要除以 √d（防止方差随维度增大而失调）
# ============================================================================

# ============================================================================
# 4. Bahdanau 注意力
#    源文件: bahdanau-attention.ipynb
#    目标文件: 04_Bahdanau注意力.py
# ----------------------------------------------------------------------------
#  内容要点:
#    - 改进 seq2seq：把"固定上下文 c"换成"每个解码步动态变化的 c_{t'}"
#    - c_{t'} = Σ_t α(s_{t'-1}, h_t) h_t，查询=上一解码步隐状态 s_{t'-1}，
#      键=值=编码器各时间步隐状态 h_t
#    - AttentionDecoder 基类（多了 attention_weights 属性）
#    - Seq2SeqAttentionDecoder：加性注意力 + GRU；首步用编码器末态初始化
#    - 训练（tokens/sec 明显变慢）与 BLEU 评估；可视化注意力权重
#  学习目标:
#    理解 Bahdanau 注意力如何"动态对齐"输入与输出，改善翻译
#  前置知识:
#    seq2seq(第9章)、加性注意力、编码器-解码器接口
#  学习建议:
#    与上一章 seq2seq 对比：唯一区别是"上下文变量"改为注意力池化输出
# ============================================================================

# ============================================================================
# 5. 多头注意力
#    源文件: multihead-attention.ipynb
#    目标文件: 05_多头注意力.py
# ----------------------------------------------------------------------------
#  内容要点:
#    - 动机：让模型在一组查询键值上"并行学习多种注意力行为"，捕捉不同范围依赖
#    - 把 q/k/v 各做 h 组不同线性投影，分别做注意力，再拼接、过 W_o 输出
#    - 头 h_i = f(W_i^q q, W_i^k k, W_i^v v)
#    - 设定 p_q=p_k=p_v=p_o/h，可并行计算 h 个头
#    - MultiHeadAttention + transpose_qkv / transpose_output（批头维转换）
#  学习目标:
#    理解"多头"如何用不同的子空间表示组合出更复杂的关系
#  前置知识:
#    缩放点积注意力、线性层、广播与 permute 转置
#  学习建议:
#    重点看懂 transpose_qkv 如何把 (batch, n, h*head) 变成 (batch*head, n, head)
# ============================================================================

