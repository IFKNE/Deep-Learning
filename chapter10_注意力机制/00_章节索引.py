# 7. Transformer
#    源文件: transformer.ipynb
#    目标文件: 07_Transformer.py
# ----------------------------------------------------------------------------
#  内容要点:
#    - 完全基于注意力（无 CNN/RNN）的编码器-解码器架构
#    - 基于位置的前馈网络 PositionWiseFFN：对每个位置用同一个两层的 MLP
#    - 残差连接 + 层规范化 AddNorm；层规范(沿特征维) vs 批量规范
#    - 编码器 EncoderBlock：多头自注意力 + AddNorm + 前馈 + AddNorm，堆叠 num_layers
#    - 解码器 DecoderBlock：掩蔽自注意力 + 编码器-解码器注意力 + 前馈，三层子结构
#    - TransformerEncoder / TransformerDecoder；训练与 BLEU；注意力权重可视化
#  学习目标:
#    端到端跑通 Transformer 的每个组件，理解残差/层规范/掩蔽的作用
#  前置知识:
#    多头注意力、自注意力与位置编码、seq2seq、层/批量规范化
#  学习建议:
#    全章重中之重。边读边核对每层张量形状，注意"没有任何层改变输入形状"
# ============================================================================

