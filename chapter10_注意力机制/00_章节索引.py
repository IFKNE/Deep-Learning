# 6. 自注意力与位置编码
#    源文件: self-attention-and-positional-encoding.ipynb
#    目标文件: 06_自注意力与位置编码.py
# ----------------------------------------------------------------------------
#  内容要点:
#    - 自注意力：查询、键、值都来自同一输入序列（y_i=f(x_i,(x_1,x_1),...)）
#    - 对比 CNN / RNN / 自注意力：计算复杂度、并行性、最大路径长度
#      CNN O(knd²)/顺序O(1)/路径O(n/k)；RNN O(nd²)/顺序O(n)/路径O(n)；
#      自注意力 O(n²d)/顺序O(1)/路径O(1)
#    - 自注意力并行且路径最短，但复杂度随序列长度平方增长
#    - 位置编码 PositionalEncoding：正弦/余弦，p_{i,2j}=sin(i/10000^{2j/d})，
#      提供绝对与相对位置信息；二进制的连续化版本
#  学习目标:
#    理解自注意力为何成为 Transformer 核心，以及位置编码的数学设计理由
#  前置知识:
#    多头注意力、CNN/RNN、正弦与余弦、矩阵乘法复杂度
#  学习建议:
#    用"二进制表示"打通位置编码的直觉，再理解相对位置的线性投影
# ============================================================================

