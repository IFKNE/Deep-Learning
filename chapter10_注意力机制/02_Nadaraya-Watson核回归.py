"""
=============================================================================
注意力汇聚：Nadaraya-Watson 核回归（Attention Pooling）—— 完整带注释版
=============================================================================
任务：用最简单、最完整的例子演示"注意力机制"——Nadaraya-Watson 核回归。
     这是一个把注意力池化写成"值的加权平均"的经典模型。

  核心：f(x) = Σ_i α(x, x_i) · y_i
       - 查询 = 新输入 x
       - 键   = 训练输入 x_i（non-parameter，非自主提示）
       - 值   = 训练输出 y_i（感官输入）
       - 权重 α 由"查询与键的距离"决定（用高斯核）

  演进：平均池化(无脑平均) → 非参数注意力(高斯核权重) → 带参数注意力(学可学习 w)。

依赖：d2l 包。本文件可独立运行。
=============================================================================
"""

# ============================================================================
# 第1步：导入依赖
# ============================================================================
import torch
from torch import nn
from d2l import torch as d2l


# ============================================================================
# 第2步：生成数据集
# ============================================================================
# 我们要学一个一元函数 f，从成对数据 {(x_i,y_i)} 预测任意新点 x 的输出。
# 真实函数：y = 2·sin(x) + x^0.8 + ε，ε ~ N(0, 0.5²)
n_train = 50  # 训练样本数
# 在 [0,5) 均匀采样 50 个点，并"排序"（排序便于观察注意力模式的对称性）
x_train, _ = torch.sort(torch.rand(n_train) * 5)


def f(x):
    # 无噪声的"真实"函数（作为对照的标准答案）
    return 2 * torch.sin(x) + x ** 0.8


# 训练输出 = 真实值 + 噪声
y_train = f(x_train) + torch.normal(0.0, 0.5, (n_train,))
# 测试样本：在 [0,5) 上等间距取点（用于画平滑曲线）
x_test = torch.arange(0, 5, 0.1)
y_truth = f(x_test)  # 测试集真实输出（无噪声）
n_test = len(x_test)
n_test  # 50


# ============================================================================
# 第3步：绘图辅助函数 plot_kernel_reg
# ============================================================================
def plot_kernel_reg(y_hat):
    # d2l.plot 画 "Truth(真实直线)" 与 "Pred(预测曲线)"
    d2l.plot(x_test, [y_truth, y_hat], 'x', 'y', legend=['Truth', 'Pred'],
             xlim=[0, 5], ylim=[-1, 5])
    # 把 50 个训练样本点(圆圈)也画上去
    d2l.plt.plot(x_train, y_train, 'o', alpha=0.5)


# ============================================================================
# 第4步：平均汇聚（最朴素的估计器，作为对照）
# ============================================================================
# f(x) = (1/n) Σ y_i —— 完全不看输入 x，直接取所有训练输出的平均值
#   这是"最笨"的做法：预测一条水平线。它忽略了输入位置信息。
y_hat = torch.repeat_interleave(y_train.mean(), n_test)
plot_kernel_reg(y_hat)
# 结果：Pred 是一条水平直线，与 Truth（波形函数）差异巨大——证明"无视输入"不可行。


# ============================================================================
# 第5步：非参数注意力汇聚（Nadaraya-Watson 核回归）
# ============================================================================
# 想法：根据输入的"位置"对 y_i 加权，而不是一视同仁：
#   f(x) = Σ_i [ K(x-x_i) / Σ_j K(x-x_j) ] · y_i
# 取高斯核 K(u) = (1/√(2π))·exp(-u²/2)，化简采样后得到：
#   f(x) = Σ_i softmax( -(x - x_i)²/2 ) · y_i
# 直观理解：键 x_i 越接近查询 x，分配给它的注意力权重越大 → "获得更多注意力"。

# X_repeat 形状 (n_test, n_train)：每一行都是同一个测试输入（同一个查询重复 n_train 次）
X_repeat = x_test.repeat_interleave(n_train).reshape((-1, n_train))

# x_train 是键。attention_weights 形状 (n_test, n_train)：
#   每一行是"对于一个给定查询，应在各值 y_train 之间分配的注意力权重"
#   softmax(-(X_repeat - x_train)²/2, dim=1)：保证每行是归一化的概率分布
attention_weights = nn.functional.softmax(-(X_repeat - x_train) ** 2 / 2, dim=1)

# y_hat 每个元素 = 值的加权平均，其中权重就是注意力权重：
#   用矩阵乘法 (n_test×n_train) @ (n_train,) = (n_test,)
y_hat = torch.matmul(attention_weights, y_train)
plot_kernel_reg(y_hat)
# 结果：Pred 曲线平滑，且明显比"平均汇聚"更接近 Truth（呈波浪形）。


# 观察注意力权重：查询=测试输入，键=训练输入。二者都排序过了，
# 可以看到"查询-键对越接近，注意力权重越高"（热图里沿对角线变亮）。
d2l.show_heatmaps(attention_weights.unsqueeze(0).unsqueeze(0),
                  xlabel='Sorted training inputs',
                  ylabel='Sorted testing inputs')


# ============================================================================
# 第6步：带参数的注意力汇聚
# ============================================================================
# 非参数版本有个"一致性"优点：数据足够时能收敛到最优。
# 但我们还想有"可学习的参数"。做法：在距离里乘一个可学习标量 w：
#   f(x) = Σ_i softmax( -((x - x_i)w)²/2 ) · y_i
# 训练这个 w，就能让模型自己决定"看重多近的邻居"。

### 小工具：批量矩阵乘法 torch.bmm
# torch.bmm 对"一批矩阵"做矩阵乘法：
#   形状 (n,a,b) × (n,b,c) → (n,a,c)
X = torch.ones((2, 1, 4))
Y = torch.ones((2, 4, 6))
torch.bmm(X, Y).shape   # torch.Size([2, 1, 6])

# 在注意力背景下，用 bmm 算"小批量里的加权平均"：
#   weights (2,10)*0.1，values (2,10)。下面把 weights 视为每行的权重(和为1)，
#   bmm(weights.unsqueeze(1), values.unsqueeze(-1)) 得到每批的加权和。
weights = torch.ones((2, 10)) * 0.1
values = torch.arange(20.0).reshape((2, 10))
torch.bmm(weights.unsqueeze(1), values.unsqueeze(-1))
# 输出：[[[4.5]], [[14.5]]]   (第 0 批均值 4.5，第 1 批均值 14.5)


# ============================================================================
# 第7步：定义带参数的注意力模型 NWKernelRegression
# ============================================================================
class NWKernelRegression(nn.Module):
    def __init__(self, **kwargs):
        super().__init__(**kwargs)
        # w 是唯一的可学习标量参数，初始化随机值并开启梯度
        self.w = nn.Parameter(torch.rand((1,), requires_grad=True))

    def forward(self, queries, keys, values):
        # queries 和 attention_weights 的形状 = (查询个数, 键-值对个数)
        # 把每个查询"平铺"成与键相同数量，便于逐查询与所有键做距离比较
        queries = queries.repeat_interleave(keys.shape[1]).reshape(
            (-1, keys.shape[1]))
        # 计算"带参数高斯核"的权重：softmax(-((queries - keys)*w)²/2)
        self.attention_weights = nn.functional.softmax(
            -((queries - keys) * self.w) ** 2 / 2, dim=1)
        # values 形状 (查询个数, 键-值对个数)
        # bmm(权重, 值) 完成"加权求和"，再展平成一维即预测值
        return torch.bmm(self.attention_weights.unsqueeze(1),
                         values.unsqueeze(-1)).reshape(-1)


# ============================================================================
# 第8步：训练带参数注意力模型
# ============================================================================
# 把训练集"自身"变成键和值：每个训练样本的输入，都要跟"除自己以外"的所有
#   训练样本的"键-值对"做注意力计算，得到它的预测值。
# X_tile (n_train, n_train)：每行是同一个训练输入
X_tile = x_train.repeat((n_train, 1))
Y_tile = y_train.repeat((n_train, 1))
# 用掩码 (1 - 单位阵) 去掉对角线（排除"自己看自己"），得到键和值
# keys / values 形状 (n_train, n_train-1)
keys = X_tile[(1 - torch.eye(n_train)).type(torch.bool)].reshape((n_train, -1))
values = Y_tile[(1 - torch.eye(n_train)).type(torch.bool)].reshape((n_train, -1))

# 用平方损失 + 随机梯度下降训练
net = NWKernelRegression()
loss = nn.MSELoss(reduction='none')
trainer = torch.optim.SGD(net.parameters(), lr=0.5)
animator = d2l.Animator(xlabel='epoch', ylabel='loss', xlim=[1, 5])

for epoch in range(5):
    trainer.zero_grad()
    l = loss(net(x_train, keys, values), y_train)
    l.sum().backward()     # 注意：loss 是"逐样本"，所以要 sum 后再反传
    trainer.step()
    print(f'epoch {epoch + 1}, loss {float(l.sum()):.6f}')
    animator.add(epoch + 1, float(l.sum()))


# ============================================================================
# 第9步：用训练好的模型做预测，并对比平滑度
# ============================================================================
# 测试时：键=全部训练输入，值=全部训练输出，查询=测试输入
keys = x_train.repeat((n_test, 1))
values = y_train.repeat((n_test, 1))
y_hat = net(x_test, keys, values).unsqueeze(1).detach()
plot_kernel_reg(y_hat)
# 结果：带参数模型的预测线更不平滑——它对"注意力权重大的区域"拟合得更激进。

# 可视化训练后的注意力权重
d2l.show_heatmaps(net.attention_weights.unsqueeze(0).unsqueeze(0),
                  xlabel='Sorted training inputs',
                  ylabel='Sorted testing inputs')


# ============================================================================
# 补充知识点
# ============================================================================
# 1. 【为什么带参数模型更"不平滑"？】
#    可学习参数 w 的加入，让模型可以"放大"距离差：w 变大时，接近查询的邻居
#    权重被显著放大、远的被压到接近 0，于是局部趋势显现得更尖锐、更贴合训练点。
#    这既是更强表达能力（可拟合噪声/细节），也带来过拟合的隐患（曲线更不平滑）。

# 2. 【平均池化 vs 非参数注意力 vs 带参数注意力】
#    - 平均池化：权重恒为 1/n，不看 x（最朴素）。
#    - 非参数注意力：权重 = softmax(-(x-x_i)²/2)，与高斯核距离相关，无需学习。
#    - 带参数注意力：权重 = softmax(-((x-x_i)w)²/2)，w 由训练学得（第一版"可学习注意力"）。

# 3. 【为什么高斯核能让权重成为"有效概率分布"？】
#    softmax 保证所有 α 非负且和为 1。所以注意力池化就是"值的加权平均"，
#    权重反映了"查询与各键的相似度"。

# 4. 【一致性（consistency）】
#    非参数 Nadaraya-Watson 核回归有一点很好：随着数据量增加会收敛到最优解。
#    这正是"非参数方法"的典型性质；而带参数版本要靠训练才能逼近。


# ============================================================================
# 核心公式回顾
# ============================================================================
#   真实函数：y = 2·sin(x) + x^0.8 + ε，ε~N(0,0.5²)
#   平均池化：f(x) = (1/n) Σ y_i
#   高斯核：  K(u) = (1/√(2π)) exp(-u²/2)
#   非参数：  f(x) = Σ_i softmax(-(x-x_i)²/2) · y_i
#   带参数：  f(x) = Σ_i softmax(-((x-x_i)w)²/2) · y_i
#   批量矩阵乘法：bmm( (n,a,b), (n,b,c) ) → (n,a,c)


