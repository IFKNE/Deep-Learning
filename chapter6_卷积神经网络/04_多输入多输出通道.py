# ============================================================================
# 补充 1：参数形状速查
# ============================================================================
"""
卷积层参数和输入/输出形状一览：

  输入 X：   (N, c_i,  H,    W)     ← 四维张量
  卷积核 W： (c_o, c_i, k_h, k_w)    ← 四阶张量（核心）
  偏置 b：   (c_o,)                  ← 每输出通道一个标量
  输出 Y：   (N, c_o, H_out, W_out)  ← 四维张量

  N    = batch size（批量大小）
  c_i  = 输入通道数（如 RGB=3）
  c_o  = 输出通道数（可任意设定，通常越来越大）
  k_h, k_w = 卷积核高、宽
  H_out = 由 H、k_h、padding、stride 共同决定

总可学习参数量 = c_o × c_i × k_h × k_w + c_o（最后 +c_o 是偏置）
"""

# ============================================================================
# 补充 2：1×1 卷积的三个经典用途
# ============================================================================
"""
1. 降维/升维（改变通道数）：
   输入 (256, H, W) → 1×1 卷积 (64, 256, 1, 1) → (64, H, W)
   用 256×64 个参数将通道从 256 降到 64
   这是 ResNet Bottleneck 的核心技巧

2. 增加非线性：
   1×1 卷积 + ReLU = 对每个像素的通道向量做非线性变换
   在不改变空间尺寸的前提下增加模型表达能力
   NiN (Network in Network) 以此闻名

3. 跨通道信息融合：
   3×3 卷积关注空间邻域，1×1 卷积关注通道间的组合
   两者配合覆盖了空间和通道两个维度的信息交互
"""

# ============================================================================
# 补充 3：计算量估算
# ============================================================================
"""
单层卷积的计算量（乘法次数）：
  FLOPs = H_out × W_out × c_o × c_i × k_h × k_w

以 VGG 第一层为例（224×224 输入，3 通道→64 通道，3×3 卷积）：
  H_out ≈ 224（padding=1 保持尺寸）
  FLOPs ≈ 224 × 224 × 64 × 3 × 3 × 3 ≈ 8.7 × 10^7（约 8700 万次乘法）

而全连接层（224×224×3 = 150528 输入 → 1000 输出）：
  FLOPs = 150528 × 1000 ≈ 1.5 × 10^8（约 1.5 亿次乘法）
  且参数量 = 1.5 亿 vs 卷积的 1728

卷积的优势：参数少但计算仍有代价（每个参数被重用了很多次）。
"""

# ============================================================================
# 补充 4：常见问题 / 练习思考
# ============================================================================
"""
Q1: 如何用 1×1 卷积实现降维？
A1: 设输入通道 c_i=256，输出通道 c_o=64
    conv = nn.Conv2d(256, 64, kernel_size=1)
    输出形状从 (256, H, W) → (64, H, W)，参数量仅 256×64+64 ≈ 16K

Q2: 两个 3×3 卷积能等效为一个 5×5 卷积吗？
A2: 是的！两个 3×3 卷积的感受野等于一个 5×5 卷积。
    但两个 3×3 有两个 ReLU 激活（更多非线性），且参数更少：
    5×5 参数 = 25c²，两个 3×3 参数 = 2×9c² = 18c²。
    这也是 VGG 全部用 3×3 的原因。
"""

# ============================================================================
# 总结
# ============================================================================
"""
1. 多输入通道：每个通道独立做互相关，结果求和
2. 多输出通道：堆叠多组卷积核，每个产生一个通道（=一个特征映射）
3. 卷积核完整形状：(c_o, c_i, k_h, k_w) — 四阶张量
4. 1×1 卷积 = 每个空间位置做全连接，用于调整通道数
5. 深层网络通常：空间尺寸 ↓、通道数 ↑（用更多通道补偿空间分辨率损失）
"""
