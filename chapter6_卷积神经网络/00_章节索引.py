# ============================================================================
# 1. 从全连接层到卷积
#    源文件: why-conv.ipynb
#    目标文件: 01_从全连接层到卷积.py
# ----------------------------------------------------------------------------
#  内容要点:
#    - 全连接层处理图像时的参数爆炸问题
#    - 平移不变性：无论物体在图像的哪个位置，检测方式应相同
#    - 局部性：每个隐藏神经元只需关注一小块局部区域
#    - 从全连接数学推导到卷积的数学表达
#    - 通道概念的引入
#  学习目标:
#    理解卷积层为什么比全连接层更适合处理图像，掌握平移不变性和局部性原理。
#  前置知识:
#    多层感知机（第4章）、线性代数（矩阵运算）
#  学习建议:
#    本节偏理论，重在理解"为什么卷积"。数学推导了解思路即可，不要求背诵。
# ============================================================================

# ============================================================================
# 2. 图像卷积（互相关运算）
#    源文件: conv-layer.ipynb
#    目标文件: 02_图像卷积.py
# ----------------------------------------------------------------------------
#  内容要点:
#    - 二维互相关运算的手动实现 (corr2d)
#    - 自定义 Conv2D 层：用 nn.Parameter 包装卷积核
#    - 边缘检测示例：用 [1, -1] 核检测垂直边缘
#    - 梯度下降学习卷积核参数
#    - 互相关 vs 严格卷积的区别
#    - 感受野 (receptive field) 概念
#  学习目标:
#    完全理解二维互相关运算的底层实现，能手动设计简单卷积核。
#  前置知识:
#    第 1 节（卷积原理）、nn.Parameter 用法（第5章）
#  学习建议:
#    务必手写 corr2d 函数，理解四重循环（或二重循环+切片）的过程。
# ============================================================================

# ============================================================================
# 3. 填充和步幅
#    源文件: padding-and-strides.ipynb
#    目标文件: 03_填充和步幅.py
# ----------------------------------------------------------------------------
#  内容要点:
#    - 填充 (padding)：在输入边界补零，控制输出尺寸
#    - 步幅 (stride)：卷积窗口每次滑动的距离
#    - 输出形状公式：(n - k + 2p) / s + 1
#    - nn.Conv2d 的 padding 和 stride 参数
#    - 为什么卷积核尺寸通常取奇数
#  学习目标:
#    掌握控制卷积输出尺寸的方法，能计算任意卷积层的输出形状。
#  前置知识:
#    第 2 节（卷积运算基础）
#  学习建议:
#    多动手计算输出形状，这是面试高频考点。
# ============================================================================

# ============================================================================
# 4. 多输入多输出通道
#    源文件: channels.ipynb
#    目标文件: 04_多输入多输出通道.py
# ----------------------------------------------------------------------------
#  内容要点:
#    - 多输入通道：每个通道一个卷积核，结果求和
#    - 多输出通道：多个卷积核堆叠，每个产生一个输出通道
#    - 1×1 卷积层：等价于在每个像素位置应用全连接层
#    - 1×1 卷积用于调整通道数、降维/升维
#  学习目标:
#    理解多通道卷积的运算机制，掌握 1×1 卷积的用途。
#  前置知识:
#    第 2 节（单通道卷积）
#  学习建议:
#    通道是 CNN 最重要的概念之一，务必理解 c_i→c_o 的参数形状变化。
# ============================================================================

# ============================================================================
# 5. 汇聚层（Pooling）
#    源文件: pooling.ipynb
#    目标文件: 05_汇聚层.py
# ----------------------------------------------------------------------------
#  内容要点:
#    - 最大汇聚 (max pooling)：取窗口内最大值
#    - 平均汇聚 (avg pooling)：取窗口内平均值
#    - 汇聚层的两个作用：降采样 + 提供平移不变性
#    - 汇聚层无参数、逐通道独立运算
#    - 填充和步幅在汇聚层中的使用
#  学习目标:
#    理解汇聚层为什么能降低计算量并增强鲁棒性。
#  前置知识:
#    第 2-3 节（卷积与填充步幅）
#  学习建议:
#    对比有无汇聚层时模型对微小平移的敏感度差异。
# ============================================================================

