# ============================================================================
# 补充 1：为什么需要汇聚层？
# ============================================================================
"""
汇聚层的两个核心作用：

1. 降采样（Reduce Spatial Resolution）：
   2×2 汇聚 + stride=2 → 空间尺寸减半
   → 特征图从 (64, 112, 112) 变为 (64, 56, 56)
   → 计算量减少 75%，显存占用减少 75%

2. 局部平移不变性（Local Translation Invariance）：
   输入微小移动 1 个像素 → 经过 2×2 max pooling 后
   → 大部分输出值不变（因为取的是窗口内最大值）
   → 模型对物体位置的微小变化更鲁棒

典型用法：
  卷积层（提取特征）→ ReLU（非线性）→ Pooling（降采样）
  这一"三件套"是经典 CNN 的标准模式。
"""

# ============================================================================
# 补充 2：Max Pooling vs Average Pooling
# ============================================================================
"""
┌────────────┬──────────────────┬──────────────────┐
│            │  Max Pooling      │  Avg Pooling      │
├────────────┼──────────────────┼──────────────────┤
│ 操作        │ 取窗口内最大值      │ 取窗口内平均值    │
│ 梯度        │ 只传给最大值位置    │ 均匀分给所有位置  │
│ 特点        │ 保留最显著特征      │ 平滑、保留背景    │
│ 适用场景    │ 分类任务（更常用）  │ 全局信息聚合      │
│ 对比        │ "最亮的地方"       │ "平均亮度"        │
└────────────┴──────────────────┴──────────────────┘

现代趋势：
  越来越多的模型（如 ResNet）用 stride=2 的卷积代替 pooling。
  pooling 仍然在特定场景有用（如 Global Average Pooling 用于分类头）。
"""

# ============================================================================
# 补充 3：Global Average Pooling (GAP)
# ============================================================================
"""
GAP = 窗口大小等于输入空间尺寸的平均汇聚

例如：输入 (512, 7, 7) → AdaptiveAvgPool2d(1) → (512, 1, 1)
  将每个 7×7 的特征图压缩为一个标量（全局平均值）

用途：
  替换全连接层作为分类头：
    传统：Conv → Flatten → FC(512×7×7, 1000) = 2500 万参数
    GAP： Conv → GlobalAvgPool → FC(512, 1000) = 51 万参数
    → 参数减少 98%，且不易过拟合！

  ResNet、GoogLeNet、SENet 等现代网络都在用 GAP。
"""

# ============================================================================
# 补充 4：常见问题 / 练习思考
# ============================================================================
"""
Q1: pooling 层会丢失信息吗？
A1: 是的，降采样必然丢失空间细节。但这是有意为之：
    - 减少计算量和显存
    - 高层不需要像素级精度（"猫在左上角还是右下角"不影响"这是猫"的判断）
    - 通道数增加弥补了空间分辨率损失（更多"角度"看更粗粒度的特征）

Q2: 为什么 pooling 不需要学习参数？
A2: max 和 avg 都是固定的数学运算，不涉及参数。
    这是一种结构性先验——"我们相信局部最大值/平均值是有意义的"。
    实际上，有人提出过可学习的 pooling（如 Mixed Pooling），但效果提升有限。

Q3: 可以把卷积 stride=2 和 pooling 都用吗？
A3: 可以，但不推荐两者同时用（降采样过度，信息损失过大）。
    通常选一种：要么 stride=2 卷积，要么 stride=1 卷积 + pooling。
"""
# ============================================================================
# 总结
# ============================================================================
"""
1. 汇聚层 = 无参数滑动窗口 + max/avg 聚合
2. 最大汇聚：保留最显著特征（更常用）
3. 平均汇聚：平滑、保留背景信息
4. 两个核心作用：降采样（省计算）+ 平移不变性（更鲁棒）
5. 逐通道独立运算，输出通道数 = 输入通道数
6. 现代趋势：stride 卷积逐渐替代 pooling，但 GAP 仍广泛使用
"""
