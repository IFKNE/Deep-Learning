"""
=============================================================================
填充和步幅 —— 控制卷积输出尺寸（完整带注释版）
=============================================================================
本节讲解控制卷积输出大小的两个关键参数：
  - 填充 (padding)：在输入边界补零，增大输出尺寸
  - 步幅 (stride)：卷积窗口每次滑动的像素数，减小输出尺寸
掌握这两个参数后，你可以精确控制每一层的输出形状。
=============================================================================
"""

# ============================================================================
# 第1步：导入库
# ============================================================================
import torch
from torch import nn


# ============================================================================
# 第2步：辅助函数 —— 计算卷积输出形状
# ============================================================================
# 这个辅助函数封装了 nn.Conv2d 的输入/输出维度变换，
# 让我们可以只关注空间维度（高、宽），不用管批量和通道维度。

def comp_conv2d(conv2d, X):
    """
    用指定的卷积层对输入 X 做前向传播，返回输出张量（仅空间维度）。

    nn.Conv2d 期望的输入格式：(批量N, 通道C, 高度H, 宽度W)
    本函数自动将二维输入包装为四维，再将四维输出解包为二维。

    参数:
        conv2d: nn.Conv2d 实例
        X: 二维输入张量，形状 (H, W)

    返回:
        二维输出张量，形状 (H_out, W_out)
    """
    # (1, 1) + X.shape = (1, 1, H, W)：添加批量维度和通道维度
    # X.reshape 不改变数据，只改变"视角"
    X = X.reshape((1, 1) + X.shape)
    Y = conv2d(X)
    # Y.shape[2:]：去掉前两维（批量和通道），只保留空间维度 (H_out, W_out)
    return Y.reshape(Y.shape[2:])


# ============================================================================
# 第1节：填充 (Padding)
# ============================================================================
# 问题：每次卷积后图像会缩小
#   3×3 图像 → 2×2 卷积 → 2×2 输出
#   连续 10 层后，图像几乎消失！
#
# 解决：在输入四周填充 0（零填充）
#   3×3 图像 + 补一圈 0 → 5×5 → 2×2 卷积 → 4×4 输出
#
# 输出尺寸公式（带填充）：
#   H_out = H_in - k_h + 2*p_h + 1
#   W_out = W_in - k_w + 2*p_w + 1
#   其中 p_h、p_w 分别是高度和宽度每侧的填充量

# kernel_size=3, padding=1：
#   输出 = 8 - 3 + 2*1 + 1 = 8 → 输入和输出尺寸相同！
# 这是常用技巧：padding=kernel_size//2（当 kernel_size 为奇数时）保持尺寸不变
conv2d = nn.Conv2d(1, 1, kernel_size=3, padding=1)
X = torch.rand(size=(8, 8))                     # 8×8 的随机输入
comp_conv2d(conv2d, X).shape                    # torch.Size([8, 8]) → 尺寸不变！


# ============================================================================
# 第2节：非对称填充
# ============================================================================
# 当卷积核高宽不同时，也可以分别设置高宽方向的填充

# kernel_size=(5, 3)：高=5 核, 宽=3 核
# padding=(2, 1)：高方向每侧补 2（共补 4），宽方向每侧补 1（共补 2）
#   输出高 = 8 - 5 + 2*2 + 1 = 8 ✓
#   输出宽 = 8 - 3 + 2*1 + 1 = 8 ✓
conv2d = nn.Conv2d(1, 1, kernel_size=(5, 3), padding=(2, 1))
comp_conv2d(conv2d, X).shape                    # torch.Size([8, 8])


# ============================================================================
# 第3节：步幅 (Stride)
# ============================================================================
# 默认 stride=1：卷积窗口每次移动 1 像素
# stride > 1：卷积窗口跳过中间像素，每次移动多步
#   效果 = 空间降采样（减少输出尺寸）

# 完整输出尺寸公式（填充 + 步幅）：
#   H_out = ⌊(H_in - k_h + 2*p_h + s_h) / s_h⌋
#   W_out = ⌊(W_in - k_w + 2*p_w + s_w) / s_w⌋
#   ⌊x⌋ = 向下取整（floor）

# stride=2：输出尺寸减半（8 → 4）
#   高 = ⌊(8 - 3 + 2*1 + 2) / 2⌋ = ⌊9/2⌋ = 4
conv2d = nn.Conv2d(1, 1, kernel_size=3, padding=1, stride=2)
comp_conv2d(conv2d, X).shape                    # torch.Size([4, 4])


# ============================================================================
# 第4节：非对称步幅
# ============================================================================
# kernel_size=(3, 5) + padding=(0, 1) + stride=(3, 4)：
#   高 = ⌊(8 - 3 + 0 + 3) / 3⌋ = ⌊8/3⌋ = 2
#   宽 = ⌊(8 - 5 + 2 + 4) / 4⌋ = ⌊9/4⌋ = 2

conv2d = nn.Conv2d(1, 1, kernel_size=(3, 5), padding=(0, 1), stride=(3, 4))
comp_conv2d(conv2d, X).shape                    # torch.Size([2, 2])


# ============================================================================
# 补充知识点
# ============================================================================

# ============================================================================
# 补充 1：为什么卷积核尺寸通常取奇数？
# ============================================================================
"""
常用卷积核尺寸：1×1, 3×3, 5×5, 7×7 —— 全是奇数！

原因：
  1. 对称填充：奇数核可以在每侧均匀填充
     例如 3×3 核 → padding=1（核的一半向下取整），每侧补 1
     偶数核（如 4×4）无法均匀填充

  2. 锚点居中：奇数核有明确的"中心像素"
     例如 3×3 的中心在 (1,1)，5×5 的中心在 (2,2)
     偶数核的中心在像素之间，不够直观

  3. 保持尺寸更方便：kernel_size=odd, padding=odd//2, stride=1
     → 输出尺寸 = 输入尺寸（自动）

现代 CNN 几乎全部使用 3×3 卷积核（VGG 开创的传统）。
"""

# ============================================================================
# 补充 2：padding 的两种模式
# ============================================================================
"""
PyTorch nn.Conv2d 支持两种 padding 模式：

  1. zeros（默认）：在边界补 0
     → 最常用，计算简单

  2. reflect / replicate / circular：
     → 用边界像素的镜像/重复/循环值填充
     → 适用于不希望边界出现"人为黑边"的场景
     → nn.Conv2d(..., padding_mode='reflect')

为什么补 0 是默认且有效的？
  网络会自动学习忽略边界的 0 值区域，
  或者学习到边界特征（如检测物体是否在图像边缘）。
  而且 0 填充也可以看作一种弱正则化（边界像素少被看到）。
"""

# ============================================================================
# 补充 3：输出尺寸速算表
# ============================================================================
"""
常用组合：

  ┌──────────┬──────────┬──────────┬───────────────────┐
  │ kernel   │ padding  │ stride   │ 效果               │
  ├──────────┼──────────┼──────────┼───────────────────┤
  │ 3        │ 1        │ 1        │ 尺寸不变 (same)    │
  │ 3        │ 0        │ 1        │ 尺寸 -2            │
  │ 3        │ 1        │ 2        │ 尺寸减半            │
  │ 5        │ 2        │ 1        │ 尺寸不变 (same)    │
  │ 1        │ 0        │ 1        │ 尺寸不变,调通道数   │
  │ 7        │ 3        │ 2        │ 尺寸减半            │
  └──────────┴──────────┴──────────┴───────────────────┘

记忆口诀：
  - 保持尺寸：kernel=odd, padding=kernel//2, stride=1
  - 减半尺寸：stride=2
  - 调通道数：kernel=1
"""

# ============================================================================
# 补充 4：常见问题 / 练习思考
# ============================================================================
"""
Q1: 为什么不用更大的 stride 替代 pooling？
A1: 确实可以！现代 CNN（如 ResNet）常用 stride=2 的卷积代替 pooling 做降采样。
    卷积有可学习参数（pooling 没有），信息损失更小，但计算量稍大。
    stride 卷积 + BN 的组合已经基本取代了传统 pooling 的地位。

Q2: 填充的 0 会不会影响训练？
A2: 不会。网络会自动学习对边界区域的处理方式。
    实际上 0 填充还有正则化效果——边界像素被"看到"的次数比中心像素少。
"""

# ============================================================================
# 总结
# ============================================================================
"""
1. 填充 (padding)：在输入边界补零
   - 目的：保持输出尺寸不变，防止信息丢失
   - 常用：padding = kernel_size // 2

2. 步幅 (stride)：卷积窗口每次移动的步长
   - stride=1（默认）：逐像素滑动
   - stride=2：空间降采样（输出尺寸减半）

3. 输出尺寸公式：
   H_out = ⌊(H_in - k_h + 2*p_h + s_h) / s_h⌋

4. 核尺寸选奇数：便于对称填充和尺寸控制
5. stride=2 卷积可代替 pooling 做降采样
"""
