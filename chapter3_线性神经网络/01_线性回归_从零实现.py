"""
=============================================================================
线性回归的从零开始实现 —— 完整带注释版
=============================================================================
本文件将 linear-regression-scratch 从零实现线性回归.ipynb 中的所有代码汇总在一起，
每一行都配有详细的中文注释，方便学习和理解。

任务：用合成数据集训练一个线性回归模型，从零实现数据流水线、模型、损失函数和优化器。
     输入：2 个特征（从标准正态分布采样）
     输出：1 个连续值（标量预测）
     真实参数：w = [2, -3.4]ᵀ, b = 4.2

整体流程：生成数据集 → 读取数据 → 初始化参数 → 定义模型 → 定义损失函数 → 定义优化算法 → 训练 → 评估
=============================================================================
"""

# ============================================================================
# 第1步：导入必要的库
# ============================================================================
# %matplotlib inline               # Jupyter 魔法命令：让 matplotlib 图表直接显示在 notebook 中
import random                       # Python 标准库，用于打乱数据顺序
import torch                        # PyTorch 深度学习框架，提供张量运算和自动求导
from d2l import torch as d2l        # 《动手学深度学习》(D2L) 配套工具库，封装了绘图等常用函数


# ============================================================================
# 第2步：生成合成数据集
# ============================================================================
# 为什么要用合成数据？因为我们可以知道真实的 w 和 b，便于验证模型是否学到了正确的参数。
# 真实模型：y = X·w + b + ε（ε 是噪声）
# 其中 w = [2, -3.4]ᵀ, b = 4.2, ε ~ N(0, 0.01²)

def synthetic_data(w, b, num_examples):
    """
    根据线性模型 y = Xw + b + 噪声 生成合成数据集。

    参数:
        w:            真实权重，形状为 (num_features, 1)
        b:            真实偏置，标量
        num_examples: 要生成的样本数量

    返回:
        X: 特征矩阵，形状为 (num_examples, len(w))
        y: 标签向量，形状为 (num_examples, 1)

    分步说明：
        (1) torch.normal(0, 1, ...): 从标准正态分布 N(0,1) 随机生成特征
        (2) torch.matmul(X, w) + b: 矩阵乘法计算 Xw + b，即线性变换
        (3) torch.normal(0, 0.01, y.shape): 添加均值为 0、标准差为 0.01 的高斯噪声
        (4) y.reshape((-1, 1)): 将标签整形为列向量
    """
    X = torch.normal(0, 1, (num_examples, len(w)))          # 从 N(0,1) 采样生成特征：(1000, 2)
    y = torch.matmul(X, w) + b                               # 计算 Xw + b：(1000, 2)×(2,1) + 标量 → (1000, 1)
    y += torch.normal(0, 0.01, y.shape)                     # 添加高斯噪声，模拟真实世界中的观测误差
    return X, y.reshape((-1, 1))                             # y 整形为列向量 (num_examples, 1)

true_w = torch.tensor([2, -3.4])                             # 真实权重：两个特征的权重分别为 2 和 -3.4
true_b = 4.2                                                 # 真实偏置
features, labels = synthetic_data(true_w, true_b, 1000)      # 生成 1000 个样本的特征 X 和标签 y
print('features:', features[0], '\nlabel:', labels[0])       # 打印第一个样本，观察数据格式

# 绘制第二个特征与标签的散点图，观察线性关系
# features[:, 1] 取所有行的第 1 列（第二个特征，索引从 0 开始）
# .detach().numpy() 将 PyTorch 张量从计算图中分离并转为 NumPy 数组，供 matplotlib 绘图
d2l.set_figsize()                                            # 设置图表大小
d2l.plt.scatter(features[:, 1].detach().numpy(), labels.detach().numpy(), 1)


# ============================================================================
# 第3步：定义数据迭代器（小批量读取）
# ============================================================================
# 为什么需要小批量读取？
#   - GPU 可以并行处理整个批量，比逐样本处理快得多
#   - 小批量随机梯度下降比全批量梯度下降收敛更快，比单样本 SGD 更稳定
#   - 合适的 batch_size（如 10~256）能在速度和稳定性之间取得平衡

def data_iter(batch_size, features, labels):
    """
    按小批量迭代地返回特征和标签。

    参数:
        batch_size: 每个小批量的样本数
        features:   特征矩阵，形状为 (num_examples, num_features)
        labels:     标签向量，形状为 (num_examples, 1)

    每次 yield:
        (batch_features, batch_labels) —— 一个小批量的特征和标签

    流程：
        (1) 生成 0 到 num_examples-1 的索引列表
        (2) 用 random.shuffle() 随机打乱索引，确保每个 epoch 的数据顺序不同
        (3) 按 batch_size 步长遍历索引，取出对应的小批量数据
        (4) 用 yield 返回（生成器函数，节省内存）
    """
    num_examples = len(features)                             # 样本总数
    indices = list(range(num_examples))                      # 创建索引列表 [0, 1, 2, ..., 999]
    random.shuffle(indices)                                  # 随机打乱索引，确保每个 epoch 样本顺序不同
    for i in range(0, num_examples, batch_size):             # 步长为 batch_size 遍历
        batch_indices = torch.tensor(                        # 取出当前批量的索引
            indices[i: min(i + batch_size, num_examples)])   # min() 防止最后一个批量超出范围
        yield features[batch_indices], labels[batch_indices] # 用 yield 返回批量，节省内存

batch_size = 10                                              # 批量大小设为 10
# 取第一个小批量并打印，观察数据形状
for X, y in data_iter(batch_size, features, labels):
    print('X (批量特征):', X, '\ny (批量标签):', y)
    break                                                    # 只打印第一个批量就跳出


# ============================================================================
# 第4步：初始化模型参数
# ============================================================================
# 线性回归模型：y = Xw + b
# 需要两个参数：权重 w（形状 2×1）和偏置 b（标量）
# 初始化策略：
#   - w 从 N(0, 0.01²) 正态分布随机初始化（小方差，避免初始梯度爆炸）
#   - b 初始化为 0
# requires_grad=True 表示需要计算梯度，训练时 PyTorch 会自动追踪对这些张量的操作

w = torch.normal(0, 0.01, size=(2, 1), requires_grad=True)  # 权重 w：形状 (2, 1)，从 N(0,0.01) 采样
b = torch.zeros(1, requires_grad=True)                       # 偏置 b：初始化为 0，形状 (1,)


# ============================================================================
# 第5步：定义模型（前向传播）
# ============================================================================
# 线性回归的数学模型：ŷ = Xw + b
#   X 形状：(batch_size, 2)
#   w 形状：(2, 1)
#   Xw 结果：(batch_size, 1) — 每个样本得到一个预测值
#   + b：广播机制，标量 b 加到向量的每个分量上

def linreg(X, w, b):
    """
    线性回归模型：计算 ŷ = Xw + b。

    参数:
        X: 输入特征，形状为 (batch_size, num_features)
        w: 权重，形状为 (num_features, 1)
        b: 偏置，标量张量

    返回:
        预测值，形状为 (batch_size, 1)

    计算：torch.matmul(X, w) 做矩阵乘法，(batch_size, 2) × (2, 1) → (batch_size, 1)
    """
    return torch.matmul(X, w) + b                            # Xw + b，利用广播机制将 b 加到每一行


# ============================================================================
# 第6步：定义损失函数（均方误差）
# ============================================================================
# 平方损失（MSE/2）：L = (ŷ - y)² / 2
#   除以 2 是为了让梯度更简洁：∂L/∂ŷ = ŷ - y（求导后 2 约掉）
#   实际中常直接使用 MSE，此处除以 2 是教材惯例

def squared_loss(y_hat, y):
    """
    计算均方损失的一半：loss = (ŷ - y)² / 2。

    参数:
        y_hat: 预测值，形状为 (batch_size, 1)
        y:     真实值，形状为 (batch_size, 1) 或 (batch_size,)

    返回:
        损失值，形状与 y_hat 相同

    注意：
        y.reshape(y_hat.shape) 确保 y 与 y_hat 形状一致，避免广播错误
    """
    return (y_hat - y.reshape(y_hat.shape)) ** 2 / 2         # (预测值 - 真实值)² / 2


# ============================================================================
# 第7步：定义优化算法（小批量随机梯度下降 SGD）
# ============================================================================
# SGD 更新公式：θ ← θ - (lr / batch_size) * Σ∇θ
#   除以 batch_size 是为了对梯度做平均，使学习率与批量大小解耦
#   torch.no_grad(): 在此上下文中不计算梯度，因为这是参数更新步骤，不需要被 autograd 追踪
#   param.grad.zero_(): 清零梯度（PyTorch 默认会累积梯度，不手动清零会叠加）

def sgd(params, lr, batch_size):
    """
    小批量随机梯度下降（SGD）。

    参数:
        params:     模型参数列表，如 [w, b]
        lr:         学习率 (learning rate)
        batch_size: 批量大小，用于对梯度做平均

    实现细节：
        with torch.no_grad(): 更新参数时不需要自动求导
        每个参数减去 学习率 × 梯度均值（梯度总和 / batch_size）
        .zero_() 清零梯度，下划线表示原地操作（in-place）
    """
    with torch.no_grad():                                    # 关闭梯度追踪，参数更新属于"手动操作"
        for param in params:                                 # 遍历每个参数（w, b）
            param -= lr * param.grad / batch_size            # θ = θ - η * (Σ∇θ / batch_size)
            param.grad.zero_()                               # 将梯度清零，准备下一个批量的计算


# ============================================================================
# 第8步：训练模型
# ============================================================================
# 训练循环：
#   for each epoch:                ← 遍历整个数据集多次
#       for each batch:            ← 每次取一个小批量
#           (1) 前向传播：计算预测值 ŷ
#           (2) 计算损失：loss(ŷ, y)
#           (3) 反向传播：loss.backward() 计算梯度
#           (4) 更新参数：sgd([w, b], lr, batch_size)

lr = 0.03                                                    # 学习率：控制每次更新的步长
num_epochs = 5                                               # 训练 5 个 epoch（完整遍历数据集 5 次）
net = linreg                                                 # 模型 = 线性回归函数
loss = squared_loss                                          # 损失函数 = 平方损失

for epoch in range(num_epochs):                              # 外层循环：扫描整个数据集 num_epochs 次
    for X, y in data_iter(batch_size, features, labels):     # 内层循环：每次取一个小批量
        l = loss(net(X, w, b), y)                            # (1)(2) 前向传播 + 计算损失
        # l 的形状为 (batch_size, 1)，不是标量
        # l.sum() 将所有样本的损失加在一起，得到一个标量
        # .backward() 自动计算梯度，存到 w.grad 和 b.grad 中
        l.sum().backward()                                   # (3) 反向传播：计算 Σloss 对 w,b 的梯度
        sgd([w, b], lr, batch_size)                          # (4) 用 SGD 更新参数

    # 每个 epoch 结束后，在整个训练集上计算损失（只用于监控，不影响训练）
    with torch.no_grad():                                    # 评估阶段不需要梯度
        train_l = loss(net(features, w, b), labels)          # 在整个训练集上计算损失
        print(f'epoch {epoch + 1}, loss {float(train_l.mean()):f}')  # 打印平均损失


# ============================================================================
# 第9步：评估模型 —— 比较学到的参数与真实参数
# ============================================================================
# 因为我们用的是合成数据，知道真实的 w 和 b，所以可以直接计算估计误差
print(f'w的估计误差: {true_w - w.reshape(true_w.shape)}')     # 真实 w 减去学到 w 的差值
print(f'b的估计误差: {true_b - b}')                           # 真实 b 减去学到 b 的差值
# 误差应该非常小（接近 0），说明模型成功学到了数据背后的线性关系


# ============================================================================
# 补充知识点
# ============================================================================

# 1. 为什么在 squared_loss 中需要 y.reshape(y_hat.shape)？
#    y 可能是 (batch_size,) 一维向量，而 y_hat 是 (batch_size, 1) 列向量
#    直接相减会触发广播，可能产生意外的 (batch_size, batch_size) 结果
#    reshape 保证两者形状一致

# 2. 学习率的影响：
#    - 学习率太小：收敛慢，需要更多 epoch
#    - 学习率太大：可能震荡甚至发散，loss 反而增大
#    - 本例中 lr=0.03 对 1000 个样本效果很好

# 3. 批量大小的权衡：
#    - 小批量（如 1-10）：更新频繁，收敛路径嘈杂但可能跳出局部最优
#    - 大批量（如 256-1000）：梯度估计更准确，但可能收敛到尖锐的极小值
#    - 常用值：32, 64, 128, 256

# 4. 自动求导（autograd）原理：
#    PyTorch 会为每个 requires_grad=True 的张量操作记录计算图
#    调用 .backward() 时自动用链式法则计算所有参数的梯度
#    本例中的计算图：X,w,b → Xw+b → ŷ → (ŷ-y)²/2 → loss
#    反向传播从 loss 开始，沿着计算图反向传播梯度到 w 和 b

# 5. 为什么 l.sum().backward() 而不是 l.mean().backward()？
#    因为 sgd 函数内部已经除以了 batch_size，所以这里 sum 或 mean 都可以
#    如果用 mean，则在 sgd 中不应再除以 batch_size
#    两者等价，只是除法放置的位置不同


# ============================================================================
# 总结
# ============================================================================
# 1. 线性回归是最简单的有监督学习模型：ŷ = Xw + b
# 2. 从零实现涉及 5 个核心组件：
#    - 数据流水线（data_iter）：随机打乱 + 小批量产出
#    - 模型（linreg）：矩阵乘法 + 广播加法
#    - 损失函数（squared_loss）：均方误差 / 2
#    - 优化算法（sgd）：梯度下降，θ = θ - η * g
#    - 训练循环：前向 → 损失 → 反向 → 更新（往复循环）
# 3. 训练完成后，学到的 w ≈ [2, -3.4]，b ≈ 4.2，与真实参数非常接近
# 4. 这个 5 步模板（数据→模型→损失→优化→循环）是几乎所有深度学习任务的通用框架
