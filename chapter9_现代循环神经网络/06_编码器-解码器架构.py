"""
=============================================================================
编码器-解码器架构（Encoder-Decoder Architecture）—— 完整带注释版
=============================================================================
任务：序列转换问题（如机器翻译）的输入、输出都是"长度可变"的序列。
     为此设计一个通用架构：编码器（encoder）把变长输入压成"定长编码状态"，
     解码器（decoder）再把该状态展开成"变长输出序列"。

本节只定义三个"接口（基类）"，不涉及具体实现；真正的 RNN 实现见下一节 seq2seq。

依赖：d2l 包。本文件可独立运行。
=============================================================================
"""

# ============================================================================
# 第1步：导入依赖
# ============================================================================
from torch import nn


# ============================================================================
# 第2步：编码器接口 Encoder
# ============================================================================
class Encoder(nn.Module):
    """编码器-解码器架构的基本编码器接口"""
    def __init__(self, **kwargs):
        # super().__init__(**kwargs)：调用父类 nn.Module 的初始化，做必要的注册
        super().__init__(**kwargs)

    # forward 是每个 nn.Module 子类必须实现的前向传播方法。
    # 这里用 raise NotImplementedError 表明"这是一个接口"，
    # 具体编码器必须覆写它。
    def forward(self, X, *args):
        raise NotImplementedError
# 接口约定：编码器接收"变长序列 X"作为输入，
#           返回一个"定长的编码状态"（具体实现的输出由子类决定）。


# ============================================================================
# 第3步：解码器接口 Decoder
# ============================================================================
class Decoder(nn.Module):
    """编码器-解码器架构的基本解码器接口"""
    def __init__(self, **kwargs):
        super().__init__(**kwargs)

    # init_state：把"编码器的输出"转成"解码器可用的初始状态"。
    #   注意：这一步可能需要额外输入，如输入的"有效长度"（见机器翻译数据集小节）。
    def init_state(self, enc_outputs, *args):
        raise NotImplementedError

    # forward：每个时间步接收"已生成的输入（词元）"和"当前状态"，
    #          输出本时间步的词元分布（logits）。
    def forward(self, X, state):
        raise NotImplementedError
# 接口约定：解码器逐个时间步生成词元，
#           每步输入 = 上一步生成(或教师强制)词元 + 编码状态；输出 = 当前词元分布。


# ============================================================================
# 第4步：合并编码器与解码器 EncoderDecoder
# ============================================================================
class EncoderDecoder(nn.Module):
    """编码器-解码器架构的基类"""
    def __init__(self, encoder, decoder, **kwargs):
        super().__init__(**kwargs)
        # 保存编码器、解码器两个子模块
        self.encoder = encoder
        self.decoder = decoder

    # 前向传播把整个流程串起来：
    #   ① encoder 吃进"源序列"得到编码输出 enc_outputs；
    #   ② decoder.init_state 用 enc_outputs 造出初始状态 dec_state；
    #   ③ decoder 用"解码输入 dec_X + 状态"逐时间步生成输出。
    def forward(self, enc_X, dec_X, *args):
        enc_outputs = self.encoder(enc_X, *args)
        dec_state = self.decoder.init_state(enc_outputs, *args)
        return self.decoder(dec_X, dec_state)
# 经典流程示例（英→法）：
#   输入英文序列 "They are watching ." → 编码器 → 状态 c；
#   解码器从 <bos> 开始，逐词元生成 "Ils regardent ."


# ============================================================================
# 补充知识点
# ============================================================================
# 1. 【为什么叫"状态"？】
#    "状态"一词启发我们用"有状态"的神经网络（如 RNN）来实现。
#    编码器把整段输入浓缩成一个固定形状的向量/状态，承载"输入序列全部信息"。

# 2. 【编码器和解码器必须是同一类网络吗？】
#    不必。二者任务不同：编码器只负责"压缩"，解码器负责"展开生成"。
#    常见组合有：CNN 编码器 + RNN 解码器（图像描述）、双向 RNN 编码器 + 单向
#    RNN 解码器（机器翻译）、乃至后来的 Transformer 编解码（双方都是 Transformer）。

# 3. 【编码器-解码器的广泛应用】
#    除机器翻译外，还适用于：文本摘要、图像描述（image captioning）、
#    语音识别、对话系统等一切"输入/输出都是变长序列"的任务。


# ============================================================================
# 核心公式回顾
# ============================================================================
#   编码器：E : 变长序列 X → 定长状态 c  （如 c = q(h_1,...,h_T)）
#   解码器：D : 定长状态 c + 已生成前缀 → 下一个词元分布
#            条件概率 P(y_{t'} | y_1..y_{t'-1}, c)
#   整体：  EncoderDecoder = Encoder ∘ init_state ∘ Decoder


