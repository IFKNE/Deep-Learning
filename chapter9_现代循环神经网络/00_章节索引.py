# 4. 双向循环神经网络
#    源文件: bi-rnn.ipynb
#    目标文件: 04_双向循环神经网络.py
# ----------------------------------------------------------------------------
#  内容要点:
#    - 动机：有些任务（填空/命名实体）需要"后文"信息，单向 RNN 用不上
#    - 隐马尔可夫模型（HMM）做动态规划：前向递归 π 与后向递归 ρ，
#      把指数级 k^T 的求和降到线性 O(kT)，从而能利用前后文
#    - 双向 RNN：前向隐状态 H→_t 从前往后、反向隐状态 H←_t 从后往前，
#      拼接成 H_t ∈ R^{n×2h} 再送输出层
#    - ⚠️ 错误应用演示：在"预测下一个词"任务上硬上双向 LSTM，模型只会复制
#      "travellererer..."——因为训练时能看到未来、测试时看不到，严重过拟合
#    - 计算慢：前向传播要"双向递归"，反向传播的梯度链特别长
#  学习目标:
#    理解双向 RNN 用上未来信息的机制，及为何不能用于"单向预测下一个词"
#  前置知识:
#    LSTM、HMM 前向后向算法（本节做了直观推导）
#  学习建议:
#    跑一遍"错误应用"示例，看 perplexity 很低但输出无限循环——记住这个反面教材
# ============================================================================

