# 7. 序列到序列学习（seq2seq）
#    源文件: seq2seq.ipynb
#    目标文件: 07_序列到序列学习.py
# ----------------------------------------------------------------------------
#  内容要点:
#    - 用两个 RNN：编码器 RNN 把源序列编码成末态隐状态；解码器 RNN 用它
#      初始化为隐状态，逐词元生成目标序列
#    - 编码器 Seq2SeqEncoder：嵌入层 nn.Embedding + 多层 nn.GRU，
#      permute 把 (batch, num_steps, embed) 变成 (num_steps, batch, embed)
#    - 解码器 Seq2SeqDecoder：每个时间步把上下文 c（广播）与输入拼接进 GRU，
#      再用 nn.Linear 输出词表上的分布
#    - 损失函数：MaskedSoftmaxCELoss —— 用 sequence_mask 把 <pad> 位置的
#      softmax 交叉熵清零，只统计有效词元
#    - 训练 train_seq2seq：教师强迫（teacher forcing）——把"正确的上一词元"
#      而不是"预测词元"作为解码器当前输入；加上 xavier 初始化、
#      Adam、梯度裁剪
#    - 预测 predict_seq2seq：评估模式、一步步自回归；遇到 <eos> 停止
#    - 评估 BLEU：n 元语法的精确度 + 长度惩罚，越接近 1 越好
#  学习目标:
#    端到端跑通"编码器→解码器→训练→预测→BLEU 评估"的完整序列翻译
#  前置知识:
#    编码器-解码器接口、机器翻译数据集、GRU/LSTM、cross entropy
#  学习建议:
#    这是全章重点。逐行跟读 Seq2SeqEncoder/Decoder 的张量形状变换，再复现训练
# ============================================================================

# ============================================================================
# 8. 束搜索
#    源文件: beam-search.ipynb
#    目标文件: 08_束搜索.py
# ----------------------------------------------------------------------------
#  内容要点:
#    - 解码器的核心问题：怎么从 |Y|^{T'} 种可能序列里挑出最优输出
#    - 贪心搜索（argmax）：每步只取当步概率最大词元，计算 O(|Y|T')，但不是最优
#    - 穷举搜索：全枚举取最大，最优但计算量 O(|Y|^{T'}) 高得离谱
#    - 束搜索（beam search）：维护 k 个候选序列，每步从 k|Y| 中挑前 k 个；
#      计算量 O(k|Y|T')，介于两者之间
#    - 打分归一化：除以 L^α（α≈0.75）惩罚长序列，避免"越长越占便宜"
#    - 贪心搜索 = 束宽为 1 的特例；束宽越大越接近最优但越贵
#  学习目标:
#    理解三种解码策略的取舍，掌握束搜索"束宽"这个核心超参数
#  前置知识:
#    seq2seq 的逐词元生成、条件概率链式展开
#  学习建议:
#    这一节没有代码，重点是数学与直觉；配合 07 节的实际预测结果来体会
