# 6. 编码器-解码器架构
#    源文件: encoder-decoder.ipynb
#    目标文件: 06_编码器-解码器架构.py
# ----------------------------------------------------------------------------
#  内容要点:
#    - 解码序列转换问题：输入、输出都是变长序列
#    - 编码器 Encoder：变长输入 → 定长"编码状态"
#    - 解码器 Decoder：定长编码状态 → 变长输出（逐词元生成）
#    - 三个基类接口：Encoder / Decoder / EncoderDecoder
#    - Decoder 新增 init_state：把编码器输出转成解码器要用的初始状态
#    - 前向流程：enc_outputs = encoder(enc_X)；dec_state = decoder.init_state(...)；
#      return decoder(dec_X, dec_state)
#  学习目标:
#    理解"编码-解码"这一通用范式（很多 RNN 之外模型也是这个骨架）
#  前置知识:
#    机器翻译数据集那一节、nn.Module 子类化
