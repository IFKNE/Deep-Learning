#  《动手学深度学习》第9章：现代循环神经网络 — 章节索引
# ============================================================================
#  第8章我们用单层、单向的 RNN 搭出了一个字符级语言模型，但它有两个硬伤：
#  一是"梯度消失/爆炸"让模型学不到长距离依赖；二是只能"顺着看"，没法利用
#  未来信息。本章（现代循环神经网络）正是为补齐这两块短板而生的：
#
#    · 门控机制（GRU / LSTM）——用可学习的"门"来记得住、放得下，缓解梯度消失；
#    · 架构扩展（深层 / 双向 RNN）——纵向加深、横向同时看过去和未来；
#    · 端到端序列转换（编码器-解码器 + seq2seq + 束搜索）——把不定长的输入
#      序列翻译成不定长的输出序列，也就是"机器翻译"这条主线。
#
#  学习主线：GRU → LSTM（两种门控）→ 深层 / 双向 RNN（两种扩展）→
#            机器翻译数据集 → 编码器-解码器架构 → 序列到序列 seq2seq → 束搜索。
# ============================================================================

# ============================================================================
# 1. 门控循环单元（GRU）
#    源文件: gru.ipynb
#    目标文件: 01_门控循环单元.py
# ----------------------------------------------------------------------------
#  内容要点:
#    - 经典 RNN 的问题：矩阵连乘导致梯度消失/爆炸，难以捕捉长距离依赖
#    - 引入两个"门"：重置门 R_t（决定忘掉多少旧状态）与更新门 Z_t（决定用多少
#      旧状态替换新候选），二者都是 sigmoid 输出的 (0,1) 向量
#    - 候选隐状态：H̃_t = tanh(X_t W_xh + (R_t ⊙ H_{t-1}) W_hh + b_h)
#    - 最终隐状态：H_t = Z_t ⊙ H_{t-1} + (1 - Z_t) ⊙ H̃_t（凸组合）
#    - 重置门管"短期依赖"、更新门管"长期依赖"
#    - 从零实现 get_params / init_gru_state / gru，再用 d2l.RNNModelScratch 训练
#    - 简洁实现：nn.GRU(num_inputs, num_hiddens) + d2l.RNNModel
#  学习目标:
#    理解 GRU 两个门各自的数学形式与作用，能对比它与经典 RNN 的差异
#  前置知识:
#    第8章 RNN 公式、sigmoid/tanh 激活、穷举时间步手动实现
#  学习建议:
#    先口算一遍"若 R_t 全为 1 且 Z_t 交替变化"会怎样，再跑代码验证困惑度
# ============================================================================

# ============================================================================
# 2. 长短期记忆网络（LSTM）
#    源文件: lstm.ipynb
#    目标文件: 02_长短期记忆网络.py
# ----------------------------------------------------------------------------
#  内容要点:
#    - 比 GRU 更早（近 20 年）、更复杂；灵感来自计算机的逻辑门
#    - 三种门：输入门 I_t、遗忘门 F_t、输出门 O_t（sigmooid）
#    - 候选记忆元：C̃_t = tanh(X_t W_xc + H_{t-1} W_hc + b_c)
#    - 记忆元：C_t = F_t ⊙ C_{t-1} + I_t ⊙ C̃_t（遗忘旧内容 + 写入新内容）
#    - 隐状态：H_t = O_t ⊙ tanh(C_t)（记忆元的"门控读出"）
#    - 隐状态有两个：H_t（传出去）与 C_t（内部记忆元）——
#      只有 H_t 进入输出层，C_t 只在内部更新（与 GRU 最大的不同）
#    - 从零实现 get_lstm_params / init_lstm_state / lstm，训练、简洁实现 nn.LSTM
#  学习目标:
#    分清楚 LSTM 的 I/F/O 三扇门与记忆元 C 的更新公式，理解为何能缓解梯度消失
#  前置知识:
#    GRU、sigmoid/tanh、按元素乘法（Hadamard 积）
#  学习建议:
#    画一张"记忆元 C 的更新"数据流图，标清楚每个门在哪一步起作用
# ============================================================================

# ============================================================================
# 3. 深层循环神经网络
#    源文件: deep-rnn.ipynb
#    目标文件: 03_深层循环神经网络.py
# ----------------------------------------------------------------------------
#  内容要点:
#    - 把多个 RNN 层"堆叠"，每层隐状态同时喂给下个时间步（横向）和下一层（纵向）
#    - 第 l 层公式：H_t^(l) = φ_l(H_t^(l-1) W_xh^(l) + H_{t-1}^(l) W_hh^(l) + b_h^(l))
#    - 输出层只用最后一层最终的隐状态：O_t = H_t^(L) W_hq + b_q
#    - 层数是超参数；用 nn.LSTM(..., num_layers=2) 即得两层模型
#    - 训练代价明显更贵（层数多了、传播链更长），调参要更谨慎
#  学习目标:
#    理解"纵向加深"与多层感知机加层的区别（RNN 有隐状态在层间/时间间传递）
#  前置知识:
#    LSTM、nn.Sequential 组合层、超参数作用
#  学习建议:
#    对比单层与两层 LSTM 的困惑度与 tokens/sec，直观感受"深度"的代价
# ============================================================================

