"""
=============================================================================
双向循环神经网络（Bidirectional Recurrent Neural Network）—— 完整带注释版
=============================================================================
任务：有些序列任务（如填空、命名实体识别）需要同时利用"上文"和"下文"。
     单向前时 RNN 只能"顺着时间看"，因此改用"双向"：一个前向循环 + 一个反向循环，
     把二者隐状态拼接后入输出层，从而每个位置都能"前后兼顾"。

注意：本节含大量 HMM 动态规划的理论动机推导；代码部分仅演示一个"错误的双向 RNN
     应用"，用来提醒我们——双向模型深度依赖"未来信息"，不能盲目用于预测任务。

依赖：d2l 包。本文件可独立运行。
=============================================================================
"""

# ============================================================================
# 理论铺垫：为什么需要"未来信息"？—— 隐马尔可夫模型的前向后向算法
# ============================================================================
# 一个直观例子是"填空任务"：
#   ① 我___。                    （信息少，答案开放）
#   ② 我___饿了。                （"很"、"不"皆可）
#   ③ 我___饿了，我可以吃半头猪。  （"很"几乎确定）
# 可以看出，"下文"对判断当前答案极其关键。单向序列模型只会"顺着看"，就吃不到
# 后文信息，在命名实体识别等任务上表现不佳。
#
# 概率图模型（HMM）解决这个问题的思路是"动态规划"：
#   - 隐变量序列 h_1..h_T，观测 x_1..x_T，联合分布
#       P(x_1..x_T, h_1..h_T) = ∏_{t=1}^T P(h_t|h_{t-1}) P(x_t|h_t)
#   - 想算 P(x_j | x_{-j})，本需对隐变量组合求和，量级 k^T（指数级，不可解）。
#   - 但用"前向递归 π_t" 和"后向递归 ρ_t" 可把求和降到 O(kT)（线性）：
#         前向： π_{t+1}(h_{t+1}) = Σ_{h_t} π_t(h_t) P(x_t|h_t) P(h_{t+1}|h_t)
#         后向： ρ_{t-1}(h_{t-1}) = Σ_{h_t} P(h_t|h_{t-1}) P(x_t|h_t) ρ_t(h_t)
#       两者结合就能求 P(x_j|x_{-j})。
#   - 这就是"双向"的统计学原型：同时用过去与未来做推断。
#
# 关键结论：HMM 里的前向/后向递归，翻译成 RNN 就是"双向 RNN"——把统计模型的
#           函数依赖结构做了泛化。


# ============================================================================
# 第1步：导入依赖、加载数据、构建双向 LSTM 模型
# ============================================================================
import torch
from torch import nn
from d2l import torch as d2l

# 加载数据
batch_size, num_steps, device = 32, 35, d2l.try_gpu()
train_iter, vocab = d2l.load_data_time_machine(batch_size, num_steps)

# 通过设置 bidirectional=True 来定义双向 LSTM 模型
vocab_size, num_hiddens, num_layers = len(vocab), 256, 2
num_inputs = vocab_size
# nn.LSTM(..., bidirectional=True)：
#   自动维护"前向"和"反向"两组循环，并把二者对应的隐状态沿隐藏维拼起来。
#   —— 输出层的输入维度也因此翻倍（每步拼接前后向二状态 → 2*num_hiddens）。
lstm_layer = nn.LSTM(num_inputs, num_hiddens, num_layers, bidirectional=True)
model = d2l.RNNModel(lstm_layer, len(vocab))
model = model.to(device)

# 训练模型
num_epochs, lr = 500, 1
d2l.train_ch8(model, train_iter, vocab, lr, num_epochs, device)
# 结果示例（注意：perplexity 很低，但输出却"无限复制"——详见下面分析）：
#   perplexity 1.1, 131129.2 tokens/sec on cuda:0
#   time travellerererererererererererererererererererererererererer
#   travellerererererererererererererererererererererererererer


# ============================================================================
# 补充知识点：一个必须引以为戒的"错误应用"示范
# ============================================================================
# 上面结果显然令人瞠目结舌：困惑度很低（模型"很会背"），但生成的文本是
# "travellerererererer..." 的无限重复。为什么?
#
# 原因：双向 RNN 在每个时间步都用到了"未来信息"。
#   - 训练阶段：给模型喂完整序列，双向层能同时看到当前词元的前后，于是轻易学会
#               "在 traveller 后面补一个 e"这种模式 —— 但它依赖的是"未来信息"。
#   - 测试/预测阶段：我们要预测"下一个词元"，此时根本没有"未来"可用，
#              模型只能退化为"机械重复上一个词"。
#   于是训练/测试分布不一致 → 测试表现糟糕（虽然训练困惑度很低）。
#
# 结论：双向 RNN 适合"已经有完整上下文"的编码任务（命名实体识别、机器翻译的
#      序列编码、完形填空），而绝不适合"逐词元预测下一个"的生成任务。
# 正确用法见第 10 章 BERT 与情感分析章节。


# ============================================================================
# 补充知识点：双向 RNN 的数学定义
# ============================================================================
#   前向隐状态： H→_t = φ( X_t W_xh^(f) + H→_{t-1} W_hh^(f) + b_h^(f) )
#   反向隐状态： H←_t = φ( X_t W_xh^(b) + H←_{t+1} W_hh^(b) + b_h^(b) )
#   拼接后入输出层： O_t = [H→_t; H←_t] W_hq + b_q
#   其中连接后的 H_t ∈ R^{n×2h}，输出权重 W_hq ∈ R^{2h×q}。
#   两个方向可各自拥有不同隐藏单元数（此时拼接维 = h_f + h_b）。


# ============================================================================
# 核心公式回顾
# ============================================================================
#   输入 X_t ∈ R^{n×d}。设单向隐藏单元 h：
#     H→_t = φ( X_t W_xh^(f) + H→_{t-1} W_hh^(f) + b_h^(f) )   （从前往后）
#     H←_t = φ( X_t W_xh^(b) + H←_{t+1} W_hh^(b) + b_h^(b) )   （从后往前）
#     H_t  = [ H→_t , H←_t ] ∈ R^{n×2h}                       （拼接）
#     O_t  = H_t W_hq + b_q ∈ R^{n×q}                       （输出层）
#
#   特点：每个时间步的隐状态同时由"之前"与"之后"的数据决定。


