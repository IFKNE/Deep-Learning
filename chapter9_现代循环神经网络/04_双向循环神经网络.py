# ============================================================================
# 总结
# ============================================================================
#  - 双向 RNN 每个时间步的隐状态由"前后文"同时决定，能利用未来信息。
#  - 与 HMM 的前向-后向动态规划算法有相似性（统计模型的通用化）。
#  - 主要用于"序列编码"与"给定双向上下文的观测估计"。
#  - 由于梯度链更长、且需要双向递归，训练代价很高。
#  - ❗ 不要盲目用于"预测下一个词"——那会因测试时看不到未来而表现崩坏。
