# 总结
# ============================================================================
#  - 解码序列生成三选一：贪心（快但可能不优）、穷举（最优但不可行）、束搜索（折衷）。
#  - 束搜索用可调的束宽 k 平衡"正确率"与"计算成本"，k=1 即贪心。
#  - 打分用 L^α 归一化惩罚长序列，避免"越长越占便宜"。
#  - 束搜索是解码期策略，不参与训练，是 seq2seq 等生成模型的标准解码组件。
