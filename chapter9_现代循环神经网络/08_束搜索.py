# ============================================================================
# 问题设定：从所有可能输出序列里挑出最优的那个
# ============================================================================
# 在任意时间步 t'，解码器输出 y_{t'} 的概率取决于：
#   - 之前的输出子序列 y_1, ..., y_{t'-1}
#   - 编码输入序列得到的上下文变量 c
# 记输出词表为 Y（含 <eos>），其大小为 |Y|；输出序列最大长度为 T'。
# 那么全部可能的输出序列共有 O(|Y|^{T'}) 种。
# 我们的目标：从这指数级多的序列里，找出条件概率最高的那一个。
#
# 最优序列的定义：最大化下式（串行联合条件概率）：
#       ∏_{t'=1}^{T'} P(y_{t'} | y_1, ..., y_{t'-1}, c)


# ============================================================================
# 策略一：贪心搜索（greedy search）
# ============================================================================
# 做法：每个时间步 t'，直接选择当前条件概率最大的那个词元：
#       y_{t'} = argmax_{y ∈ Y} P(y | y_1, ..., y_{t'-1}, c)
# 一旦遇到 <eos> 或达到最大长度 T'，就结束输出。
#
# 计算代价：每一步只需看 |Y| 种，共 T' 步 → O(|Y| · T')，非常小。
#
# 问题：贪心不能保证全局最优。
# 例：假设时间步 2 选择了第二高概率的词元 "C"（而非最高概率 "B"），
#     后续时间步 3、4 的条件概率会随之改变，最终整体序列概率可能反而更高。
# 经典反例说明（教材例子）：
#   路径 A：选 B → 整体概率 0.5 × 0.4 × 0.4 × 0.6 = 0.048
#   路径 B：选 C → 整体概率 0.5 × 0.3 × 0.6 × 0.6 = 0.054  ← 更大！
# 贪心每步只看"当下"，却看不见"局部最优会堵死后面更优路径"。


# ============================================================================
# 策略二：穷举搜索（exhaustive search）
# ============================================================================
# 做法：枚举所有 |Y|^{T'} 种可能的输出序列，计算各自的条件概率，
#       取概率最大的那一个。这必然能拿到全局最优。
#
# 计算代价：O(|Y|^{T'})，高得惊人。
#   例：|Y| = 10000，T' = 10 时，要评估 10000^10 = 10^40 个序列，
#       现有计算机几乎不可能完成。
#
# 结论：穷举最优但不可行；贪心可行但不最优。


# ============================================================================
# 策略三：束搜索（beam search）—— 介于两者之间的折衷
# ============================================================================
# 想法：同时保留多个"候选序列"，每一步都挑最可能的前 k 个往下走。
# 超参数：束宽（beam size）k。
#
# 过程：
#   时间步 1：从 |Y| 个词元里选概率最高的 k 个，作为 k 条候选序列的开头。
#   后续每个时间步：基于上一步的 k 条候选，各扩展出 |Y| 个选择，
#         于是得到 k·|Y| 个新候选，从中再挑概率最高的 k 个。
#   到达最大长度后，得到最终候选集合，选其中条件概率乘积最高的一条输出。
#
# 教材示例（词表 {A,B,C,D,E} 含 <eos>，k=2，最大长度 3）：
#   步1：选 A、C。
#   步2：算 P(A,y2|c) 与 P(C,y2|c) 共 2×5=10 个值，取最大俩，如 (A,B)、(C,E)。
#   步3：算 P(A,B,y3|c) 与 P(C,E,y3|c) 共 2×5=10 个值，取最大俩，如 (A,B,D)、(C,E,D)。
#   最终候选：A、C、A,B、C,E、A,B,D、C,E,D 六条，再从中挑最好。
#
# 打分归一化：直接比较"条件概率乘积"会偏向更长的序列（项更多）。
#   因此用带长度的归一化打分：
#       (1/L^α) · log P(y_1,...,y_L|c) = (1/L^α) · Σ_{t'=1}^{L} log P(y_{t'}|...)
#   其中 L 是候选序列长度，α 通常取 0.75。分母的 L^α 用来"惩罚长序列"。
#
# 计算代价：每步维护 k 条候选 × 扩展 |Y| → O(k · |Y| · T')，
#           介于贪心 O(|Y|·T') 与穷举 O(|Y|^{T'}) 之间。
# 特例：束宽 k=1 时，束搜索就退化为贪心搜索。


# ============================================================================
# 补充知识点
# ============================================================================
# 1. 【三种策略的总结对比】
#    - 贪心搜索：计算量最小，精度相对较低。
#    - 穷举搜索：精度最高，计算量最大（不可行）。
#    - 束搜索  ：束宽 k 可调，在"正确率"与"计算代价"之间权衡。
#
# 2. 【为什么贪心 = 束宽为 1 的束搜索？】
#    束搜索每步保留 k 条候选；当 k=1 时每一步只剩一条"最优候选"，即贪心。
#
# 3. 【实际应用中的取舍】
#    - 若精度最重要 → 用更大的束宽（甚至穷举）；
#    - 若实时性/成本最重要 → 用束宽 1 即贪心，或小束宽。
#    机器翻译中常取 k ≈ 5~10，兼顾效果与速度。
#
# 4. 【束搜索是"解码"阶段的外挂算法】
#    它只改"如何选词"，不影响模型的训练（训练用 teacher forcing 直接监督）。
#    训练时我们有真值标签做监督；推理时才用搜索策略逐步采样。


# ============================================================================
# 核心公式回顾
# ============================================================================
#   概率定义：P(y_{t'} | y_1..y_{t'-1}, c)
#   最优目标：max  ∏_{t'=1}^{T'} P(y_{t'} | y_1..y_{t'-1}, c)
#   贪心  ：y_{t'} = argmax_{y∈Y} P(y | y_1..y_{t'-1}, c)，代价 O(|Y|·T')
#   穷举  ：全枚举最大化，代价 O(|Y|^{T'})
#   束搜索：维护 k 条候选，每步从 k|Y| 中选 k，代价 O(k·|Y|·T')
#   打分  ：(1/L^α) Σ_{t'=1}^{L} log P(y_{t'} | ...)，α≈0.75，惩罚长序列
#   特例  ：k=1 时束搜索 = 贪心搜索


