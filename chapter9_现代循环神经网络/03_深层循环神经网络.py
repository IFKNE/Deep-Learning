"""
=============================================================================
深层循环神经网络（Deep Recurrent Neural Network）—— 完整带注释版
=============================================================================
任务：把之前"只有一层"的 RNN 横向堆叠成多层，让网络同时拥有"时间维"和"深度维"。
     每层隐状态既传给"当前层的下一个时间步"（横向），又传给"下一层的当前时间步"
     （纵向），从而既能捕捉序列内部依赖，又能分层抽象信息。

依赖：d2l 包。本文件可独立运行。
=============================================================================
"""

# ============================================================================
# 第1步：导入依赖、加载数据集
# ============================================================================
import torch
from torch import nn
from d2l import torch as d2l

batch_size, num_steps = 32, 35
train_iter, vocab = d2l.load_data_time_machine(batch_size, num_steps)


# ============================================================================
# 第2步：用高层 API 构建"两层 LSTM"模型
# ============================================================================
# 词表大小（= 输入/输出维数）、隐藏单元数、隐藏层层数
vocab_size, num_hiddens, num_layers = len(vocab), 256, 2
num_inputs = vocab_size
device = d2l.try_gpu()

# nn.LSTM(input_size, hidden_size, num_layers)：
#   第三个参数 num_layers = 2 表示"堆叠两层 LSTM"。
#   这与第 2 节的单层 LSTM 唯一区别就是这里设了层数，其余完全一致。
lstm_layer = nn.LSTM(num_inputs, num_hiddens, num_layers)

# d2l.RNNModel：高层封装，自动接入 nn.LSTM 层
model = d2l.RNNModel(lstm_layer, len(vocab))
# 搬到 GPU（若有）
model = model.to(device)


# ============================================================================
# 第3步：训练与预测
# ============================================================================
# 由于用了两层 LSTM，训练速度被明显拖慢（传播链更长）。
num_epochs, lr = 500, 2
# d2l.train_ch8：与前面相同的训练循环。这里把学习率写成 lr*1.0 以匹配源码。
d2l.train_ch8(model, train_iter, vocab, lr * 1.0, num_epochs, device)
# 结果示例：
#   perplexity 1.0, 186005.7 tokens/sec on cuda:0
#   time traveller for so it will be convenient to speak of himwas e ...


# ============================================================================
# 补充知识点
# ============================================================================
# 1. 【为什么是"既有横向又有纵向"？】
#    单层 RNN 可以看成"时间维"上的递归：每个时间步更新一个 H。
#    多层 RNN 在此之上再加"深度维"：
#      - 第 l 层的 H_t^(l) 由「第 l 层上一时间步 H_{t-1}^(l)（横向）」
#        和「上一层当前时间步 H_t^(l-1)（纵向）」共同决定。
#    也就是说，信息既能"在时间中流动"，也能"在层间向上抽象"。

# 2. 【函数依赖关系（L 层通用公式）】
#    令 H_t^(0) = X_t（输入当作第 0 层的"隐状态"），第 l 层激活函数为 φ_l：
#       H_t^(l) = φ_l( H_t^(l-1) W_xh^(l) + H_{t-1}^(l) W_hh^(l) + b_h^(l) )
#    输出层只使用最后一层的最终隐状态：
#       O_t = H_t^(L) W_hq + b_q
#    其中 W_xh^(l)/W_hh^(l)/b_h^(l) 是第 l 层参数，W_hq / b_q 是输出层参数。

# 3. 【与多层感知机"加层"的区别】
#    MLP 加层只需把上一层的输出当本层输入；RNN 加层还要同时考虑"时间步之间的
#    递归"，因此更深层的 RNN 需要更小心地初始化与调参（学习率、梯度裁剪）。

# 4. 【成本与调参】
#    - 层数越多 → 前向/反向链越长 → 训练越慢、越容易数值不稳定。
#    - 需要谨慎设置学习率、梯度裁剪阈值，并对权重做合适的初始化。


# ============================================================================
# 核心公式回顾
# ============================================================================
#   设输入 X_t ∈ R^{n×d}，第 l 层隐状态 H_t^(l) ∈ R^{n×h}，输出 O_t ∈ R^{n×q}，
#   并令 H_t^(0) = X_t。
#
#   H_t^(l) = φ_l( H_t^(l-1) W_xh^(l) + H_{t-1}^(l) W_hh^(l) + b_h^(l) )
#   O_t     = H_t^(L) W_hq + b_q
#
#   其中 L 和 h 是超参数。把 H_t^(l) 替换成 GRU/LSTM 的隐状态更新式，
#   就能得到深层门控 RNN / 深层 LSTM。


