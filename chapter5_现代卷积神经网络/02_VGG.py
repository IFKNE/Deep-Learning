"""
=============================================================================
使用块的网络（VGG）—— 完整带注释版
=============================================================================
VGG (Visual Geometry Group) 由牛津大学提出，核心思想是：
  "使用更深的网络和更小的卷积核（全部 3×3）堆叠来替代大卷积核"

核心贡献：
  - VGG块：将多个 3×3 Conv + ReLU + MaxPool 封装为可复用的"块"
  - 两个 3×3 的感受野 = 一个 5×5，三个 3×3 = 一个 7×7
  - 参数更少、非线性更多

输入: Fashion-MNIST 28×28 → resize 到 224×224
输出: 10 类分类
=============================================================================
"""

import torch
from torch import nn
from d2l import torch as d2l


# ============================================================================
# VGG 块
# ============================================================================
# VGG 块的核心设计：
#   1. 多个 3×3 卷积层（填充=1，保持高宽不变）+ ReLU
#   2. 最后接一个 2×2 最大池化层（步幅=2，高宽减半）
#
# 为什么用多个 3×3 代替一个大卷积核？
#   - 两个 3×3 卷积的感受野 = 5×5，但参数只有 2×9=18 个权重
#     而一个 5×5 卷积有 25 个权重
#   - 更重要的是，每个 3×3 后都有 ReLU，提供了更多非线性
#   - 相同感受野下，参数更少、非线性更多 → 更好的表达能力

def vgg_block(num_convs, in_channels, out_channels):
    """
    构建一个 VGG 块。

    参数:
        num_convs: 块中卷积层的数量
        in_channels: 输入通道数
        out_channels: 输出通道数（块内所有卷积层统一使用）

    返回:
        nn.Sequential: 包含卷积层+ReLU+池化层的 VGG 块
    """
    layers = []
    for _ in range(num_convs):
        # nn.Conv2d(输入通道, 输出通道, 卷积核=3, 填充=1)
        #   kernel_size=3, padding=1 → 输出高宽 = 输入高宽（保持尺寸）
        layers.append(nn.Conv2d(in_channels, out_channels,
                                kernel_size=3, padding=1))
        layers.append(nn.ReLU())
        # 更新 in_channels 为 out_channels，因为下一层输入通道 = 当前输出通道
        in_channels = out_channels
    # 每个块最后加一个 MaxPool2d(kernel_size=2, stride=2)
    #   高宽减半，例如 224×224 → 112×112
    layers.append(nn.MaxPool2d(kernel_size=2, stride=2))
    # *layers 解包列表，将列表元素作为独立参数传给 Sequential
    return nn.Sequential(*layers)


# ============================================================================
# VGG-11 网络架构
# ============================================================================
# conv_arch 定义了 5 个 VGG 块的 (卷积层数量, 输出通道数)
#   块1: 1个卷积层, 64通道  → 224×224 → 112×112
#   块2: 1个卷积层, 128通道 → 112×112 → 56×56
#   块3: 2个卷积层, 256通道 → 56×56   → 28×28
#   块4: 2个卷积层, 512通道 → 28×28   → 14×14
#   块5: 2个卷积层, 512通道 → 14×14   → 7×7
# 总共 1+1+2+2+2 = 8 个卷积层，所以叫 VGG-11（8卷积+3全连接）
conv_arch = ((1, 64), (1, 128), (2, 256), (2, 512), (2, 512))


def vgg(conv_arch):
    """
    按给定架构构建 VGG 网络。

    参数:
        conv_arch: 元组列表，每个元素为 (卷积层数量, 输出通道数)

    返回:
        nn.Sequential: 完整的 VGG 网络
    """
    conv_blks = []
    in_channels = 1  # Fashion-MNIST 是灰度图，初始通道=1

    # ---- 卷积层部分 ----
    for (num_convs, out_channels) in conv_arch:
        # 每轮循环添加一个 VGG 块，通道数逐渐增加
        conv_blks.append(vgg_block(num_convs, in_channels, out_channels))
        in_channels = out_channels  # 下一块的输入通道 = 当前块的输出通道

    # ---- 全连接层部分（与 AlexNet 相同） ----
    # VGG 卷积部分结束时输出形状为 (batch, 512, 7, 7) = 512×7×7 = 25088
    # Flatten 展平为 (batch, 25088)
    # 然后经过 3 个全连接层：25088→4096→4096→10
    return nn.Sequential(
        *conv_blks, nn.Flatten(),
        # 第1个全连接层: 25088 → 4096
        nn.Linear(out_channels * 7 * 7, 4096), nn.ReLU(),
        nn.Dropout(0.5),  # dropout 概率 0.5 防止过拟合
        # 第2个全连接层: 4096 → 4096
        nn.Linear(4096, 4096), nn.ReLU(),
        nn.Dropout(0.5),
        # 输出层: 4096 → 10
        nn.Linear(4096, 10))

# 构建原始 VGG-11 网络
net = vgg(conv_arch)


# ============================================================================
# 查看各层输出形状
# ============================================================================
# torch.randn(size=形状): 从标准正态分布 N(0,1) 随机采样
X = torch.randn(size=(1, 1, 224, 224))
print("=== VGG-11 各层输出形状 ===")
for blk in net:
    X = blk(X)
    print(blk.__class__.__name__, 'output shape:\t', X.shape)
# 观察规律：每过一个 VGG 块（Sequential），高宽减半，通道翻倍


# ============================================================================
# 简化版 VGG（用于 Fashion-MNIST 训练）
# ============================================================================
# 原始 VGG-11 计算量很大，Fashion-MNIST 只是 28×28 的简单数据集
# 用 ratio=4 将所有通道数除以 4，大幅减小模型
#   原始: 64, 128, 256, 512, 512
#   简化: 16, 32,  64,  128, 128
# 列表推导式: [(pair[0], pair[1] // ratio) for pair in conv_arch]
#   → 遍历 conv_arch 中每个元组，对通道数做整除
ratio = 4
small_conv_arch = [(pair[0], pair[1] // ratio) for pair in conv_arch]
net = vgg(small_conv_arch)


# ============================================================================
# 训练 VGG
# ============================================================================
# lr=0.05: 比 AlexNet (0.01) 略大，因为简化版 VGG 参数量更少，可以用稍大学习率
# resize=224: VGG 预期输入 224×224
lr, num_epochs, batch_size = 0.05, 10, 128
train_iter, test_iter = d2l.load_data_fashion_mnist(batch_size, resize=224)
d2l.train_ch6(net, train_iter, test_iter, num_epochs, lr, d2l.try_gpu())
# 预期: loss ~0.18, train acc ~0.93, test acc ~0.92


# ============================================================================
# 补充知识点
# ============================================================================

# 1. 打印层尺寸时只有 8 个结果（5 VGG块 + Flatten + 3 Linear）而非 11 个？
#    因为每个 VGG 块是 nn.Sequential，打印时打印的是 Sequential 整体
#    而非内部的每个卷积层和 ReLU。这说明块封装会隐藏内部细节。

# 2. VGG 为什么比 AlexNet 更慢、更占显存？
#    - VGG 有 3 个 4096 的全连接层，参数约 102M（远大于 AlexNet 的 60M）
#    - 全连接层参数量: 7×7×512×4096 ≈ 102M → 大量计算和内存消耗
#    - 这也是后来 NiN 和 GoogLeNet 用全局平均池化替代全连接层的原因

# 3. 为什么深层窄卷积比浅层宽卷积更有效？
#    VGG 论文实验发现：同样计算量下，增加深度（更多层）比增加宽度（更多通道）效果好
#    3×3 卷积是能捕获中心+邻居的最小尺寸，堆叠多个等效于更大感受野

# ============================================================================
# 核心公式回顾
# ============================================================================
#   两个 3×3 卷积感受野：3 + (3-1) = 5（等价于 5×5 卷积）
#   三个 3×3 卷积感受野：3 + (3-1) + (3-1) = 7（等价于 7×7 卷积）
#   参数量对比（C个通道）: 3个3×3 为 3×C×3×3 = 27C²，1个7×7 为 C×7×7 = 49C²
#   VGG 块输出尺寸: H_out = H_in / 2  (因为 2×2 池化 stride=2)

# ============================================================================
# 总结
# ============================================================================
# 1. VGG 用可复用的"块"简化深层网络的设计
# 2. 小卷积核 (3×3) 堆叠替代大卷积核 = 参数更少 + 非线性更多
# 3. VGG-11 是经典架构（8 卷积 + 3 全连接），VGG-16/19 更深
# 4. 缺点是全连接层参数过多（~102M），后来被全局平均池化替代
# 5. 块设计思想影响了后续所有架构（ResNet、DenseNet等）
