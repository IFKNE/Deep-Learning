# ============================================================================
# 无隐状态的神经网络
# ============================================================================
# --- 引入：为什么需要"隐状态"？ ---
# n 元语法模型：P(x_t | x_{t-1},...,x_{t-n+1})，只依赖最近 n-1 个词。
#   若想纳入更早的词，就要增大 n；但词表 V 需要存储 |V|^n 个数字，
#   参数会随 n 呈【指数】爆炸，工程上不可行。
# 于是改用"隐变量模型"：用一个隐状态 h_{t-1} 把"到 t-1 为止"的序列信息浓缩出来：
#   P(x_t | x_{t-1},...,x_1) ≈ P(x_t | h_{t-1})
# 再递归地由当前输入 x_t 和上一步隐状态 h_{t-1} 计算本步隐状态：
#   h_t = f(x_t, h_{t-1})
#   注：若 f 真的"只存下全部历史"，这一步不是近似；但这种做法计算/存储代价过高。
#
# 先澄清两个易混概念：
#   隐藏层（hidden layer）：在"输入→输出"这条路径上、观测角度看不到的那一层。
#   隐状态（hidden state）：只能由先前时间步的数据算出来、作为"当前步输入"的状态。
#   它们指的不是同一个东西。恰恰是"带隐状态的神经网络"才叫循环神经网络（RNN）。

# --- 无隐状态的单隐藏层 MLP 数学推导（对应本节第一个 ## 标题） ---
# 设隐藏层激活函数为 φ，小批量样本 X ∈ R^{n×d}（n=批量大小，d=输入维度），
# 则隐藏层输出 H ∈ R^{n×h} 由下式计算：
#   H = φ(X·W_xh + b_h)
#   其中：
#     φ     : 逐元素激活函数（如 ReLU），给网络引入非线性
#     W_xh  : 隐藏层权重 ∈ R^{d×h}
#     b_h   : 隐藏层偏置 ∈ R^{1×h}，靠广播机制自动与每一行相加
#     h     : 隐藏单元个数
# 再把 H 作为输出层的输入：
#   O = H·W_hq + b_q
#   其中 O ∈ R^{n×q}、W_hq ∈ R^{h×q}、b_q ∈ R^{1×q}。
#   若是分类问题，再用 softmax(O) 得到各类别的概率分布。
# 这里的关键：计算是"一步到位"的，算完 H 之后不会为下一时刻记住任何东西 → 无状态。


# ============================================================================
# 有隐状态的循环神经网络
# ============================================================================
# 引入隐状态后，情况完全不同了。
#   时间步 t 的小批量输入 X_t ∈ R^{n×d}：每一行是某个序列在时刻 t 的一个样本。
#   上一时刻隐状态 H_{t-1} ∈ R^{n×h} 被保存下来，并引入新权重 W_hh ∈ R^{h×h}。
# 当前隐状态由【当前输入】与【上一时刻隐状态】一起算得（本节核心公式）：
#   H_t = φ(X_t·W_xh + H_{t-1}·W_hh + b_h)
#   与 MLP 相比只多了一项 H_{t-1}·W_hh —— 正是它把上一时刻的记忆带进了当前时刻。
# 于是 H_t 捕获了序列直到当前时刻的历史信息，就像神经网络此刻的"状态/记忆"，
# 所以称为隐状态（hidden state）。
# 因为每一步都套用同一个公式递归计算，这个计算是【循环】的（recurrent），
# 执行该计算的层就叫循环层（recurrent layer）。输出层与 MLP 相同：
#   O_t = H_t·W_hq + b_q

# --- 参数共享（最关键的结论）---
# 循环神经网络的全部参数：
#   隐藏层权重  W_xh ∈ R^{d×h}，W_hh ∈ R^{h×h}；偏置 b_h ∈ R^{1×h}
#   输出层权重  W_hq ∈ R^{h×q}；偏置 b_q ∈ R^{1×q}
# 重要：不同时间步 t 用的是【同一套】参数（W_xh、W_hh、b_h ...）。
#   因此 RNN 的参数开销【不】随时间步增加而增大——
#   这正是序列建模的精髓：用固定大小的参数去处理任意长度的序列。

# --- 循环计算的两种等价数学形式 ---
# 任意时间步 t 算隐状态，可拆成两步：
#   1. 拼接当前输入 X_t 与上一时刻隐状态 H_{t-1}；
#   2. 把拼接结果送入带激活函数 φ 的全连接层 → 得到 H_t。
# 数学上，"X_t·W_xh + H_{t-1}·W_hh" 等价于"先拼接、再一次矩阵乘法"：
#   [X_t ⊕ H_{t-1}] · [W_xh ⊕ W_hh]
#   （⊕ 表示拼接：X 沿"列"拼、W 沿"行"拼，下面用两段代码验证这一等价性）


# ==== 拼接等价性演示 ①：先分别乘、再加（对应源码第 2 个 code 单元 code#2）====
# 先标清各张量形状：
#   X    (3, 1) —— 当前时间步输入：n=3 个样本、特征维 d=1
#   W_xh (1, 4) —— 输入→隐层权重：d=1 → h=4
#   H    (3, 4) —— 上一时间步隐状态：n=3 个样本、隐单元 h=4
#   W_hh (4, 4) —— 隐状态→隐状态权重：h=4 → h=4
# torch.normal(0, 1, shape) = 从标准正态分布 N(0, 1) 随机采样，生成指定形状的张量
# 用同名变量同时给多个张量赋值（逗号分割 = 元组解包，依次赋值）
X, W_xh = torch.normal(0, 1, (3, 1)), torch.normal(0, 1, (1, 4))
H, W_hh = torch.normal(0, 1, (3, 4)), torch.normal(0, 1, (4, 4))
# 分两步各自做矩阵乘法再相加：
#   X·W_xh : (3,1)×(1,4) → (3,4)
#   H·W_hh : (3,4)×(4,4) → (3,4)
#   两个同形 (3,4) 结果逐元素相加，最终形状仍为 (3,4)
torch.matmul(X, W_xh) + torch.matmul(H, W_hh)


# ==== 拼接等价性演示 ②：先拼接、再一次矩阵乘法（对应源码第 4 个 code 单元 code#4）====
# 与上面同形：这次用 torch.cat 把矩阵先拼起来，再做一次 matmul。
#   torch.cat((X, H), 1)  ：沿 axis=1（列）拼。X(3,1) + H(3,4) → (3,5)
#                           行数都是 3，能在"列"方向拼接；
#   torch.cat((W_xh,W_hh), 0)：沿 axis=0（行）拼。W_xh(1,4) + W_hh(4,4) → (5,4)
#                           列数都是 4，能在"行"方向拼接。
# 拼接后的 (3,5)×(5,4) → (3,4)，与上一代码单元结果形状完全一致。
# 数学上等价：  [X|H]·[W_xh;W_hh] = X·W_xh + H·W_hh
#   这就直观体现了循环层的计算方式：把当前输入与历史隐状态并到一起，送入全连接层。
torch.matmul(torch.cat((X, H), 1), torch.cat((W_xh, W_hh), 0))


# ============================================================================
# 基于循环神经网络的字符级语言模型
# ============================================================================
# 语言模型目标：根据过去和当前的词元预测【下一个】词元，
#   所以把原始序列整体"向左偏移一个词元"当作标签：输入 "machin" → 标签 "achine"。
# 为了简化训练，本节用【字符级】语言模型：把文本切成字符而不是单词。
#   例如批量大小 = 1、序列为 "machine"：
#     输入 "m a c h i n"（= "machin"）  → 逐步预测输出 "a c h i n e"（= "achine"）
# 训练流程：每个时间步先对输出层做 softmax 得到概率分布，
#   再用交叉熵损失衡量"模型输出分布"与"真实标签"之间的差距。
# 由于隐状态是循环计算，第 3 个时间步的输出 O_3 由前三个字符 "m","a","c" 共同决定；
#   而该时刻的真实标签是 "h"—— 于是这一时间步的损失取决于：
#   "给定 m,a,c 这两个（实为三个）字符时，模型给 'h' 分配的概率大小"。
# 实际训练中批量大小 n>1，每个词元用一个 d 维向量表示，
#   因此时间步 t 的输入 X_t 是一个 n×d 矩阵（与"有隐状态"小节讨论的一致）。


# ============================================================================
# 困惑度（Perplexity）
# ============================================================================
# 如何衡量语言模型质量？先看对 "It is raining ..." 的三种续写：
#   1) "It is raining outside"            —— 合理、最连贯（尽管未必最完美）✓
#   2) "It is raining banana tree"        —— 语义荒谬，但已学会拼写与词的弱关联
#   3) "It is raining piouw;kcj pwepoiut" —— 训练不足，根本无法拟合数据
# 直接用"序列似然概率"度量很别扭：短序列天然比长序列更容易出现，
#   直接比概率无法公平对比不同长度的文档（《战争与和平》比《小王子》短，概率自然偏小）。
# 于是借助信息论：
#   压缩一段序列所需【比特数越少】= 模型越好。用所有 n 个词元的交叉熵损失的【平均】来衡量，
#   这样不同长度的文档才可比：
#     (1/n) · Σ_{t=1..n}  [ -log P(x_t | x_{t-1}, ..., x_1) ]
#   其中 P 由语言模型给出，x_t 是时间步 t 实际观测到的词元。

# --- 困惑度公式（本节核心推导，全部展开）---
# 困惑度就是上面这个"平均交叉熵"的指数：
#   Perplexity = exp( (1/n) · Σ_{t=1..n} [ -log P(x_t | x_{t-1}, ..., x_1) ] )
#   （等价写法，把负号提出）:
#              = exp( -(1/n) · Σ_{t=1..n} log P(x_t | x_{t-1}, ..., x_1) )
# 直观理解：困惑度 ≈ "下一个词元实际可选个数的调和平均"。

# --- 三个边界参考值（用来校准"好与坏"）---
#   最好：模型总是以概率 1 预测正确标签词元  → Perplexity = 1（完美）。
#   最坏：模型总是以概率 0 预测标签词元    → Perplexity = +∞（全错）。
#   基线：模型在词表所有词元上【均匀分布】→ Perplexity = 词表中唯一词元的个数。
#         （等同"不做任何压缩、直接存序列"；这是能做到的最优编码，给一切真实模型
#           设置了一个必须超越的上限 —— 真实模型困惑度必须小于词表大小。）
# 小结：困惑度越低 = 模型对下一词元的预测越确定、越准确 = 语言模型越好。


# ============================================================================
# 补充知识点
# ============================================================================
# 1. 隐藏层 vs 隐状态（最易混淆）
#    隐藏层：输入→输出路径上、无法直接观测到的那一层。
#    隐状态：只能由"此前的时间步"推算出来、并作为当前步输入的状态量。
#    RNN 之所以"循环"，正是因为隐状态在每个时间步用同一套公式递归传递。

# 2. 为什么 RNN 参数不随序列长度增长？
#    时间步 t 的计算只依赖 (W_xh, W_hh, b_h, W_hq, b_q)，这些参数在时间轴上【共享】。
#    无论序列是 10 步还是 1000 步，用的都是同一组参数（大小固定）。
#    这是 RNN 能处理"任意长度序列"的根本原因，代价是"递推式前向/反向，难以并行"。

# 3. 拼接矩阵乘法的维度对不上怎么办？
#    本节的技巧是"X 沿列拼、W 沿行拼"，强制让"输入特征"与"隐状态特征"对齐：
#      [X(3,1) | H(3,4)]  →  (3,5)     即 3 个样本、每行 5 = 1+4 个特征
#      [W_xh(1,4) ; W_hh(4,4)] → (5,4) 权重行数 5 = 1+4，列数都是隐单元 4
#    于是 (3,5)×(5,4)=(3,4)，恰好还原 "X·W_xh + H·W_hh"。
#    在 PyTorch 里对应 torch.cat 的 dim=1（列）/ dim=0（行），形状对不上会直接报错。

# 4. 困惑度为什么是"调和平均"式的直觉？
#    困惑度 = 2^平均交叉熵（当 log 以 2 为底时）。一个均匀分布的词表大小为 K 时，
#    词元选择"完全不确定"，困惑度 = K；模型越确定，困惑度越接近 1。
#    所以它可以理解成"模型实际上是在 K 个候选里捏了一把，平均犹豫的候选数"。


# ============================================================================
# 核心公式回顾
# ============================================================================
# 隐变量模型（把长历史压缩成隐状态）：
#   P(x_t | x_{t-1},...,x_1) ≈ P(x_t | h_{t-1})，   h_t = f(x_t, h_{t-1})
#
# 无隐状态 MLP（一步到位、无记忆）：
#   H = φ(X·W_xh + b_h)
#   O = H·W_hq + b_q
#
# 有隐状态 RNN（循环、有记忆，本节主题）：
#   H_t = φ(X_t·W_xh + H_{t-1}·W_hh + b_h)
#   O_t = H_t·W_hq + b_q
#   权重 W_xh∈R^{d×h}, W_hh∈R^{h×h}, W_hq∈R^{h×q}，偏置 b_h∈R^{1×h}, b_q∈R^{1×q}
#
# 拼接等价（两种写法算出同一结果）：
#   X_t·W_xh + H_{t-1}·W_hh  ≡  [X_t | H_{t-1}] · [W_xh ; W_hh]
#
# 平均交叉熵（评价语言模型）：
#   (1/n) · Σ_{t=1..n} [ -log P(x_t | x_{t-1}, ..., x_1) ]
#
# 困惑度（Perplexity）：
#   Perplexity = exp( -(1/n) · Σ_{t=1..n} log P(x_t | x_{t-1}, ..., x_1) )
#     1 = 完美；+∞ = 全错；= 词表大小 = 均匀分布基线


