# 总结
# ============================================================================
# 1. 对隐状态使用【循环计算】的神经网络叫循环神经网络（RNN）。
# 2. 隐状态能捕获"直到当前时间步"的序列历史信息，像网络此刻的记忆/状态。
# 3. RNN 的参数数量【不会】随时间步增加而增加（参数在时间轴上共享）。
# 4. 用 RNN 可搭建字符级语言模型：输入 "machin" → 标签 "achine"，逐字符预测。
# 5. 用困惑度（Perplexity）评价语言模型质量：越低越好，1 为理想下限、词表大小为上限。
# 6. 本节演示了 "X·W_xh + H·W_hh" 与 "[X|H]·[W_xh;W_hh]" 的矩阵等价，
#    直观理解循环层"合并输入与历史隐状态再一起映射"的计算本质。
