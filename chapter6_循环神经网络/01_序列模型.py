"""
=============================================================================
序列模型（Sequence Models）—— 完整带注释版
=============================================================================
本章从"循环神经网络（RNN）"入手的第一节，先不急着引入 RNN，
而是用最朴素的"自回归模型（autoregressive model）"来体验序列建模的
本质：如何用历史观测预测下一个时间步。

核心问题：
  x_t ~ P(x_t | x_{t-1}, ..., x_1)          # 用过去的序列预测未来的值

关键概念：
  - 时间步 (time step): t 是离散的，序列按 t = 1, 2, ..., T 展开
  - 自回归模型: 只取最近 tau 个观测 x_{t-1},...,x_{t-tau} 来预测 x_t
  - 马尔可夫条件: 若取 tau 个历史就足够精确，称序列满足马尔可夫条件
  - 隐变量自回归模型: 用一个隐藏的"总结" h_t 压缩全部历史
  - 单步预测 vs 多步(k步)预测: 多步预测要用"自己预测的结果"作为新输入，
    会造成误差累积，预测质量随步数 k 快速衰减

本文件实践流程：
  1. 用正弦函数 + 噪声生成 1000 个时间步的序列数据
  2. 按 tau=4 把序列切成"特征-标签"对（滑动窗口）
  3. 用两层 MLP（nn.Sequential + MSELoss + Adam）训练单步预测模型
  4. 用训练好的模型做单步预测，再做 k 步预测（k=1,4,16,64）
  5. 观察误差累积导致的多步预测衰减现象

输入: 正弦序列 x_t = sin(0.01 t) + 噪声, t = 1..1000
输出: 预测曲线（单步/多步）对比
=============================================================================
"""

import torch
from torch import nn
from d2l import torch as d2l


# ============================================================================
# 统计工具
# ============================================================================
# 处理序列数据需要专门的统计工具和新的深度网络架构。为直观起见，
# 先用股票价格（富时100指数）作类比：
#   用 x_t 表示"价格"，即在时间步 t 处观察到的值。
#   交易员想在 t 日表现良好 → 通过历史预测 x_t：
#       x_t ~ P(x_t | x_{t-1}, ..., x_1)
# 例如股票、音乐、语音、文本、视频、地震等都是序列数据，顺序一旦被打乱，
# 就失去了原本含义（"狗咬人" vs "人咬狗"字相同却含义迥异）。

# ----------------------------------------------------------------------------
# 自回归模型 (Autoregressive Models)
# ----------------------------------------------------------------------------
# 【为什么要用自回归模型？】
#   直接用回归模型 P(x_t | x_{t-1}, ..., x_1) 有个大问题：输入的数量随 t 变化。
#   t 越大，输入 x_{t-1},...,x_1 越多，输入维度不固定，根本无法训练固定形状的网络。
# 解决策略有两种：
#
# 策略一（自回归模型 / 马尔可夫近似）：
#   假设"很久以前"的历史对当前预测已无影响，只取最近长度为 tau 的观测：
#       x_t ~ P(x_t | x_{t-1}, ..., x_{t-tau})
#   好处：输入维度固定为 tau（只要 t > tau），参数数量不变，可放心训练深度网络。
#   之所以叫"自回归"：因为它是对"自己"做回归——用 x 的历史预测 x 自身。
#
# 策略二（隐变量自回归模型 / latent autoregressive models）：
#   用一个从未被观测到的"总结" h_t 压缩全部历史，同时更新预测和总结：
#       x_t_hat = P(x_t | h_t)         # 预测由隐变量决定
#       h_t     = g(h_{t-1}, x_{t-1})  # 隐变量随新观测不断更新
#   由于 h_t 只被"间接观测"，故称"隐变量"。这正是后面 RNN 的前身。
#
# 【如何生成训练数据？时间流动的"静止性"假设】
#   用历史观测预测下一个未来观测。虽然具体值 x_t 会变，但我们假设
#   序列本身的"动力学（规律）"不随 t 改变 —— 统计上称这种不变动力学为"静止的"
#   (stationary)。于是整条序列的联合概率可分解（乘法法则）：
#       P(x_1, ..., x_T) = Π_{t=1}^{T} P(x_t | x_{t-1}, ..., x_1)
#   注意：这里假设不随时间漂移，否则我们无法用现有数据预测"新的动力学"。
#   若处理的是离散对象（如单词），则用"分类器"而非"回归模型"来估计上述概率。

# ----------------------------------------------------------------------------
# 马尔可夫模型 (Markov Models)
# ----------------------------------------------------------------------------
# 若用 x_{t-1},...,x_{t-tau} 近似估计 x_t 足够精确，则称序列满足【马尔可夫条件】。
#   特别地，当 tau = 1 时得到【一阶马尔可夫模型】：
#       P(x_1,...,x_T) = Π_{t=1}^{T} P(x_t | x_{t-1}),  其中 P(x_1|x_0) = P(x_1)
# 当 x_t 只取离散值时模型非常好用——可用动态规划沿马尔可夫链精确计算。
# 例如高效计算 P(x_{t+1} | x_{t-1})（两步之间"跳过"中间一步）：
#
#   P(x_{t+1} | x_{t-1})
#     = Σ_{x_t} P(x_{t+1}, x_t, x_{t-1}) / P(x_{t-1})          # 全概率公式
#     = Σ_{x_t} P(x_{t+1} | x_t, x_{t-1}) P(x_t, x_{t-1}) / P(x_{t-1})
#     = Σ_{x_t} P(x_{t+1} | x_t) P(x_t | x_{t-1})              # 马尔可夫性质
# 这把"隔一步"的概率拆成了"相邻两步"概率的乘积，可见只需极短历史即可。

# ----------------------------------------------------------------------------
# 因果关系 (Causality)
# ----------------------------------------------------------------------------
# 原则上也能把概率倒序展开：
#     P(x_1,...,x_T) = Π_{t=T}^{1} P(x_t | x_{t+1},...,x_T)
# 但在很多场景下数据存在一个自然的"时间前进方向"：未来不能影响过去。
# 改变 x_t 会影响之后 x_{t+1}，却不可能反过来。
# 因此解释 P(x_{t+1}|x_t)（沿时间正向）通常比 P(x_t|x_{t+1}) 更容易。
# 例如存在加性噪声时显然能写出 x_{t+1} = f(x_t) + ε，而反过来则未必成立。
# 这个"向前推进的方向"正是我们通常感兴趣的预测方向。


# ============================================================================
# 训练
# ============================================================================
# 生成数据：用正弦函数 + 可加性噪声，时间步 t = 1, 2, ..., 1000。
#   真实模型是 x_t = sin(0.01 t) + ε，我们的模型只能学到无噪声的"规律"部分。

# 注意：原 notebook 的第一行是 Jupyter 魔数 `%matplotlib inline`（用于让 plt 图
# 直接内嵌显示在 notebook 里）。本文件是独立 .py，不写这条魔数。

T = 1000  # 总共产生 1000 个时间步（这里没用 shape，T 是总点数）
# torch.arange(1, T+1): 生成整数 1..1000，并转成 float32（正弦运算需要浮点）
time = torch.arange(1, T + 1, dtype=torch.float32)
# 序列 = 正弦 "规律" sin(0.01 t) + 可加性噪声（均值 0、标准差 0.2 的高斯噪声）
# torch.normal(0, 0.2, (T,)): 从 N(0, 0.2²) 中采样 T 个噪声点，形状 (1000,)
#   x.shape = (1000,)  —— 一个一维序列，这就是我们要建模的时间序列
x = torch.sin(0.01 * time) + torch.normal(0, 0.2, (T,))
# d2l.plot: D2L 封装的绘图函数，画 (time, x) 曲线，横轴 time、纵轴 x
#   参数依次为 (横轴, 纵轴列表, x轴名, y轴名, xlim=..., figsize=...)
d2l.plot(time, [x], 'time', 'x', xlim=[1, 1000], figsize=(6, 3))


# 接下来把序列转换成"特征-标签"对。基于嵌入维度 tau（滞后量）：
#   每个训练样本：特征 X = [x_{t-tau}, ..., x_{t-1}]（最近 tau 个观测）
#                 标签 y = x_t（要预测的下一个值）
# 比原数据少 tau 个样本，因为前 tau 个点没有足够历史可作特征。
tau = 4  # 滞后量（自回归的窗口大小）：用最近 4 个值预测下一个值
# features 形状 (T - tau, tau) = (996, 4)：每一行是一条特征（4 个历史值）
features = torch.zeros((T - tau, tau))
for i in range(tau):
    # features[:, i] = x[i : T-tau+i]
    #   第 j 行的第 i 个特征 = x[i + j]，即 features[j, :] = [x_j, ..., x_{j+3}]
    #   等价于每个时间步 j，用 [x_j, x_{j+1}, x_{j+2}, x_{j+3}] 预测 x_{j+4}
    features[:, i] = x[i: T - tau + i]
# labels = x[tau:]，即每个特征的"下一个真值"，reshape 成 (996, 1) 列向量
#   因为网络输出是单值，标签也要保持 (N, 1) 才能与输出形状对齐做 MSE
labels = x[tau:].reshape((-1, 1))


# 划分训练集：仅用前 n_train=600 个"特征-标签"对训练（保留 396 个用于评估外推能力）
batch_size, n_train = 16, 600
# 只有前 n_train 个样本用于训练
# d2l.load_array: D2L 以 @save 注册进 d2l 包的函数，把张量组拼成 PyTorch 的
#   DataLoader。用法与前面的线性回归简洁实现完全一致（前面几节直接调用过），
#   is_train=True 表示训练批，会开启随机打乱与批迭代。
train_iter = d2l.load_array((features[:n_train], labels[:n_train]),
                            batch_size, is_train=True)


# 用相当简单的架构训练：一个有两个全连接层的多层感知机（MLP），ReLU 激活 + 平方损失。
# 初始化网络权重的函数
def init_weights(m):
    # 遍历每个子层，若是 nn.Linear（全连接层）就做 Xavier 均匀初始化
    #   Xavier 初始化让输入/输出的方差保持一致，避免深层网络梯度消失/爆炸
    if type(m) == nn.Linear:
        nn.init.xavier_uniform_(m.weight)


# 一个简单的多层感知机
def get_net():
    net = nn.Sequential(nn.Linear(4, 10),   # 输入 4（tau 个特征）→ 隐藏层 10
                        nn.ReLU(),          # 非线性激活，引入非线性拟合能力
                        nn.Linear(10, 1))   # 隐藏层 10 → 输出 1（下一个值）
    net.apply(init_weights)  # apply 递归地对每个子层调用 init_weights 完成初始化
    return net

# 平方损失。注意：MSELoss 计算的是 (y_hat - y)²，没有系数 1/2，
#   所以梯度里也不含 1/2，优化时相当于学习率被缩放，但不影响求最优解。
#   reduction='none' 表示不对批内样本聚合，返回每个样本的损失（形状同输出），
#   后面需要手动 .sum() —— 这与从零实现里对批量损失求和的行为一致。
loss = nn.MSELoss(reduction='none')


# 训练模型：训练循环与前面"线性回归简洁实现"几乎一模一样，只是换了优化器。
def train(net, train_iter, loss, epochs, lr):
    # 用 Adam 优化器（而非 SGD）。Adam 自适应调整每个参数的学习率，收敛通常更快，
    #   几个 epoch 就能把损失压下来，非常适合这个小型回归任务。
    trainer = torch.optim.Adam(net.parameters(), lr)
    for epoch in range(epochs):
        for X, y in train_iter:  # 每个批：X 形状 (16,4)，y 形状 (16,1)
            trainer.zero_grad()           # 清空上一步累积的梯度
            l = loss(net(X), y)           # 前向 + 算平方损失，l 形状 (16,1)
            l.sum().backward()            # 求和后反向传播，自动算出各参数梯度
            trainer.step()                # Adam 用梯度更新参数
        # d2l.evaluate_loss: @save 注册进 d2l 包的函数，用当前参数在整个训练集上
        #   求平均损失并返回，用于打印每个 epoch 的效果。
        print(f'epoch {epoch + 1}, '
              f'loss: {d2l.evaluate_loss(net, train_iter, loss):f}')

net = get_net()
train(net, train_iter, loss, 5, 0.01)


# ============================================================================
# 预测
# ============================================================================
# 训练损失很小，模型理应工作得不错。先检验它"预测下一个时间步"的能力，
# 即【单步预测】(one-step-ahead prediction)：每个输入都用真实的 x 构造。

# onestep_preds: 用训练好的 net 对全部特征做预测
#   features 是 (996, 4)，net 输出 (996, 1)
onestep_preds = net(features)
# 画图对比：data = 真实序列 x，1-step preds = 单步预测。
#   因为单步预测的输出从 t=tau 开始（前 tau 个没有特征），所以横轴取 time[tau:]。
d2l.plot([time, time[tau:]],
         [x.detach().numpy(), onestep_preds.detach().numpy()], 'time',
         'x', legend=['data', '1-step preds'], xlim=[1, 1000],
         figsize=(6, 3))


# 单步预测效果不错，即使超过 n_train + tau = 604 时间步仍可信。
# 但存在一个隐患：假设观测只到 x_{604}，想要 x_{605} 之后的值就难办了——
# 我们必须一步步向前推，把"自己预测的结果"当作下一次输入！
#   由于观测只到 604，求 x_605 需用 x_601..x_604（这可以）；
#   但求 x_606 时要用的 x_605 还没被观测到，只能填入刚预测的 x_605_hat。
# 于是：
#   x_605_hat = f(x_601, x_602, x_603, x_604)
#   x_606_hat = f(x_602, x_603, x_604, x_605_hat)     # 混入了自己的预测
#   x_607_hat = f(x_603, x_604, x_605_hat, x_606_hat) # 全用预测值
#   ...
# 这样"用自己预测当输入"来推更远未来，就叫【k 步预测】(k-step-ahead-prediction)。
# 从观测到 x_t，往后推第 k 步的预测记为 x_{t+k}。下面试试这种多步预测的效果。

multistep_preds = torch.zeros(T)  # 开一个和序列等长的容器，形状 (1000,)
# 前 n_train + tau 个直接填入真实观测值（这些点"已经发生了"，无需预测）
multistep_preds[: n_train + tau] = x[: n_train + tau]
# 从 n_train+tau 开始往后递推：每一步用"最近 tau 个值"预测"下一个值"
for i in range(n_train + tau, T):
    # 取 multistep_preds[i-tau : i]（最近 tau 个值，形状 (tau,)）
    #   reshape((1, -1)) → (1, tau)，与网络输入形状对齐
    # 注意：前几个还混着真实值，后面就全是"上一轮预测出来的值"
    multistep_preds[i] = net(
        multistep_preds[i - tau:i].reshape((1, -1)))

# 画三条曲线对比：真实数据、单步预测、多步预测
d2l.plot([time, time[tau:], time[n_train + tau:]],
         [x.detach().numpy(), onestep_preds.detach().numpy(),
          multistep_preds[n_train + tau:].detach().numpy()], 'time',
         'x', legend=['data', '1-step preds', 'multistep preds'],
         xlim=[1, 1000], figsize=(6, 3))


# 【为什么多步预测会快速衰减？】
# 根本原因是"错误的累积"。假设第 1 步之后积累了误差 ε_1 = ε̄，
# 那第 2 步的输入被扰动了 ε_1，于是第 2 步误差变成 ε_2 = ε̄ + c·ε_1（c 为某常数），
# 后面照此类推，误差像滚雪球一样被逐级放大，很快偏离真实观测。
# 现实类比：未来 24 小时天气预报往往很准，但再往后精度就迅速下跌。
# 令 max_steps = 64，我们分 k = 1, 4, 16, 64 步，定量观察不同步数的预测质量。

max_steps = 64  # 最长预测步数（最多向后推 64 步）

# 构造一个更大的特征矩阵，每一列代表不同预测偏移量，形状不同
#   features 形状 (T - tau - max_steps + 1, tau + max_steps)
features = torch.zeros((T - tau - max_steps + 1, tau + max_steps))
# 列 i（i < tau）是来自 x 的真实观测，其时间步从 i 到 i + T - tau - max_steps + 1
for i in range(tau):
    features[:, i] = x[i: i + T - tau - max_steps + 1]

# 列 i（i >= tau）是来自（i - tau + 1）步的预测（即用前面的 tau 列推出来的），
#   其时间步从 i 到 i + T - tau - max_steps + 1
for i in range(tau, tau + max_steps):
    # net(features[:, i-tau : i])：用最近 tau 列（这些列已经是"预测出的序列"）
    #   预测出下一列的值，reshape(-1) 摊平成一维再存入第 i 列
    features[:, i] = net(features[:, i - tau:i]).reshape(-1)

# 取 k = 1, 4, 16, 64 四档步数，分别画出"第 k 步预测"对应的那条特征列
steps = (1, 4, 16, 64)
d2l.plot([time[tau + i - 1: T - max_steps + i] for i in steps],
         [features[:, (tau + i - 1)].detach().numpy() for i in steps], 'time', 'x',
         legend=[f'{i}-step preds' for i in steps], xlim=[5, 1000],
         figsize=(6, 3))


# ============================================================================
# 补充知识点
# ============================================================================

# 1. 为什么输入必须用"真实历史"而非"预测历史"来训练？
#    训练时我们始终用真实的 x 构造特征（监督学习），只在"推理多步预测"时才
#    用模型自己的输出当输入。若训练时也喂预测值（teacher forcing 的相反面），
#    网络会因为没见过自己的错误分布而崩溃。这与"时间正向、因果"一致。

# 2. 自回归模型与隐变量自回归模型的取舍
#    自回归模型（tau 个固定历史）实现简单、参数固定，但 tau 太大则维度爆炸、
#    太小则丢失长程依赖。隐变量自回归模型（h_t = g(h_{t-1}, x_{t-1})）能用
#    恒定大小的 h_t 无限压缩历史，是 RNN 的思想雏形，也是后续章节的核心。

# 3. 为什么用 Adam 而不是 SGD？
#    SGD 对各参数统一学习率，而 Adam 自适应地放缩每个参数的学习步长，
#    能在很少的 epoch（5 个）内快速收敛，适合小模型快速迭代实验。

# 4. 训练集划分的用意
#    只在 600 个点上训练，却在 t>604 之后做预测，本质是在考察模型的"外推能力"
#    (extrapolation)。外推比内插（interpolation，在已有观测间估计）难得多，
#    这正是多步预测失败暴露出的核心难点。

# 5. MSELoss(reduction='none') + 手动 .sum()
#    reduction='none' 保留每个样本的逐点损失（形状 (N,1)），
#    l.sum().backward() 把批内损失求和再反传。这与 D2L 从零实现里的
#    "批量损失求和"保持行为一致，便于比较。

# ============================================================================
# 核心公式回顾
# ============================================================================
#   序列联合概率（乘法法则，静止性假设）:
#       P(x_1,...,x_T) = Π_{t=1}^{T} P(x_t | x_{t-1}, ..., x_1)
#   自回归模型（tau 阶马尔可夫近似）:
#       P(x_t | x_{t-1}, ..., x_{t-tau})     —— 输入维度固定为 tau
#   隐变量自回归模型:
#       x_t_hat = P(x_t | h_t),   h_t = g(h_{t-1}, x_{t-1})
#   一阶马尔可夫模型（tau=1）:
#       P(x_1,...,x_T) = Π_{t=1}^{T} P(x_t | x_{t-1})
#   马尔可夫隔步展开（动态规划）:
#       P(x_{t+1}|x_{t-1}) = Σ_{x_t} P(x_{t+1}|x_t) P(x_t|x_{t-1})
#   数据生成:  x_t = sin(0.01 t) + ε,  ε ~ N(0, 0.2²)
#   网络:       net(x_[t-tau..t-1]) -> x_t_hat, 拟合 y = x_t
#   多步递推:   x_{t+k}_hat = f(x_{t+k-tau}, ..., x_{t+k-1})
#   误差累积:   ε_{k+1} ≈ ε̄ + c·ε_k   （c 为某放大常数，误差逐级放大）

# ============================================================================
# 总结
# ============================================================================
# 1. 序列数据本质是"有序的时间过程"，顺序被打乱就失去意义。
# 2. 自回归模型：用固定窗口 tau 的历史预测下一个值，参数数量固定，可训练深度网络。
# 3. 马尔可夫条件：用有限历史（tau 步）近似整个历史足够精确时成立；tau=1 即一阶马尔可夫。
# 4. 时间有因果方向（未来不影响过去），正向估计比反向更容易。
# 5. 单步预测效果好；多步（k 步）预测因"用自己的预测当输入"而误差累积，
#    随步数 k 增大预测质量迅速下降（k=16、64 时几乎无用）。
# 6. 改进方向（后续章节）：引入隐变量/RNN 等架构来更好地刻画长程依赖，
#    抑制错误累积，这正是不久之后"循环神经网络"要解决的问题。
